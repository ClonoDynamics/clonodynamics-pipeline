"""
7-pseudo_forward_technical_null_compact.py
==========================================

ClonoDynamics Step 7 — compact-native pseudo 1x12 technical-null benchmark.

This script is written specifically for the 14-column compact files generated by:

    pseudo_1x12_build_upstream_multirepresentation_streaming.py
        --compact-step7-cache
        --compact-step7-dt 1
        --cleanup-after-compact

Expected input layout
---------------------
<ensemble-root>/
    C000001/step7_cache/step7_dt1.parquet
    C000002/step7_cache/step7_dt1.parquet
    ...
    C002000/step7_cache/step7_dt1.parquet

Required compact schema (and ONLY schema used by this analyzer)
---------------------------------------------------------------
    configuration_id
    subject
    dt
    x0_latent
    xmid_latent
    xstar_latent
    dx_latent
    x_observed_rep1_t0
    x_observed_rep2_t0
    dx_observed_rep1
    dx_observed_rep2
    forward_ab_eligible
    forward_ba_eligible
    common4

Statistical design
------------------
The ensemble contains ONE biological source subject measured 12 times and
reassembled into many randomized 6-timepoint x 2-replicate pseudo-longitudinal
configurations.

`configuration_id` is a randomization realization, NOT a biological subject.
Therefore:
    - no subject bootstrap is performed;
    - configuration percentiles are RANDOMIZATION intervals, not biological CIs;
    - no nested pseudo-time permutation is performed.

Primary observed replicate-decoupled forward estimator
-------------------------------------------------------
For each configuration, AB and BA are estimated SEPARATELY:

    AB:
        conditioning  = x_observed_rep1_t0
        displacement  = dx_observed_rep2
        eligibility   = forward_ab_eligible

    BA:
        conditioning  = x_observed_rep2_t0
        displacement  = dx_observed_rep1
        eligibility   = forward_ba_eligible

AB and BA are NEVER concatenated to estimate the primary curve.

Instead, after binning on the SAME fixed global abundance bins:

    cross_combined(bin)
        = 0.5 * cross_AB(bin)
        + 0.5 * cross_BA(bin)

for mean displacement, median-displacement descriptor and P(dx>0).

Thus AB and BA have exactly equal fold weight in every combined bin,
independently of their row counts.

The global forward bin edges are also derived with equal AB/BA influence:
within every selected configuration the edge-estimation sample contains the
same number of AB-eligible and BA-eligible conditioning values.

Matched same-measure coupling control
-------------------------------------
On the shared `common4` support:

    same_A:
        x_observed_rep1_t0 -> dx_observed_rep1

    cross_AB_matched:
        x_observed_rep1_t0 -> dx_observed_rep2

    same_B:
        x_observed_rep2_t0 -> dx_observed_rep2

    cross_BA_matched:
        x_observed_rep2_t0 -> dx_observed_rep1

Again:

    same_combined
        = 0.5 * same_A + 0.5 * same_B

    cross_combined_matched
        = 0.5 * cross_AB_matched + 0.5 * cross_BA_matched

bin by bin.

Secondary latent conditioning-geometry diagnostic
-------------------------------------------------
The compact cache also permits a descriptive comparison of:

    x0_latent
    xmid_latent
    xstar_latent

against the same `dx_latent`.

Because the compact cache does NOT retain `obs_class_reference`,
this block is explicitly UNRESTRICTED with respect to TT/TF/FT/FF and must not
be described as the historical TT-only conditioning benchmark.

No universal conditioning-coordinate "winner" is selected here.

Resume safety
-------------
Each configuration checkpoint is tied to an analysis signature containing:
    - selected configuration IDs and compact-file identities;
    - all analysis parameters;
    - the exact global bin edges;
    - script version.

Changing from --max-configs 3 to the full ensemble changes the signature, so
test checkpoints are automatically invalidated.

Typical smoke test
------------------
python code/dynamics_4/7-pseudo_forward_technical_null_compact.py \
  --ensemble-root ./results_4/pseudo/ensemble_results_v3 \
  --outdir ./results_4/7-pseudo_forward_technical_null_compact \
  --expected-configs 2000 \
  --max-configs 3 \
  --dt 1 \
  --seed 123

Production
----------
Run the same command without --max-configs 3.
"""

