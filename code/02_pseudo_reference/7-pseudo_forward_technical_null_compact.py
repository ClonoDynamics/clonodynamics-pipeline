def summarize_metric_distribution(metrics: pd.DataFrame) -> pd.DataFrame:
    rows: List[Dict[str, object]] = []

    for keys, g in metrics.groupby(
        ["section", "representation", "metric"],
        sort=True,
    ):
        x = finite_array(g["value"])
        if x.size == 0:
            continue

        rows.append(
            {
                "section": keys[0],
                "representation": keys[1],
                "metric": keys[2],
                "n_configurations": int(x.size),
                "mean": float(np.mean(x)),
                "median": float(np.median(x)),
                "sd": float(np.std(x, ddof=0)),
                "randomization_q025": float(np.quantile(x, 0.025)),
                "randomization_q975": float(np.quantile(x, 0.975)),
                "min": float(np.min(x)),
                "max": float(np.max(x)),
            }
        )

    return pd.DataFrame(rows)


def curve_randomization_envelope(curves: pd.DataFrame) -> pd.DataFrame:
    if curves.empty:
        return pd.DataFrame()

    rows: List[Dict[str, object]] = []

    for keys, g in curves.groupby(
        ["section", "representation", "bin"],
        sort=True,
    ):
        row: Dict[str, object] = {
            "section": keys[0],
            "representation": keys[1],
            "bin": int(keys[2]),
            "n_configurations": int(
                g["configuration_id"].nunique()
            ),
        }

        for col in [
            "x_lo",
            "x_hi",
            "x_center",
            "x_median",
            "n_rows",
            "n_rows_fold_A",
            "n_rows_fold_B",
            "mean_dx",
            "median_dx",
            "p_dx_gt0",
        ]:
            if col not in g.columns:
                continue
            x = finite_array(g[col])
            if x.size == 0:
                continue

            row[col + "_median"] = float(np.median(x))
            row[col + "_randomization_q025"] = float(
                np.quantile(x, 0.025)
            )
            row[col + "_randomization_q975"] = float(
                np.quantile(x, 0.975)
            )

        rows.append(row)

    return pd.DataFrame(rows)


def summarize_simple_table(
    frame: pd.DataFrame,
    id_col: str = "configuration_id",
) -> pd.DataFrame:
    rows: List[Dict[str, object]] = []

    for col in frame.columns:
        if col == id_col:
            continue
        x = finite_array(frame[col])
        if x.size == 0:
            continue

        rows.append(
            {
                "metric": col,
                "n_configurations": int(x.size),
                "mean": float(np.mean(x)),
                "median": float(np.median(x)),
                "sd": float(np.std(x, ddof=0)),
                "randomization_q025": float(np.quantile(x, 0.025)),
                "randomization_q975": float(np.quantile(x, 0.975)),
                "min": float(np.min(x)),
                "max": float(np.max(x)),
            }
        )

    return pd.DataFrame(rows)


def randomization_pairwise_effects(
    metrics: pd.DataFrame,
) -> pd.DataFrame:
    """
    Paired configuration-level differences.

    This does NOT declare a universal winner. It reports how often one
    representation is numerically lower/higher than another for the same
    metric across the same randomized configurations.
    """
    rows: List[Dict[str, object]] = []

    for (section, metric), g in metrics.groupby(
        ["section", "metric"],
        sort=True,
    ):
        pivot = g.pivot_table(
            index="configuration_id",
            columns="representation",
            values="value",
            aggfunc="first",
        )

        reps = list(pivot.columns)
        for a, b in combinations(reps, 2):
            pair = pivot[[a, b]].dropna()
            if pair.empty:
                continue

            delta = (
                pair[a].to_numpy(float)
                - pair[b].to_numpy(float)
            )

            rows.append(
                {
                    "section": section,
                    "metric": metric,
                    "representation_a": a,
                    "representation_b": b,
                    "n_configurations": int(len(delta)),
                    "median_delta_a_minus_b": float(np.median(delta)),
                    "randomization_q025": float(np.quantile(delta, 0.025)),
                    "randomization_q975": float(np.quantile(delta, 0.975)),
                    "fraction_a_lt_b": float(np.mean(delta < 0)),
                    "fraction_a_gt_b": float(np.mean(delta > 0)),
                    "fraction_equal": float(np.mean(delta == 0)),
                }
            )

    return pd.DataFrame(rows)


