def load_checkpoint(
    path: Path,
    analysis_signature: str,
) -> Optional[Dict[str, object]]:
    if not path.is_file():
        return None
    try:
        obj = json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return None

    if obj.get("status") != "complete":
        return None
    if obj.get("analysis_signature") != analysis_signature:
        return None
    return obj


