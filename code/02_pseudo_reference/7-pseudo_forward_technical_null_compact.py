def quantile_edges(
    x: np.ndarray,
    n_bins: int,
    q_low: float,
    q_high: float,
) -> np.ndarray:
    x = np.asarray(x, dtype=float)
    x = x[np.isfinite(x)]
    if x.size == 0:
        raise ValueError("No finite values available for bin-edge construction")

    probs = np.linspace(float(q_low), float(q_high), int(n_bins) + 1)
    edges = np.unique(np.quantile(x, probs).astype(float))

    if edges.size < 3 or not np.all(np.diff(edges) > 0):
        raise ValueError(
            "Could not construct enough strictly increasing quantile edges"
        )
    return edges


def equal_width_edges(
    low: float,
    high: float,
    n_bins: int,
) -> np.ndarray:
    if not np.isfinite(low) or not np.isfinite(high) or low >= high:
        raise ValueError(f"Invalid abundance range: low={low}, high={high}")
    return np.linspace(float(low), float(high), int(n_bins) + 1)


def derive_forward_edges_equal_fold_weight(
    manifest: pd.DataFrame,
    args: argparse.Namespace,
) -> Tuple[np.ndarray, Dict[str, object]]:
    """
    Derive global forward bin edges from an equal-weight AB/BA sample.

    For every configuration:
        m = min(target_per_fold, n_AB, n_BA)

    and exactly m AB conditioning values + m BA conditioning values are added
    to the edge-estimation pool.

    Therefore:
        - AB and BA have equal influence within every configuration;
        - configurations have equal influence whenever both folds contain at
          least target_per_fold finite eligible rows (true in the production
          dataset under normal settings).
    """
    pooled: List[np.ndarray] = []
    per_config_rows: List[Dict[str, object]] = []

    target_per_fold = max(1, int(args.edge_sample_per_config) // 2)

    for i, row in manifest.reset_index(drop=True).iterrows():
        path = Path(row["compact"])
        d = pd.read_parquet(
            path,
            columns=[
                "x_observed_rep1_t0",
                "x_observed_rep2_t0",
                "forward_ab_eligible",
                "forward_ba_eligible",
            ],
        )

        ab_mask = normalize_bool(d["forward_ab_eligible"])
        ba_mask = normalize_bool(d["forward_ba_eligible"])

        x_ab = finite_array(d.loc[ab_mask, "x_observed_rep1_t0"])
        x_ba = finite_array(d.loc[ba_mask, "x_observed_rep2_t0"])

        m = min(target_per_fold, len(x_ab), len(x_ba))
        if m <= 0:
            raise RuntimeError(
                f"{row['configuration_id']}: cannot build equal-weight "
                "forward edge sample because one fold is empty"
            )

        rng_ab = np.random.default_rng(int(args.seed) + 2 * i)
        rng_ba = np.random.default_rng(int(args.seed) + 2 * i + 1)

        s_ab = sample_without_replacement(x_ab, m, rng_ab)
        s_ba = sample_without_replacement(x_ba, m, rng_ba)

        # Enforce equality exactly, even in pathological sampling cases.
        m2 = min(len(s_ab), len(s_ba))
        s_ab = s_ab[:m2]
        s_ba = s_ba[:m2]

        pooled.extend([s_ab, s_ba])
        per_config_rows.append(
            {
                "configuration_id": str(row["configuration_id"]),
                "n_edge_AB": int(len(s_ab)),
                "n_edge_BA": int(len(s_ba)),
                "equal_AB_BA": bool(len(s_ab) == len(s_ba)),
            }
        )

    x = np.concatenate(pooled)
    if args.forward_binning == "quantile":
        edges = quantile_edges(
            x,
            args.forward_n_bins,
            args.forward_q_low,
            args.forward_q_high,
        )
    else:
        lo = float(np.quantile(x, args.forward_q_low))
        hi = float(np.quantile(x, args.forward_q_high))
        edges = equal_width_edges(lo, hi, args.forward_n_bins)

    audit = {
        "policy": "equal AB/BA rows per configuration",
        "target_rows_per_fold_per_configuration": int(target_per_fold),
        "n_edge_pool_rows": int(len(x)),
        "n_bins": int(len(edges) - 1),
        "x_min": float(edges[0]),
        "x_max": float(edges[-1]),
        "binning": str(args.forward_binning),
        "q_low": float(args.forward_q_low),
        "q_high": float(args.forward_q_high),
        "all_configurations_equal_AB_BA_edge_weight": bool(
            all(r["equal_AB_BA"] for r in per_config_rows)
        ),
    }

    return edges, audit


def derive_conditioning_edges(
    manifest: pd.DataFrame,
    args: argparse.Namespace,
) -> Tuple[np.ndarray, Dict[str, object]]:
    """
    Derive a common absolute x-range for x0/xmid/xstar.

    Equal numbers of finite complete-case rows are sampled from every
    configuration, so the randomization configurations contribute equally to
    this descriptive secondary diagnostic.
    """
    sampled: Dict[str, List[np.ndarray]] = {
        c: [] for c in LATENT_CANDIDATES
    }

    target = int(args.conditioning_edge_sample_per_config)

    for i, row in manifest.reset_index(drop=True).iterrows():
        d = pd.read_parquet(
            Path(row["compact"]),
            columns=LATENT_CANDIDATES + ["dx_latent"],
        )

        keep = np.isfinite(
            pd.to_numeric(d["dx_latent"], errors="coerce").to_numpy(float)
        )
        for c in LATENT_CANDIDATES:
            keep &= np.isfinite(
                pd.to_numeric(d[c], errors="coerce").to_numpy(float)
            )

        d = d.loc[keep, LATENT_CANDIDATES].copy()
        if d.empty:
            raise RuntimeError(
                f"{row['configuration_id']}: no complete latent conditioning rows"
            )

        m = min(target, len(d))
        rng = np.random.default_rng(int(args.seed) + 100000 + i)
        if len(d) > m:
            idx = rng.choice(len(d), size=m, replace=False)
            d = d.iloc[idx]

        for c in LATENT_CANDIDATES:
            sampled[c].append(
                pd.to_numeric(d[c], errors="coerce").to_numpy(float)
            )

    pooled = {c: np.concatenate(sampled[c]) for c in LATENT_CANDIDATES}

    lows = [
        float(np.quantile(pooled[c], args.conditioning_q_low))
        for c in LATENT_CANDIDATES
    ]
    highs = [
        float(np.quantile(pooled[c], args.conditioning_q_high))
        for c in LATENT_CANDIDATES
    ]

    lo = max(lows)
    hi = min(highs)
    edges = equal_width_edges(lo, hi, args.conditioning_n_bins)

    return edges, {
        "policy": "equal configuration sampling; common candidate support",
        "rows_per_configuration_target": int(target),
        "n_bins": int(len(edges) - 1),
        "x_min": float(edges[0]),
        "x_max": float(edges[-1]),
        "q_low": float(args.conditioning_q_low),
        "q_high": float(args.conditioning_q_high),
    }


def write_edges(path: Path, edges: np.ndarray) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(
        {
            "bin": np.arange(1, len(edges), dtype=int),
            "x_lo": edges[:-1],
            "x_hi": edges[1:],
            "x_center": 0.5 * (edges[:-1] + edges[1:]),
        }
    ).to_csv(path, index=False)


