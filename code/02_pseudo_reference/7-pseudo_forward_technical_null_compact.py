def analyze_configuration(
    path: Path,
    cid: str,
    args: argparse.Namespace,
    forward_edges: np.ndarray,
    conditioning_edges: np.ndarray,
) -> Dict[str, object]:
    d = pd.read_parquet(path, columns=COMPACT_COLUMNS)

    if len(d) == 0:
        raise RuntimeError(f"{cid}: empty compact cache")

    ab_eligible = normalize_bool(d["forward_ab_eligible"])
    ba_eligible = normalize_bool(d["forward_ba_eligible"])
    common4 = normalize_bool(d["common4"])

    # ------------------------------------------------------------------
    # 1. PRIMARY OBSERVED REPLICATE-DECOUPLED FORWARD NULL
    # ------------------------------------------------------------------
    cross_ab = binned_curve(
        d,
        x_col="x_observed_rep1_t0",
        y_col="dx_observed_rep2",
        mask=ab_eligible,
        edges=forward_edges,
        min_n=args.min_n_fold,
        section="primary_forward",
        representation="cross_AB",
    )

    cross_ba = binned_curve(
        d,
        x_col="x_observed_rep2_t0",
        y_col="dx_observed_rep1",
        mask=ba_eligible,
        edges=forward_edges,
        min_n=args.min_n_fold,
        section="primary_forward",
        representation="cross_BA",
    )

    cross_combined = combine_equal_fold_weight(
        cross_ab,
        cross_ba,
        section="primary_forward",
        representation="cross_combined",
        fold_a_name="cross_AB",
        fold_b_name="cross_BA",
    )

    # ------------------------------------------------------------------
    # 2. MATCHED SAME-vs-CROSS CONTROL ON common4
    # ------------------------------------------------------------------
    same_a = binned_curve(
        d,
        x_col="x_observed_rep1_t0",
        y_col="dx_observed_rep1",
        mask=common4,
        edges=forward_edges,
        min_n=args.matched_min_n_fold,
        section="matched_same_vs_cross",
        representation="same_A",
    )

    same_b = binned_curve(
        d,
        x_col="x_observed_rep2_t0",
        y_col="dx_observed_rep2",
        mask=common4,
        edges=forward_edges,
        min_n=args.matched_min_n_fold,
        section="matched_same_vs_cross",
        representation="same_B",
    )

    cross_ab_matched = binned_curve(
        d,
        x_col="x_observed_rep1_t0",
        y_col="dx_observed_rep2",
        mask=common4,
        edges=forward_edges,
        min_n=args.matched_min_n_fold,
        section="matched_same_vs_cross",
        representation="cross_AB_matched",
    )

    cross_ba_matched = binned_curve(
        d,
        x_col="x_observed_rep2_t0",
        y_col="dx_observed_rep1",
        mask=common4,
        edges=forward_edges,
        min_n=args.matched_min_n_fold,
        section="matched_same_vs_cross",
        representation="cross_BA_matched",
    )

    same_combined = combine_equal_fold_weight(
        same_a,
        same_b,
        section="matched_same_vs_cross",
        representation="same_combined",
        fold_a_name="same_A",
        fold_b_name="same_B",
    )

    cross_combined_matched = combine_equal_fold_weight(
        cross_ab_matched,
        cross_ba_matched,
        section="matched_same_vs_cross",
        representation="cross_combined_matched",
        fold_a_name="cross_AB_matched",
        fold_b_name="cross_BA_matched",
    )

    # ------------------------------------------------------------------
    # 3. SECONDARY UNRESTRICTED LATENT CONDITIONING GEOMETRY
    # ------------------------------------------------------------------
    latent_complete = np.isfinite(
        pd.to_numeric(d["dx_latent"], errors="coerce").to_numpy(float)
    )
    for c in LATENT_CANDIDATES:
        latent_complete &= np.isfinite(
            pd.to_numeric(d[c], errors="coerce").to_numpy(float)
        )

    conditioning_curves: Dict[str, pd.DataFrame] = {}
    for c in LATENT_CANDIDATES:
        conditioning_curves[c] = binned_curve(
            d,
            x_col=c,
            y_col="dx_latent",
            mask=latent_complete,
            edges=conditioning_edges,
            min_n=args.conditioning_min_n,
            section="conditioning_geometry_unrestricted",
            representation=c,
        )

    curve_tables = [
        cross_ab,
        cross_ba,
        cross_combined,
        same_a,
        same_b,
        same_combined,
        cross_ab_matched,
        cross_ba_matched,
        cross_combined_matched,
        *conditioning_curves.values(),
    ]
    curve_tables = [x for x in curve_tables if not x.empty]

    curves = (
        pd.concat(curve_tables, ignore_index=True, sort=False)
        if curve_tables else pd.DataFrame()
    )

    metrics: List[Dict[str, object]] = []

    primary_metrics = {}
    for rep, curve in [
        ("cross_AB", cross_ab),
        ("cross_BA", cross_ba),
        ("cross_combined", cross_combined),
    ]:
        cm = curve_metrics(curve, args.min_valid_bins)
        primary_metrics[rep] = cm
        metrics += metric_records("primary_forward", rep, cm)

    matched_metrics = {}
    for rep, curve in [
        ("same_A", same_a),
        ("same_B", same_b),
        ("same_combined", same_combined),
        ("cross_AB_matched", cross_ab_matched),
        ("cross_BA_matched", cross_ba_matched),
        ("cross_combined_matched", cross_combined_matched),
    ]:
        cm = curve_metrics(curve, args.matched_min_valid_bins)
        matched_metrics[rep] = cm
        metrics += metric_records("matched_same_vs_cross", rep, cm)

    conditioning_metrics = {}
    for rep, curve in conditioning_curves.items():
        cm = curve_metrics(curve, args.conditioning_min_valid_bins)
        conditioning_metrics[rep] = cm
        metrics += metric_records(
            "conditioning_geometry_unrestricted",
            rep,
            cm,
        )

    # Direct matched decoupling effect.
    same_abs = matched_metrics["same_combined"]["mean_abs_bin_mean_dx"]
    cross_abs = matched_metrics["cross_combined_matched"]["mean_abs_bin_mean_dx"]

    if (
        np.isfinite(same_abs)
        and np.isfinite(cross_abs)
        and float(same_abs) > 0
    ):
        retained = float(cross_abs) / float(same_abs)
        reduction = 100.0 * (1.0 - retained)
    else:
        retained = np.nan
        reduction = np.nan

    matched_effect = {
        "same_mean_abs_bin_mean_dx": same_abs,
        "cross_mean_abs_bin_mean_dx": cross_abs,
        "cross_retained_fraction_of_same": retained,
        "percent_reduction_after_decoupling": reduction,
        "same_slope": matched_metrics["same_combined"]["slope_mean_dx_vs_x"],
        "cross_slope": matched_metrics["cross_combined_matched"]["slope_mean_dx_vs_x"],
    }

    support = {
        "n_rows": int(len(d)),
        "n_forward_ab_eligible": int(ab_eligible.sum()),
        "n_forward_ba_eligible": int(ba_eligible.sum()),
        "n_common4": int(common4.sum()),
        "forward_ab_fraction": float(ab_eligible.mean()),
        "forward_ba_fraction": float(ba_eligible.mean()),
        "common4_fraction": float(common4.mean()),
    }

    return {
        "metrics": metrics,
        "curves": curves.to_dict(orient="records"),
        "AB_BA_concordance": fold_concordance(cross_ab, cross_ba),
        "matched_decoupling_effect": matched_effect,
        "support": support,
        "conditioning_metrics": conditioning_metrics,
    }


