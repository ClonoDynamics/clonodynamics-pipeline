    print("[INFO] configurations selected          :", len(manifest))
    print("[INFO] biological source subjects       : 1")
    print("[INFO] configuration_id as biological N : NO")
    print("[INFO] compact schema columns used       : 14")
    print("[INFO] primary estimator                 : observed cross AB/BA")
    print("[INFO] AB/BA combination                 : exact 0.5 / 0.5 after binning")
    print("[INFO] row-count AB/BA weighting         : NEVER")

    # Validate a small leading subset before doing any edge work.
    for r in manifest.head(min(3, len(manifest))).itertuples(index=False):
        validate_compact(
            Path(r.compact),
            str(r.configuration_id),
            int(args.dt),
            bool(args.require_exact_14_column_schema),
        )

    # Global fixed bins.
    forward_edges, forward_edge_audit = (
        derive_forward_edges_equal_fold_weight(manifest, args)
    )
    conditioning_edges, conditioning_edge_audit = (
        derive_conditioning_edges(manifest, args)
    )

    forward_edges_path = (
        outdir / "01_primary_forward" / "forward_bin_edges.csv"
    )
    conditioning_edges_path = (
        outdir
        / "03_conditioning_geometry_unrestricted"
        / "conditioning_bin_edges.csv"
    )

    write_edges(forward_edges_path, forward_edges)
    write_edges(conditioning_edges_path, conditioning_edges)

    manifest.to_csv(
        outdir / "00_configuration_manifest.csv",
        index=False,
    )

    # Signature deliberately depends on the selected ensemble, inputs, params,
    # and exact numeric bin edges.
    signature_payload = {
        "script_version": SCRIPT_VERSION,
        "selected_configuration_ids":
            manifest["configuration_id"].astype(str).tolist(),
        "input_identities": [
            {
                "configuration_id": str(r.configuration_id),
                "compact": path_identity(Path(r.compact)),
            }
            for r in manifest.itertuples(index=False)
        ],
        "parameters": {
            "dt": int(args.dt),
            "forward_n_bins": int(args.forward_n_bins),
            "forward_binning": str(args.forward_binning),
            "forward_q_low": float(args.forward_q_low),
            "forward_q_high": float(args.forward_q_high),
            "min_n_fold": int(args.min_n_fold),
            "min_valid_bins": int(args.min_valid_bins),
            "edge_sample_per_config": int(args.edge_sample_per_config),
            "matched_min_n_fold": int(args.matched_min_n_fold),
            "matched_min_valid_bins": int(args.matched_min_valid_bins),
            "conditioning_n_bins": int(args.conditioning_n_bins),
            "conditioning_q_low": float(args.conditioning_q_low),
            "conditioning_q_high": float(args.conditioning_q_high),
            "conditioning_min_n": int(args.conditioning_min_n),
            "conditioning_min_valid_bins":
                int(args.conditioning_min_valid_bins),
            "conditioning_edge_sample_per_config":
                int(args.conditioning_edge_sample_per_config),
            "seed": int(args.seed),
        },
        "forward_edges": [float(x) for x in forward_edges],
        "conditioning_edges": [float(x) for x in conditioning_edges],
        "AB_BA_combination_policy": "exact_equal_fold_weight_after_binning",
        "AB_BA_row_count_weighting": False,
    }

    analysis_signature = stable_hash(signature_payload)

    (outdir / "00_run_signature.json").write_text(
        json.dumps(
            {
                "analysis_signature": analysis_signature,
                "signature_payload": signature_payload,
            },
            indent=2,
            sort_keys=True,
        )
        + "\n",
        encoding="utf-8",
    )

    print("[INFO] analysis signature:", analysis_signature[:16] + "...")

    statuses: List[Dict[str, object]] = []

    for i, row in manifest.reset_index(drop=True).iterrows():
        cid = str(row["configuration_id"])
        path = Path(row["compact"])
        checkpoint = checkpoint_dir / f"{cid}.json"

        previous = (
            None
            if args.restart
            else load_checkpoint(checkpoint, analysis_signature)
        )

        if previous is not None:
            print("[resume-safe]", cid)
            statuses.append(
                {
                    "configuration_id": cid,
                    "status": "complete",
                    "execution": "resumed",
                }
            )
            pd.DataFrame(statuses).to_csv(
                outdir / "00_run_status.csv",
                index=False,
            )
            continue

        if checkpoint.exists():
            print("[stale checkpoint -> recompute]", cid)
            checkpoint.unlink()

        print(f"[config {i+1}/{len(manifest)}] {cid}")

        try:
            audit = validate_compact(
                path,
                cid,
                int(args.dt),
                bool(args.require_exact_14_column_schema),
            )

            result = analyze_configuration(
                path,
                cid,
                args,
                forward_edges,
                conditioning_edges,
            )

            payload = {
                "configuration_id": cid,
                "analysis_signature": analysis_signature,
                "input_identity": path_identity(path),
                "input_audit": audit,
                "metrics": result["metrics"],
                "curves": result["curves"],
                "AB_BA_concordance": result["AB_BA_concordance"],
                "matched_decoupling_effect":
                    result["matched_decoupling_effect"],
                "support": result["support"],
                "conditioning_metrics": result["conditioning_metrics"],
                "status": "complete",
            }

            checkpoint.write_text(
                json.dumps(
                    json_safe(payload),
                    indent=2,
                    sort_keys=True,
                )
                + "\n",
                encoding="utf-8",
            )

            statuses.append(
                {
                    "configuration_id": cid,
                    "status": "complete",
                    "execution": "computed",
                }
            )

        except Exception as exc:
            statuses.append(
                {
                    "configuration_id": cid,
                    "status": "failed",
                    "execution": "computed",
                    "message": f"{type(exc).__name__}: {exc}",
                }
            )

            pd.DataFrame(statuses).to_csv(
                outdir / "00_run_status.csv",
                index=False,
            )

            if not args.continue_on_error:
                raise

            print("[ERROR]", cid, exc, file=sys.stderr)

        pd.DataFrame(statuses).to_csv(
            outdir / "00_run_status.csv",
            index=False,
        )

    # Reassemble only checkpoints matching the current exact signature.
    metric_rows: List[Dict[str, object]] = []
    curve_rows: List[Dict[str, object]] = []
    concordance_rows: List[Dict[str, object]] = []
    matched_rows: List[Dict[str, object]] = []
    support_rows: List[Dict[str, object]] = []

    n_complete = 0

    for row in manifest.itertuples(index=False):
        cid = str(row.configuration_id)
        obj = load_checkpoint(
            checkpoint_dir / f"{cid}.json",
            analysis_signature,
        )

        if obj is None:
            continue

        n_complete += 1

        for rec in obj.get("metrics", []):
            metric_rows.append(
                {"configuration_id": cid, **rec}
            )

        for rec in obj.get("curves", []):
            curve_rows.append(
                {"configuration_id": cid, **rec}
            )

        concordance_rows.append(
            {
                "configuration_id": cid,
                **obj.get("AB_BA_concordance", {}),
            }
        )

        matched_rows.append(
            {
                "configuration_id": cid,
                **obj.get("matched_decoupling_effect", {}),
            }
        )

        support_rows.append(
            {
                "configuration_id": cid,
                **obj.get("support", {}),
            }
        )

    if n_complete == 0:
        raise RuntimeError(
            "No completed configuration matches the current analysis signature"
        )

    metrics = pd.DataFrame(metric_rows)
    curves = pd.DataFrame(curve_rows)
    concordance = pd.DataFrame(concordance_rows)
    matched = pd.DataFrame(matched_rows)
    support = pd.DataFrame(support_rows)

    # Top-level outputs.
    metrics.to_csv(
        outdir / "01_configuration_metrics_long.csv",
        index=False,
    )

    ensemble_metrics = summarize_metric_distribution(metrics)
    ensemble_metrics.to_csv(
        outdir / "02_ensemble_metric_summary.csv",
        index=False,
    )

    # Curves can be moderately large, so retain Parquet plus ensemble CSV.
    curves.to_parquet(
        outdir / "03_configuration_curves_long.parquet",
        index=False,
        compression="zstd",
    )

    envelope = curve_randomization_envelope(curves)
    envelope.to_csv(
        outdir / "04_curve_randomization_envelope.csv",
        index=False,
    )

    concordance.to_csv(
        outdir / "05_AB_BA_concordance_by_configuration.csv",
        index=False,
    )
    summarize_simple_table(concordance).to_csv(
        outdir / "06_AB_BA_concordance_ensemble_summary.csv",
        index=False,
    )

    matched.to_csv(
        outdir / "07_matched_same_vs_cross_by_configuration.csv",
        index=False,
    )
    summarize_simple_table(matched).to_csv(
        outdir / "08_matched_same_vs_cross_ensemble_summary.csv",
        index=False,
    )

    support.to_csv(
        outdir / "09_support_by_configuration.csv",
        index=False,
    )
    summarize_simple_table(support).to_csv(
        outdir / "10_support_ensemble_summary.csv",
        index=False,
    )

    randomization_pairwise_effects(metrics).to_csv(
        outdir / "11_randomization_pairwise_effects.csv",
        index=False,
    )

    # Stage-specific manuscript-friendly outputs.
    primary_env = envelope[
        envelope["section"].astype(str).eq("primary_forward")
    ].copy()
    primary_env.to_csv(
        outdir
        / "01_primary_forward"
        / "ensemble_primary_forward_curves.csv",
        index=False,
    )

    matched_env = envelope[
        envelope["section"].astype(str).eq("matched_same_vs_cross")
    ].copy()
    matched_dir = outdir / "02_matched_same_vs_cross"
    matched_dir.mkdir(parents=True, exist_ok=True)
    matched_env.to_csv(
        matched_dir / "ensemble_matched_same_vs_cross_curves.csv",
        index=False,
    )

    conditioning_env = envelope[
        envelope["section"].astype(str).eq(
            "conditioning_geometry_unrestricted"
        )
    ].copy()
    conditioning_env.to_csv(
        outdir
        / "03_conditioning_geometry_unrestricted"
        / "ensemble_conditioning_curves.csv",
        index=False,
    )

    # Compact manuscript-oriented summary uses the randomization median, not a
    # pooled analysis across configurations.
    compat = ensemble_metrics[
        [
            "section",
            "representation",
            "metric",
            "median",
            "randomization_q025",
            "randomization_q975",
            "n_configurations",
        ]
    ].rename(columns={"median": "value"})
    compat.to_csv(
        outdir / "00_benchmark_summary.csv",
        index=False,
    )

    run_config = {
        "script": Path(__file__).name,
        "script_version": SCRIPT_VERSION,
        "analysis_signature": analysis_signature,
        "ensemble_root": str(ensemble_root),
        "outdir": str(outdir),
        "n_complete_configurations_discovered": int(len(full_manifest)),
        "n_configurations_selected": int(len(manifest)),
        "n_current_signature_checkpoints": int(n_complete),
        "source_biological_subjects": 1,
        "configuration_id_is_biological_subject": False,
        "subject_bootstrap_used": False,
        "nested_pseudo_time_permutation_used": False,
        "randomization_interval_is_biological_CI": False,
        "compact_input_contract": COMPACT_COLUMNS,
        "primary_forward": {
            "AB": {
                "conditioning": "x_observed_rep1_t0",
                "displacement": "dx_observed_rep2",
                "eligibility": "forward_ab_eligible",
            },
            "BA": {
                "conditioning": "x_observed_rep2_t0",
                "displacement": "dx_observed_rep1",
                "eligibility": "forward_ba_eligible",
            },
            "combined_policy": "0.5*AB + 0.5*BA after binning",
            "row_count_weighting": False,
            "global_edge_policy": forward_edge_audit,
        },
        "matched_same_vs_cross": {
            "support": "common4",
            "same_combined_policy": "0.5*same_A + 0.5*same_B",
            "cross_combined_policy":
                "0.5*cross_AB_matched + 0.5*cross_BA_matched",
            "row_count_weighting": False,
        },
        "conditioning_geometry": {
            "role": "secondary descriptive diagnostic",
            "operational_observation_class_restriction": None,
            "reason":
                "obs_class_reference is not retained in the 14-column compact cache",
            "candidates": LATENT_CANDIDATES,
            "displacement": "dx_latent",
            "global_edge_policy": conditioning_edge_audit,
        },
        "seed": int(args.seed),
    }

    (outdir / "00_run_config.json").write_text(
        json.dumps(
            json_safe(run_config),
            indent=2,
            sort_keys=True,
        )
        + "\n",
        encoding="utf-8",
    )

    write_readme(outdir)
    write_pipeline_manifest(outdir)

    print("\n[DONE] Step 7 compact pseudo technical-null benchmark")
    print("Selected configurations          :", len(manifest))
    print("Completed configurations         :", n_complete)
    print("Biological source subjects       : 1")
    print("configuration_id as biological N : NO")
    print("AB/BA equal fold weight          : YES (0.5 / 0.5)")
    print("AB/BA row-count weighting        : NO")
    print("Nested pseudo-time permutation   : NO")
    print("Subject bootstrap                : NO")
    print("Summary                          :", outdir / "02_ensemble_metric_summary.csv")

    return 0


