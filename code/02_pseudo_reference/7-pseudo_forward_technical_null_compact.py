def discover_configurations(
    ensemble_root: Path,
    expected_configs: int,
) -> pd.DataFrame:
    rows: List[Dict[str, object]] = []

    for cdir in sorted(ensemble_root.glob("C*")):
        if not cdir.is_dir():
            continue
        compact = cdir / COMPACT_REL
        if compact.is_file() and compact.stat().st_size > 0:
            rows.append(
                {
                    "configuration_id": cdir.name,
                    "configuration_dir": str(cdir.resolve()),
                    "compact": str(compact.resolve()),
                }
            )

    if not rows:
        raise FileNotFoundError(
            f"No compact Step-7 files found under {ensemble_root}. "
            f"Expected Cxxxxxx/{COMPACT_REL}."
        )

    manifest = (
        pd.DataFrame(rows)
        .sort_values("configuration_id")
        .reset_index(drop=True)
    )

    if int(expected_configs) > 0:
        n = int(expected_configs)
        expected_ids = [f"C{i:06d}" for i in range(1, n + 1)]
        got_ids = manifest["configuration_id"].astype(str).tolist()

        if got_ids != expected_ids:
            missing = [x for x in expected_ids if x not in set(got_ids)][:10]
            extra = [x for x in got_ids if x not in set(expected_ids)][:10]
            raise ValueError(
                f"Expected contiguous C000001..C{n:06d}; "
                f"found {len(got_ids)} compact configurations. "
                f"First missing={missing}; first unexpected={extra}"
            )

    return manifest


def validate_compact(
    path: Path,
    cid: str,
    dt: int,
    require_exact_schema: bool,
) -> Dict[str, object]:
    cols = parquet_columns(path)
    colset = set(cols)

    missing = sorted(set(COMPACT_COLUMNS) - colset)
    if missing:
        raise ValueError(
            f"{cid}: compact cache missing required columns {missing}"
        )

    extras = sorted(colset - set(COMPACT_COLUMNS))
    if require_exact_schema and extras:
        raise ValueError(
            f"{cid}: compact cache contains unexpected extra columns {extras}"
        )

    d = pd.read_parquet(
        path,
        columns=[
            "configuration_id",
            "subject",
            "dt",
            "forward_ab_eligible",
            "forward_ba_eligible",
            "common4",
        ],
    )

    if d.empty:
        raise ValueError(f"{cid}: compact cache is empty")

    ids = set(d["configuration_id"].astype(str).dropna().unique())
    if ids != {cid}:
        raise ValueError(
            f"{cid}: cache contains configuration_id values {sorted(ids)}"
        )

    subjects = set(
        pd.to_numeric(d["subject"], errors="coerce")
        .dropna()
        .astype(int)
        .unique()
    )
    if subjects != {1}:
        raise ValueError(
            f"{cid}: expected biological source subject {{1}}, found {subjects}"
        )

    dts = sorted(
        pd.to_numeric(d["dt"], errors="coerce")
        .dropna()
        .astype(int)
        .unique()
        .tolist()
    )
    if dts != [int(dt)]:
        raise ValueError(
            f"{cid}: expected compact dt={dt}, found {dts}"
        )

    ab = normalize_bool(d["forward_ab_eligible"])
    ba = normalize_bool(d["forward_ba_eligible"])
    c4 = normalize_bool(d["common4"])

    audit = {
        "n_rows": int(len(d)),
        "n_forward_ab_eligible": int(ab.sum()),
        "n_forward_ba_eligible": int(ba.sum()),
        "n_common4": int(c4.sum()),
    }

    if min(
        audit["n_forward_ab_eligible"],
        audit["n_forward_ba_eligible"],
        audit["n_common4"],
    ) <= 0:
        raise RuntimeError(
            f"{cid}: one or more required support sets are empty: {audit}"
        )

    return audit


