def assign_bins(x: np.ndarray, edges: np.ndarray) -> np.ndarray:
    x = np.asarray(x, dtype=float)
    out = np.zeros(x.size, dtype=np.int32)

    finite = np.isfinite(x)
    if not finite.any():
        return out

    xx = x[finite]
    idx = np.searchsorted(edges, xx, side="right") - 1
    idx[xx == edges[-1]] = len(edges) - 2

    valid = (idx >= 0) & (idx < len(edges) - 1)
    positions = np.where(finite)[0]
    out[positions[valid]] = idx[valid] + 1
    return out


def binned_curve(
    frame: pd.DataFrame,
    x_col: str,
    y_col: str,
    mask: np.ndarray,
    edges: np.ndarray,
    min_n: int,
    section: str,
    representation: str,
) -> pd.DataFrame:
    x = pd.to_numeric(frame[x_col], errors="coerce").to_numpy(float)
    y = pd.to_numeric(frame[y_col], errors="coerce").to_numpy(float)

    keep = (
        np.asarray(mask, dtype=bool)
        & np.isfinite(x)
        & np.isfinite(y)
    )

    x = x[keep]
    y = y[keep]

    if len(x) == 0:
        return pd.DataFrame()

    bins = assign_bins(x, edges)
    within = bins > 0
    x = x[within]
    y = y[within]
    bins = bins[within]

    rows: List[Dict[str, object]] = []

    for b in range(1, len(edges)):
        sel = bins == b
        n = int(sel.sum())
        if n == 0:
            continue

        yy = y[sel]
        xx = x[sel]

        rows.append(
            {
                "section": section,
                "representation": representation,
                "bin": int(b),
                "x_lo": float(edges[b - 1]),
                "x_hi": float(edges[b]),
                "x_center": float(0.5 * (edges[b - 1] + edges[b])),
                "x_median": float(np.median(xx)),
                "n_rows": n,
                "mean_dx": float(np.mean(yy)),
                "median_dx": float(np.median(yy)),
                "p_dx_gt0": float(np.mean(yy > 0)),
                "meets_min_n": bool(n >= int(min_n)),
            }
        )

    return pd.DataFrame(rows)


def combine_equal_fold_weight(
    fold_a: pd.DataFrame,
    fold_b: pd.DataFrame,
    section: str,
    representation: str,
    fold_a_name: str,
    fold_b_name: str,
) -> pd.DataFrame:
    """
    Combine two already-binned folds with EXACT 0.5 / 0.5 weight.

    Row counts are retained for audit only and NEVER used as weights.
    A combined bin is inferentially valid only when both component folds meet
    the fold-specific minimum-n threshold.
    """
    if fold_a.empty or fold_b.empty:
        return pd.DataFrame()

    a = fold_a[
        [
            "bin",
            "x_lo",
            "x_hi",
            "x_center",
            "x_median",
            "n_rows",
            "mean_dx",
            "median_dx",
            "p_dx_gt0",
            "meets_min_n",
        ]
    ].rename(
        columns={
            "x_median": "x_median_A",
            "n_rows": "n_rows_A",
            "mean_dx": "mean_dx_A",
            "median_dx": "median_dx_A",
            "p_dx_gt0": "p_dx_gt0_A",
            "meets_min_n": "valid_A",
        }
    )

    b = fold_b[
        [
            "bin",
            "x_median",
            "n_rows",
            "mean_dx",
            "median_dx",
            "p_dx_gt0",
            "meets_min_n",
        ]
    ].rename(
        columns={
            "x_median": "x_median_B",
            "n_rows": "n_rows_B",
            "mean_dx": "mean_dx_B",
            "median_dx": "median_dx_B",
            "p_dx_gt0": "p_dx_gt0_B",
            "meets_min_n": "valid_B",
        }
    )

    m = a.merge(b, on="bin", how="inner")
    rows: List[Dict[str, object]] = []

    for r in m.itertuples(index=False):
        rows.append(
            {
                "section": section,
                "representation": representation,
                "bin": int(r.bin),
                "x_lo": float(r.x_lo),
                "x_hi": float(r.x_hi),
                "x_center": float(r.x_center),
                "x_median": float(
                    0.5 * float(r.x_median_A)
                    + 0.5 * float(r.x_median_B)
                ),
                # Audit only; not an estimator weight.
                "n_rows": int(r.n_rows_A + r.n_rows_B),
                "n_rows_fold_A": int(r.n_rows_A),
                "n_rows_fold_B": int(r.n_rows_B),
                "mean_dx": float(
                    0.5 * float(r.mean_dx_A)
                    + 0.5 * float(r.mean_dx_B)
                ),
                # Equal-weight fold descriptor, NOT pooled-row median.
                "median_dx": float(
                    0.5 * float(r.median_dx_A)
                    + 0.5 * float(r.median_dx_B)
                ),
                "p_dx_gt0": float(
                    0.5 * float(r.p_dx_gt0_A)
                    + 0.5 * float(r.p_dx_gt0_B)
                ),
                "meets_min_n": bool(r.valid_A and r.valid_B),
                "fold_A": fold_a_name,
                "fold_B": fold_b_name,
                "fold_A_weight": 0.5,
                "fold_B_weight": 0.5,
                "row_count_weighting_used": False,
            }
        )

    return pd.DataFrame(rows)


def curve_metrics(
    curve: pd.DataFrame,
    min_valid_bins: int,
) -> Dict[str, object]:
    if curve.empty:
        return {
            "n_bins_valid": 0,
            "mean_bin_mean_dx": np.nan,
            "mean_abs_bin_mean_dx": np.nan,
            "rms_bin_mean_dx": np.nan,
            "max_abs_bin_mean_dx": np.nan,
            "mean_abs_probability_bias": np.nan,
            "slope_mean_dx_vs_x": np.nan,
            "intercept_mean_dx_vs_x": np.nan,
            "zero_crossing_x": np.nan,
        }

    valid = curve[curve["meets_min_n"].astype(bool)].copy()

    if len(valid) < int(min_valid_bins):
        return {
            "n_bins_valid": int(len(valid)),
            "mean_bin_mean_dx": np.nan,
            "mean_abs_bin_mean_dx": np.nan,
            "rms_bin_mean_dx": np.nan,
            "max_abs_bin_mean_dx": np.nan,
            "mean_abs_probability_bias": np.nan,
            "slope_mean_dx_vs_x": np.nan,
            "intercept_mean_dx_vs_x": np.nan,
            "zero_crossing_x": np.nan,
        }

    x = pd.to_numeric(valid["x_center"], errors="coerce").to_numpy(float)
    y = pd.to_numeric(valid["mean_dx"], errors="coerce").to_numpy(float)
    p = pd.to_numeric(valid["p_dx_gt0"], errors="coerce").to_numpy(float)

    slope, intercept, zero = safe_slope_intercept(x, y)

    return {
        "n_bins_valid": int(len(valid)),
        "mean_bin_mean_dx": float(np.mean(y)),
        "mean_abs_bin_mean_dx": float(np.mean(np.abs(y))),
        "rms_bin_mean_dx": float(np.sqrt(np.mean(y * y))),
        "max_abs_bin_mean_dx": float(np.max(np.abs(y))),
        "mean_abs_probability_bias": float(np.mean(np.abs(p - 0.5))),
        "slope_mean_dx_vs_x": slope,
        "intercept_mean_dx_vs_x": intercept,
        "zero_crossing_x": zero,
    }


def metric_records(
    section: str,
    representation: str,
    metrics: Dict[str, object],
) -> List[Dict[str, object]]:
    return [
        {
            "section": section,
            "representation": representation,
            "metric": metric,
            "value": value,
        }
        for metric, value in metrics.items()
    ]


def fold_concordance(
    ab: pd.DataFrame,
    ba: pd.DataFrame,
) -> Dict[str, object]:
    if ab.empty or ba.empty:
        return {
            "n_matched_valid_bins": 0,
            "pearson_r_AB_BA": np.nan,
            "mean_abs_AB_BA_difference": np.nan,
            "rms_AB_BA_difference": np.nan,
            "max_abs_AB_BA_difference": np.nan,
        }

    a = ab[ab["meets_min_n"].astype(bool)][
        ["bin", "mean_dx"]
    ].rename(columns={"mean_dx": "AB"})

    b = ba[ba["meets_min_n"].astype(bool)][
        ["bin", "mean_dx"]
    ].rename(columns={"mean_dx": "BA"})

    m = a.merge(b, on="bin", how="inner").dropna()

    if m.empty:
        return {
            "n_matched_valid_bins": 0,
            "pearson_r_AB_BA": np.nan,
            "mean_abs_AB_BA_difference": np.nan,
            "rms_AB_BA_difference": np.nan,
            "max_abs_AB_BA_difference": np.nan,
        }

    x = m["AB"].to_numpy(float)
    y = m["BA"].to_numpy(float)
    d = x - y

    return {
        "n_matched_valid_bins": int(len(m)),
        "pearson_r_AB_BA": safe_pearson(x, y),
        "mean_abs_AB_BA_difference": float(np.mean(np.abs(d))),
        "rms_AB_BA_difference": float(np.sqrt(np.mean(d * d))),
        "max_abs_AB_BA_difference": float(np.max(np.abs(d))),
    }


