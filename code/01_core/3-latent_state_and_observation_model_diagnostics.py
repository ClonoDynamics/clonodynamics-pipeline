def _spearman_from_unit_frame(df: pl.DataFrame, x: str, y: str) -> Optional[float]:
    """Spearman rho across aggregated analysis units, or None if undefined."""
    if df.height < 3:
        return None
    finite = df.filter(pl.col(x).is_finite() & pl.col(y).is_finite())
    if finite.height < 3:
        return None
    if finite.get_column(x).n_unique() < 2 or finite.get_column(y).n_unique() < 2:
        return None
    value = finite.select(pl.corr(x, y, method="spearman").alias("rho"))["rho"][0]
    return float(value) if value is not None else None


def _pearson_from_unit_frame(df: pl.DataFrame, x: str, y: str) -> Optional[float]:
    """Pearson r across aggregated analysis units, or None if undefined."""
    if df.height < 3:
        return None
    finite = df.filter(pl.col(x).is_finite() & pl.col(y).is_finite())
    if finite.height < 3:
        return None
    if finite.get_column(x).n_unique() < 2 or finite.get_column(y).n_unique() < 2:
        return None
    value = finite.select(pl.corr(x, y, method="pearson").alias("r"))["r"][0]
    return float(value) if value is not None else None


def _linear_fit_from_unit_frame(df: pl.DataFrame, x: str, y: str) -> dict:
    """Simple OLS y ~ intercept + slope*x across aggregated analysis units."""
    finite = df.filter(pl.col(x).is_finite() & pl.col(y).is_finite())
    if finite.height < 3:
        return {"n": int(finite.height), "slope": None, "intercept": None, "r2": None}
    xv = np.asarray(finite.get_column(x).to_list(), dtype=float)
    yv = np.asarray(finite.get_column(y).to_list(), dtype=float)
    if np.unique(xv).size < 2 or np.unique(yv).size < 2:
        return {"n": int(finite.height), "slope": None, "intercept": None, "r2": None}
    x_mean = float(np.mean(xv))
    y_mean = float(np.mean(yv))
    ss_x = float(np.sum((xv - x_mean) ** 2))
    if not np.isfinite(ss_x) or ss_x <= 0:
        return {"n": int(finite.height), "slope": None, "intercept": None, "r2": None}
    slope = float(np.sum((xv - x_mean) * (yv - y_mean)) / ss_x)
    intercept = float(y_mean - slope * x_mean)
    fitted = intercept + slope * xv
    ss_tot = float(np.sum((yv - y_mean) ** 2))
    ss_res = float(np.sum((yv - fitted) ** 2))
    r2 = float(1.0 - ss_res / ss_tot) if ss_tot > 0 else None
    return {"n": int(finite.height), "slope": slope, "intercept": intercept, "r2": r2}


