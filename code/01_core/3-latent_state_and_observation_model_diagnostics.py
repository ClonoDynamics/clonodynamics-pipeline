def ensure_dir(path: Path) -> Path:
    path.mkdir(parents=True, exist_ok=True)
    return path


def resolve_input(path: Path, pattern: str) -> Path:
    if path.is_file():
        return path
    if not path.is_dir():
        raise FileNotFoundError("Input does not exist: %s" % path)
    matches = sorted(path.glob(pattern))
    if len(matches) != 1:
        raise FileNotFoundError(
            "Expected exactly one file matching %r in %s; found %d" %
            (pattern, path, len(matches))
        )
    return matches[0]


def scan_table(path: Path) -> pl.LazyFrame:
    suffix = path.suffix.lower()
    if suffix in (".parquet", ".pq"):
        return pl.scan_parquet(path)
    if suffix in (".csv", ".tsv", ".txt"):
        sep = "\t" if suffix in (".tsv", ".txt") else ","
        return pl.scan_csv(path, separator=sep, infer_schema_length=10000)
    raise ValueError("Unsupported input format: %s" % suffix)


def require_columns(names, required) -> None:
    missing = [c for c in required if c not in names]
    if missing:
        raise ValueError("Missing required Step-2 columns: %s" % ", ".join(missing))


def first_present(names, candidates):
    for c in candidates:
        if c in names:
            return c
    return None


def attach_exact_overlap(
    lf: pl.LazyFrame,
    overlap_path: Optional[Path],
    clone_col: str,
    exact_bc_col: Optional[str],
) -> tuple:
    """Attach an exact posterior-overlap scalar when available.

    External table must contain subject, time, clone_col and one exact-BC
    column. The result is normalized to cqc_replicate_bhattacharyya_exact.
    """
    names = lf.collect_schema().names()
    source_col = None
    source_description = None

    if exact_bc_col and exact_bc_col in names:
        source_col = exact_bc_col
        source_description = "input_column:%s" % exact_bc_col
    elif not exact_bc_col:
        source_col = first_present(names, EXACT_BC_CANDIDATES)
        if source_col:
            source_description = "input_column:%s" % source_col

    if source_col:
        if source_col != "cqc_replicate_bhattacharyya_exact":
            lf = lf.with_columns(
                pl.col(source_col).cast(pl.Float64, strict=False)
                .alias("cqc_replicate_bhattacharyya_exact")
            )
        return lf, source_description

    if overlap_path is None:
        return lf, None

    olf = scan_table(overlap_path)
    onames = olf.collect_schema().names()
    require_columns(onames, ["subject", "time", clone_col])
    source_col = exact_bc_col if exact_bc_col else first_present(onames, EXACT_BC_CANDIDATES)
    if source_col is None:
        raise ValueError(
            "Exact-overlap table contains no recognized Bhattacharyya column. "
            "Use --exact-bc-col to identify it."
        )
    olf = olf.select([
        pl.col("subject"), pl.col("time"), pl.col(clone_col),
        pl.col(source_col).cast(pl.Float64, strict=False)
        .alias("cqc_replicate_bhattacharyya_exact"),
    ])
    lf = lf.join(olf, on=["subject", "time", clone_col], how="left")
    return lf, "external_table:%s:%s" % (overlap_path, source_col)



def attach_inverse_simpson_support(
    lf: pl.LazyFrame,
    support_path: Optional[Path],
    clone_col: str,
    support_col: Optional[str],
) -> tuple:
    """Attach exact inverse-Simpson posterior support when available.

    The metric is 1 / sum(p_i^2) on the discrete posterior grid. It cannot be
    reconstructed from entropy or marginal summaries, so it is accepted only
    as an existing Step-2 column or from an external keyed table.
    """
    names = lf.collect_schema().names()
    source_col = None
    source_description = None
    if support_col and support_col in names:
        source_col = support_col
        source_description = "input_column:%s" % support_col
    elif not support_col:
        source_col = first_present(names, INVERSE_SIMPSON_CANDIDATES)
        if source_col:
            source_description = "input_column:%s" % source_col
    if source_col:
        if source_col != "cqc_effective_posterior_support_simpson":
            lf = lf.with_columns(
                pl.col(source_col).cast(pl.Float64, strict=False)
                .alias("cqc_effective_posterior_support_simpson")
            )
        return lf, source_description
    if support_path is None:
        return lf, None
    slf = scan_table(support_path)
    snames = slf.collect_schema().names()
    require_columns(snames, ["subject", "time", clone_col])
    source_col = support_col if support_col else first_present(snames, INVERSE_SIMPSON_CANDIDATES)
    if source_col is None:
        raise ValueError(
            "Posterior-support table contains no recognized inverse-Simpson column. "
            "Use --inverse-simpson-col to identify it."
        )
    slf = slf.select([
        pl.col("subject"), pl.col("time"), pl.col(clone_col),
        pl.col(source_col).cast(pl.Float64, strict=False)
        .alias("cqc_effective_posterior_support_simpson"),
    ])
    lf = lf.join(slf, on=["subject", "time", clone_col], how="left")
    return lf, "external_table:%s:%s" % (support_path, source_col)


def attach_positive_state_context(lf: pl.LazyFrame) -> tuple:
    """Ensure the revised Step-2 positive-state fields are available.

    Canonical v8 Step-2 outputs are used directly. For legacy inputs, fields are
    reconstructed only when the required observed count/frequency columns are
    available. This compatibility path does not alter the latent posterior.
    """
    names = set(lf.collect_schema().names())
    reconstructed = []

    if "n_positive_replicates" not in names:
        if {"count_rep1", "count_rep2"}.issubset(names):
            lf = lf.with_columns(
                (
                    (pl.col("count_rep1").cast(pl.Float64, strict=False) > 0).cast(pl.Int64)
                    + (pl.col("count_rep2").cast(pl.Float64, strict=False) > 0).cast(pl.Int64)
                ).alias("n_positive_replicates")
            )
            reconstructed.append("n_positive_replicates")
        else:
            raise ValueError(
                "Step 3 requires n_positive_replicates or count_rep1/count_rep2 "
                "to reconstruct the revised Step-2 detection-support stratum."
            )

    names = set(lf.collect_schema().names())
    if "positive_state_class" not in names:
        lf = lf.with_columns(
            pl.when(pl.col("n_positive_replicates") == 2)
            .then(pl.lit("TWO_POSITIVE"))
            .when(pl.col("n_positive_replicates") == 1)
            .then(pl.lit("ONE_POSITIVE"))
            .otherwise(pl.lit("UNSUPPORTED"))
            .alias("positive_state_class")
        )
        reconstructed.append("positive_state_class")

    names = set(lf.collect_schema().names())
    if "positive_replicate_source" not in names:
        if {"count_rep1", "count_rep2"}.issubset(names):
            c1 = pl.col("count_rep1").cast(pl.Float64, strict=False) > 0
            c2 = pl.col("count_rep2").cast(pl.Float64, strict=False) > 0
            lf = lf.with_columns(
                pl.when(c1 & c2).then(pl.lit("BOTH"))
                .when(c1 & ~c2).then(pl.lit("REP1_ONLY"))
                .when(~c1 & c2).then(pl.lit("REP2_ONLY"))
                .otherwise(pl.lit("NONE"))
                .alias("positive_replicate_source")
            )
        else:
            lf = lf.with_columns(
                pl.when(pl.col("n_positive_replicates") == 2)
                .then(pl.lit("BOTH"))
                .when(pl.col("n_positive_replicates") == 1)
                .then(pl.lit("UNKNOWN_ONE_POSITIVE"))
                .otherwise(pl.lit("NONE"))
                .alias("positive_replicate_source")
            )
        reconstructed.append("positive_replicate_source")

    names = set(lf.collect_schema().names())
    if "f_positive_current" not in names:
        if "freq_geo" in names:
            lf = lf.with_columns(
                pl.col("freq_geo").cast(pl.Float64, strict=False)
                .alias("f_positive_current")
            )
            reconstructed.append("f_positive_current")
        else:
            raise ValueError(
                "Step 3 requires f_positive_current or legacy freq_geo."
            )

    names = set(lf.collect_schema().names())
    if "x_positive_current" not in names:
        if "x_obs_geo" in names:
            lf = lf.with_columns(
                pl.col("x_obs_geo").cast(pl.Float64, strict=False)
                .alias("x_positive_current")
            )
            reconstructed.append("x_positive_current")
        else:
            lf = lf.with_columns(
                pl.col("f_positive_current").cast(pl.Float64, strict=False)
                .clip(lower_bound=1e-300).log().alias("x_positive_current")
            )
            reconstructed.append("x_positive_current")

    source = (
        "canonical_step2_replicate_resolved_fields"
        if not reconstructed
        else "legacy_reconstruction:" + ",".join(reconstructed)
    )
    return lf, source


def build_diagnostics(
    lf: pl.LazyFrame,
    clone_col: str,
    grid_size: int,
    exact_overlap_path: Optional[Path],
    exact_bc_col: Optional[str],
    require_exact_overlap: bool,
    posterior_support_path: Optional[Path],
    inverse_simpson_col: Optional[str],
    require_inverse_simpson: bool,
) -> tuple:
    lf, positive_context_source = attach_positive_state_context(lf)
    names = lf.collect_schema().names()
    required = [
        "subject", "time", clone_col,
        "x_latent_median", "x_latent_sd", "x_latent_q025", "x_latent_q975",
        "posterior_entropy", "p_detect_state", "p_dropout_state",
        "p_detect_rep1", "p_detect_rep2",
        "x_rep1_latent_median", "x_rep2_latent_median",
        "rep1_x_latent_sd", "rep2_x_latent_sd",
        "f_positive_current", "x_positive_current",
        "n_positive_replicates", "positive_state_class",
    ]
    require_columns(names, required)

    lf, exact_source = attach_exact_overlap(
        lf, exact_overlap_path, clone_col, exact_bc_col
    )
    lf, support_source = attach_inverse_simpson_support(
        lf, posterior_support_path, clone_col, inverse_simpson_col
    )
    names = lf.collect_schema().names()
    if require_inverse_simpson and "cqc_effective_posterior_support_simpson" not in names:
        raise ValueError(
            "Exact inverse-Simpson posterior support was required but is unavailable. "
            "Supply --posterior-support-table or a recognized input column."
        )
    if require_exact_overlap and "cqc_replicate_bhattacharyya_exact" not in names:
        raise ValueError(
            "Exact posterior overlap was required but is unavailable. Supply "
            "--exact-overlap-table or an exact-BC column from Step 2."
        )

    context = [
        "pair_id", "count_rep1", "count_rep2", "depth_rep1", "depth_rep2",
        "freq_rep1", "freq_rep2", "x_obs_rep1", "x_obs_rep2",
        "f_observed_rep1", "f_observed_rep2", "x_observed_rep1", "x_observed_rep2",
        "freq_geo", "x_obs_geo",
        "f_latent_mean", "f_latent_median",
        "f_latent_q025", "f_latent_q975", "x_latent_mean", "x_latent_median",
        "f_positive_current", "x_positive_current",
        "n_positive_replicates", "positive_state_class",
        "positive_replicate_source", "positive_abundance_method",
        "logP", "p_value", "observable", "p_detect_state", "p_dropout_state",
        "p_detect_rep1", "p_detect_rep2", "p_dropout_rep1", "p_dropout_rep2",
        "cqc_replicate_bhattacharyya_exact",
        "cqc_effective_posterior_support_simpson",
    ]
    selected = ["subject", "time", clone_col] + [c for c in context if c in names] + required[3:]
    selected = list(dict.fromkeys(selected))

    non_numeric = {
        "subject", "time", clone_col, "pair_id", "observable",
        "positive_state_class", "positive_replicate_source",
        "positive_abundance_method",
    }
    numeric = [c for c in selected if c not in non_numeric]
    q = lf.select([pl.col(c) for c in selected]).with_columns([
        pl.col(c).cast(pl.Float64, strict=False) for c in numeric
    ])

    log_grid = math.log(float(grid_size))
    s1 = pl.col("rep1_x_latent_sd").clip(lower_bound=0.0)
    s2 = pl.col("rep2_x_latent_sd").clip(lower_bound=0.0)
    s1sq = s1.pow(2)
    s2sq = s2.pow(2)
    variance_sum = s1sq + s2sq + pl.lit(EPS)
    delta = (pl.col("x_rep1_latent_median") - pl.col("x_rep2_latent_median")).abs()
    width_x = pl.col("x_latent_q975") - pl.col("x_latent_q025")

    expressions = [
        width_x.alias("cqc_posterior_width95_x"),
        width_x.exp().alias("cqc_posterior_fold_range95"),
        pl.col("x_latent_sd").alias("cqc_posterior_sd_x"),
        pl.col("posterior_entropy").alias("cqc_posterior_entropy"),
        pl.col("posterior_entropy").exp().alias("cqc_effective_posterior_support"),
        (pl.col("posterior_entropy") / pl.lit(log_grid))
            .clip(0.0, 1.0).alias("cqc_posterior_entropy_normalized"),
        pl.col("p_detect_state").clip(0.0, 1.0)
            .alias("cqc_state_detectability"),
        pl.col("p_dropout_state").clip(0.0, 1.0)
            .alias("cqc_state_dropout"),
        # Factorized union of the replicate-specific posterior-predictive
        # detection means. This is NOT algebraically identical to the exact
        # paired-state quantity, because the latter integrates q1(f)q2(f)
        # over the shared posterior whereas this factorizes the expectations.
        (
            1.0
            - (1.0 - pl.col("p_detect_rep1").clip(0.0, 1.0))
              * (1.0 - pl.col("p_detect_rep2").clip(0.0, 1.0))
        ).clip(0.0, 1.0).alias("cqc_factorized_union_detectability"),
        (
            pl.col("p_detect_state").clip(0.0, 1.0)
            - (
                1.0
                - (1.0 - pl.col("p_detect_rep1").clip(0.0, 1.0))
                  * (1.0 - pl.col("p_detect_rep2").clip(0.0, 1.0))
              )
        ).alias("cqc_delta_state_vs_factorized_union"),
        (
            pl.col("p_detect_state").clip(0.0, 1.0)
            - (
                1.0
                - (1.0 - pl.col("p_detect_rep1").clip(0.0, 1.0))
                  * (1.0 - pl.col("p_detect_rep2").clip(0.0, 1.0))
              )
        ).abs().alias("cqc_abs_delta_state_vs_factorized_union"),
        # Historical aliases retained for downstream compatibility.
        (
            1.0
            - (1.0 - pl.col("p_detect_rep1").clip(0.0, 1.0))
              * (1.0 - pl.col("p_detect_rep2").clip(0.0, 1.0))
        ).clip(0.0, 1.0).alias("cqc_union_detectability"),
        (
            pl.col("p_detect_state").clip(0.0, 1.0)
            - (
                1.0
                - (1.0 - pl.col("p_detect_rep1").clip(0.0, 1.0))
                  * (1.0 - pl.col("p_detect_rep2").clip(0.0, 1.0))
              )
        ).alias("cqc_delta_detectability"),
        (
            pl.col("p_detect_state").clip(0.0, 1.0)
            - (
                1.0
                - (1.0 - pl.col("p_detect_rep1").clip(0.0, 1.0))
                  * (1.0 - pl.col("p_detect_rep2").clip(0.0, 1.0))
              )
        ).abs().alias("cqc_abs_delta_detectability"),
        (
            pl.col("p_detect_rep1").clip(0.0, 1.0)
            * pl.col("p_detect_rep2").clip(0.0, 1.0)
        ).sqrt().alias("cqc_replicate_joint_detection_evidence"),
        # Backward-compatible alias. This remains a replicate-level QC metric,
        # not the primary detectability of the latent biological state.
        (
            pl.col("p_detect_rep1").clip(0.0, 1.0)
            * pl.col("p_detect_rep2").clip(0.0, 1.0)
        ).sqrt().alias("cqc_joint_detection_evidence"),
        (pl.col("p_detect_rep1") - pl.col("p_detect_rep2")).abs()
            .alias("cqc_detection_imbalance"),
        delta.alias("cqc_replicate_abs_delta_x"),
        (delta / variance_sum.sqrt()).alias("cqc_replicate_standardized_delta"),
        (pl.col("x_latent_median") - pl.col("x_positive_current"))
            .alias("cqc_latent_minus_positive_x"),
        (pl.col("x_latent_median") - pl.col("x_positive_current")).abs()
            .alias("cqc_abs_latent_minus_positive_x"),
    ]

    if {"depth_rep1", "depth_rep2", "positive_replicate_source"}.issubset(names):
        zero_depth = (
            pl.when(pl.col("positive_replicate_source") == "REP1_ONLY")
            .then(pl.col("depth_rep2"))
            .when(pl.col("positive_replicate_source") == "REP2_ONLY")
            .then(pl.col("depth_rep1"))
            .otherwise(pl.lit(None, dtype=pl.Float64))
        )
        positive_depth = (
            pl.when(pl.col("positive_replicate_source") == "REP1_ONLY")
            .then(pl.col("depth_rep1"))
            .when(pl.col("positive_replicate_source") == "REP2_ONLY")
            .then(pl.col("depth_rep2"))
            .otherwise(pl.lit(None, dtype=pl.Float64))
        )
        expressions.extend([
            zero_depth.alias("cqc_zero_replicate_depth"),
            positive_depth.alias("cqc_positive_replicate_depth"),
            pl.when(zero_depth > 0).then(zero_depth.log()).otherwise(None)
                .alias("cqc_zero_replicate_log_depth"),
            pl.when(positive_depth > 0).then(positive_depth.log()).otherwise(None)
                .alias("cqc_positive_replicate_log_depth"),
        ])

    # Relative uncertainty in linear frequency space, where available.
    if all(c in names for c in ["f_latent_q025", "f_latent_q975", "f_latent_median"]):
        expressions.append(
            ((pl.col("f_latent_q975") - pl.col("f_latent_q025")) /
             pl.col("f_latent_median").abs().clip(lower_bound=EPS))
            .alias("cqc_posterior_relative_width95_f")
        )

    q = q.with_columns(expressions)

    # Gaussian fallback retained only when exact overlap is not supplied.
    scale_term = ((2.0 * s1 * s2) / variance_sum).clip(0.0, 1.0).sqrt()
    location_term = (-(delta.pow(2)) / (4.0 * variance_sum)).exp()
    q = q.with_columns(
        (scale_term * location_term).clip(0.0, 1.0)
        .alias("cqc_replicate_bhattacharyya_gaussian")
    )

    has_exact = "cqc_replicate_bhattacharyya_exact" in q.collect_schema().names()
    if has_exact:
        q = q.with_columns([
            pl.col("cqc_replicate_bhattacharyya_exact").clip(0.0, 1.0),
            pl.coalesce([
                pl.col("cqc_replicate_bhattacharyya_exact"),
                pl.col("cqc_replicate_bhattacharyya_gaussian"),
            ]).alias("cqc_replicate_bhattacharyya"),
            pl.when(pl.col("cqc_replicate_bhattacharyya_exact").is_not_null())
              .then(pl.lit("EXACT_DISCRETE_POSTERIOR"))
              .otherwise(pl.lit("GAUSSIAN_FALLBACK"))
              .alias("cqc_replicate_agreement_source"),
        ])
    else:
        q = q.with_columns([
            pl.col("cqc_replicate_bhattacharyya_gaussian")
              .alias("cqc_replicate_bhattacharyya"),
            pl.lit("GAUSSIAN_FALLBACK").alias("cqc_replicate_agreement_source"),
        ])

    q = q.with_columns(
        (1.0 - pl.col("cqc_replicate_bhattacharyya"))
        .clip(0.0, 1.0).sqrt().alias("cqc_replicate_hellinger")
    )

    diagnostic_cols = [
        "cqc_posterior_width95_x",
        "cqc_posterior_fold_range95",
        "cqc_posterior_sd_x",
        "cqc_posterior_entropy",
        "cqc_effective_posterior_support",
        "cqc_state_detectability",
        "cqc_state_dropout",
        "cqc_factorized_union_detectability",
        "cqc_delta_state_vs_factorized_union",
        "cqc_abs_delta_state_vs_factorized_union",
        "cqc_replicate_joint_detection_evidence",
        "cqc_detection_imbalance",
        "cqc_replicate_abs_delta_x",
        "cqc_replicate_standardized_delta",
        "cqc_replicate_bhattacharyya",
        "cqc_replicate_hellinger",
    ]
    qnames = q.collect_schema().names()
    if "cqc_posterior_relative_width95_f" in qnames:
        diagnostic_cols.append("cqc_posterior_relative_width95_f")
    if "cqc_effective_posterior_support_simpson" in qnames:
        diagnostic_cols.append("cqc_effective_posterior_support_simpson")

    valid_expr = pl.all_horizontal([pl.col(c).is_finite() for c in diagnostic_cols])
    q = q.with_columns([
        valid_expr.alias("cqc_diagnostics_valid"),
        pl.when(valid_expr).then(pl.lit("VALID")).otherwise(pl.lit("INVALID_NUMERICAL"))
            .alias("cqc_diagnostic_status"),
        pl.lit(True).alias("cqc_included_downstream"),
    ])
    return q, exact_source, support_source, positive_context_source


