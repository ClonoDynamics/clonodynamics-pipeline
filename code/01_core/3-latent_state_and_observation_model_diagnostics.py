def write_state_detectability_factorized_union_diagnostic(
    lf: pl.LazyFrame, output_dir: Path
) -> None:
    """Compare exact paired-state detectability with the factorized-union approximation.

    The quantities are not expected to be identical: the exact state-level
    dropout integrates q1(f)q2(f) over the shared posterior, whereas the
    factorized union combines the separately integrated replicate dropout
    probabilities. The difference therefore quantifies posterior coupling, not
    calibration error.
    """
    finite = lf.filter(
        pl.all_horizontal([
            pl.col("cqc_state_detectability").is_finite(),
            pl.col("cqc_factorized_union_detectability").is_finite(),
            pl.col("cqc_delta_state_vs_factorized_union").is_finite(),
            pl.col("cqc_abs_delta_state_vs_factorized_union").is_finite(),
            pl.col("cqc_state_dropout").is_finite(),
        ])
    )
    summary = finite.select([
        pl.len().alias("n_clonotype_timepoints"),
        pl.col("cqc_delta_state_vs_factorized_union").mean().alias(
            "mean_signed_delta_state_minus_factorized_union"
        ),
        pl.col("cqc_abs_delta_state_vs_factorized_union").mean().alias(
            "mean_absolute_delta_state_vs_factorized_union"
        ),
        pl.col("cqc_abs_delta_state_vs_factorized_union").median().alias(
            "median_absolute_delta_state_vs_factorized_union"
        ),
        pl.col("cqc_abs_delta_state_vs_factorized_union").quantile(0.99).alias(
            "q99_absolute_delta_state_vs_factorized_union"
        ),
        pl.col("cqc_abs_delta_state_vs_factorized_union").max().alias(
            "max_absolute_delta_state_vs_factorized_union"
        ),
        (pl.col("cqc_abs_delta_state_vs_factorized_union") > 1e-12).mean().alias(
            "fraction_abs_delta_gt_1e_12"
        ),
        (pl.col("cqc_abs_delta_state_vs_factorized_union") > 1e-6).mean().alias(
            "fraction_abs_delta_gt_1e_6"
        ),
        (pl.col("cqc_abs_delta_state_vs_factorized_union") > 1e-3).mean().alias(
            "fraction_abs_delta_gt_1e_3"
        ),
        (pl.col("cqc_state_detectability") + pl.col("cqc_state_dropout") - 1.0)
            .abs().max().alias("max_state_dropout_complementarity_error"),
        pl.corr(
            "cqc_state_detectability",
            "cqc_factorized_union_detectability",
            method="pearson",
        ).alias("pearson_state_vs_factorized_union"),
        pl.corr(
            "cqc_state_detectability",
            "cqc_factorized_union_detectability",
            method="spearman",
        ).alias("spearman_state_vs_factorized_union"),
    ]).collect(engine="streaming")

    summary.write_csv(
        output_dir / "state_detectability_factorized_union_diagnostic.csv"
    )

    # Compatibility aliases. These files contain the same posterior-coupling
    # diagnostic and must not be described as independent validation.
    summary.write_csv(
        output_dir / "state_detectability_internal_consistency_summary.csv"
    )
    summary.write_csv(
        output_dir / "state_detectability_validation_summary.csv"
    )


