def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=(
            "Assemble generic finite-time transitions from Step-4 "
            "multirepresentation trajectories without estimand-specific filtering."
        ),
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )

    parser.add_argument("--trajectories", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--file-sep", default="\t")
    parser.add_argument("--extra-group-cols", default="")

    parser.add_argument("--min-dt", type=int, default=1)
    parser.add_argument("--max-dt", type=int, default=5)

    parser.add_argument("--parquet-compression", default="zstd")
    parser.add_argument("--parquet-row-group-size", type=int, default=100000)
    parser.add_argument("--write-csv-compat", action="store_true")

    parser.add_argument("--posterior-dir", type=Path, default=None)
    parser.add_argument(
        "--posterior-template",
        default="latent_per_clone_logP_{subject}_{time}.posterior.npz",
        help="Relative template inside --posterior-dir; may use extra-group placeholders.",
    )
    parser.add_argument(
        "--allow-shared-posterior-files",
        action="store_true",
        help=(
            "Allow grouped workflows to reuse posterior files whose template does "
            "not contain every extra grouping placeholder. Use only deliberately."
        ),
    )
    parser.add_argument("--n-posterior-samples", type=int, default=1000)
    parser.add_argument("--posterior-seed", type=int, default=123)
    parser.add_argument("--posterior-chunk-size", type=int, default=5000)

    parser.add_argument("--work-dir", type=Path, default=None)
    parser.add_argument("--resume", action=argparse.BooleanOptionalAction, default=True)
    parser.add_argument("--restart", action="store_true")
    parser.add_argument("--keep-work-dir", action="store_true")
    parser.add_argument("--report-md", type=Path, default=None)
    return parser


def validate_arguments(args: argparse.Namespace, extra_group_cols: Sequence[str]) -> None:
    if not args.trajectories.exists():
        raise FileNotFoundError(f"Trajectory file not found: {args.trajectories}")
    if args.out.suffix.lower() not in PARQUET_SUFFIXES:
        raise ValueError("--out must be a .parquet or .pq file")
    if int(args.min_dt) < 1:
        raise ValueError("--min-dt must be at least 1")
    if int(args.max_dt) < int(args.min_dt):
        raise ValueError("--max-dt must be >= --min-dt")
    if int(args.parquet_row_group_size) <= 0:
        raise ValueError("--parquet-row-group-size must be positive")
    if int(args.posterior_chunk_size) <= 0:
        raise ValueError("--posterior-chunk-size must be positive")

    if args.posterior_dir is not None:
        if not args.posterior_dir.exists():
            raise FileNotFoundError(
                f"Posterior directory not found: {args.posterior_dir}"
            )
        if int(args.n_posterior_samples) <= 0:
            raise ValueError("--n-posterior-samples must be positive")
        if extra_group_cols and not args.allow_shared_posterior_files:
            missing_placeholders = [
                column
                for column in extra_group_cols
                if "{" + column + "}" not in args.posterior_template
            ]
            if missing_placeholders:
                raise ValueError(
                    "Grouped posterior propagation requires every extra group column "
                    "in --posterior-template to prevent cross-configuration reuse. "
                    "Missing placeholders: " + ", ".join(missing_placeholders)
                )


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = build_parser().parse_args(argv)
    extra_group_cols = split_csv(args.extra_group_cols)
    validate_arguments(args, extra_group_cols)

    print(f"[STEP5] {SCRIPT_VERSION}")
    input_scan = scan_table(args.trajectories, args.file_sep)
    schema_names = input_scan.collect_schema().names()

    require_columns(
        schema_names,
        list(extra_group_cols) + CORE_REQUIRED_COLUMNS,
    )
    validate_state_contract(input_scan, extra_group_cols)
    validate_unique_state_keys(input_scan, extra_group_cols)
    reference_alpha = validate_reference_contract(input_scan)

    endpoint_columns = [
        column
        for column in (CORE_REQUIRED_COLUMNS + OPTIONAL_ENDPOINT_COLUMNS)
        if column in set(schema_names)
        and column not in {"subject", "aaSeqCDR3", "time"}
    ]
    # Remove exact duplicates while preserving order.
    endpoint_columns = list(dict.fromkeys(endpoint_columns))

    unit_cols = list(extra_group_cols) + ["subject"]
    units_frame = collect_streaming(
        input_scan.select(unit_cols).unique().sort(unit_cols)
    )
    units = units_frame.to_dicts()

    print(f"[STEP5] Processing units: {len(units):,}")
    print(f"[STEP5] reference_alpha={reference_alpha:g}")
    print(f"[STEP5] lags={args.min_dt}..{args.max_dt}")
    print(
        "[STEP5] extra groups:", extra_group_cols if extra_group_cols else "<none>"
    )

    work_directory = args.work_dir or (
        args.out.parent / f".{args.out.stem}_step5_work"
    )
    manifest = build_manifest(args, extra_group_cols, reference_alpha)
    prepare_work_directory(work_directory, manifest, bool(args.restart))

    raw_directory = work_directory / "raw"
    parts_directory = work_directory / "parts"
    raw_directory.mkdir(parents=True, exist_ok=True)
    parts_directory.mkdir(parents=True, exist_ok=True)

    expected_parts: List[Path] = []
    empty_pairs = 0
    prepared_state_rows = 0

    for unit_row in units:
        subject = int(unit_row["subject"])
        unit_values = {column: unit_row[column] for column in extra_group_cols}
        unit_token = unit_identity(unit_values, subject)
        print(f"[STEP5] Preparing unit {unit_token}")

        unit_frame = prepare_unit(
            trajectories=args.trajectories,
            separator=args.file_sep,
            subject=subject,
            unit_values=unit_values,
            extra_group_cols=extra_group_cols,
            endpoint_columns=endpoint_columns,
        )
        prepared_state_rows += int(unit_frame.height)
        if unit_frame.is_empty():
            continue

        times = sorted(
            int(value) for value in unit_frame.get_column("time").unique().to_list()
        )

        for index, t0 in enumerate(times[:-1]):
            for t1 in times[index + 1 :]:
                dt_value = int(t1 - t0)
                if dt_value < int(args.min_dt) or dt_value > int(args.max_dt):
                    continue

                stem = f"{unit_token}__t{t0:03d}_t{t1:03d}_all"
                raw_path = raw_directory / f"{stem}.raw.parquet"
                part_path = parts_directory / f"{stem}.parquet"

                if pair_is_complete(part_path, bool(args.resume)):
                    if part_path.exists():
                        expected_parts.append(part_path)
                        print(f"[STEP5] Reusing completed part: {part_path.name}")
                    else:
                        empty_pairs += 1
                    continue

                transitions = build_temporal_pair(
                    unit_frame=unit_frame,
                    subject=subject,
                    unit_values=unit_values,
                    t0=t0,
                    t1=t1,
                    reference_alpha=reference_alpha,
                )

                marker = empty_marker_path(part_path)
                remove_if_exists(marker)
                remove_if_exists(raw_path)

                raw_rows = write_raw_pair(
                    transitions=transitions,
                    raw_path=raw_path,
                    compression=args.parquet_compression,
                    row_group_size=int(args.parquet_row_group_size),
                )
                del transitions
                gc.collect()

                if raw_rows == 0:
                    write_empty_marker(marker, subject, unit_values, t0, t1)
                    empty_pairs += 1
                    print(
                        f"[STEP5] Empty pair {unit_token} {t0}->{t1}"
                    )
                else:
                    rows = finalize_pair_part(
                        raw_path=raw_path,
                        part_path=part_path,
                        args=args,
                        subject=subject,
                        unit_values=unit_values,
                        t0=t0,
                        t1=t1,
                    )
                    expected_parts.append(part_path)
                    print(
                        f"[STEP5] Completed {unit_token} {t0}->{t1}: {rows:,} rows"
                    )
                gc.collect()

        del unit_frame
        gc.collect()

    completed_parts = sorted({path for path in expected_parts if path.exists()})
    print(f"[STEP5] Combining {len(completed_parts):,} completed parts")
    combine_parts(
        parts=completed_parts,
        output=args.out,
        compression=args.parquet_compression,
        batch_size=int(args.posterior_chunk_size),
        row_group_size=int(args.parquet_row_group_size),
    )

    if args.write_csv_compat:
        csv_path = args.out.with_suffix(".csv")
        print(f"[STEP5] Writing large CSV compatibility copy: {csv_path}")
        csv_lazy = pl.scan_parquet(args.out)
        try:
            csv_lazy.sink_csv(csv_path)
        except (AttributeError, TypeError):
            collect_streaming(csv_lazy).write_csv(csv_path)

    output_summary = summarize_output(args.out, extra_group_cols)
    output_schema = pl.scan_parquet(args.out).collect_schema().names()

    report_payload: Dict[str, Any] = {
        "timestamp": datetime.now().isoformat(timespec="seconds"),
        "script": Path(__file__).name,
        "script_version": SCRIPT_VERSION,
        "trajectories": str(args.trajectories),
        "output": str(args.out),
        "extra_group_cols": extra_group_cols,
        "processing_units": len(units),
        "prepared_state_rows": int(prepared_state_rows),
        "min_dt": int(args.min_dt),
        "max_dt": int(args.max_dt),
        "reference_alpha": float(reference_alpha),
        "transition_mode": "all_temporal_pairs",
        "observation_class_filtering": False,
        "structural_weights": False,
        "posterior_propagation": args.posterior_dir is not None,
        "completed_parts": len(completed_parts),
        "empty_pairs": int(empty_pairs),
        "output_columns": output_schema,
        **output_summary,
    }

    report_path = args.report_md or (
        args.out.parent / "transition_assembly_report.md"
    )
    write_report(report_path, report_payload)

    output_manifest = {
        "script": Path(__file__).name,
        "script_version": SCRIPT_VERSION,
        "canonical_step4_source": "4-multirepresentation_trajectory_assembly.py",
        "canonical_output": str(args.out),
        "extra_group_cols": extra_group_cols,
        "reference_alpha": float(reference_alpha),
        "transition_universe": (
            "inner join of canonical Step-4 states by aaSeqCDR3 for all temporal "
            "pairs within requested lag range"
        ),
        "state_layers": {
            "model_based_consensus": [
                "x0_latent",
                "x1_latent",
                "dx_latent",
                "xmid_latent",
                "xstar_latent",
            ],
            "replicate_resolved_observed": [
                "x_observed_rep1_t0",
                "x_observed_rep1_t1",
                "dx_observed_rep1",
                "x_observed_rep2_t0",
                "x_observed_rep2_t1",
                "dx_observed_rep2",
            ],
            "observation_annotations": [
                "p_value_t0",
                "p_value_t1",
                "observable_reference_t0",
                "observable_reference_t1",
                "obs_class_reference",
                "p_detect_state_t0",
                "p_detect_state_t1",
            ],
        },
        "eligibility_flags": {
            "forward_ab_eligible": (
                "rep1 positive at t0 AND rep2 positive at t0 and t1"
            ),
            "forward_ba_eligible": (
                "rep2 positive at t0 AND rep1 positive at t0 and t1"
            ),
            "common4": "both replicates positive at both endpoints",
        },
        "reference_observation_classes_are_biological_states": False,
        "observation_class_filtering": False,
        "structural_weights": False,
        "dynamic_estimands_defined_here": False,
        "primary_downstream_estimands": {
            "forward": "observed replicate-decoupled AB/BA",
            "fluctuations": (
                "cross-replicate covariance of dx_observed_rep1 and "
                "dx_observed_rep2 on common4"
            ),
            "fluctuation_conditioning": "xmid_latent",
        },
        "optional_model_based_posterior_propagation": args.posterior_dir is not None,
    }
    manifest_path = args.out.parent / "transition_assembly_manifest.json"
    manifest_path.write_text(
        json.dumps(output_manifest, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )

    print(f"[STEP5] Wrote transitions: {args.out}")
    print(f"[STEP5] Wrote report: {report_path}")
    print(f"[STEP5] Wrote manifest: {manifest_path}")

    if not args.keep_work_dir:
        shutil.rmtree(work_directory, ignore_errors=True)

    print("[STEP5] Completed. No estimand-specific filtering or weighting was applied.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
