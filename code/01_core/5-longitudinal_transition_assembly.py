def ensure_parent(path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)


def remove_if_exists(path: Path) -> None:
    try:
        path.unlink()
    except FileNotFoundError:
        pass


def collect_streaming(lf: pl.LazyFrame) -> pl.DataFrame:
    try:
        return lf.collect(engine="streaming")
    except TypeError:
        return lf.collect(streaming=True)


def sink_parquet_streaming(
    lf: pl.LazyFrame,
    path: Path,
    compression: str,
    row_group_size: int,
) -> None:
    ensure_parent(path)
    kwargs: Dict[str, Any] = {
        "compression": compression,
        "statistics": True,
        "maintain_order": True,
    }
    if row_group_size > 0:
        kwargs["row_group_size"] = int(row_group_size)

    try:
        lf.sink_parquet(path, engine="streaming", mkdir=True, **kwargs)
    except TypeError:
        try:
            lf.sink_parquet(path, **kwargs)
        except TypeError:
            kwargs.pop("row_group_size", None)
            lf.sink_parquet(path, **kwargs)


def split_csv(text: Optional[str]) -> list[str]:
    if text is None:
        return []
    return [item.strip() for item in str(text).split(",") if item.strip()]


def scan_table(path: Path, separator: str) -> pl.LazyFrame:
    suffix = path.suffix.lower()
    if suffix in PARQUET_SUFFIXES:
        return pl.scan_parquet(path)
    if suffix == ".csv":
        return pl.scan_csv(path, separator=",", infer_schema_length=10000)
    if suffix == ".tsv":
        return pl.scan_csv(path, separator="\t", infer_schema_length=10000)
    if suffix == ".txt":
        return pl.scan_csv(path, separator=separator, infer_schema_length=10000)
    raise ValueError(
        f"Unsupported trajectory format: {path.suffix}. Use Parquet, CSV, TSV or TXT."
    )


def input_signature(path: Path) -> Dict[str, Any]:
    stat = path.stat()
    return {
        "path": str(path.resolve()),
        "size_bytes": int(stat.st_size),
        "mtime_ns": int(stat.st_mtime_ns),
    }


def sanitize_token(value: Any) -> str:
    text = str(value)
    text = re.sub(r"[^A-Za-z0-9_.-]+", "-", text)
    return text[:60] or "empty"


def unit_identity(
    unit_values: Mapping[str, Any],
    subject: int,
) -> str:
    parts = [f"{key}={unit_values[key]}" for key in sorted(unit_values)]
    parts.append(f"subject={int(subject)}")
    payload = "|".join(parts)
    digest = hashlib.blake2b(payload.encode("utf-8"), digest_size=6).hexdigest()
    readable = "__".join(
        f"{sanitize_token(key)}={sanitize_token(value)}"
        for key, value in sorted(unit_values.items())
    )
    prefix = (readable + "__") if readable else ""
    return f"{prefix}s{int(subject):04d}__{digest}"


def unit_filter_expr(
    subject: int,
    unit_values: Mapping[str, Any],
) -> pl.Expr:
    expression = pl.col("subject") == int(subject)
    for column, value in unit_values.items():
        expression = expression & (pl.col(column) == pl.lit(value))
    return expression


def require_columns(
    schema_names: Sequence[str],
    required: Sequence[str],
) -> None:
    names = set(schema_names)
    missing = [column for column in required if column not in names]
    if missing:
        raise ValueError(
            "Step-5 input is missing required Step-4 production columns: "
            + ", ".join(missing)
        )


def validate_reference_contract(
    input_scan: pl.LazyFrame,
) -> float:
    """Validate reference-alpha and reference-observability consistency."""
    summary = collect_streaming(
        input_scan.select(
            [
                pl.col("reference_alpha").n_unique().alias("n_alpha"),
                pl.col("reference_alpha").min().alias("alpha_min"),
                pl.col("reference_alpha").max().alias("alpha_max"),
                (
                    pl.col("observable_reference").cast(pl.Boolean, strict=False)
                    != (pl.col("p_value") < pl.col("reference_alpha"))
                )
                .fill_null(True)
                .sum()
                .alias("n_observable_mismatch"),
            ]
        )
    ).row(0, named=True)

    n_alpha = int(summary["n_alpha"] or 0)
    if n_alpha != 1:
        raise ValueError(
            "Step-5 production input must contain exactly one reference_alpha; "
            f"found {n_alpha}."
        )

    alpha = float(summary["alpha_min"])
    if not (0.0 < alpha < 1.0):
        raise ValueError(f"Invalid reference_alpha={alpha}; expected 0 < alpha < 1.")

    mismatches = int(summary["n_observable_mismatch"] or 0)
    if mismatches:
        raise ValueError(
            "observable_reference does not match p_value < reference_alpha for "
            f"{mismatches:,} states. Rebuild Step 4 before Step 5."
        )
    return alpha


def validate_state_contract(
    input_scan: pl.LazyFrame,
    extra_group_cols: Sequence[str],
) -> None:
    """Fail on malformed Step-4 observed/positivity fields."""
    checks: List[pl.Expr] = [
        pl.len().alias("n_rows"),
        (
            pl.col("count_rep1").is_null()
            | pl.col("count_rep2").is_null()
            | (pl.col("count_rep1") < 0)
            | (pl.col("count_rep2") < 0)
        ).sum().alias("invalid_counts"),
        (
            pl.col("depth_rep1").is_null()
            | pl.col("depth_rep2").is_null()
            | (pl.col("depth_rep1") <= 0)
            | (pl.col("depth_rep2") <= 0)
        ).sum().alias("invalid_depths"),
        (
            pl.col("x_latent").is_null()
            | ~pl.col("x_latent").is_finite()
            | pl.col("f_latent").is_null()
            | ~pl.col("f_latent").is_finite()
            | (pl.col("f_latent") <= 0)
        ).sum().alias("invalid_latent"),
        (
            pl.col("p_value").is_null()
            | ~pl.col("p_value").is_finite()
            | (pl.col("p_value") < 0)
            | (pl.col("p_value") > 1)
        ).sum().alias("invalid_p_value"),
        (
            pl.col("p_detect_state").is_null()
            | ~pl.col("p_detect_state").is_finite()
            | (pl.col("p_detect_state") < 0)
            | (pl.col("p_detect_state") > 1)
            | pl.col("p_dropout_state").is_null()
            | ~pl.col("p_dropout_state").is_finite()
            | (pl.col("p_dropout_state") < 0)
            | (pl.col("p_dropout_state") > 1)
        ).sum().alias("invalid_detectability"),
        (
            pl.col("read_positive_rep1").cast(pl.Boolean, strict=False)
            != (pl.col("count_rep1") > 0)
        ).fill_null(True).sum().alias("rep1_positivity_mismatch"),
        (
            pl.col("read_positive_rep2").cast(pl.Boolean, strict=False)
            != (pl.col("count_rep2") > 0)
        ).fill_null(True).sum().alias("rep2_positivity_mismatch"),
        (
            ((pl.col("count_rep1") > 0) & pl.col("x_observed_rep1").is_null())
            | ((pl.col("count_rep1") == 0) & pl.col("x_observed_rep1").is_not_null())
        ).sum().alias("rep1_log_observation_mismatch"),
        (
            ((pl.col("count_rep2") > 0) & pl.col("x_observed_rep2").is_null())
            | ((pl.col("count_rep2") == 0) & pl.col("x_observed_rep2").is_not_null())
        ).sum().alias("rep2_log_observation_mismatch"),
    ]

    for column in extra_group_cols:
        checks.append(pl.col(column).is_null().sum().alias(f"null_group__{column}"))

    summary = collect_streaming(input_scan.select(checks)).row(0, named=True)
    problems = {
        key: int(value or 0)
        for key, value in summary.items()
        if key != "n_rows" and int(value or 0) > 0
    }
    if problems:
        raise ValueError(
            "Step-5 input failed the Step-4 state contract: "
            + ", ".join(f"{key}={value}" for key, value in problems.items())
        )


def validate_unique_state_keys(
    input_scan: pl.LazyFrame,
    extra_group_cols: Sequence[str],
) -> None:
    key_cols = list(extra_group_cols) + ["subject", "aaSeqCDR3", "time"]
    duplicates = collect_streaming(
        input_scan
        .group_by(key_cols)
        .agg(pl.len().alias("n_rows"))
        .filter(pl.col("n_rows") > 1)
        .sort("n_rows", descending=True)
        .head(10)
    )
    if not duplicates.is_empty():
        raise ValueError(
            "Duplicate trajectory state keys detected. Step 5 does not aggregate "
            "duplicate states. Examples:\n" + str(duplicates)
        )


def prepare_unit(
    trajectories: Path,
    separator: str,
    subject: int,
    unit_values: Mapping[str, Any],
    extra_group_cols: Sequence[str],
    endpoint_columns: Sequence[str],
) -> pl.DataFrame:
    scan = scan_table(trajectories, separator)
    filtered = scan.filter(unit_filter_expr(subject, unit_values))
    selected = ["aaSeqCDR3", "time"] + list(endpoint_columns)
    frame = collect_streaming(
        filtered
        .select([pl.col(column) for column in selected])
        .sort(["aaSeqCDR3", "time"])
    )
    return frame


def endpoint_frame(
    unit_frame: pl.DataFrame,
    time_value: int,
    suffix: str,
) -> pl.DataFrame:
    endpoint = unit_frame.filter(pl.col("time") == int(time_value)).drop("time")
    rename_map = {
        column: f"{column}_{suffix}"
        for column in endpoint.columns
        if column != "aaSeqCDR3"
    }
    return endpoint.rename(rename_map)


def _literal_group_expressions(
    unit_values: Mapping[str, Any],
) -> List[pl.Expr]:
    return [pl.lit(value).alias(column) for column, value in unit_values.items()]


def transition_projection(
    joined: pl.DataFrame,
    subject: int,
    unit_values: Mapping[str, Any],
    t0: int,
    t1: int,
    reference_alpha: float,
) -> pl.DataFrame:
    """Build one generic transition block without estimand-specific filtering."""
    dt_value = int(t1 - t0)

    rp1_t0 = pl.col("read_positive_rep1_t0").cast(pl.Boolean, strict=False)
    rp1_t1 = pl.col("read_positive_rep1_t1").cast(pl.Boolean, strict=False)
    rp2_t0 = pl.col("read_positive_rep2_t0").cast(pl.Boolean, strict=False)
    rp2_t1 = pl.col("read_positive_rep2_t1").cast(pl.Boolean, strict=False)

    obs0_bool = pl.col("observable_reference_t0").cast(pl.Boolean, strict=False)
    obs1_bool = pl.col("observable_reference_t1").cast(pl.Boolean, strict=False)
    obs0_label = pl.when(obs0_bool).then(pl.lit("T")).otherwise(pl.lit("F"))
    obs1_label = pl.when(obs1_bool).then(pl.lit("T")).otherwise(pl.lit("F"))

    expressions: List[pl.Expr] = []
    expressions.extend(_literal_group_expressions(unit_values))
    expressions.extend(
        [
            pl.lit(int(subject), dtype=pl.Int64).alias("subject"),
            pl.col("aaSeqCDR3"),
            pl.lit(int(t0), dtype=pl.Int64).alias("t0"),
            pl.lit(int(t1), dtype=pl.Int64).alias("t1"),
            pl.lit(dt_value, dtype=pl.Int64).alias("dt"),
            pl.lit("all").alias("pattern"),
            # model-based consensus
            pl.col("f_latent_t0").alias("f0_latent"),
            pl.col("f_latent_t1").alias("f1_latent"),
            # stable compatibility aliases retained for existing downstream readers
            pl.col("f_latent_t0").alias("freq0_latent"),
            pl.col("f_latent_t1").alias("freq1_latent"),
            pl.col("x_latent_t0").alias("x0_latent"),
            pl.col("x_latent_t1").alias("x1_latent"),
            (pl.col("x_latent_t1") - pl.col("x_latent_t0")).alias("dx_latent"),
            (0.5 * (pl.col("x_latent_t0") + pl.col("x_latent_t1"))).alias(
                "xmid_latent"
            ),
            pl.col("x_latent_t0").alias("x0_condition_latent"),
            pl.col("x_latent_t0").alias("x0_condition"),
            pl.lit(dt_value, dtype=pl.Int64).alias("n_steps"),
            # replicate-resolved observed endpoints
            pl.col("count_rep1_t0"),
            pl.col("count_rep1_t1"),
            pl.col("count_rep2_t0"),
            pl.col("count_rep2_t1"),
            pl.col("depth_rep1_t0"),
            pl.col("depth_rep1_t1"),
            pl.col("depth_rep2_t0"),
            pl.col("depth_rep2_t1"),
            pl.col("f_observed_rep1_t0"),
            pl.col("f_observed_rep1_t1"),
            pl.col("f_observed_rep2_t0"),
            pl.col("f_observed_rep2_t1"),
            pl.col("x_observed_rep1_t0"),
            pl.col("x_observed_rep1_t1"),
            pl.col("x_observed_rep2_t0"),
            pl.col("x_observed_rep2_t1"),
            (pl.col("x_observed_rep1_t1") - pl.col("x_observed_rep1_t0")).alias(
                "dx_observed_rep1"
            ),
            (pl.col("x_observed_rep2_t1") - pl.col("x_observed_rep2_t0")).alias(
                "dx_observed_rep2"
            ),
            rp1_t0.alias("read_positive_rep1_t0"),
            rp1_t1.alias("read_positive_rep1_t1"),
            rp2_t0.alias("read_positive_rep2_t0"),
            rp2_t1.alias("read_positive_rep2_t1"),
            (rp1_t0 & rp2_t0).alias("both_replicates_positive_t0"),
            (rp1_t1 & rp2_t1).alias("both_replicates_positive_t1"),
            # primary-estimand eligibility flags
            (rp1_t0 & rp2_t0 & rp2_t1).alias("forward_ab_eligible"),
            (rp2_t0 & rp1_t0 & rp1_t1).alias("forward_ba_eligible"),
            (rp1_t0 & rp2_t0 & rp1_t1 & rp2_t1).alias("common4"),
            # operational observation layer
            pl.col("p_value_t0").alias("p_value_t0"),
            pl.col("p_value_t1").alias("p_value_t1"),
            pl.lit(float(reference_alpha), dtype=pl.Float64).alias("reference_alpha"),
            obs0_bool.alias("observable_reference_t0"),
            obs1_bool.alias("observable_reference_t1"),
            pl.concat_str([obs0_label, obs1_label]).alias("obs_class_reference"),
            # compatibility aliases: explicitly reference-threshold classes
            obs0_label.alias("obs0"),
            obs1_label.alias("obs1"),
            pl.concat_str([obs0_label, obs1_label]).alias("obs_class"),
            # model-based detectability annotations
            pl.col("p_detect_state_t0").alias("p_detect_state_t0"),
            pl.col("p_detect_state_t1").alias("p_detect_state_t1"),
            pl.col("p_dropout_state_t0").alias("p_dropout_state_t0"),
            pl.col("p_dropout_state_t1").alias("p_dropout_state_t1"),
        ]
    )

    # Optional state identifiers.
    for column in ["pair_id"]:
        c0 = f"{column}_t0"
        c1 = f"{column}_t1"
        if c0 in joined.columns:
            expressions.append(pl.col(c0))
        if c1 in joined.columns:
            expressions.append(pl.col(c1))

    # Optional latent uncertainty and xstar sensitivity coordinate.
    if {"x_latent_sd_t0", "x_latent_sd_t1"}.issubset(joined.columns):
        sd0 = pl.col("x_latent_sd_t0")
        sd1 = pl.col("x_latent_sd_t1")
        valid_sd = sd0.is_finite() & sd1.is_finite() & (sd0 > 0) & (sd1 > 0)
        w0 = 1.0 / (sd0.pow(2) + 1e-12)
        w1 = 1.0 / (sd1.pow(2) + 1e-12)
        midpoint = 0.5 * (pl.col("x_latent_t0") + pl.col("x_latent_t1"))
        xstar = (
            pl.when(valid_sd)
            .then((w0 * pl.col("x_latent_t0") + w1 * pl.col("x_latent_t1")) / (w0 + w1))
            .otherwise(midpoint)
        )
        expressions.extend(
            [
                sd0.alias("x0_latent_sd"),
                sd1.alias("x1_latent_sd"),
                (sd0.pow(2) + sd1.pow(2)).sqrt().alias("dx_latent_sd_approx"),
                xstar.alias("xstar_latent"),
                pl.when(valid_sd)
                .then(pl.lit("inverse_variance_weighted"))
                .otherwise(pl.lit("midpoint_fallback"))
                .alias("xstar_source"),
            ]
        )
    else:
        expressions.extend(
            [
                pl.lit(float("nan"), dtype=pl.Float64).alias("x0_latent_sd"),
                pl.lit(float("nan"), dtype=pl.Float64).alias("x1_latent_sd"),
                pl.lit(float("nan"), dtype=pl.Float64).alias("dx_latent_sd_approx"),
                (0.5 * (pl.col("x_latent_t0") + pl.col("x_latent_t1"))).alias(
                    "xstar_latent"
                ),
                pl.lit("midpoint_fallback").alias("xstar_source"),
            ]
        )

    # Optional latent endpoint quantiles.
    for source, out0, out1 in [
        ("f_latent_q025", "f0_latent_q025", "f1_latent_q025"),
        ("f_latent_q975", "f0_latent_q975", "f1_latent_q975"),
        ("x_latent_q025", "x0_latent_q025", "x1_latent_q025"),
        ("x_latent_q975", "x0_latent_q975", "x1_latent_q975"),
    ]:
        c0 = f"{source}_t0"
        c1 = f"{source}_t1"
        if c0 in joined.columns:
            expressions.append(pl.col(c0).alias(out0))
        if c1 in joined.columns:
            expressions.append(pl.col(c1).alias(out1))

    # Auxiliary positive-only representation.
    if {"x_positive_current_t0", "x_positive_current_t1"}.issubset(joined.columns):
        expressions.extend(
            [
                pl.col("x_positive_current_t0"),
                pl.col("x_positive_current_t1"),
                (
                    pl.col("x_positive_current_t1")
                    - pl.col("x_positive_current_t0")
                ).alias("dx_positive_current"),
            ]
        )
    if {"f_positive_current_t0", "f_positive_current_t1"}.issubset(joined.columns):
        expressions.extend(
            [pl.col("f_positive_current_t0"), pl.col("f_positive_current_t1")]
        )

    for source in [
        "positive_state_class",
        "positive_replicate_source",
        "n_positive_replicates",
        "posterior_entropy",
        "logP",
        "replicate_posterior_bhattacharyya",
        "p_detect_rep1",
        "p_detect_rep2",
        "p_dropout_rep1",
        "p_dropout_rep2",
    ]:
        c0 = f"{source}_t0"
        c1 = f"{source}_t1"
        if c0 in joined.columns:
            expressions.append(pl.col(c0))
        if c1 in joined.columns:
            expressions.append(pl.col(c1))

    # Preserve optional single-replicate latent summaries as endpoint fields.
    optional_endpoint_names = [
        column
        for column in OPTIONAL_ENDPOINT_COLUMNS
        if column.startswith("rep1_")
        or column.startswith("rep2_")
        or column.startswith("f_rep")
        or column.startswith("x_rep")
    ]
    for source in optional_endpoint_names:
        c0 = f"{source}_t0"
        c1 = f"{source}_t1"
        if c0 in joined.columns:
            expressions.append(pl.col(c0))
        if c1 in joined.columns:
            expressions.append(pl.col(c1))

    return joined.select(expressions).sort(
        list(unit_values.keys()) + ["subject", "aaSeqCDR3", "t0", "t1"]
    )


