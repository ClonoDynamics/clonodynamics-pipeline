def summarize_output(output: Path, extra_group_cols: Sequence[str]) -> Dict[str, Any]:
    lf = pl.scan_parquet(output)
    total_rows = int(pq.ParquetFile(output).metadata.num_rows)

    by_dt = collect_streaming(
        lf.group_by("dt")
        .agg(
            [
                pl.len().alias("n_transitions"),
                pl.col("common4").cast(pl.Float64).mean().alias("fraction_common4"),
                pl.col("forward_ab_eligible").cast(pl.Float64).mean().alias(
                    "fraction_forward_ab_eligible"
                ),
                pl.col("forward_ba_eligible").cast(pl.Float64).mean().alias(
                    "fraction_forward_ba_eligible"
                ),
            ]
        )
        .sort("dt")
    )

    by_class = collect_streaming(
        lf.group_by("obs_class_reference")
        .agg(pl.len().alias("n"))
        .sort("obs_class_reference")
    )

    overall_flags = collect_streaming(
        lf.select(
            [
                pl.col("common4").cast(pl.Float64).mean().alias("fraction_common4"),
                pl.col("forward_ab_eligible").cast(pl.Float64).mean().alias(
                    "fraction_forward_ab_eligible"
                ),
                pl.col("forward_ba_eligible").cast(pl.Float64).mean().alias(
                    "fraction_forward_ba_eligible"
                ),
                pl.col("subject").n_unique().alias("n_subjects"),
                pl.struct(list(extra_group_cols) + ["subject", "aaSeqCDR3"])
                .n_unique()
                .alias("n_subject_clone_pairs"),
                pl.struct(list(extra_group_cols) + ["subject", "t0", "t1"])
                .n_unique()
                .alias("n_subject_interval_pairs"),
            ]
        )
    ).row(0, named=True)

    summary: Dict[str, Any] = {
        "transition_rows": total_rows,
        "n_subjects": int(overall_flags["n_subjects"]),
        "n_subject_clone_pairs": int(overall_flags["n_subject_clone_pairs"]),
        "n_subject_interval_pairs": int(overall_flags["n_subject_interval_pairs"]),
        "fraction_common4": float(overall_flags["fraction_common4"]),
        "fraction_forward_ab_eligible": float(
            overall_flags["fraction_forward_ab_eligible"]
        ),
        "fraction_forward_ba_eligible": float(
            overall_flags["fraction_forward_ba_eligible"]
        ),
        "counts_by_dt": {
            str(row[0]): int(row[1]) for row in by_dt.iter_rows()
        },
        "common4_fraction_by_dt": {
            str(row[0]): float(row[2]) for row in by_dt.iter_rows()
        },
        "counts_by_reference_obs_class": {
            str(row[0]): int(row[1]) for row in by_class.iter_rows()
        },
    }

    schema_names = set(lf.collect_schema().names())
    if "posterior_success" in schema_names:
        posterior = collect_streaming(
            lf.select(
                [
                    pl.col("posterior_success").sum().alias("n_success"),
                    pl.col("posterior_success").mean().alias("fraction"),
                ]
            )
        ).row(0, named=True)
        summary["posterior_success_n"] = int(posterior["n_success"] or 0)
        summary["posterior_success_fraction"] = float(posterior["fraction"] or 0.0)

    return summary


def write_report(path: Path, payload: Dict[str, Any]) -> None:
    ensure_parent(path)
    with path.open("w", encoding="utf-8") as handle:
        handle.write("# Longitudinal transition assembly report\n\n")
        for key, value in payload.items():
            if isinstance(value, (dict, list, tuple)):
                value = json.dumps(value, ensure_ascii=False)
            handle.write(f"- {key}: {value}\n")


