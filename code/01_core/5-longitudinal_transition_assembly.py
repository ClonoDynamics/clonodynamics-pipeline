def posterior_path(
    posterior_dir: Path,
    template: str,
    subject: int,
    time_value: int,
    unit_values: Mapping[str, Any],
) -> Path:
    values: Dict[str, Any] = dict(unit_values)
    values.update({"subject": int(subject), "time": int(time_value)})
    try:
        relative = template.format(**values)
    except KeyError as exc:
        raise KeyError(
            f"Posterior template placeholder {exc} cannot be resolved from "
            f"available values: {sorted(values)}"
        ) from exc
    return posterior_dir / relative


def load_posterior_file(path: Path) -> Dict[str, Any]:
    if not path.exists():
        raise FileNotFoundError(str(path))

    with np.load(path, allow_pickle=True) as archive:
        required = {"f_grid", "posterior_matrix", "aaSeqCDR3"}
        missing = required.difference(archive.files)
        if missing:
            raise KeyError(
                f"Posterior file {path.name} is missing arrays: {sorted(missing)}"
            )
        f_grid = np.asarray(archive["f_grid"], dtype=np.float64)
        posterior_matrix = np.asarray(archive["posterior_matrix"], dtype=np.float32)
        clones = np.asarray(archive["aaSeqCDR3"]).astype(str)

    if f_grid.ndim != 1:
        raise ValueError(f"f_grid must be one-dimensional in {path.name}")
    if posterior_matrix.ndim != 2:
        raise ValueError(f"posterior_matrix must be two-dimensional in {path.name}")

    if (
        posterior_matrix.shape[0] == f_grid.size
        and posterior_matrix.shape[1] == clones.size
    ):
        posterior_matrix = posterior_matrix.T

    if posterior_matrix.shape[0] != clones.size:
        raise ValueError(
            f"Posterior rows ({posterior_matrix.shape[0]:,}) do not match clones "
            f"({clones.size:,}) in {path.name}"
        )
    if posterior_matrix.shape[1] != f_grid.size:
        raise ValueError(
            f"Posterior columns ({posterior_matrix.shape[1]:,}) do not match f_grid "
            f"({f_grid.size:,}) in {path.name}"
        )

    safe_grid = np.maximum(f_grid, np.finfo(np.float64).tiny)
    return {
        "x_grid": np.log(safe_grid),
        "posterior_matrix": posterior_matrix,
        "clone_to_index": {clone: idx for idx, clone in enumerate(clones)},
    }


def sample_posterior(
    x_grid: np.ndarray,
    probabilities: np.ndarray,
    n_samples: int,
    rng: np.random.Generator,
) -> np.ndarray:
    probs = np.asarray(probabilities, dtype=np.float64)
    probs = np.where(np.isfinite(probs) & (probs > 0), probs, 0.0)
    total = float(probs.sum())
    if not np.isfinite(total) or total <= 0:
        raise ValueError("Posterior probabilities are empty or non-finite")
    probs /= total
    return rng.choice(x_grid, size=int(n_samples), replace=True, p=probs)


def deterministic_pair_seed(
    base_seed: int,
    subject: int,
    t0: int,
    t1: int,
    unit_values: Mapping[str, Any],
) -> int:
    groups = "|".join(
        f"{key}={unit_values[key]}" for key in sorted(unit_values)
    )
    payload = f"{base_seed}|{groups}|subject={subject}|{t0}|{t1}|all"
    digest = hashlib.blake2b(payload.encode("utf-8"), digest_size=8).digest()
    return int.from_bytes(digest, byteorder="little", signed=False) % (2**32)


def append_posterior_columns(
    record_batch: pa.RecordBatch,
    posterior0: Optional[Dict[str, Any]],
    posterior1: Optional[Dict[str, Any]],
    file_error: Optional[str],
    n_samples: int,
    rng: np.random.Generator,
) -> pa.Table:
    table = pa.Table.from_batches([record_batch])
    clones = table.column("aaSeqCDR3").to_pylist()
    row_count = len(clones)

    output_arrays: Dict[str, np.ndarray] = {
        column: np.full(row_count, np.nan, dtype=np.float64)
        for column in POSTERIOR_FLOAT_COLUMNS
    }
    success = np.zeros(row_count, dtype=np.bool_)
    messages: List[str] = [""] * row_count

    if file_error is not None or posterior0 is None or posterior1 is None:
        messages = [file_error or "posterior_file_error"] * row_count
    else:
        map0 = posterior0["clone_to_index"]
        map1 = posterior1["clone_to_index"]
        grid0 = posterior0["x_grid"]
        grid1 = posterior1["x_grid"]
        matrix0 = posterior0["posterior_matrix"]
        matrix1 = posterior1["posterior_matrix"]
        ddof = 1 if int(n_samples) > 1 else 0

        for row_index, raw_clone in enumerate(clones):
            clone = str(raw_clone)
            try:
                idx0 = map0.get(clone)
                idx1 = map1.get(clone)
                if idx0 is None:
                    raise KeyError(f"clone missing at t0: {clone}")
                if idx1 is None:
                    raise KeyError(f"clone missing at t1: {clone}")

                samples0 = sample_posterior(grid0, matrix0[idx0], n_samples, rng)
                samples1 = sample_posterior(grid1, matrix1[idx1], n_samples, rng)
                displacement = samples1 - samples0

                output_arrays["x0_post_mean"][row_index] = float(np.mean(samples0))
                output_arrays["x1_post_mean"][row_index] = float(np.mean(samples1))
                output_arrays["x0_post_median"][row_index] = float(np.median(samples0))
                output_arrays["x1_post_median"][row_index] = float(np.median(samples1))
                output_arrays["dx_post_mean"][row_index] = float(np.mean(displacement))
                output_arrays["dx_post_median"][row_index] = float(np.median(displacement))
                output_arrays["dx_post_q025"][row_index] = float(
                    np.quantile(displacement, 0.025)
                )
                output_arrays["dx_post_q975"][row_index] = float(
                    np.quantile(displacement, 0.975)
                )
                output_arrays["dx_post_sd"][row_index] = float(
                    np.std(displacement, ddof=ddof)
                )
                output_arrays["p_dx_gt0"][row_index] = float(
                    np.mean(displacement > 0)
                )
                output_arrays["p_dx_lt0"][row_index] = float(
                    np.mean(displacement < 0)
                )
                success[row_index] = True
            except Exception as exc:
                messages[row_index] = (
                    f"transition_error: {type(exc).__name__}: {exc}"
                )

    for column in POSTERIOR_FLOAT_COLUMNS:
        table = table.append_column(
            column, pa.array(output_arrays[column], type=pa.float64())
        )
    table = table.append_column(
        "posterior_success", pa.array(success, type=pa.bool_())
    )
    table = table.append_column(
        "posterior_message", pa.array(messages, type=pa.string())
    )
    return table


def enrich_pair_with_posterior(
    raw_path: Path,
    output_path: Path,
    posterior_dir: Path,
    posterior_template: str,
    subject: int,
    unit_values: Mapping[str, Any],
    t0: int,
    t1: int,
    n_samples: int,
    seed: int,
    batch_size: int,
    compression: str,
    row_group_size: int,
) -> None:
    posterior0: Optional[Dict[str, Any]] = None
    posterior1: Optional[Dict[str, Any]] = None
    file_error: Optional[str] = None

    try:
        posterior0 = load_posterior_file(
            posterior_path(
                posterior_dir, posterior_template, subject, t0, unit_values
            )
        )
        posterior1 = load_posterior_file(
            posterior_path(
                posterior_dir, posterior_template, subject, t1, unit_values
            )
        )
    except Exception as exc:
        file_error = f"posterior_file_error: {type(exc).__name__}: {exc}"

    rng = np.random.default_rng(
        deterministic_pair_seed(seed, subject, t0, t1, unit_values)
    )

    parquet_file = pq.ParquetFile(raw_path)
    writer: Optional[pq.ParquetWriter] = None
    try:
        for record_batch in parquet_file.iter_batches(
            batch_size=int(batch_size), use_threads=True
        ):
            enriched = append_posterior_columns(
                record_batch=record_batch,
                posterior0=posterior0,
                posterior1=posterior1,
                file_error=file_error,
                n_samples=int(n_samples),
                rng=rng,
            )
            if writer is None:
                ensure_parent(output_path)
                writer = pq.ParquetWriter(
                    output_path,
                    enriched.schema,
                    compression=compression,
                    use_dictionary=True,
                    write_statistics=True,
                )
            writer.write_table(enriched, row_group_size=int(row_group_size))
            del enriched, record_batch
    finally:
        if writer is not None:
            writer.close()
        del posterior0, posterior1
        gc.collect()


def copy_pair_without_posterior(
    raw_path: Path,
    output_path: Path,
    batch_size: int,
    compression: str,
    row_group_size: int,
) -> None:
    parquet_file = pq.ParquetFile(raw_path)
    writer: Optional[pq.ParquetWriter] = None
    try:
        for record_batch in parquet_file.iter_batches(
            batch_size=int(batch_size), use_threads=True
        ):
            table = pa.Table.from_batches([record_batch])
            if writer is None:
                ensure_parent(output_path)
                writer = pq.ParquetWriter(
                    output_path,
                    table.schema,
                    compression=compression,
                    use_dictionary=True,
                    write_statistics=True,
                )
            writer.write_table(table, row_group_size=int(row_group_size))
            del table, record_batch
    finally:
        if writer is not None:
            writer.close()


