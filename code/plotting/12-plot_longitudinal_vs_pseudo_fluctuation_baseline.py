def main(argv: Optional[Sequence[str]] = None) -> int:
    args = build_parser().parse_args(argv)

    if not 0.0 <= args.ci_alpha <= 1.0:
        raise ValueError("--ci-alpha must be between 0 and 1.")
    if not 0.0 <= args.pseudo_alpha <= 1.0:
        raise ValueError("--pseudo-alpha must be between 0 and 1.")
    if args.max_display_markers < 1:
        raise ValueError("--max-display-markers must be >= 1.")

    analysis_dir = args.analysis_dir.expanduser().resolve()
    if not analysis_dir.is_dir():
        raise NotADirectoryError(
            "Step-12 analysis directory not found: {}".format(analysis_dir)
        )

    figures_dir = (
        args.figures_dir.expanduser().resolve()
        if args.figures_dir is not None
        else analysis_dir / "figures_longitudinal_vs_pseudo_fluctuation_baseline"
    )
    figures_dir.mkdir(parents=True, exist_ok=True)

    formats = parse_formats(args.formats)
    font_family_used = setup_style(args.font_size)

    tables = load_tables(analysis_dir)
    metadata = load_metadata(analysis_dir)
    validate_step12_schema(tables)

    longitudinal_dt = resolve_longitudinal_dt(tables, metadata)

    written: List[Path] = []

    if args.figure_set in {"all", "main"}:
        written.extend(
            plot_main(
                tables,
                longitudinal_dt,
                figures_dir,
                formats,
                args,
            )
        )

    if args.figure_set in {"all", "supplementary"}:
        written.extend(
            plot_supplementary(
                tables,
                longitudinal_dt,
                figures_dir,
                formats,
                args,
            )
        )

    if args.figure_set in {"all", "standalone"}:
        written.extend(
            plot_standalones(
                tables,
                longitudinal_dt,
                figures_dir,
                formats,
                args,
            )
        )

    pd.DataFrame(
        {
            "file": [path.name for path in written],
            "figure": [path.stem for path in written],
            "format": [path.suffix.lstrip(".") for path in written],
        }
    ).to_csv(figures_dir / "figure_manifest.csv", index=False)

    config = metadata.get("config", {})
    summary = tables.get("summary", pd.DataFrame())

    plot_config = {
        "script": Path(__file__).name,
        "script_version": SCRIPT_VERSION,
        "analysis_source": "12-longitudinal_vs_pseudo_fluctuation_baseline.py",
        "analysis_dir": str(analysis_dir),
        "figures_dir": str(figures_dir),
        "figure_set": args.figure_set,
        "formats": formats,
        "font_family_used": font_family_used,
        "font_size": float(args.font_size),
        "line_width": float(args.line_width),
        "marker_size": float(args.marker_size),
        "ci_alpha": float(args.ci_alpha),
        "pseudo_alpha": float(args.pseudo_alpha),
        "legend_mode": args.legend_mode,
        "show_ci": bool(args.show_ci),
        "max_display_markers": int(args.max_display_markers),
        "longitudinal_dt": longitudinal_dt,
        "primary_metric": "var_dx",
        "complementary_metric": "msd",
        "mad_role": "descriptive_fixed_pseudo_reference_only",
        "mad_panel_available": bool(mad_available(tables["shared_grid"])),
        "figure_sizes_inches": FIGURE_SIZES_INCHES,
        "axis_config": AXIS_CONFIG,
        "analysis_recomputed": False,
        "shared_support_recomputed": False,
        "pseudo_configurations_recomputed": False,
        "empirical_tests_recomputed": False,
        "pseudo_baseline_subtracted_before_step13": False,
        "source_analysis_script_version": (
            config.get("script_version")
            if isinstance(config, dict)
            else None
        ),
        "comparison_summary_available": bool(not summary.empty),
    }

    (figures_dir / "plot_config.json").write_text(
        json.dumps(plot_config, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )

    print("[DONE] Step-12 plotting complete")
    print("[INFO] Analysis directory: {}".format(analysis_dir))
    print("[INFO] Figures directory: {}".format(figures_dir))
    print("[INFO] Longitudinal lag: {}".format(longitudinal_dt))
    print("[INFO] MAD fixed reference available: {}".format(
        mad_available(tables["shared_grid"])
    ))
    print("[INFO] {} rendered files".format(len(written)))

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
