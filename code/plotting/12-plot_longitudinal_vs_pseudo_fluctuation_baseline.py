"""
12-plot_longitudinal_vs_pseudo_fluctuation_baseline.py
======================================================

Plot-only companion to ClonoDynamics Step 12:

    12-longitudinal_vs_pseudo_fluctuation_baseline.py

Scientific role
---------------
Step 12 compares genuine longitudinal fluctuation magnitude with the
pseudo-longitudinal technical baseline on shared ABSOLUTE latent-abundance
support.

The primary comparison is:

    Var(Delta x_latent | xstar_latent)

for longitudinal TT transitions at one selected lag, normally dt = 1.

The complementary comparison is:

    MSD = E[(Delta x_latent)^2 | xstar_latent].

MAD is retained as a descriptive robust comparison only.

Step 12 preserves the native absolute xstar geometry of the longitudinal and
pseudo datasets. It does not convert abundance to percentiles/ranks, force
common clonotype-level binning across datasets, or extrapolate outside the
support represented by both datasets.

The pseudo reference is generated from arbitrary pseudo-time configurations.
For Var and MSD, each global ordering/reversal equivalence class is represented
once because global reversal changes the sign of dx but leaves xstar, dx^2 and
sample variance unchanged.

Analysis / plotting boundary
----------------------------
This script reads ONLY Step-12 output files. It does not directly reload Step 11,
Step 8 or pseudo Step-4 trajectories and does not:

    - rebuild pseudo directed-pair sufficient statistics;
    - regenerate pseudo-time configurations;
    - recompute the stable pseudo abundance support;
    - interpolate longitudinal or pseudo curves;
    - recompute empirical null distributions;
    - recompute empirical P-values;
    - redefine the cross-dataset abundance geometry;
    - subtract the pseudo baseline before temporal-scaling analysis.

The term "excess" is used only for the descriptive Step-12 quantity:

    longitudinal value - pseudo technical-reference median.

It must not be interpreted as pure biological variance/noise.

Position in the pipeline
------------------------
Step 12 is a cross-dataset comparison:

    Step 11 genuine longitudinal fluctuations
                    \
                     \
                      v
                   Step 12
                      ^
                     /
                    /
    Step 8 pseudo representation assessment
        +
    pseudo Step-4 trajectories

Step 12 does NOT feed Step 13 computationally. Step 13 fits temporal models to
the genuine longitudinal Step-11 fluctuation data; the Step-12 technical
baseline is not subtracted beforehand.

Analysis input
--------------
Required:

    --analysis-dir

pointing to the output directory generated by:

    12-longitudinal_vs_pseudo_fluctuation_baseline.py

Core required Step-12 tables
----------------------------
    07_shared_grid_comparison.csv
        Primary pointwise comparison on shared absolute xstar support. Contains
        longitudinal Var/MSD curves and confidence intervals, pseudo medians and
        95% configuration envelopes, descriptive excess/ratio quantities, and
        the optional fixed-reference MAD comparison.

    08_pseudo_shared_grid_configuration_metrics.csv
        Configuration-level integrated pseudo-null metrics on the Step-12 shared
        grid.

    09_empirical_tests.csv
        Precomputed empirical tests for integrated Var and MSD.

Optional provenance / descriptive tables
----------------------------------------
    01_longitudinal_dt1_native_curve.csv
    05_pseudo_native_envelope.csv
    06_shared_absolute_support_summary.csv
    10_comparison_summary.csv
    11_pseudo_fixed_reference_curve.csv

The fixed pseudo MAD reference is optional in the analysis. The MAD panel is
drawn only when finite fixed-reference MAD values are already present in
`07_shared_grid_comparison.csv`.

Metadata
--------
When present, the plotter reads:

    00_run_config.json
    12_fluctuation_baseline_report.json

for provenance and display labels only.

Generated figures
-----------------
Main composite:

    00_main_longitudinal_vs_pseudo_fluctuation_baseline_ABC

        A  conditional variance: longitudinal versus pseudo technical baseline
        B  MSD: longitudinal versus pseudo technical baseline
        C  empirical pseudo-null distribution of mean conditional variance over
           shared support, with the longitudinal statistic overlaid

Supplementary composite:

    Sx_fluctuation_baseline_diagnostics_ABCD

        A  empirical pseudo-null distribution of mean MSD over shared support
        B  MAD: longitudinal versus fixed pseudo reference, descriptive only
        C  excess conditional variance = longitudinal - pseudo median
        D  excess MSD = longitudinal - pseudo median

Standalone figures:

    01_variance_longitudinal_vs_pseudo
    02_msd_longitudinal_vs_pseudo
    03_variance_integrated_pseudo_null
    04_msd_integrated_pseudo_null
    05_mad_longitudinal_vs_pseudo          [when available]
    06_excess_variance
    07_excess_msd

Non-figure outputs
------------------
Only graphical provenance is written:

    figure_manifest.csv
    plot_config.json

No new inferential/scientific summary table is created by the plotting layer.

Rendering policy
----------------
The 101-point shared grid is an evaluation/interpolation grid created by Step 12,
not a set of 101 independently estimated abundance bins. The longitudinal curve
therefore uses sparse display markers while the full interpolated curve is
retained.

Integrated pseudo-null panels use the already-computed configuration metrics in:

    08_pseudo_shared_grid_configuration_metrics.csv

and the longitudinal statistics/P-values already computed in:

    09_empirical_tests.csv.

Figure customization
--------------------
Edit:

    FIGURE_SIZES_INCHES

for per-figure dimensions in inches, and:

    AXIS_CONFIG

for per-panel:

    xlim
    ylim
    xscale
    yscale
    xtick_step
    ytick_step

All default axis limits are data-driven so that current Step-12 confidence
intervals are not silently clipped. Manuscript-specific ranges can be imposed
later by editing `AXIS_CONFIG`.

Example
-------
python3 ./code/plotting/12-plot_longitudinal_vs_pseudo_fluctuation_baseline.py \
    --analysis-dir \
    ./clonodynamics_longitudinal_vs_pseudo_results/12-longitudinal-vs-pseudo-fluctuation-baseline \
    --figures-dir ./figures/12-longitudinal-vs-pseudo-fluctuation-baseline \
    --formats pdf,png
"""

