def empirical_row(tests: pd.DataFrame, metric: str) -> pd.Series:
    d = tests.loc[tests["metric"].astype(str) == metric]
    if len(d) != 1:
        raise ValueError(
            "Expected one empirical-test row for {!r}; found {}".format(
                metric, len(d)
            )
        )
    return d.iloc[0]


def p_label(value: float) -> str:
    if not np.isfinite(value):
        return r"$P_{\mathrm{emp}}$ = NA"
    if value < 0.001:
        return r"$P_{\mathrm{emp}}<0.001$"
    return r"$P_{\mathrm{emp}}={:.3f}$".format(value)


def draw_metric_curve(
    ax: plt.Axes,
    shared: pd.DataFrame,
    metric: str,
    axis_key: str,
    longitudinal_dt: Optional[float],
    args: argparse.Namespace,
) -> None:
    prefix = "var_dx" if metric == "var_dx" else "msd"

    long_col = "longitudinal_{}".format(prefix)
    long_lo = "longitudinal_{}_ci_low".format(prefix)
    long_hi = "longitudinal_{}_ci_high".format(prefix)

    pseudo_col = "pseudo_{}_median".format(prefix)
    pseudo_lo = "pseudo_{}_q025".format(prefix)
    pseudo_hi = "pseudo_{}_q975".format(prefix)

    d = shared.sort_values("xstar").copy()

    x = numeric_array(d["xstar"])
    yl = numeric_array(d[long_col])
    yllo = numeric_array(d[long_lo])
    ylhi = numeric_array(d[long_hi])

    yp = numeric_array(d[pseudo_col])
    yplo = numeric_array(d[pseudo_lo])
    yphi = numeric_array(d[pseudo_hi])

    valid_l = np.isfinite(x) & np.isfinite(yl)
    valid_lb = valid_l & np.isfinite(yllo) & np.isfinite(ylhi)

    valid_p = np.isfinite(x) & np.isfinite(yp)
    valid_pb = valid_p & np.isfinite(yplo) & np.isfinite(yphi)

    line_long = ax.plot(
        x[valid_l],
        yl[valid_l],
        linewidth=args.line_width,
        label="Longitudinal, {}".format(dt_text(longitudinal_dt)),
    )[0]

    if args.show_ci and valid_lb.any():
        ax.fill_between(
            x[valid_lb],
            yllo[valid_lb],
            ylhi[valid_lb],
            color=line_long.get_color(),
            alpha=args.ci_alpha,
            linewidth=0,
        )

    line_pseudo = ax.plot(
        x[valid_p],
        yp[valid_p],
        linewidth=args.line_width,
        linestyle="--",
        label="Pseudo technical baseline",
    )[0]

    if args.show_ci and valid_pb.any():
        ax.fill_between(
            x[valid_pb],
            yplo[valid_pb],
            yphi[valid_pb],
            color=line_pseudo.get_color(),
            alpha=args.pseudo_alpha,
            linewidth=0,
        )

    # Sparse markers emphasize that the shared grid is an interpolation/evaluation
    # grid generated by Step 12 rather than a set of independently estimated bins.
    idx = np.flatnonzero(valid_l)
    if idx.size:
        step = max(1, int(np.ceil(idx.size / float(args.max_display_markers))))
        take = idx[::step]
        ax.plot(
            x[take],
            yl[take],
            linestyle="none",
            marker="o",
            markersize=args.marker_size,
            color=line_long.get_color(),
        )

    ax.set_xlabel(r"Transition-centred latent abundance, $x^\star$")
    ax.set_ylabel(
        r"$\mathrm{Var}(\Delta x\mid x^\star)$"
        if metric == "var_dx"
        else r"$\mathrm{MSD}(\Delta x\mid x^\star)$"
    )

    style_axes(ax)
    apply_axis_config(ax, axis_key)
    apply_legend(ax, args.legend_mode)


def draw_integrated_null(
    ax: plt.Axes,
    pseudo_metrics: pd.DataFrame,
    tests: pd.DataFrame,
    metric: str,
    axis_key: str,
) -> None:
    pseudo_col = (
        "mean_var_dx_shared"
        if metric == "var_dx"
        else "mean_msd_shared"
    )

    valid_flag = pseudo_metrics["valid_for_integrated_test"].astype(bool)
    values = pd.to_numeric(
        pseudo_metrics.loc[valid_flag, pseudo_col],
        errors="coerce",
    ).to_numpy(dtype=float)
    values = values[np.isfinite(values)]

    if values.size < 2:
        raise ValueError(
            "Too few valid pseudo configurations for metric {}".format(metric)
        )

    row = empirical_row(tests, metric)
    longitudinal = float(row["longitudinal_mean_over_shared_support"])
    pseudo_median = float(row["pseudo_median"])
    pval = float(row["empirical_p_upper"])

    parts = ax.violinplot(
        [values],
        positions=[0.0],
        vert=False,
        widths=0.50,
        showmeans=False,
        showmedians=False,
        showextrema=False,
    )
    for body in parts["bodies"]:
        body.set_alpha(0.30)
        body.set_linewidth(0.7)

    ax.plot(
        pseudo_median,
        0.0,
        marker="|",
        markersize=9,
        markeredgewidth=1.2,
        linestyle="none",
        label="Pseudo median",
    )
    ax.plot(
        longitudinal,
        0.0,
        marker="D",
        markersize=4.5,
        linestyle="none",
        label="Longitudinal",
        zorder=5,
    )

    ax.set_ylim(-0.42, 0.42)
    ax.set_yticks([])
    ax.set_xlabel(
        r"Mean $\mathrm{Var}(\Delta x\mid x^\star)$ over shared support"
        if metric == "var_dx"
        else r"Mean MSD over shared support"
    )

    style_axes(ax)
    ax.spines["left"].set_visible(False)
    apply_axis_config(ax, axis_key)

    annotation_box(
        ax,
        "Longitudinal = {:.3f}\nPseudo median = {:.3f}\n{}\nPseudo configurations = {:,}".format(
            longitudinal,
            pseudo_median,
            p_label(pval),
            int(values.size),
        ),
    )
    apply_legend(ax, "inside")


def mad_available(shared: pd.DataFrame) -> bool:
    required = {
        "xstar",
        "longitudinal_mad_dx",
        "pseudo_mad_dx_fixed_reference",
    }
    if not required.issubset(shared.columns):
        return False

    long_values = pd.to_numeric(
        shared["longitudinal_mad_dx"], errors="coerce"
    ).to_numpy(dtype=float)
    pseudo_values = pd.to_numeric(
        shared["pseudo_mad_dx_fixed_reference"], errors="coerce"
    ).to_numpy(dtype=float)

    return bool(np.isfinite(long_values).any() and np.isfinite(pseudo_values).any())


def draw_mad_curve(
    ax: plt.Axes,
    shared: pd.DataFrame,
    axis_key: str,
    longitudinal_dt: Optional[float],
    args: argparse.Namespace,
) -> bool:
    if not mad_available(shared):
        ax.axis("off")
        ax.text(
            0.5,
            0.5,
            "Fixed pseudo MAD reference\nnot available",
            transform=ax.transAxes,
            ha="center",
            va="center",
        )
        return False

    d = shared.sort_values("xstar")
    x = numeric_array(d["xstar"])
    y_long = numeric_array(d["longitudinal_mad_dx"])
    y_pseudo = numeric_array(d["pseudo_mad_dx_fixed_reference"])

    valid_long = np.isfinite(x) & np.isfinite(y_long)
    valid_pseudo = np.isfinite(x) & np.isfinite(y_pseudo)

    ax.plot(
        x[valid_long],
        y_long[valid_long],
        linewidth=args.line_width,
        marker="o",
        markersize=args.marker_size,
        label="Longitudinal, {}".format(dt_text(longitudinal_dt)),
    )
    ax.plot(
        x[valid_pseudo],
        y_pseudo[valid_pseudo],
        linewidth=args.line_width,
        linestyle="--",
        label="Pseudo fixed reference",
    )

    ax.set_xlabel(r"Transition-centred latent abundance, $x^\star$")
    ax.set_ylabel(r"MAD($\Delta x\mid x^\star$)")
    style_axes(ax)
    apply_axis_config(ax, axis_key)
    apply_legend(ax, args.legend_mode)
    return True


def draw_excess_curve(
    ax: plt.Axes,
    shared: pd.DataFrame,
    metric: str,
    axis_key: str,
    args: argparse.Namespace,
) -> None:
    column = "excess_var_dx" if metric == "var_dx" else "excess_msd"

    d = shared.sort_values("xstar")
    x = numeric_array(d["xstar"])
    y = numeric_array(d[column])
    valid = np.isfinite(x) & np.isfinite(y)

    ax.plot(
        x[valid],
        y[valid],
        linewidth=args.line_width,
        marker="o",
        markersize=args.marker_size,
    )
    reference_horizontal(ax, 0.0)

    ax.set_xlabel(r"Transition-centred latent abundance, $x^\star$")
    ax.set_ylabel(
        "Longitudinal - pseudo median\n"
        + (
            r"Var($\Delta x\mid x^\star$)"
            if metric == "var_dx"
            else r"MSD($\Delta x\mid x^\star$)"
        )
    )

    style_axes(ax)
    apply_axis_config(ax, axis_key)


