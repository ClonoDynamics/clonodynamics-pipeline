def setup_style(font_size: float) -> str:
    try:
        from matplotlib import font_manager

        font_manager.findfont("Arial", fallback_to_default=False)
        family = "Arial"
    except Exception:
        family = "DejaVu Sans"
        eprint("[WARN] Arial not found; using DejaVu Sans.")

    tick_font = max(float(font_size) - 1.0, 5.0)

    plt.rcParams.update(
        {
            "font.family": family,
            "font.size": float(font_size),
            "axes.labelsize": float(font_size),
            "axes.titlesize": float(font_size),
            "xtick.labelsize": tick_font,
            "ytick.labelsize": tick_font,
            "legend.fontsize": tick_font,
            "legend.title_fontsize": tick_font,
            "axes.linewidth": 0.7,
            "xtick.major.width": 0.7,
            "ytick.major.width": 0.7,
            "xtick.major.size": 2.5,
            "ytick.major.size": 2.5,
            "xtick.direction": "out",
            "ytick.direction": "out",
            "pdf.fonttype": 42,
            "ps.fonttype": 42,
        }
    )
    return family


def style_axes(ax: plt.Axes) -> None:
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    ax.tick_params(direction="out")


def reference_horizontal(ax: plt.Axes, value: float) -> None:
    ax.axhline(
        value,
        linewidth=0.8,
        linestyle="--",
        color=ax.spines["bottom"].get_edgecolor(),
    )


def add_panel_label(ax: plt.Axes, label: str, font_size: float) -> None:
    ax.text(
        -0.14,
        1.08,
        label,
        transform=ax.transAxes,
        fontsize=max(float(font_size) + 1.0, 8.0),
        fontweight="bold",
        va="top",
        ha="left",
    )


def annotation_box(ax: plt.Axes, text: str) -> None:
    ax.text(
        0.03,
        0.97,
        text,
        transform=ax.transAxes,
        ha="left",
        va="top",
        fontsize=max(float(plt.rcParams["font.size"]) - 0.5, 5.0),
    )


def apply_axis_config(ax: plt.Axes, key: str) -> None:
    cfg = AXIS_CONFIG.get(key, {})

    if cfg.get("xscale"):
        ax.set_xscale(str(cfg["xscale"]))
    if cfg.get("yscale"):
        ax.set_yscale(str(cfg["yscale"]))

    if cfg.get("xlim") is not None:
        lo, hi = cfg["xlim"]
        old_lo, old_hi = ax.get_xlim()
        ax.set_xlim(old_lo if lo is None else lo, old_hi if hi is None else hi)

    if cfg.get("ylim") is not None:
        lo, hi = cfg["ylim"]
        old_lo, old_hi = ax.get_ylim()
        ax.set_ylim(old_lo if lo is None else lo, old_hi if hi is None else hi)

    if cfg.get("xtick_step") is not None:
        ax.xaxis.set_major_locator(MultipleLocator(float(cfg["xtick_step"])))
    if cfg.get("ytick_step") is not None:
        ax.yaxis.set_major_locator(MultipleLocator(float(cfg["ytick_step"])))


def apply_legend(ax: plt.Axes, mode: str) -> None:
    handles, labels = ax.get_legend_handles_labels()
    if not handles or mode == "none":
        return

    if mode == "outside":
        ax.legend(
            handles,
            labels,
            frameon=False,
            loc="center left",
            bbox_to_anchor=(1.02, 0.5),
            borderaxespad=0.0,
        )
    else:
        ax.legend(handles, labels, frameon=False, loc="best")


def save_figure(
    fig: plt.Figure,
    outdir: Path,
    stem: str,
    formats: Sequence[str],
    dpi: int,
) -> List[Path]:
    outdir.mkdir(parents=True, exist_ok=True)
    written: List[Path] = []

    for fmt in formats:
        path = outdir / "{}.{}".format(stem, fmt)
        kwargs = {
            "bbox_inches": "tight",
            "pad_inches": 0.04,
        }
        if fmt == "png":
            kwargs["dpi"] = int(dpi)
        fig.savefig(path, **kwargs)
        written.append(path)
        print("[SAVED] {}".format(path))

    plt.close(fig)
    return written


