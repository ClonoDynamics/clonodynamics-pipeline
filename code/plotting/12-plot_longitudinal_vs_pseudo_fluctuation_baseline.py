def eprint(*args, **kwargs) -> None:
    print(*args, file=sys.stderr, **kwargs)


def read_required(path: Path) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError("Required Step-12 output not found: {}".format(path))
    df = pd.read_csv(path)
    if df.empty:
        raise ValueError("Required Step-12 output is empty: {}".format(path))
    return df


def read_optional(path: Path) -> pd.DataFrame:
    if not path.exists():
        return pd.DataFrame()
    return pd.read_csv(path)


def load_tables(analysis_dir: Path) -> Dict[str, pd.DataFrame]:
    tables = {
        key: read_required(analysis_dir / filename)
        for key, filename in CORE_REQUIRED_FILES.items()
    }
    tables.update(
        {
            key: read_optional(analysis_dir / filename)
            for key, filename in OPTIONAL_FILES.items()
        }
    )
    return tables


def load_json_optional(path: Path) -> Dict[str, object]:
    if not path.exists():
        return {}
    data = json.loads(path.read_text(encoding="utf-8"))
    return data if isinstance(data, dict) else {}


def load_metadata(analysis_dir: Path) -> Dict[str, object]:
    config = load_json_optional(analysis_dir / "00_run_config.json")
    report = load_json_optional(analysis_dir / "12_fluctuation_baseline_report.json")
    return {
        "config": config,
        "report": report,
    }


def require_columns(
    df: pd.DataFrame,
    columns: Sequence[str],
    label: str,
) -> None:
    missing = [column for column in columns if column not in df.columns]
    if missing:
        raise ValueError(
            "{} missing required columns {}. Available: {}".format(
                label, missing, list(df.columns)
            )
        )


def numeric_array(series: pd.Series) -> np.ndarray:
    return pd.to_numeric(series, errors="coerce").to_numpy(dtype=float)


def parse_formats(text: str) -> List[str]:
    values = [value.strip().lower() for value in str(text).split(",") if value.strip()]
    allowed = {"pdf", "png", "svg"}
    invalid = [value for value in values if value not in allowed]
    if invalid:
        raise ValueError(
            "Unsupported figure format(s): {}. Use pdf,png,svg.".format(invalid)
        )

    out: List[str] = []
    for value in values:
        if value not in out:
            out.append(value)

    if not out:
        raise ValueError("At least one figure format is required.")
    return out


def resolve_longitudinal_dt(
    tables: Dict[str, pd.DataFrame],
    metadata: Dict[str, object],
) -> Optional[float]:
    config = metadata.get("config", {})
    if isinstance(config, dict) and config.get("longitudinal_dt") is not None:
        try:
            return float(config["longitudinal_dt"])
        except Exception:
            pass

    summary = tables.get("summary", pd.DataFrame())
    if not summary.empty and "longitudinal_dt" in summary.columns:
        values = pd.to_numeric(summary["longitudinal_dt"], errors="coerce").dropna()
        if not values.empty:
            return float(values.iloc[0])

    native = tables.get("longitudinal_native", pd.DataFrame())
    if not native.empty and "dt" in native.columns:
        values = pd.to_numeric(native["dt"], errors="coerce").dropna()
        if not values.empty:
            return float(values.iloc[0])

    return None


def dt_text(value: Optional[float]) -> str:
    if value is None or not np.isfinite(value):
        return "selected lag"
    value = float(value)
    if value.is_integer():
        return r"$\Delta t={}$".format(int(value))
    return r"$\Delta t={:g}$".format(value)


