def plot_main(
    tables: Dict[str, pd.DataFrame],
    outdir: Path,
    formats: Sequence[str],
    args: argparse.Namespace,
) -> List[Path]:
    fig, axes = plt.subplots(
        1, 3,
        figsize=FIGURE_SIZES_INCHES["00_main_longitudinal_vs_pseudo_forward_drift_ABC"],
    )

    draw_shared_grid(
        axes[0], tables["shared_grid"], args.line_width,
        args.marker_size, args.ci_alpha, "MainA"
    )
    draw_null_distribution(
        axes[1], tables["pseudo_null"], tables["empirical_tests"],
        "slope", r"Slope of $E[\Delta x\mid x_0]$", "MainB", args.seed
    )
    draw_null_distribution(
        axes[2], tables["pseudo_null"], tables["empirical_tests"],
        "centered_mean_abs_drift", "Centered mean absolute drift",
        "MainC", args.seed + 1
    )

    for ax, label in zip(axes, ["A", "B", "C"]):
        add_panel_label(ax, label, args.font_size)

    fig.subplots_adjust(wspace=0.42)
    return save_figure(
        fig, outdir,
        "00_main_longitudinal_vs_pseudo_forward_drift_ABC",
        formats, args.dpi,
    )


def plot_supplementary(
    tables: Dict[str, pd.DataFrame],
    outdir: Path,
    formats: Sequence[str],
    args: argparse.Namespace,
) -> List[Path]:
    fig, axes = plt.subplots(
        2, 2,
        figsize=FIGURE_SIZES_INCHES["Sx_longitudinal_vs_pseudo_comparison_diagnostics"],
    )
    axA, axB, axC, axD = axes.ravel()

    draw_native_curves(
        axA, tables["native"], args.line_width, args.marker_size, "SxA"
    )
    draw_difference(
        axB, tables["shared_grid"], args.line_width, args.marker_size, "SxB"
    )
    draw_null_distribution(
        axC, tables["pseudo_null"], tables["empirical_tests"],
        "centered_rms_drift", "Centered RMS drift", "SxC", args.seed + 2
    )
    draw_null_distribution(
        axD, tables["pseudo_null"], tables["empirical_tests"],
        "mean_dx", "Mean drift offset", "SxD", args.seed + 3
    )

    for ax, label in zip(axes.ravel(), ["A", "B", "C", "D"]):
        add_panel_label(ax, label, args.font_size)

    fig.subplots_adjust(wspace=0.42, hspace=0.42)
    return save_figure(
        fig, outdir,
        "Sx_longitudinal_vs_pseudo_comparison_diagnostics",
        formats, args.dpi,
    )


def plot_standalones(
    tables: Dict[str, pd.DataFrame],
    outdir: Path,
    formats: Sequence[str],
    args: argparse.Namespace,
) -> List[Path]:
    written: List[Path] = []

    specs = [
        ("01_longitudinal_vs_pseudo_forward_drift", "shared"),
        ("02_slope_pseudo_null", "slope"),
        ("03_centered_mean_abs_drift_pseudo_null", "centered_mean_abs_drift"),
        ("04_native_forward_drift_curves", "native"),
        ("05_longitudinal_minus_pseudo", "difference"),
        ("06_centered_rms_drift_pseudo_null", "centered_rms_drift"),
        ("07_mean_drift_offset_pseudo_null", "mean_dx"),
    ]

    for i, (stem, kind) in enumerate(specs):
        fig, ax = plt.subplots(figsize=FIGURE_SIZES_INCHES[stem])

        if kind == "shared":
            draw_shared_grid(
                ax, tables["shared_grid"], args.line_width,
                args.marker_size, args.ci_alpha, stem
            )
        elif kind == "native":
            draw_native_curves(
                ax, tables["native"], args.line_width, args.marker_size, stem
            )
        elif kind == "difference":
            draw_difference(
                ax, tables["shared_grid"], args.line_width, args.marker_size, stem
            )
        else:
            labels = {
                "slope": r"Slope of $E[\Delta x\mid x_0]$",
                "centered_mean_abs_drift": "Centered mean absolute drift",
                "centered_rms_drift": "Centered RMS drift",
                "mean_dx": "Mean drift offset",
            }
            draw_null_distribution(
                ax, tables["pseudo_null"], tables["empirical_tests"],
                kind, labels[kind], stem, args.seed + i
            )

        written.extend(save_figure(fig, outdir, stem, formats, args.dpi))

    return written


