"""
10-plot_longitudinal_vs_pseudo_forward_drift.py
===============================================

Plot-only companion to ClonoDynamics Step 10:

    10-longitudinal_vs_pseudo_forward_drift.py

Scientific role
---------------
Step 10 compares the genuine longitudinal replicate-decoupled forward-drift
profile from Step 9 with the pseudo-longitudinal technical-null distribution
generated by Step 7.

The primary estimand is:

    E[Delta x_latent | x0]

using the replicate-decoupled:

    cross_combined

representation in both datasets.

The comparison preserves each dataset's native absolute latent-abundance
geometry. Step 10 does not impose common bin edges, convert abundance to ranks
or percentiles, or extrapolate outside observed support. Instead, already
estimated curves are compared on their shared absolute-abundance support.

This plotting script reads ONLY Step-10 outputs. It does not directly reload
Step-7 or Step-9 analysis directories and does not recompute the Step-10 shared
grid, empirical null metrics, or P-values.

The plotter does not:

    - interpolate native curves;
    - recompute shared support;
    - recalculate pseudo order/reverse metrics;
    - recompute empirical P-values;
    - modify the Step-10 comparison estimand;
    - redefine abundance geometry.

Position in the pipeline
------------------------
    Step 7 pseudo conditioning / ordering benchmark
                       \
                        \
                         v
                      Step 10
                         ^
                        /
                       /
    Step 9 genuine replicate-decoupled forward drift

Step 8 is not a direct input to Step 10.

Analysis input
--------------
Required:

    --analysis-dir

pointing to the output directory generated by:

    10-longitudinal_vs_pseudo_forward_drift.py

Required Step-10 tables
-----------------------
    01_native_forward_drift_curves.csv
        Native longitudinal and pseudo curves before shared-support
        interpolation.

    02_shared_support_grid.csv
        Primary pointwise genuine-versus-pseudo comparison on the shared
        absolute abundance grid.

    03_pseudo_overlap_null_metrics.csv
        One row per pseudo reverse-pair curve with shared-support summary
        metrics.

    04_empirical_tests.csv
        Precomputed empirical tests for slope, centered drift magnitude and
        mean offset.

    05_support_summary.csv
        Native and shared absolute-support metadata.

    09_comparison_summary.csv
        Manuscript-oriented Step-10 comparison summary.

Propagated Step-9 robustness tables
-----------------------------------
Step 10 also writes:

    06_longitudinal_fold_concordance.csv
    07_longitudinal_subject_drift.csv
    08_longitudinal_loso_drift.csv

These are carried forward for provenance and convenience. They are not
replotted here because the dedicated Step-9 plotter is the canonical
visualization layer for genuine-longitudinal robustness diagnostics.

Generated figures
-----------------
Main composite:

    00_main_longitudinal_vs_pseudo_forward_drift_ABC

        A  longitudinal forward drift versus pseudo median/95% envelope
        B  longitudinal slope relative to the pseudo empirical null
        C  longitudinal centered mean absolute drift relative to the pseudo null

Supplementary comparison composite:

    Sx_longitudinal_vs_pseudo_comparison_diagnostics

        A  native longitudinal and pseudo curves before shared-grid interpolation
        B  longitudinal-minus-pseudo drift on the shared grid
        C  centered RMS drift relative to the pseudo null
        D  mean drift offset relative to the pseudo null

Standalone figures:

    01_longitudinal_vs_pseudo_forward_drift
    02_slope_pseudo_null
    03_centered_mean_abs_drift_pseudo_null
    04_native_forward_drift_curves
    05_longitudinal_minus_pseudo
    06_centered_rms_drift_pseudo_null
    07_mean_drift_offset_pseudo_null

Non-figure outputs
------------------
Only graphical provenance is written:

    figure_manifest.csv
    plot_config.json

No new scientific summary or inferential table is produced by this plotter.

Rendering policy
----------------
Null-distribution figures use the already-computed values in:

    03_pseudo_overlap_null_metrics.csv

and the already-computed longitudinal statistic and empirical P-value in:

    04_empirical_tests.csv.

Random jitter, controlled by --seed, is used only to prevent overplotting of
points in the one-dimensional null-distribution display. It has no analytical
role.

Figure customization
--------------------
Edit:

    FIGURE_SIZES_INCHES

for per-figure dimensions in inches, and:

    AXIS_CONFIG

for per-panel:

    xlim
    ylim
    xscale
    yscale
    xtick_step
    ytick_step

Example
-------
python3 ./code/plotting/10-plot_longitudinal_vs_pseudo_forward_drift.py \
    --analysis-dir \
    ./comparison_results/10-longitudinal-vs-pseudo-forward-drift \
    --figures-dir ./figures/10-longitudinal-vs-pseudo-forward-drift \
    --formats pdf,png
"""

