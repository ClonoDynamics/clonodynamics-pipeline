def draw_shared_grid(
    ax: plt.Axes,
    shared: pd.DataFrame,
    line_width: float,
    marker_size: float,
    ci_alpha: float,
    axis_key: str,
) -> None:
    require_columns(
        shared,
        [
            "x",
            "longitudinal_mean_dx",
            "longitudinal_ci025",
            "longitudinal_ci975",
            "pseudo_median_dx",
            "pseudo_q025",
            "pseudo_q975",
        ],
        "02_shared_support_grid.csv",
    )
    d = shared.sort_values("x")
    x = pd.to_numeric(d["x"], errors="coerce").to_numpy(float)

    long_y = pd.to_numeric(d["longitudinal_mean_dx"], errors="coerce").to_numpy(float)
    long_lo = pd.to_numeric(d["longitudinal_ci025"], errors="coerce").to_numpy(float)
    long_hi = pd.to_numeric(d["longitudinal_ci975"], errors="coerce").to_numpy(float)
    pseudo_y = pd.to_numeric(d["pseudo_median_dx"], errors="coerce").to_numpy(float)
    pseudo_lo = pd.to_numeric(d["pseudo_q025"], errors="coerce").to_numpy(float)
    pseudo_hi = pd.to_numeric(d["pseudo_q975"], errors="coerce").to_numpy(float)

    ok_l = np.isfinite(x) & np.isfinite(long_y)
    line_l = ax.plot(
        x[ok_l], long_y[ok_l],
        marker="o", markersize=marker_size,
        linewidth=line_width, label="Longitudinal"
    )[0]
    ok_lci = np.isfinite(x) & np.isfinite(long_lo) & np.isfinite(long_hi)
    if ok_lci.any():
        ax.fill_between(
            x[ok_lci], long_lo[ok_lci], long_hi[ok_lci],
            color=line_l.get_color(), alpha=ci_alpha, linewidth=0
        )

    ok_p = np.isfinite(x) & np.isfinite(pseudo_y)
    line_p = ax.plot(
        x[ok_p], pseudo_y[ok_p],
        linewidth=line_width, label="Pseudo median"
    )[0]
    ok_pci = np.isfinite(x) & np.isfinite(pseudo_lo) & np.isfinite(pseudo_hi)
    if ok_pci.any():
        ax.fill_between(
            x[ok_pci], pseudo_lo[ok_pci], pseudo_hi[ok_pci],
            color=line_p.get_color(), alpha=ci_alpha, linewidth=0
        )

    ax.axhline(0.0, linewidth=0.8, linestyle="--", color="0.35")
    ax.set_xlabel(r"Initial latent abundance, $x_0$")
    ax.set_ylabel(r"Mean latent displacement")
    style_axes(ax)
    apply_axis_config(ax, axis_key)
    ax.legend(frameon=False)


def draw_null_distribution(
    ax: plt.Axes,
    pseudo_null: pd.DataFrame,
    tests: pd.DataFrame,
    metric: str,
    xlabel: str,
    axis_key: str,
    seed: int,
) -> None:
    require_columns(pseudo_null, [metric], "03_pseudo_overlap_null_metrics.csv")
    values = pd.to_numeric(pseudo_null[metric], errors="coerce").dropna().to_numpy(float)
    if values.size == 0:
        raise ValueError("No finite pseudo values for {}".format(metric))

    row = empirical_row(tests, metric)
    observed = float(pd.to_numeric(pd.Series([row["longitudinal_value"]]), errors="coerce").iloc[0])
    p = float(pd.to_numeric(pd.Series([row["empirical_p"]]), errors="coerce").iloc[0])

    rng = np.random.default_rng(int(seed))
    y = rng.normal(0.0, 0.035, size=values.size)
    ax.scatter(values, y, s=9, alpha=0.35, linewidths=0)
    ax.axvline(np.median(values), linewidth=1.0, linestyle="--", color="0.35", label="Pseudo median")
    ax.axvline(observed, linewidth=1.3, color="0.1", label="Longitudinal")

    ax.set_yticks([])
    ax.set_xlabel(xlabel)
    ax.set_ylabel("")
    style_axes(ax)
    apply_axis_config(ax, axis_key)
    annotation_box(ax, "{}\nn = {} pseudo curves".format(p_label(p), values.size))
    ax.legend(frameon=False, loc="best")


def draw_native_curves(
    ax: plt.Axes,
    native: pd.DataFrame,
    line_width: float,
    marker_size: float,
    axis_key: str,
) -> None:
    require_columns(
        native,
        ["dataset", "x_center", "mean_dx"],
        "01_native_forward_drift_curves.csv",
    )
    for dataset, label in [("longitudinal", "Longitudinal native"), ("pseudo", "Pseudo native")]:
        d = native.loc[native["dataset"].astype(str) == dataset].sort_values("x_center")
        if d.empty:
            continue
        x = pd.to_numeric(d["x_center"], errors="coerce").to_numpy(float)
        y = pd.to_numeric(d["mean_dx"], errors="coerce").to_numpy(float)
        ok = np.isfinite(x) & np.isfinite(y)
        if ok.any():
            ax.plot(
                x[ok], y[ok],
                marker="o", markersize=marker_size,
                linewidth=line_width, label=label
            )
    ax.axhline(0.0, linewidth=0.8, linestyle="--", color="0.35")
    ax.set_xlabel(r"Native absolute latent abundance, $x_0$")
    ax.set_ylabel(r"Mean latent displacement")
    style_axes(ax)
    apply_axis_config(ax, axis_key)
    ax.legend(frameon=False)


def draw_difference(
    ax: plt.Axes,
    shared: pd.DataFrame,
    line_width: float,
    marker_size: float,
    axis_key: str,
) -> None:
    require_columns(
        shared,
        ["x", "longitudinal_minus_pseudo"],
        "02_shared_support_grid.csv",
    )
    d = shared.sort_values("x")
    x = pd.to_numeric(d["x"], errors="coerce").to_numpy(float)
    y = pd.to_numeric(d["longitudinal_minus_pseudo"], errors="coerce").to_numpy(float)
    ok = np.isfinite(x) & np.isfinite(y)
    ax.plot(
        x[ok], y[ok],
        marker="o", markersize=marker_size,
        linewidth=line_width
    )
    ax.axhline(0.0, linewidth=0.8, linestyle="--", color="0.35")
    ax.set_xlabel(r"Shared latent abundance, $x_0$")
    ax.set_ylabel("Longitudinal − pseudo mean drift")
    style_axes(ax)
    apply_axis_config(ax, axis_key)


