def plot_core_coverage(
    p13: pd.DataFrame,
    core: Optional[pd.DataFrame],
    alphas: Sequence[float],
    reference_alpha: float,
    figdir: Path,
    tabledir: Path,
    args: argparse.Namespace,
    manifest: List[Dict[str, object]],
) -> None:
    data = normalize_alpha(p13)
    require_columns(
        data,
        ["alpha", "estimator", "metric", "bin_left", "bin_right"],
        "P13 model comparison",
    )
    data = data[
        (data["estimator"].astype(str) == str(args.primary_estimator))
        & (data["metric"].astype(str) == "var_dx")
    ].copy()
    rows = []
    for alpha in alphas:
        d = data[np.isclose(data["alpha"], alpha, rtol=0, atol=1e-12)]
        if d.empty:
            continue
        rows.append(
            {
                "alpha": alpha,
                "x_min": pd.to_numeric(d["bin_left"], errors="coerce").min(),
                "x_max": pd.to_numeric(d["bin_right"], errors="coerce").max(),
            }
        )
    coverage = pd.DataFrame(rows).dropna()
    if coverage.empty:
        return

    coverage.to_csv(tabledir / "08_cross_alpha_core_coverage.csv", index=False)

    common_min = None
    common_max = None
    if core is not None and not core.empty:
        if {"bin_left", "bin_right"}.issubset(core.columns):
            common_min = pd.to_numeric(core["bin_left"], errors="coerce").min()
            common_max = pd.to_numeric(core["bin_right"], errors="coerce").max()

    fig, ax = plt.subplots(figsize=(args.width, args.height))
    positions = np.arange(len(alphas))
    index = {float(alpha): i for i, alpha in enumerate(alphas)}
    for row in coverage.itertuples(index=False):
        y = index.get(float(row.alpha))
        if y is None:
            continue
        ax.hlines(y, row.x_min, row.x_max, linewidth=2.0)
        ax.plot([row.x_min, row.x_max], [y, y], marker="|", linestyle="None")
    if common_min is not None and math.isfinite(float(common_min)):
        ax.axvline(common_min, linestyle="--", linewidth=0.8)
    if common_max is not None and math.isfinite(float(common_max)):
        ax.axvline(common_max, linestyle="--", linewidth=0.8)
    ax.set_yticks(positions)
    ax.set_yticklabels([alpha_label(a, reference_alpha) for a in alphas])
    ax.set_xlabel(r"Transition-centred latent abundance, $x_\star$")
    ax.set_ylabel(r"Operational $\alpha$")
    style_axes(ax)
    save_figure(
        fig,
        figdir,
        "12_cross_alpha_temporal_core_coverage",
        args,
        manifest,
        "cross_alpha_core_coverage",
    )


