def formats(args: argparse.Namespace) -> List[str]:
    values = [v.lower() for v in parse_csv_strings(args.formats)]
    allowed = {"pdf", "png", "svg"}
    bad = sorted(set(values) - allowed)
    if bad:
        raise ValueError("Unsupported formats: {}".format(bad))
    return list(dict.fromkeys(values or ["pdf"]))


def save_figure(
    fig,
    figdir: Path,
    stem: str,
    args: argparse.Namespace,
    manifest: List[Dict[str, object]],
    family: str,
    metric: str = "",
    dt: Optional[int] = None,
) -> None:
    figdir.mkdir(parents=True, exist_ok=True)
    for fmt in formats(args):
        path = figdir / "{}.{}".format(stem, fmt)
        fig.savefig(path, dpi=args.dpi, bbox_inches="tight")
        manifest.append(
            {
                "filename": path.name,
                "family": family,
                "metric": metric,
                "dt": "" if dt is None else int(dt),
                "format": fmt,
            }
        )
    plt.close(fig)


