def pooled_class_composition(frame: pd.DataFrame) -> pd.DataFrame:
    require_columns(frame, ["alpha", "obs_class", "n_transitions"], "class composition")
    data = numeric(frame, ["alpha", "n_transitions"])
    pooled = (
        data.groupby(["alpha", "obs_class"], as_index=False)["n_transitions"]
        .sum()
        .sort_values(["alpha", "obs_class"])
    )
    pooled["fraction"] = (
        pooled["n_transitions"]
        / pooled.groupby("alpha")["n_transitions"].transform("sum")
    )
    return pooled


def filter_alpha_order(
    frame: pd.DataFrame,
    alphas: Sequence[float],
) -> pd.DataFrame:
    data = normalize_alpha(frame)
    mask = np.zeros(len(data), dtype=bool)
    for alpha in alphas:
        mask |= np.isclose(
            data["alpha"].to_numpy(float),
            float(alpha),
            rtol=0.0,
            atol=1e-12,
        )
    return data.loc[mask].copy()


def derive_p09_differences(
    frame: pd.DataFrame,
    reference_alpha: float,
    metrics: Sequence[str],
) -> pd.DataFrame:
    data = filter_alpha_order(frame, sorted(frame["alpha"].dropna().unique(), reverse=True))
    require_columns(data, ["alpha", "bin", "x_center"], "P09 combined curves")
    ref = data[np.isclose(data["alpha"], reference_alpha, rtol=0, atol=1e-12)]
    rows = []
    for alpha in sorted(data["alpha"].dropna().unique(), reverse=True):
        current = data[np.isclose(data["alpha"], alpha, rtol=0, atol=1e-12)]
        for metric in metrics:
            if metric not in data.columns:
                continue
            left = current[["bin", "x_center", metric]].rename(columns={metric: "value"})
            right = ref[["bin", metric]].rename(columns={metric: "reference_value"})
            joined = left.merge(right, on="bin", how="inner")
            joined = numeric(joined, ["x_center", "value", "reference_value"]).dropna(
                subset=["x_center", "value", "reference_value"]
            )
            if joined.empty:
                continue
            joined["difference"] = joined["value"] - joined["reference_value"]
            joined["alpha"] = float(alpha)
            joined["reference_alpha"] = float(reference_alpha)
            joined["metric"] = metric
            rows.append(joined)
    return pd.concat(rows, ignore_index=True) if rows else pd.DataFrame()


def derive_p11_differences(
    frame: pd.DataFrame,
    reference_alpha: float,
    metrics: Sequence[str],
) -> pd.DataFrame:
    data = normalize_alpha(frame)
    require_columns(data, ["alpha", "dt", "bin_id", "bin_mid"], "P11 combined curves")
    ref = data[np.isclose(data["alpha"], reference_alpha, rtol=0, atol=1e-12)]
    rows = []
    for alpha in sorted(data["alpha"].dropna().unique(), reverse=True):
        current = data[np.isclose(data["alpha"], alpha, rtol=0, atol=1e-12)]
        for metric in metrics:
            if metric not in data.columns:
                continue
            left = current[["dt", "bin_id", "bin_mid", metric]].rename(
                columns={metric: "value"}
            )
            right = ref[["dt", "bin_id", metric]].rename(
                columns={metric: "reference_value"}
            )
            joined = left.merge(right, on=["dt", "bin_id"], how="inner")
            joined = numeric(
                joined, ["dt", "bin_id", "bin_mid", "value", "reference_value"]
            ).dropna(
                subset=["dt", "bin_id", "bin_mid", "value", "reference_value"]
            )
            if joined.empty:
                continue
            joined["difference"] = joined["value"] - joined["reference_value"]
            joined["alpha"] = float(alpha)
            joined["reference_alpha"] = float(reference_alpha)
            joined["metric"] = metric
            rows.append(joined)
    return pd.concat(rows, ignore_index=True) if rows else pd.DataFrame()


def resolve_core_bins(
    core: Optional[pd.DataFrame],
    p13: Optional[pd.DataFrame],
    p11: Optional[pd.DataFrame],
    alphas: Sequence[float],
) -> List[int]:
    if core is not None and not core.empty and "bin_id" in core.columns:
        values = pd.to_numeric(core["bin_id"], errors="coerce").dropna().astype(int)
        if not values.empty:
            return sorted(set(values.tolist()))

    source = p13 if p13 is not None and not p13.empty else p11
    if source is None or source.empty or "bin_id" not in source.columns:
        return []

    data = normalize_alpha(source)
    data["bin_id"] = pd.to_numeric(data["bin_id"], errors="coerce")
    data = data.dropna(subset=["bin_id"]).copy()
    data["bin_id"] = data["bin_id"].astype(int)

    sets: List[set] = []
    for alpha in alphas:
        subset = data[np.isclose(data["alpha"], alpha, rtol=0, atol=1e-12)]
        bins = set(subset["bin_id"].unique().tolist())
        if bins:
            sets.append(bins)
    if not sets:
        return []
    common = sorted(set.intersection(*sets))
    if not common:
        return []

    runs: List[List[int]] = []
    current = [common[0]]
    for value in common[1:]:
        if value == current[-1] + 1:
            current.append(value)
        else:
            runs.append(current)
            current = [value]
    runs.append(current)
    runs.sort(key=lambda run: (len(run), -run[0]), reverse=True)
    return runs[0]


