def plot_class_composition(
    pooled: pd.DataFrame,
    alphas: Sequence[float],
    reference_alpha: float,
    figdir: Path,
    tabledir: Path,
    args: argparse.Namespace,
    manifest: List[Dict[str, object]],
) -> None:
    tabledir.mkdir(parents=True, exist_ok=True)
    pooled.to_csv(tabledir / "01_class_composition_pooled.csv", index=False)

    fig, ax = plt.subplots(figsize=(args.width, args.height))
    classes = [v for v in ("TT", "TF", "FT", "FF") if v in set(pooled["obs_class"])]
    for obs_class in classes:
        d = pooled[pooled["obs_class"] == obs_class].sort_values("alpha")
        ax.plot(
            d["alpha"],
            d["fraction"],
            marker="o",
            linewidth=args.line_width,
            markersize=args.marker_size,
            label=obs_class,
        )
    ax.axvline(reference_alpha, linestyle="--", linewidth=0.8)
    ax.set_xlabel(r"Operational observation threshold, $\alpha$")
    ax.set_ylabel("Fraction of transitions")
    ax.set_ylim(0, 1)
