def read_json(path: Path) -> Dict[str, object]:
    if not path.exists():
        return {}
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception as exc:
        warnings.warn("Could not read {}: {}".format(path, exc))
        return {}


def find_table(
    folder: Path,
    stems: Union[Sequence[str], str],
    required: bool = False,
) -> Optional[Path]:
    if isinstance(stems, str):
        stems = [stems]
    for stem in stems:
        for suffix in (".parquet", ".pq", ".csv", ".tsv", ".txt"):
            path = folder / "{}{}".format(stem, suffix)
            if path.exists():
                return path
    if required:
        raise FileNotFoundError(
            "Could not find any of {} in {}".format(list(stems), folder)
        )
    return None


def read_table(path: Path) -> pd.DataFrame:
    suffix = path.suffix.lower()
    if suffix == ".csv":
        return pd.read_csv(path)
    if suffix in {".tsv", ".txt"}:
        return pd.read_csv(path, sep="\t")
    if suffix in {".parquet", ".pq"}:
        try:
            return pd.read_parquet(path)
        except Exception as pandas_error:
            try:
                import polars as pl  # type: ignore
                return pl.read_parquet(path).to_pandas()
            except Exception as polars_error:
                csv_fallback = path.with_suffix(".csv")
                if csv_fallback.exists():
                    warnings.warn(
                        "Could not read parquet {}; using {}.".format(
                            path, csv_fallback
                        )
                    )
                    return pd.read_csv(csv_fallback)
                raise RuntimeError(
                    "Could not read {}. pandas: {}; polars: {}".format(
                        path, pandas_error, polars_error
                    )
                )
    raise ValueError("Unsupported table format: {}".format(path))


def require_columns(
    frame: pd.DataFrame,
    columns: Sequence[str],
    label: str,
) -> None:
    missing = [c for c in columns if c not in frame.columns]
    if missing:
        raise ValueError(
            "{} is missing required columns {}. Available: {}".format(
                label, missing, list(frame.columns)
            )
        )


def numeric(frame: pd.DataFrame, columns: Sequence[str]) -> pd.DataFrame:
    out = frame.copy()
    for column in columns:
        if column in out.columns:
            out[column] = pd.to_numeric(out[column], errors="coerce")
    return out.replace([np.inf, -np.inf], np.nan)


def alpha_close(a: float, b: float, tol: float = 1e-12) -> bool:
    return abs(float(a) - float(b)) <= tol


def alpha_label(alpha: float, reference_alpha: float) -> str:
    text = "{:g}".format(float(alpha))
    return "{} (reference)".format(text) if alpha_close(alpha, reference_alpha) else text


def alpha_tag(alpha: float) -> str:
    return "{:g}".format(float(alpha)).replace(".", "p").replace("-", "m")


def resolve_alpha_column(frame: pd.DataFrame) -> str:
    for column in ("alpha", "observation_alpha", "detectability_alpha"):
        if column in frame.columns:
            return column
    raise ValueError(
        "No alpha column found; expected alpha, observation_alpha or detectability_alpha."
    )


def normalize_alpha(frame: pd.DataFrame) -> pd.DataFrame:
    out = frame.copy()
    source = resolve_alpha_column(out)
    out["alpha"] = pd.to_numeric(out[source], errors="coerce")
    return out.dropna(subset=["alpha"])


def resolve_alphas(
    args: argparse.Namespace,
    config: Dict[str, object],
    frames: Sequence[Optional[pd.DataFrame]],
) -> List[float]:
    explicit = parse_csv_floats(args.alphas)
    if explicit:
        return list(dict.fromkeys(explicit))

    raw = config.get("alphas", None)
    if isinstance(raw, (list, tuple)):
        values = []
        for value in raw:
            try:
                number = float(value)
            except Exception:
                continue
            if math.isfinite(number):
                values.append(number)
        if values:
            return list(dict.fromkeys(values))

    found: List[float] = []
    for frame in frames:
        if frame is None or frame.empty:
            continue
        try:
            source = resolve_alpha_column(frame)
        except ValueError:
            continue
        values = pd.to_numeric(frame[source], errors="coerce").dropna().tolist()
        found.extend(float(v) for v in values if math.isfinite(float(v)))

    if found:
        return sorted(set(found), reverse=True)
    return list(DEFAULT_ALPHAS)


def resolve_reference_alpha(
    args: argparse.Namespace,
    config: Dict[str, object],
    alphas: Sequence[float],
) -> float:
    if args.reference_alpha is not None:
        reference = float(args.reference_alpha)
    else:
        try:
            reference = float(config.get("reference_alpha", 0.05))
        except Exception:
            reference = 0.05

    if not any(alpha_close(reference, alpha) for alpha in alphas):
        raise ValueError(
            "Reference alpha {} is not in selected alphas {}.".format(
                reference, list(alphas)
            )
        )
    return reference


def resolve_dts(
    args: argparse.Namespace,
    config: Dict[str, object],
    p11: Optional[pd.DataFrame],
) -> List[int]:
    explicit = parse_csv_ints(args.dt_values)
    if explicit:
        return sorted(set(explicit))

    raw = config.get("selected_dt", None)
    if isinstance(raw, (list, tuple)):
        values = []
        for value in raw:
            try:
                values.append(int(value))
            except Exception:
                pass
        if values:
            return sorted(set(values))

    if p11 is not None and "dt" in p11.columns:
        return sorted(
            set(
                pd.to_numeric(p11["dt"], errors="coerce")
                .dropna()
                .astype(int)
                .tolist()
            )
        )
    return [1, 2, 3, 4, 5]


