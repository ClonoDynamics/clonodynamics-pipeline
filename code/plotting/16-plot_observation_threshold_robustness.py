def maybe_ci(
    ax,
    data: pd.DataFrame,
    x_col: str,
    low_col: str,
    high_col: str,
    alpha: float,
    reference_alpha: float,
    args: argparse.Namespace,
    line,
) -> None:
    if args.ci_mode == "none":
        return
    if args.ci_mode == "reference" and not alpha_close(alpha, reference_alpha):
        return
    if low_col not in data.columns or high_col not in data.columns:
        return

    x = pd.to_numeric(data[x_col], errors="coerce").to_numpy(float)
    low = pd.to_numeric(data[low_col], errors="coerce").to_numpy(float)
    high = pd.to_numeric(data[high_col], errors="coerce").to_numpy(float)
    valid = np.isfinite(x) & np.isfinite(low) & np.isfinite(high)
    if valid.any():
        ax.fill_between(
            x[valid],
            low[valid],
            high[valid],
            alpha=0.12,
            linewidth=0,
            color=line.get_color(),
        )


def padded_limits(
    values: Iterable[float],
    padding: float,
    include: Sequence[float] = (),
    hard: Optional[Tuple[float, float]] = None,
) -> Tuple[float, float]:
    array = np.asarray(list(values), dtype=float)
    array = array[np.isfinite(array)]
    extra = np.asarray([v for v in include if math.isfinite(float(v))], dtype=float)
    if extra.size:
        array = np.concatenate([array, extra]) if array.size else extra

    if not array.size:
        low, high = 0.0, 1.0
    else:
        low = float(np.min(array))
        high = float(np.max(array))
        span = high - low
        if span <= 0:
            span = max(abs(low), abs(high), 1.0)
        low -= span * padding
        high += span * padding

    if hard is not None:
        low = max(low, hard[0])
        high = min(high, hard[1])
    if high <= low:
        high = low + 1.0
    return low, high


