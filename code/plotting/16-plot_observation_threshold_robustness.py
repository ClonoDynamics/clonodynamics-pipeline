"""
16-plot_observation_threshold_robustness.py
===========================================

Paper-oriented plotter for ClonoDynamics P16 operational observation-threshold
robustness.

The plotter reads only outputs generated by:

    16-analyze_observation_threshold_robustness.py

It does not reclassify endpoint states, rerun P09/P11/P13, reconstruct
transitions, refit temporal models, or modify inferential quantities.

Scientific scope
----------------
P16 varies the empirical lower-tail threshold used to define the binary
operational observation state:

    T(alpha) = 1[p_endpoint < alpha]
    F(alpha) = 1[p_endpoint >= alpha]

The default alpha sweep is:

    0.10, 0.05, 0.025, 0.01

with alpha = 0.05 as the reference.

This is not a sensitivity analysis of posterior-predictive detectability and
T/F must not be interpreted as biological presence/absence.

Expected P16 inputs
-------------------
Required for the basic threshold-domain figures:
    00_run_config.json
    03_class_composition_by_alpha_dt.csv
    06_tt_retention_by_alpha.csv

Generated when P09 was run:
    15_combined_p09_forward_drift_by_bin.csv/parquet

Generated when P11 was run:
    09_combined_p11_binned_dynamics.csv/parquet
or compatibility alias:
    09_combined_step5_binned_dynamics.csv/parquet

Generated when P13 was run:
    12_combined_p13_model_comparison_by_bin.csv/parquet
or compatibility alias:
    12_combined_step51_model_comparison_by_bin.csv/parquet

Preferred common temporal core:
    14_cross_alpha_common_core.csv

Figure families
---------------
01  Pooled TT/TF/FT/FF composition across alpha
02  TT retention relative to reference alpha
03  P09 cross-alpha forward mean displacement
04  P09 cross-alpha positive-displacement probability
05  P09 non-reference minus reference forward differences
06  P11 cross-alpha conditional variance by temporal lag
07  P11 cross-alpha MSD by temporal lag
08  P11 non-reference minus reference fluctuation differences
09  P13 cross-alpha constant-model preference
10  P13 cross-alpha signed-linear slopes with bootstrap intervals
11  P13 cross-alpha positive-incremental slopes [optional]
12  Cross-alpha temporal-core coverage [when available]

Design principles
-----------------
- English labels.
- Arial by default.
- One figure per file; no multi-panel subplots.
- Legends outside by default.
- Reference-alpha confidence bands can be shown without overplotting all bands.
- Missing optional inputs are skipped with explicit warnings.
- The exact cross-alpha P13 core is read from P16 outputs; it is never hard-coded.

Python >= 3.9
Required: numpy, pandas, matplotlib
"""

