def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
        description="Plot ClonoDynamics Step-9 replicate-decoupled forward-drift outputs.",
    )
    parser.add_argument(
        "--analysis-dir",
        required=True,
        type=Path,
        help="Output directory produced by 9-replicate_decoupled_forward_drift.py.",
    )
    parser.add_argument(
        "--figures-dir",
        type=Path,
        default=None,
        help=(
            "Figure output directory. Default: "
            "<analysis-dir>/figures_replicate_decoupled_forward_drift"
        ),
    )
    parser.add_argument(
        "--figure-set",
        choices=["all", "main", "supplementary", "standalone"],
        default="all",
    )
    parser.add_argument("--formats", default="pdf,png")
    parser.add_argument("--dpi", type=int, default=PLOT_STYLE_DEFAULTS["dpi"])
    parser.add_argument("--font-size", type=float, default=PLOT_STYLE_DEFAULTS["font_size"])
    parser.add_argument("--line-width", type=float, default=PLOT_STYLE_DEFAULTS["line_width"])
    parser.add_argument("--marker-size", type=float, default=PLOT_STYLE_DEFAULTS["marker_size"])
    parser.add_argument("--ci-alpha", type=float, default=PLOT_STYLE_DEFAULTS["ci_alpha"])
    parser.add_argument(
        "--subject-min-n",
        type=int,
        default=20,
        help="Display-only minimum n required in BOTH AB and BA for a subject/bin.",
    )
    return parser


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = build_parser().parse_args(argv)

    analysis_dir = args.analysis_dir.expanduser().resolve()
    if not analysis_dir.is_dir():
        raise NotADirectoryError(analysis_dir)

    figures_dir = (
        args.figures_dir.expanduser().resolve()
        if args.figures_dir is not None
        else analysis_dir / "figures_replicate_decoupled_forward_drift"
    )
    figures_dir.mkdir(parents=True, exist_ok=True)

    formats = parse_formats(args.formats)
    font_used = setup_style(args.font_size)
    tables = load_tables(analysis_dir)

    written: List[Path] = []

    if args.figure_set in {"all", "main"}:
        written.extend(plot_main(tables, figures_dir, formats, args))

    if args.figure_set in {"all", "supplementary"}:
        written.extend(plot_supplementary(tables, figures_dir, formats, args))

    if args.figure_set in {"all", "standalone"}:
        written.extend(plot_standalones(tables, figures_dir, formats, args))

    manifest = pd.DataFrame(
        {
            "file": [p.name for p in written],
            "figure": [p.stem for p in written],
            "format": [p.suffix.lstrip(".") for p in written],
        }
    )
    manifest.to_csv(figures_dir / "figure_manifest.csv", index=False)

    config = {
        "script": Path(__file__).name,
        "script_version": SCRIPT_VERSION,
        "analysis_source": "9-replicate_decoupled_forward_drift.py",
        "analysis_dir": str(analysis_dir),
        "figures_dir": str(figures_dir),
        "figure_set": args.figure_set,
        "formats": formats,
        "dpi": int(args.dpi),
        "font_size": float(args.font_size),
        "font_family_used": font_used,
        "line_width": float(args.line_width),
        "marker_size": float(args.marker_size),
        "ci_alpha": float(args.ci_alpha),
        "subject_min_n_display_only": int(args.subject_min_n),
        "primary_representation": PRIMARY_REPRESENTATION,
        "figure_sizes_inches": FIGURE_SIZES_INCHES,
        "axis_config": AXIS_CONFIG,
        "analysis_recomputed": False,
    }
    (figures_dir / "plot_config.json").write_text(
        json.dumps(config, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )

    print("[DONE] Step-9 plotting complete")
    print("[INFO] Analysis: {}".format(analysis_dir))
    print("[INFO] Figures: {}".format(figures_dir))
    print("[INFO] {} rendered files".format(len(written)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
