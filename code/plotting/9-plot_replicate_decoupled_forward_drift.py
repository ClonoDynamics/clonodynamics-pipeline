def draw_primary_curve(
    ax: plt.Axes,
    by_bin: pd.DataFrame,
    line_width: float,
    marker_size: float,
    ci_alpha: float,
    axis_key: str,
) -> None:
    d = cohort_curve(by_bin)
    x, y = finite_xy(d, "x_center", "mean_dx")
    line = ax.plot(
        x, y, marker="o", markersize=marker_size,
        linewidth=line_width, label="cross_combined"
    )[0]

    if {"mean_dx_ci025", "mean_dx_ci975"}.issubset(d.columns):
        low = pd.to_numeric(d["mean_dx_ci025"], errors="coerce").to_numpy(float)
        high = pd.to_numeric(d["mean_dx_ci975"], errors="coerce").to_numpy(float)
        xx = pd.to_numeric(d["x_center"], errors="coerce").to_numpy(float)
        ok = np.isfinite(xx) & np.isfinite(low) & np.isfinite(high)
        if ok.any():
            ax.fill_between(
                xx[ok], low[ok], high[ok],
                color=line.get_color(), alpha=ci_alpha, linewidth=0
            )

    ax.axhline(0.0, linewidth=0.8, linestyle="--", color="0.35")
    ax.set_xlabel(r"Initial latent abundance, $x_0$")
    ax.set_ylabel(r"Mean latent displacement")
    style_axes(ax)
    apply_axis_config(ax, axis_key)


def draw_ab_ba(
    ax: plt.Axes,
    by_fold: pd.DataFrame,
    concordance: pd.DataFrame,
    line_width: float,
    marker_size: float,
    axis_key: str,
) -> None:
    for representation, label in [("cross_AB", "AB"), ("cross_BA", "BA")]:
        d = fold_curve(by_fold, representation)
        x, y = finite_xy(d, "x_center", "mean_dx")
        ax.plot(
            x, y, marker="o", markersize=marker_size,
            linewidth=line_width, label=label
        )

    ax.axhline(0.0, linewidth=0.8, linestyle="--", color="0.35")
    ax.set_xlabel(r"Initial latent abundance, $x_0$")
    ax.set_ylabel(r"Mean latent displacement")
    style_axes(ax)
    apply_axis_config(ax, axis_key)
    ax.legend(frameon=False)

    if not concordance.empty:
        row = concordance.iloc[0]
        r = pd.to_numeric(pd.Series([row.get("pearson_r_AB_BA")]), errors="coerce").iloc[0]
        n = pd.to_numeric(pd.Series([row.get("n_matched_bins")]), errors="coerce").iloc[0]
        if np.isfinite(r):
            annotation_box(
                ax,
                "AB/BA Pearson r = {:.3f}\nmatched bins = {}".format(
                    float(r), int(n) if np.isfinite(n) else "NA"
                ),
            )


def matched_same_cross(matched: pd.DataFrame) -> pd.DataFrame:
    require_columns(
        matched,
        ["bin", "x_center", "mean_dx_same", "mean_dx_cross"],
        "forward_drift_matched_same_vs_cross.csv",
    )
    return (
        matched.groupby(["bin", "x_center"], as_index=False)
        .agg(
            mean_dx_same=("mean_dx_same", "mean"),
            mean_dx_cross=("mean_dx_cross", "mean"),
        )
        .sort_values("x_center")
    )


def draw_same_cross(
    ax: plt.Axes,
    matched: pd.DataFrame,
    line_width: float,
    marker_size: float,
    axis_key: str,
) -> None:
    d = matched_same_cross(matched)
    ax.plot(
        d["x_center"], d["mean_dx_same"],
        marker="o", markersize=marker_size,
        linewidth=line_width, label="Same-replicate"
    )
    ax.plot(
        d["x_center"], d["mean_dx_cross"],
        marker="o", markersize=marker_size,
        linewidth=line_width, label="Replicate-decoupled"
    )
    ax.axhline(0.0, linewidth=0.8, linestyle="--", color="0.35")
    ax.set_xlabel(r"Initial latent abundance, $x_0$")
    ax.set_ylabel(r"Mean latent displacement")
    style_axes(ax)
    apply_axis_config(ax, axis_key)
    ax.legend(frameon=False)


def draw_mean_median_sensitivity(
    ax: plt.Axes,
    by_bin: pd.DataFrame,
    sensitivity: pd.DataFrame,
    line_width: float,
    marker_size: float,
    axis_key: str,
) -> bool:
    primary = cohort_curve(by_bin)
    median = combined_fold_curve(
        sensitivity,
        ["cross_median_AB", "cross_median_BA"],
    )
    if median.empty:
        ax.axis("off")
        ax.text(
            0.5, 0.5,
            "Posterior-median sensitivity\nnot available",
            ha="center", va="center", transform=ax.transAxes
        )
        return False

    ax.plot(
        primary["x_center"], primary["mean_dx"],
        marker="o", markersize=marker_size,
        linewidth=line_width, label="Posterior-mean outcome"
    )
    ax.plot(
        median["x_center"], median["mean_dx"],
        marker="o", markersize=marker_size,
        linewidth=line_width, label="Posterior-median outcome"
    )
    ax.axhline(0.0, linewidth=0.8, linestyle="--", color="0.35")
    ax.set_xlabel(r"Initial latent abundance, $x_0$")
    ax.set_ylabel(r"Mean latent displacement")
    style_axes(ax)
    apply_axis_config(ax, axis_key)
    ax.legend(frameon=False)
    return True


def draw_subjects(
    ax: plt.Axes,
    subjects: pd.DataFrame,
    by_bin: pd.DataFrame,
    subject_min_n: int,
    line_width: float,
    marker_size: float,
    axis_key: str,
) -> None:
    require_columns(
        subjects,
        ["subject", "representation", "x_center", "mean_dx", "n_AB", "n_BA"],
        "forward_drift_subject_by_bin.csv",
    )
    d = subjects.loc[subjects["representation"].astype(str) == PRIMARY_REPRESENTATION].copy()
    d["n_AB"] = pd.to_numeric(d["n_AB"], errors="coerce")
    d["n_BA"] = pd.to_numeric(d["n_BA"], errors="coerce")
    if subject_min_n > 0:
        d = d.loc[(d["n_AB"] >= subject_min_n) & (d["n_BA"] >= subject_min_n)].copy()

    subjects_present = sorted(d["subject"].dropna().unique().tolist(), key=lambda x: str(x))
    first = True
    for subject in subjects_present:
        s = d.loc[d["subject"] == subject].sort_values("x_center")
        x, y = finite_xy(s, "x_center", "mean_dx")
        if x.size == 0:
            continue
        ax.plot(
            x, y,
            linewidth=max(line_width * 0.65, 0.5),
            marker="o",
            markersize=max(marker_size * 0.55, 1.0),
            alpha=0.5,
            label="Individual subjects" if first else "_nolegend_",
        )
        first = False

    cohort = cohort_curve(by_bin)
    x, y = finite_xy(cohort, "x_center", "mean_dx")
    ax.plot(x, y, linewidth=max(line_width * 1.4, 1.2), color="0.1", label="Cohort")

    ax.axhline(0.0, linewidth=0.8, linestyle="--", color="0.35")
    ax.set_xlabel(r"Initial latent abundance, $x_0$")
    ax.set_ylabel(r"Mean latent displacement")
    style_axes(ax)
    apply_axis_config(ax, axis_key)
    annotation_box(ax, "Displayed subjects = {}".format(len(subjects_present)))
    ax.legend(frameon=False)


