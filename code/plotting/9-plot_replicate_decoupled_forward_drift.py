def read_required(path: Path) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError("Required Step-9 table not found: {}".format(path))
    df = pd.read_csv(path)
    if df.empty:
        raise ValueError("Required Step-9 table is empty: {}".format(path))
    return df


def read_optional(path: Path) -> pd.DataFrame:
    if not path.exists():
        return pd.DataFrame()
    return pd.read_csv(path)


def load_tables(analysis_dir: Path) -> Dict[str, pd.DataFrame]:
    tables = {
        key: read_required(analysis_dir / filename)
        for key, filename in REQUIRED_FILES.items()
    }
    tables.update(
        {
            key: read_optional(analysis_dir / filename)
            for key, filename in OPTIONAL_FILES.items()
        }
    )
    return tables


def require_columns(df: pd.DataFrame, columns: Sequence[str], label: str) -> None:
    missing = [c for c in columns if c not in df.columns]
    if missing:
        raise ValueError(
            "{} missing required columns {}. Available: {}".format(
                label, missing, list(df.columns)
            )
        )


def finite_xy(df: pd.DataFrame, x_col: str, y_col: str) -> Tuple[np.ndarray, np.ndarray]:
    x = pd.to_numeric(df[x_col], errors="coerce").to_numpy(float)
    y = pd.to_numeric(df[y_col], errors="coerce").to_numpy(float)
    keep = np.isfinite(x) & np.isfinite(y)
    return x[keep], y[keep]


def parse_formats(text: str) -> List[str]:
    values = [v.strip().lower() for v in str(text).split(",") if v.strip()]
    allowed = {"pdf", "png", "svg"}
    invalid = [v for v in values if v not in allowed]
    if invalid:
        raise ValueError("Unsupported formats: {}".format(invalid))
    out: List[str] = []
    for value in values:
        if value not in out:
            out.append(value)
    if not out:
        raise ValueError("At least one output format is required.")
    return out


def save_figure(
    fig: plt.Figure,
    outdir: Path,
    stem: str,
    formats: Sequence[str],
    dpi: int,
) -> List[Path]:
    outdir.mkdir(parents=True, exist_ok=True)
    written: List[Path] = []
    for fmt in formats:
        path = outdir / "{}.{}".format(stem, fmt)
        kwargs = {"bbox_inches": "tight", "pad_inches": 0.04}
        if fmt == "png":
            kwargs["dpi"] = int(dpi)
        fig.savefig(path, **kwargs)
        written.append(path)
        print("[SAVED] {}".format(path))
    plt.close(fig)
    return written


def cohort_curve(by_bin: pd.DataFrame, representation: str = PRIMARY_REPRESENTATION) -> pd.DataFrame:
    require_columns(by_bin, ["representation", "x_center", "mean_dx"], "forward_drift_by_bin.csv")
    d = by_bin.loc[by_bin["representation"].astype(str) == representation].copy()
    if d.empty:
        raise ValueError("{} not found in forward_drift_by_bin.csv".format(representation))
    return d.sort_values("x_center")


def fold_curve(by_fold: pd.DataFrame, representation: str) -> pd.DataFrame:
    require_columns(by_fold, ["representation", "x_center", "mean_dx"], "forward_drift_by_fold.csv")
    d = by_fold.loc[by_fold["representation"].astype(str) == representation].copy()
    if d.empty:
        raise ValueError("{} not found in forward_drift_by_fold.csv".format(representation))
    return d.sort_values("x_center")


def combined_fold_curve(
    table: pd.DataFrame,
    representations: Sequence[str],
) -> pd.DataFrame:
    require_columns(table, ["representation", "bin", "x_center", "mean_dx"], "fold sensitivity table")
    d = table.loc[table["representation"].astype(str).isin(list(representations))].copy()
    if d.empty:
        return pd.DataFrame()
    return (
        d.groupby(["bin", "x_center"], as_index=False)["mean_dx"]
        .mean()
        .sort_values("x_center")
    )


