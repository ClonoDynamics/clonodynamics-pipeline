# -*- coding: utf-8 -*-

"""
6-plot_latent_transition_dataset_characterization.py
====================================================

Plot-only companion to ClonoDynamics Step 6:

    6-latent_transition_dataset_characterization.py

Purpose
-------
Visualize the descriptive structure of the longitudinal latent-transition
dataset generated by Step 5 and summarized by Step 6.

The plotter performs no transition reconstruction, no re-thresholding of
detectability, no posterior filtering and no dynamical inference. It reads
only already-generated Step-6 summary tables.

Required analysis inputs
------------------------
--analysis-dir must contain:

    02_subject_interval_coverage.csv
    04_coverage_summary_by_dt.csv
    06_observation_class_composition_by_dt.csv
    07_observation_class_composition_overall.csv

Optional, for audit only:

    08_propagated_field_completeness.csv
    09_dataset_overview.csv

Generated figures
-----------------
Single panels:

    S2A_longitudinal_coverage_by_dt
    S2B_subject_interval_coverage_heatmap
    S2C_observation_class_composition_by_dt

Combined manuscript supplementary figure:

    Supplementary_Figure_S2_transition_dataset_characterization

Panel definitions
-----------------
A
    Total transition rows and contributing subject-specific interval pairs
    across temporal lags.

B
    Number of transitions for each subject x nominal interval pair, displayed
    as log10(n transitions + 1).

C
    Relative TT / TF / FT / FF transition composition across temporal lags.
    Transition classes are inherited unchanged from Step 5.

Figure customization
--------------------
Edit FIGURE_SIZES_INCHES and AXIS_CONFIG near the top of this file to adjust
individual panel geometry or axis ranges without touching plotting logic.

Example
-------
python3 ./code/plotting/6-plot_latent_transition_dataset_characterization.py \
    --analysis-dir \
    ./dataset_longitudinal_clonodynamics_results/longitudinal/6-latent_transition_dataset_characterization \
    --figures-dir \
    ./dataset_longitudinal_clonodynamics_results/longitudinal/6-latent_transition_dataset_characterization/figures \
    --png
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd


OBS_CLASSES = ("TT", "TF", "FT", "FF")

FIGURE_SIZES_INCHES = {
    "S2A_longitudinal_coverage_by_dt": (4.6, 2.8),
    "S2B_subject_interval_coverage_heatmap": (7.0, 3.4),
    "S2C_observation_class_composition_by_dt": (4.6, 2.8),
    "Supplementary_Figure_S2_transition_dataset_characterization": (7.2, 6.2),
}

AXIS_CONFIG = {
    "S2A_longitudinal_coverage_by_dt": {
        "xlim": None, "ylim": None, "xticks": None, "yticks": None,
    },
    "S2B_subject_interval_coverage_heatmap": {
        "xlim": None, "ylim": None, "xticks": None, "yticks": None,
    },
    "S2C_observation_class_composition_by_dt": {
        "xlim": None, "ylim": (0.0, 1.0), "xticks": None, "yticks": None,
    },
}


def ensure_dir(path: Path) -> Path:
    path.mkdir(parents=True, exist_ok=True)
    return path


def read_required(path: Path) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError(f"Required Step-6 table not found: {path}")
    return pd.read_csv(path)


def apply_rcparams(args: argparse.Namespace) -> None:
    plt.rcParams.update({
        "font.family": args.font_family,
        "font.size": args.font_size,
        "axes.labelsize": args.font_size,
        "xtick.labelsize": args.font_size,
        "ytick.labelsize": args.font_size,
        "legend.fontsize": args.legend_fontsize,
        "axes.linewidth": args.axes_w,
        "xtick.major.width": args.tick_w,
        "ytick.major.width": args.tick_w,
        "xtick.major.size": args.tick_len,
        "ytick.major.size": args.tick_len,
        "axes.spines.top": False,
        "axes.spines.right": False,
        "axes.grid": False,
        "pdf.fonttype": 42,
        "ps.fonttype": 42,
        "savefig.dpi": args.dpi,
    })


def apply_axis_config(ax: plt.Axes, stem: str) -> None:
    cfg = AXIS_CONFIG.get(stem, {})
    if cfg.get("xlim") is not None:
        ax.set_xlim(*cfg["xlim"])
    if cfg.get("ylim") is not None:
        ax.set_ylim(*cfg["ylim"])
    if cfg.get("xticks") is not None:
        ax.set_xticks(cfg["xticks"])
    if cfg.get("yticks") is not None:
        ax.set_yticks(cfg["yticks"])


def clean_axes(ax: plt.Axes) -> None:
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)


def label_panel(ax: plt.Axes, label: str, args: argparse.Namespace) -> None:
    ax.text(
        args.panel_label_x,
        args.panel_label_y,
        label,
        transform=ax.transAxes,
        ha="left",
        va="top",
        fontsize=args.panel_label_fontsize,
        fontweight="bold",
    )


def save_figure(
    fig: plt.Figure,
    base: Path,
    args: argparse.Namespace,
) -> None:
    kwargs = dict(bbox_inches="tight", pad_inches=args.pad_inches)
    if args.pdf:
        fig.savefig(base.with_suffix(".pdf"), **kwargs)
        print(f"[SAVED FIGURE] {base.with_suffix('.pdf')}")
    if args.png:
        fig.savefig(base.with_suffix(".png"), dpi=args.dpi, **kwargs)
        print(f"[SAVED FIGURE] {base.with_suffix('.png')}")
    if args.svg:
        fig.savefig(base.with_suffix(".svg"), **kwargs)
        print(f"[SAVED FIGURE] {base.with_suffix('.svg')}")


def prepare_dt_coverage(df: pd.DataFrame) -> pd.DataFrame:
    required = {"dt", "n_transitions", "n_subject_interval_pairs"}
    missing = required.difference(df.columns)
    if missing:
        raise ValueError(
            "04_coverage_summary_by_dt.csv missing columns: "
            + ", ".join(sorted(missing))
        )
    out = df.copy()
    for col in required:
        out[col] = pd.to_numeric(out[col], errors="coerce")
    return out.dropna(subset=["dt", "n_transitions", "n_subject_interval_pairs"]).sort_values("dt")


def prepare_subject_interval(df: pd.DataFrame) -> pd.DataFrame:
    required = {"subject", "t0", "t1", "dt", "n_transitions"}
    missing = required.difference(df.columns)
    if missing:
        raise ValueError(
            "02_subject_interval_coverage.csv missing columns: "
            + ", ".join(sorted(missing))
        )
    out = df.copy()
    for col in ["t0", "t1", "dt", "n_transitions"]:
        out[col] = pd.to_numeric(out[col], errors="coerce")
    return out.dropna(subset=["subject", "t0", "t1", "dt", "n_transitions"])


def prepare_class_by_dt(df: pd.DataFrame) -> pd.DataFrame:
    required = {"dt", "obs_class", "n_transitions", "transition_fraction"}
    missing = required.difference(df.columns)
    if missing:
        raise ValueError(
            "06_observation_class_composition_by_dt.csv missing columns: "
            + ", ".join(sorted(missing))
        )
    out = df.copy()
    out["dt"] = pd.to_numeric(out["dt"], errors="coerce")
    out["n_transitions"] = pd.to_numeric(out["n_transitions"], errors="coerce")
    out["transition_fraction"] = pd.to_numeric(
        out["transition_fraction"], errors="coerce"
    )
    out["obs_class"] = out["obs_class"].astype(str)
    return out.dropna(subset=["dt", "n_transitions", "transition_fraction"])


def panel_A(
    ax: plt.Axes,
    dt_coverage: pd.DataFrame,
    args: argparse.Namespace,
    *,
    add_legend: bool = True,
) -> Tuple[plt.Line2D, plt.Line2D, plt.Axes]:
    d = prepare_dt_coverage(dt_coverage)
    x = d["dt"].to_numpy(float)
    transitions = d["n_transitions"].to_numpy(float)
    pairs = d["n_subject_interval_pairs"].to_numpy(float)

    line1 = ax.plot(
        x, transitions, marker="o", linewidth=args.line_w,
        label="Transitions",
    )[0]
    ax.set_xlabel(r"Temporal lag, $\Delta t$ (weeks)")
    ax.set_ylabel("Transitions")
    ax.ticklabel_format(axis="y", style="sci", scilimits=(0, 0))
    ax.set_xticks(x)
    clean_axes(ax)

    ax2 = ax.twinx()
    line2 = ax2.plot(
        x, pairs, marker="s", linewidth=args.line_w,
        linestyle="--", label="Subject–interval pairs",
    )[0]
    ax2.set_ylabel("Subject–interval pairs")
    ax2.spines["top"].set_visible(False)

    apply_axis_config(ax, "S2A_longitudinal_coverage_by_dt")

    if add_legend:
        ax.legend(
            [line1, line2],
            ["Transitions", "Subject–interval pairs"],
            frameon=False,
            loc="upper left",
            bbox_to_anchor=(1.18, 1.0),
            borderaxespad=0.0,
        )
    return line1, line2, ax2


def interval_order(subject_interval: pd.DataFrame) -> List[Tuple[float, float, float]]:
    d = prepare_subject_interval(subject_interval)
    keys = (
        d[["t0", "t1", "dt"]]
        .drop_duplicates()
        .sort_values(["dt", "t0", "t1"])
    )
    return [tuple(x) for x in keys[["t0", "t1", "dt"]].to_numpy()]


def panel_B(
    ax: plt.Axes,
    subject_interval: pd.DataFrame,
    args: argparse.Namespace,
    *,
    add_colorbar: bool = True,
):
    d = prepare_subject_interval(subject_interval)
    keys = interval_order(d)
    subjects = sorted(d["subject"].drop_duplicates().tolist())

    key_index = {key: i for i, key in enumerate(keys)}
    sub_index = {sub: i for i, sub in enumerate(subjects)}
    matrix = np.full((len(subjects), len(keys)), np.nan, dtype=float)

    for row in d.itertuples(index=False):
        key = (float(row.t0), float(row.t1), float(row.dt))
        matrix[sub_index[row.subject], key_index[key]] = float(row.n_transitions)

    display = np.log10(matrix + 1.0)
    im = ax.imshow(display, aspect="auto", interpolation="nearest")

    labels = [
        f"{int(t0) if float(t0).is_integer() else t0}→"
        f"{int(t1) if float(t1).is_integer() else t1}\n"
        f"Δt={int(dt) if float(dt).is_integer() else dt}"
        for t0, t1, dt in keys
    ]
    ax.set_xticks(np.arange(len(keys)))
    ax.set_xticklabels(labels, rotation=45, ha="right")
    ax.set_yticks(np.arange(len(subjects)))
    ax.set_yticklabels([str(x) for x in subjects])
    ax.set_xlabel("Nominal sampling-time pair")
    ax.set_ylabel("Subject")

    if add_colorbar:
        cbar = ax.figure.colorbar(im, ax=ax, fraction=0.035, pad=0.03)
        cbar.set_label(r"$\log_{10}$(transitions + 1)")

    apply_axis_config(ax, "S2B_subject_interval_coverage_heatmap")
    return im


def panel_C(
    ax: plt.Axes,
    class_by_dt: pd.DataFrame,
    args: argparse.Namespace,
    *,
    add_legend: bool = True,
) -> None:
    d = prepare_class_by_dt(class_by_dt)
    dts = sorted(d["dt"].drop_duplicates().tolist())
    pivot = (
        d.pivot_table(
            index="dt",
            columns="obs_class",
            values="transition_fraction",
            aggfunc="first",
        )
        .reindex(index=dts, columns=list(OBS_CLASSES))
        .fillna(0.0)
    )

    bottom = np.zeros(len(pivot), dtype=float)
    x = np.arange(len(pivot))

    for cls in OBS_CLASSES:
        vals = pivot[cls].to_numpy(float)
        ax.bar(
            x, vals, bottom=bottom, width=0.72,
            label=cls, linewidth=0,
        )
        bottom += vals

    ax.set_xticks(x)
    ax.set_xticklabels([
        str(int(dt)) if float(dt).is_integer() else str(dt)
        for dt in pivot.index
    ])
    ax.set_xlabel(r"Temporal lag, $\Delta t$ (weeks)")
    ax.set_ylabel("Transition fraction")
    ax.set_ylim(0.0, 1.0)
    clean_axes(ax)
    apply_axis_config(ax, "S2C_observation_class_composition_by_dt")

    if add_legend:
        ax.legend(
            frameon=False,
            loc="upper left",
            bbox_to_anchor=(1.02, 1.0),
            borderaxespad=0.0,
            title="Observation class",
        )


def make_single_panels(
    fig_dir: Path,
    dt_coverage: pd.DataFrame,
    subject_interval: pd.DataFrame,
    class_by_dt: pd.DataFrame,
    args: argparse.Namespace,
) -> None:
    stem = "S2A_longitudinal_coverage_by_dt"
    fig, ax = plt.subplots(figsize=FIGURE_SIZES_INCHES[stem])
    panel_A(ax, dt_coverage, args, add_legend=True)
    fig.subplots_adjust(right=0.72, bottom=0.20)
    save_figure(fig, fig_dir / stem, args)
    plt.close(fig)

    stem = "S2B_subject_interval_coverage_heatmap"
    fig, ax = plt.subplots(figsize=FIGURE_SIZES_INCHES[stem])
    panel_B(ax, subject_interval, args, add_colorbar=True)
    fig.tight_layout()
    save_figure(fig, fig_dir / stem, args)
    plt.close(fig)

    stem = "S2C_observation_class_composition_by_dt"
    fig, ax = plt.subplots(figsize=FIGURE_SIZES_INCHES[stem])
    panel_C(ax, class_by_dt, args, add_legend=True)
    fig.subplots_adjust(right=0.77, bottom=0.20)
    save_figure(fig, fig_dir / stem, args)
    plt.close(fig)


def make_multipanel(
    fig_dir: Path,
    dt_coverage: pd.DataFrame,
    subject_interval: pd.DataFrame,
    class_by_dt: pd.DataFrame,
    args: argparse.Namespace,
) -> None:
    stem = "Supplementary_Figure_S2_transition_dataset_characterization"
    fig = plt.figure(figsize=FIGURE_SIZES_INCHES[stem])

    # A and C share the top row; B spans the full bottom row.
    gs = fig.add_gridspec(
        2, 2,
        height_ratios=[1.0, 1.35],
        left=0.10, right=0.93, bottom=0.10, top=0.96,
        wspace=0.55, hspace=0.62,
    )

    axA = fig.add_subplot(gs[0, 0])
    line1, line2, axA2 = panel_A(axA, dt_coverage, args, add_legend=False)
    label_panel(axA, "A", args)

    axC = fig.add_subplot(gs[0, 1])
    panel_C(axC, class_by_dt, args, add_legend=False)
    label_panel(axC, "C", args)

    axB = fig.add_subplot(gs[1, :])
    im = panel_B(axB, subject_interval, args, add_colorbar=False)
    label_panel(axB, "B", args)

    # Compact figure-level legends / colorbar.
    fig.legend(
        [line1, line2],
        ["Transitions", "Subject–interval pairs"],
        frameon=False,
        loc="upper left",
        bbox_to_anchor=(0.10, 0.995),
        ncol=2,
        handlelength=1.6,
    )

    handlesC, labelsC = axC.get_legend_handles_labels()
    fig.legend(
        handlesC, labelsC,
        frameon=False,
        loc="upper right",
        bbox_to_anchor=(0.93, 0.995),
        ncol=4,
        title="Observation class",
        handlelength=1.2,
        columnspacing=0.8,
    )

    cbar = fig.colorbar(
        im, ax=axB,
        orientation="vertical",
        fraction=0.018,
        pad=0.02,
    )
    cbar.set_label(r"$\log_{10}$(transitions + 1)")

    save_figure(fig, fig_dir / stem, args)
    plt.close(fig)


def write_manifest(fig_dir: Path) -> None:
    rows = [
        {
            "panel": "S2A",
            "stem": "S2A_longitudinal_coverage_by_dt",
            "source_table": "04_coverage_summary_by_dt.csv",
            "purpose": "Transition and subject-interval coverage across temporal lags.",
        },
        {
            "panel": "S2B",
            "stem": "S2B_subject_interval_coverage_heatmap",
            "source_table": "02_subject_interval_coverage.csv",
            "purpose": "Subject-by-nominal-interval transition coverage.",
        },
        {
            "panel": "S2C",
            "stem": "S2C_observation_class_composition_by_dt",
            "source_table": "06_observation_class_composition_by_dt.csv",
            "purpose": "TT/TF/FT/FF composition across temporal lags.",
        },
    ]
    pd.DataFrame(rows).to_csv(fig_dir / "figure_manifest.csv", index=False)


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        description="Plot ClonoDynamics Step-6 transition-dataset characterization outputs."
    )
    p.add_argument("--analysis-dir", type=Path, required=True)
    p.add_argument("--figures-dir", type=Path, required=True)

    p.add_argument("--font-family", default="Arial")
    p.add_argument("--font-size", type=float, default=8.0)
    p.add_argument("--legend-fontsize", type=float, default=7.0)
    p.add_argument("--dpi", type=int, default=600)

    p.add_argument("--axes-w", type=float, default=0.7)
    p.add_argument("--tick-w", type=float, default=0.7)
    p.add_argument("--tick-len", type=float, default=2.5)
    p.add_argument("--line-w", type=float, default=1.0)

    p.add_argument("--panel-label-fontsize", type=float, default=9.0)
    p.add_argument("--panel-label-x", type=float, default=-0.17)
    p.add_argument("--panel-label-y", type=float, default=1.06)

    p.add_argument("--pad-inches", type=float, default=0.05)

    p.add_argument(
        "--pdf",
        action=argparse.BooleanOptionalAction,
        default=True,
    )
    p.add_argument(
        "--png",
        action=argparse.BooleanOptionalAction,
        default=False,
    )
    p.add_argument(
        "--svg",
        action=argparse.BooleanOptionalAction,
        default=False,
    )
    p.add_argument(
        "--make-single-panels",
        action=argparse.BooleanOptionalAction,
        default=True,
    )
    p.add_argument(
        "--make-multipanel",
        action=argparse.BooleanOptionalAction,
        default=True,
    )
    return p


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = build_parser().parse_args(argv)

    analysis_dir = args.analysis_dir.expanduser().resolve()
    fig_dir = ensure_dir(args.figures_dir.expanduser().resolve())

    apply_rcparams(args)

    subject_interval = read_required(
        analysis_dir / "02_subject_interval_coverage.csv"
    )
    dt_coverage = read_required(
        analysis_dir / "04_coverage_summary_by_dt.csv"
    )
    class_by_dt = read_required(
        analysis_dir / "06_observation_class_composition_by_dt.csv"
    )
    # Loaded for schema/audit consistency even though the current S2 uses
    # the by-lag class table for visualization.
    read_required(
        analysis_dir / "07_observation_class_composition_overall.csv"
    )

    if args.make_single_panels:
        make_single_panels(
            fig_dir, dt_coverage, subject_interval, class_by_dt, args
        )

    if args.make_multipanel:
        make_multipanel(
            fig_dir, dt_coverage, subject_interval, class_by_dt, args
        )

    write_manifest(fig_dir)

    print("[Step-6 plot] Completed.")
    print(f"[DATA] {analysis_dir}")
    print(f"[FIGS] {fig_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
