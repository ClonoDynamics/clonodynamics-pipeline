def ensure_dir(path: Path) -> Path:
    path.mkdir(parents=True, exist_ok=True)
    return path


def read_table(path: Path) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError(f"Input table not found: {path}")

    suffix = path.suffix.lower()
    if suffix in {".parquet", ".pq"}:
        return pd.read_parquet(path)
    if suffix == ".csv":
        return pd.read_csv(path)
    if suffix in {".tsv", ".txt"}:
        return pd.read_csv(path, sep="\t")

    raise ValueError(f"Unsupported table format: {path}")


def find_table(
    analysis_dir: Path,
    stem: str,
    *,
    required: bool,
) -> Optional[Path]:
    for suffix in (".parquet", ".csv", ".tsv", ".txt"):
        candidate = analysis_dir / f"{stem}{suffix}"
        if candidate.exists():
            return candidate

    if required:
        raise FileNotFoundError(
            f"Required Step-11 output '{stem}' not found in: {analysis_dir}"
        )
    return None


def load_required_table(analysis_dir: Path, stem: str) -> pd.DataFrame:
    path = find_table(analysis_dir, stem, required=True)
    assert path is not None
    frame = read_table(path)
    if frame.empty:
        raise ValueError(f"Required Step-11 table is empty: {path}")
    return frame


def load_optional_table(analysis_dir: Path, stem: str) -> pd.DataFrame:
    path = find_table(analysis_dir, stem, required=False)
    if path is None:
        return pd.DataFrame()

    frame = read_table(path)
    if frame.empty:
        warnings.warn(f"Optional Step-11 table is empty: {path}")
    return frame


def load_metadata(analysis_dir: Path) -> Dict[str, object]:
    for name in ("00_analysis_metadata.json", "00_run_config.json"):
        path = analysis_dir / name
        if path.exists():
            with path.open("r", encoding="utf-8") as handle:
                data = json.load(handle)
            if isinstance(data, dict):
                return data
    return {}


def write_manifest(rows: List[Dict[str, object]], path: Path) -> None:
    pd.DataFrame(rows).to_csv(path, index=False)


