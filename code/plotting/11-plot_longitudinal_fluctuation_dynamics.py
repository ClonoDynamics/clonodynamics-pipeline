def require_columns(df: pd.DataFrame, columns: Iterable[str], label: str) -> None:
    missing = [column for column in columns if column not in df.columns]
    if missing:
        raise ValueError(
            f"{label} is missing required columns: {missing}. "
            f"Available columns: {list(df.columns)}"
        )


def numeric(df: pd.DataFrame, columns: Iterable[str]) -> pd.DataFrame:
    out = df.copy()
    for column in columns:
        if column in out.columns:
            out[column] = pd.to_numeric(out[column], errors="coerce")
    return out.replace([np.inf, -np.inf], np.nan)


def parse_csv(text: str) -> List[str]:
    return [value.strip() for value in str(text or "").split(",") if value.strip()]


def parse_dt_values(text: str, available: Sequence[float]) -> List[float]:
    available_values = sorted({float(v) for v in available if np.isfinite(v)})
    if not str(text or "").strip():
        return available_values

    requested = [float(v) for v in parse_csv(text)]
    missing = [v for v in requested if v not in available_values]
    if missing:
        warnings.warn(f"Requested dt values not available and ignored: {missing}")
    return [v for v in requested if v in available_values]


def format_dt(value: float) -> str:
    value = float(value)
    return str(int(value)) if value.is_integer() else f"{value:g}"


def dt_label(value: float) -> str:
    return rf"$\Delta t={format_dt(value)}$"


def validate_primary_curves(curves: pd.DataFrame) -> None:
    required = [
        "dt",
        "bin_id",
        "bin_mid",
        "n",
        "n_subjects",
        "mean_dx",
        "median_dx",
        "ppos",
        "msd",
        "var_dx",
        "mad_dx",
    ]
    require_columns(curves, required, "10_binned_dynamics_long")

    keys = [column for column in ("representation", "conditioning", "mode") if column in curves]
    for column in keys:
        values = sorted(curves[column].dropna().astype(str).unique())
        if len(values) > 1:
            raise ValueError(
                "10_binned_dynamics_long contains multiple values for "
                f"{column}: {values}. A Step-11 analysis directory should "
                "represent one analysis configuration."
            )


def filter_dt(df: pd.DataFrame, dt_values: Sequence[float]) -> pd.DataFrame:
    if df.empty or "dt" not in df.columns:
        return df.copy()
    dt = pd.to_numeric(df["dt"], errors="coerce")
    return df[dt.isin([float(v) for v in dt_values])].copy()


