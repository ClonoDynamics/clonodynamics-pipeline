def metric_label(metric: str) -> str:
    return METRIC_LABELS.get(metric, metric)


def plot_curve_with_optional_ci(
    ax: plt.Axes,
    data: pd.DataFrame,
    metric: str,
    label: str,
    args: argparse.Namespace,
) -> bool:
    if data.empty or metric not in data.columns:
        return False

    d = numeric(data, ["bin_mid", metric]).sort_values("bin_mid")
    x = d["bin_mid"].to_numpy(float)
    y = d[metric].to_numpy(float)
    valid = np.isfinite(x) & np.isfinite(y)
    if not valid.any():
        return False

    line = ax.plot(
        x[valid],
        y[valid],
        marker="o",
        linewidth=args.line_width,
        markersize=args.marker_size,
        label=label,
    )[0]

    low_col = f"{metric}_ci_low"
    high_col = f"{metric}_ci_high"
    if args.show_ci and low_col in d.columns and high_col in d.columns:
        low = pd.to_numeric(d[low_col], errors="coerce").to_numpy(float)
        high = pd.to_numeric(d[high_col], errors="coerce").to_numpy(float)
        ok = valid & np.isfinite(low) & np.isfinite(high)
        if ok.any():
            ax.fill_between(
                x[ok],
                low[ok],
                high[ok],
                color=line.get_color(),
                alpha=args.ci_alpha,
                linewidth=0,
            )

    return True


def add_metric_baseline(ax: plt.Axes, metric: str) -> None:
    baseline = BASELINE_BY_METRIC.get(metric)
    if baseline is not None:
        ax.axhline(baseline, linewidth=0.8, linestyle="--", color="0.35")


