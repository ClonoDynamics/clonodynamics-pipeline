def plot_loo_robustness(
    loo: pd.DataFrame,
    dt_values: Sequence[float],
    metrics: Sequence[str],
    estimators: Sequence[str],
    figures_dir: Path,
    formats: Sequence[str],
    args: argparse.Namespace,
) -> List[Dict[str, object]]:
    if loo.empty:
        return []

    require_columns(
        loo,
        [
            "estimator",
            "metric",
            "dt",
            "bin_mid",
            "full_value",
            "loo_min",
            "loo_max",
        ],
        "16_leave_one_subject_out_summary",
    )

    d0 = numeric(
        loo,
        ["dt", "bin_mid", "full_value", "loo_min", "loo_max"],
    )

    rows: List[Dict[str, object]] = []

    for estimator in estimators:
        de = d0[d0["estimator"].astype(str) == estimator]
        if de.empty:
            continue

        for metric in metrics:
            dm = de[de["metric"].astype(str) == metric]
            if dm.empty:
                continue

            stem = f"07_loo_robustness_{metric}_{estimator}"
            fig, ax = plt.subplots(figsize=resolve_figure_size(stem))
            any_plot = False

            for dt in dt_values:
                d = dm[dm["dt"] == float(dt)].sort_values("bin_mid")
                if d.empty:
                    continue

                x = d["bin_mid"].to_numpy(float)
                full = d["full_value"].to_numpy(float)
                low = d["loo_min"].to_numpy(float)
                high = d["loo_max"].to_numpy(float)

                valid = np.isfinite(x) & np.isfinite(full)
                if not valid.any():
                    continue

                line = ax.plot(
                    x[valid],
                    full[valid],
                    marker="o",
                    linewidth=args.line_width,
                    markersize=args.marker_size,
                    label=dt_label(dt),
                )[0]

                band_ok = valid & np.isfinite(low) & np.isfinite(high)
                if band_ok.any():
                    ax.fill_between(
                        x[band_ok],
                        low[band_ok],
                        high[band_ok],
                        color=line.get_color(),
                        alpha=args.loo_alpha,
                        linewidth=0,
                    )

                any_plot = True

            if not any_plot:
                plt.close(fig)
                continue

            add_metric_baseline(ax, metric)
            ax.set_xlabel(r"Latent abundance, $x^*$")
            ax.set_ylabel(metric_label(metric))
            apply_axis_config(ax, stem)
            style_axes(ax)
            apply_legend(ax, args, title="Lag")
            fig.tight_layout()

            files = save_figure(fig, figures_dir, stem, formats, args)
            rows.extend(
                {
                    "figure": name,
                    "family": "loo_robustness",
                    "metric": metric,
                    "estimator": estimator,
                    "source_table": "16_leave_one_subject_out_summary",
                }
                for name in files
            )

    return rows


