    print(f"[FIGURES]  {figures_dir}")
    print(f"[DT]       {dt_values}")
    print(f"[FILES]    {len(figure_rows)} rendered files")

    if metadata:
        print(
            "[PROVENANCE] representation={!r}; conditioning={!r}; mode={!r}".format(
                metadata.get("representation"),
                metadata.get("conditioning"),
                metadata.get("mode"),
            )
        )

    return 0


