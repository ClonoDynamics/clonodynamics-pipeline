def resolve_figure_size(stem: str) -> Tuple[float, float]:
    if stem in FIGURE_SIZES_INCHES:
        return FIGURE_SIZES_INCHES[stem]

    for prefix in (
        "05_weighting_sensitivity",
        "06_weighting_difference",
        "07_loo_robustness",
    ):
        if stem.startswith(prefix):
            return FIGURE_SIZES_INCHES[prefix]

    raise KeyError(f"No FIGURE_SIZES_INCHES entry for: {stem}")


def resolve_axis_config(stem: str) -> Dict[str, object]:
    if stem in AXIS_CONFIG:
        return dict(AXIS_CONFIG[stem])

    for prefix in (
        "05_weighting_sensitivity",
        "06_weighting_difference",
        "07_loo_robustness",
    ):
        if stem.startswith(prefix):
            return dict(AXIS_CONFIG[prefix])

    return {
        "xlim": None,
        "ylim": None,
        "xscale": None,
        "yscale": None,
        "xtick_step": None,
        "ytick_step": None,
    }


def apply_axis_config(ax: plt.Axes, stem: str) -> None:
    cfg = resolve_axis_config(stem)

    if cfg.get("xscale"):
        ax.set_xscale(str(cfg["xscale"]))
    if cfg.get("yscale"):
        ax.set_yscale(str(cfg["yscale"]))

    if cfg.get("xlim") is not None:
        ax.set_xlim(*cfg["xlim"])
    if cfg.get("ylim") is not None:
        ax.set_ylim(*cfg["ylim"])

    if cfg.get("xtick_step") is not None:
        ax.xaxis.set_major_locator(MultipleLocator(float(cfg["xtick_step"])))
    if cfg.get("ytick_step") is not None:
        ax.yaxis.set_major_locator(MultipleLocator(float(cfg["ytick_step"])))


def apply_legend(ax: plt.Axes, args: argparse.Namespace, title: str) -> None:
    handles, labels = ax.get_legend_handles_labels()
    if not handles:
        return

    if args.legend_mode == "none":
        return

    kwargs = {
        "frameon": False,
        "title": title,
        "title_fontsize": max(args.font_size - 1.0, 5.0),
        "handlelength": 1.2,
        "labelspacing": 0.25,
        "handletextpad": 0.4,
    }

    if args.legend_mode == "outside":
        ax.legend(
            handles,
            labels,
            loc="center left",
            bbox_to_anchor=(1.02, 0.5),
            borderaxespad=0.0,
            **kwargs,
        )
    else:
        ax.legend(handles, labels, loc="best", **kwargs)


def formats_to_run(args: argparse.Namespace) -> List[str]:
    formats = []
    if args.pdf:
        formats.append("pdf")
    if args.png:
        formats.append("png")
    if args.svg:
        formats.append("svg")
    if not formats:
        raise ValueError("At least one output format must be enabled.")
    return formats


def save_figure(
    fig: plt.Figure,
    figures_dir: Path,
    stem: str,
    formats: Sequence[str],
    args: argparse.Namespace,
) -> List[str]:
    figures_dir.mkdir(parents=True, exist_ok=True)
    outputs: List[str] = []

    for fmt in formats:
        path = figures_dir / f"{stem}.{fmt}"
        kwargs = {
            "bbox_inches": "tight",
            "pad_inches": args.pad_inches,
        }
        if fmt == "png":
            kwargs["dpi"] = args.dpi
        fig.savefig(path, **kwargs)
        outputs.append(path.name)
        print(f"[SAVED] {path}")

    plt.close(fig)
    return outputs


