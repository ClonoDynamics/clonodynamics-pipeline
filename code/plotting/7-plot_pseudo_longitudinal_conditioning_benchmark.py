def read_csv(
    path: Path, label: str, required: bool = True
) -> Optional[pd.DataFrame]:
    path = Path(path)
    if not path.exists():
        if required:
            raise FileNotFoundError(f"{label} not found: {path}")
        print(f"[NOTE] optional {label} not found: {path}")
        return None
    df = pd.read_csv(path)
    if df.empty:
        if required:
            raise ValueError(f"{label} is empty: {path}")
        print(f"[NOTE] optional {label} is empty: {path}")
        return None
    print(f"[OK] {label}: {path}")
    return df


def require_columns(df: pd.DataFrame, required: Sequence[str], label: str) -> None:
    missing = [c for c in required if c not in df.columns]
    if missing:
        raise ValueError(
            f"{label} is missing required columns {missing}. "
            f"Available: {list(df.columns)}"
        )


def first_existing(columns: Sequence[str], candidates: Sequence[str]) -> Optional[str]:
    names = set(columns)
    for c in candidates:
        if c in names:
            return c
    return None


