def normalize_conditioning_name(value: object) -> Optional[str]:
    s = str(value).strip().lower().replace("*", "star").replace("-", "_")
    s = s.replace(" ", "_")

    if s in {"x0", "initial", "initial_state", "naive_x0", "baseline"}:
        return "x0"
    if "naive" in s and "x0" in s:
        return "x0"
    if s in {"mid", "xmid", "midpoint", "x_mid", "transition_midpoint"}:
        return "midpoint"
    if "midpoint" in s or s == "xmid":
        return "midpoint"
    if s in {"xstar", "x_star", "star", "uncertainty_weighted"}:
        return "xstar"
    if "xstar" in s or "x_star" in s:
        return "xstar"
    return None


def choose_conditioning_y(df: pd.DataFrame, requested: str) -> Tuple[str, Optional[str], Optional[str]]:
    if requested == "median":
        y_candidates = ["median_dx", "median_displacement", "dx_median", "mean_dx"]
    else:
        y_candidates = ["mean_dx", "mean_displacement", "dx_mean", "median_dx"]

    ycol = first_existing(df.columns, y_candidates)
    if ycol is None:
        raise ValueError(
            "Could not identify a displacement column in conditioning curves. "
            "Expected one of: mean_dx, median_dx, mean_displacement, median_displacement."
        )

    if ycol.startswith("mean_dx") or ycol == "mean_dx":
        low = first_existing(
            df.columns,
            ["mean_dx_ci_low", "mean_dx_ci025", "mean_dx_q025", "mean_dx_lower"],
        )
        high = first_existing(
            df.columns,
            ["mean_dx_ci_high", "mean_dx_ci975", "mean_dx_q975", "mean_dx_upper"],
        )
    else:
        low = first_existing(
            df.columns,
            ["median_dx_ci_low", "median_dx_ci025", "median_dx_q025", "median_dx_lower"],
        )
        high = first_existing(
            df.columns,
            ["median_dx_ci_high", "median_dx_ci975", "median_dx_q975", "median_dx_upper"],
        )
    return ycol, low, high


def normalize_conditioning_curves(
    raw: pd.DataFrame,
    representation: str,
    abundance_coordinate: str,
    dt_value: int,
    y_requested: str,
    show_all_bins: bool,
) -> Tuple[pd.DataFrame, str]:
    """Return columns: conditioning, x, y, lower, upper."""

    d = raw.copy()

    # The dedicated conditioning benchmark marks the bins that enter the pooled
    # comparison with used_in_benchmark_summary. By default the manuscript panel
    # shows exactly those common valid bins, so the plotted support matches the
    # reported benchmark metrics. --conditioning-show-all-bins restores the full
    # diagnostic curve.
    if (not show_all_bins) and ("used_in_benchmark_summary" in d.columns):
        raw_flag = d["used_in_benchmark_summary"]
        if pd.api.types.is_bool_dtype(raw_flag):
            keep_flag = raw_flag.fillna(False)
        elif pd.api.types.is_numeric_dtype(raw_flag):
            keep_flag = pd.to_numeric(raw_flag, errors="coerce").fillna(0).ne(0)
        else:
            keep_flag = (
                raw_flag.astype(str)
                .str.strip()
                .str.lower()
                .isin(["true", "t", "1", "yes", "y"])
            )
        n_before = int(len(d))
        d = d.loc[keep_flag].copy()
        print(
            "[FILTER] conditioning benchmark common valid bins: "
            f"{len(d):,}/{n_before:,} curve rows retained"
        )
        if d.empty:
            raise ValueError(
                "No conditioning-curve rows remain after filtering "
                "used_in_benchmark_summary=True. Use --conditioning-show-all-bins "
                "for diagnostic plotting."
            )

    # Restrict to the requested representation when the conditioning table contains multiple representations.
    if "representation" in d.columns and "conditioning" in d.columns:
        reps = d["representation"].astype(str).str.lower()
        exact = reps.eq(str(representation).lower())
        if exact.any():
            d = d.loc[exact].copy()
        else:
            contains = reps.str.contains(str(representation).lower(), regex=False)
            if contains.any():
                d = d.loc[contains].copy()

    # Absolute abundance only. Percentile/quantile coordinates are deliberately
    # excluded from this manuscript figure.
    if "abundance_coordinate" in d.columns:
        vals = d["abundance_coordinate"].astype(str).str.lower()
        target = str(abundance_coordinate).lower()
        exact = vals.eq(target)
        if exact.any():
            d = d.loc[exact].copy()
        else:
            absolute = vals.str.contains("absolute", regex=False)
            if absolute.any():
                d = d.loc[absolute].copy()

    if "dt" in d.columns:
        dt_numeric = pd.to_numeric(d["dt"], errors="coerce")
        keep = dt_numeric.eq(int(dt_value))
        if keep.any():
            d = d.loc[keep].copy()

    # Determine conditioning labels either from an explicit conditioning column
    # or from representation names in compact conditioning tables.
    if "candidate" in d.columns:
        # Native output of the validated conditioning engine bundled in current Step 7
        cond = d["candidate"].map(normalize_conditioning_name)
    elif "conditioning" in d.columns:
        cond = d["conditioning"].map(normalize_conditioning_name)
    elif "representation" in d.columns:
        cond = d["representation"].map(normalize_conditioning_name)
    else:
        candidate_col = first_existing(
            d.columns, ["coordinate", "conditioning_coordinate", "cond"]
        )
        if candidate_col is None:
            raise ValueError(
                "Conditioning curve file needs a 'candidate' or 'conditioning' column, "
                "or another coordinate-label column from which x0/midpoint/xstar can be inferred."
            )
        cond = d[candidate_col].map(normalize_conditioning_name)

    d = d.assign(_conditioning=cond)
    d = d.loc[d["_conditioning"].isin(["x0", "midpoint", "xstar"])].copy()

    xcol = first_existing(
        d.columns,
        ["x_center", "bin_mid", "x_mid", "conditioning_center", "x_raw_median", "x_median"],
    )
    if xcol is None:
        raise ValueError(
            "Could not identify abundance-bin center in conditioning curves. "
            "Expected one of x_center, bin_mid, x_mid, x_raw_median, x_median."
        )

    ycol, lowcol, highcol = choose_conditioning_y(d, y_requested)

    out = pd.DataFrame(
        {
            "conditioning": d["_conditioning"].astype(str),
            "x": pd.to_numeric(d[xcol], errors="coerce"),
            "y": pd.to_numeric(d[ycol], errors="coerce"),
        }
    )
    out["lower"] = (
        pd.to_numeric(d[lowcol], errors="coerce") if lowcol is not None else np.nan
    )
    out["upper"] = (
        pd.to_numeric(d[highcol], errors="coerce") if highcol is not None else np.nan
    )
    out = out.loc[np.isfinite(out["x"]) & np.isfinite(out["y"])].copy()

    present = set(out["conditioning"].unique())
    required = {"x0", "midpoint", "xstar"}
    missing = sorted(required - present)
    if missing:
        raise ValueError(
            "Conditioning curve file does not contain all three required coordinates. "
            f"Missing: {missing}; present: {sorted(present)}. "
            "For the main Step-7 benchmark we need x0, midpoint and xstar."
        )

    ylabel = "Median latent displacement" if ycol.startswith("median") else "Mean latent displacement"
    return out, ylabel


