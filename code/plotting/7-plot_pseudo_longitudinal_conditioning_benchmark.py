def compute_shared_limits(
    conditioning: pd.DataFrame,
    same_cross: pd.DataFrame,
    x_pad_frac: float = 0.04,
    y_pad_frac: float = 0.06,
) -> Tuple[Tuple[float, float], Tuple[float, float]]:
    xvals = [
        pd.to_numeric(conditioning["x"], errors="coerce").to_numpy(dtype=float),
        pd.to_numeric(same_cross["x_center"], errors="coerce").to_numpy(dtype=float),
    ]
    yvals = [
        pd.to_numeric(conditioning["y"], errors="coerce").to_numpy(dtype=float),
        pd.to_numeric(same_cross["mean_dx_same"], errors="coerce").to_numpy(dtype=float),
        pd.to_numeric(same_cross["mean_dx_cross"], errors="coerce").to_numpy(dtype=float),
    ]
    for c in ["lower", "upper"]:
        if c in conditioning.columns:
            yvals.append(pd.to_numeric(conditioning[c], errors="coerce").to_numpy(dtype=float))

    x = np.concatenate([v[np.isfinite(v)] for v in xvals if np.isfinite(v).any()])
    y = np.concatenate([v[np.isfinite(v)] for v in yvals if np.isfinite(v).any()])
    if x.size == 0 or y.size == 0:
        raise ValueError("Could not compute shared axis limits for conditioning and same/cross panels.")

    xmin, xmax = float(np.min(x)), float(np.max(x))
    ymin, ymax = float(np.min(y)), float(np.max(y))
    xspan = max(xmax - xmin, 1e-6)
    yspan = max(ymax - ymin, 1e-6)
    xmin -= x_pad_frac * xspan
    xmax += x_pad_frac * xspan
    ymin = min(ymin - y_pad_frac * yspan, -0.01)
    ymax = max(ymax + y_pad_frac * yspan, 0.01)
    return (xmin, xmax), (ymin, ymax)


