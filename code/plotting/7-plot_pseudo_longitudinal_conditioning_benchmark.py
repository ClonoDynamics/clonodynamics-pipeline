def finite(values: pd.Series) -> np.ndarray:
    x = pd.to_numeric(values, errors="coerce").to_numpy(dtype=float)
    return x[np.isfinite(x)]


def combined_curve_from_representations(
    df: pd.DataFrame,
    representations: Sequence[str],
    value_col: str = "mean_dx",
) -> pd.DataFrame:
    require_columns(df, ["representation", "bin", "x_center", value_col], "curve table")
    d = df[df["representation"].isin(list(representations))].copy()
    if d.empty:
        raise ValueError("No rows found for representations: {}".format(representations))
    d[value_col] = pd.to_numeric(d[value_col], errors="coerce")
    out = (
        d.groupby(["bin", "x_center"], as_index=False)[value_col]
        .mean()
        .sort_values("x_center")
    )
    return out


def rep_curve(df: pd.DataFrame, representation: str) -> pd.DataFrame:
    require_columns(df, ["representation", "x_center", "mean_dx"], "forward-drift table")
    d = df[df["representation"] == representation].copy()
    if d.empty:
        raise ValueError("Representation not found: {}".format(representation))
    return d.sort_values("x_center")


