def metric_pair(metrics: pd.DataFrame, metric: str) -> Tuple[np.ndarray, np.ndarray]:
    require_columns(metrics, ["representation", metric], "reverse-pair metrics")
    same = finite(metrics.loc[metrics["representation"] == "same_combined", metric])
    cross = finite(metrics.loc[metrics["representation"] == "cross_combined", metric])
    if same.size == 0 or cross.size == 0:
        raise ValueError("Missing same/cross values for metric {}".format(metric))
    return same, cross


def hist_pair(
    ax: plt.Axes,
    same: np.ndarray,
    cross: np.ndarray,
    xlabel: str,
    bins: int,
) -> None:
    lo = float(min(np.min(same), np.min(cross)))
    hi = float(max(np.max(same), np.max(cross)))
    edges = np.linspace(lo, hi, int(bins) + 1)

    _, _, same_patches = ax.hist(
        same, bins=edges, alpha=0.55, label=r"Same-replicate $x_0$"
    )
    _, _, cross_patches = ax.hist(
        cross, bins=edges, alpha=0.55, label=r"Replicate-decoupled $x_0$"
    )

    same_color = same_patches[0].get_facecolor() if same_patches else None
    cross_color = cross_patches[0].get_facecolor() if cross_patches else None
    ax.axvline(
        float(np.median(same)), linewidth=1.0, linestyle="--", color=same_color
    )
    ax.axvline(
        float(np.median(cross)), linewidth=1.0, linestyle="--", color=cross_color
    )
    ax.set_xlabel(xlabel)
    ax.set_ylabel("Number of order/reverse pairs")
    ax.legend(frameon=False)


