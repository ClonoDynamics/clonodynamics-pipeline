def reconstruct_same_cross(matched: pd.DataFrame) -> pd.DataFrame:
    require_columns(
        matched,
        ["fold", "bin", "x_center", "mean_dx_same", "mean_dx_cross"],
        "matched same-vs-cross",
    )
    parts: List[pd.DataFrame] = []
    for fold in sorted(matched["fold"].dropna().unique()):
        s = matched.loc[
            matched["fold"] == fold,
            ["bin", "x_center", "mean_dx_same", "mean_dx_cross"],
        ].copy()
        s["fold"] = fold
        parts.append(s)
    if not parts:
        raise ValueError("No fold rows found in matched same-vs-cross table")
    allf = pd.concat(parts, ignore_index=True)
    out = (
        allf.groupby(["bin", "x_center"], as_index=False)
        .agg(
            mean_dx_same=("mean_dx_same", "mean"),
            mean_dx_cross=("mean_dx_cross", "mean"),
        )
        .sort_values("x_center")
    )
    return out


def reconstruct_coupling_delta(matched: pd.DataFrame) -> pd.DataFrame:
    require_columns(
        matched,
        ["fold", "bin", "x_center", "delta_mean_same_minus_cross"],
        "matched same-vs-cross",
    )
    d = matched.copy()
    d["delta_mean_same_minus_cross"] = pd.to_numeric(
        d["delta_mean_same_minus_cross"], errors="coerce"
    )
    out = (
        d.groupby(["bin", "x_center"], as_index=False)
        .agg(delta=("delta_mean_same_minus_cross", "mean"))
        .sort_values("x_center")
    )
    return out


