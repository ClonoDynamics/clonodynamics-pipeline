def main() -> None:
    args = build_parser().parse_args()
    print("[INFO] {} | {}".format(Path(__file__).name, SCRIPT_VERSION))
    benchmark_dir = Path(args.analysis_dir).expanduser().resolve()
    outdir = ensure_dir(
        Path(args.figures_dir).expanduser().resolve()
        if args.figures_dir is not None
        else benchmark_dir / "figures_pseudo_longitudinal_conditioning_benchmark"
    )

    PLOT_STYLE_DEFAULTS["dpi"] = int(args.dpi)
    PLOT_STYLE_DEFAULTS["font_size"] = float(args.font_size)
    if not benchmark_dir.is_dir():
        raise NotADirectoryError(
            "Step-7 pseudo-longitudinal conditioning benchmark directory not found: {}".format(benchmark_dir)
        )

    conditioning_dir = benchmark_dir / "01_conditioning_geometry"
    replicate_dir = benchmark_dir / "02_replicate_decoupling"
    ordering_dir = benchmark_dir / "03_ordering_robustness"

    required_dirs = [
        (conditioning_dir, "conditioning-geometry"),
        (replicate_dir, "replicate-decoupling"),
        (ordering_dir, "ordering-robustness"),
    ]
    for path, label in required_dirs:
        if not path.is_dir():
            raise NotADirectoryError(
                "{} directory not found inside benchmark: {}".format(label, path)
            )

    conditioning_path = conditioning_dir / "03_pooled_bias_curves.csv"

    conditioning_raw = read_csv(conditioning_path, "conditioning benchmark curves")
    assert conditioning_raw is not None
    conditioning, conditioning_ylabel = normalize_conditioning_curves(
        conditioning_raw, args.conditioning_representation,
        args.conditioning_abundance_coordinate, args.conditioning_dt,
        args.conditioning_y, args.conditioning_show_all_bins
    )

    matched = read_csv(replicate_dir / "forward_drift_matched_same_vs_cross.csv", "replicate-decoupling matched same-vs-cross")
    metrics = read_csv(ordering_dir / "pseudo_reverse_pair_metrics.csv", "ordering-robustness reverse-pair metrics")
    assert matched is not None and metrics is not None
    require_columns(metrics, ["representation", "slope", "centered_mean_abs_drift"], "ordering-robustness reverse-pair metrics")

    if args.figure_set in {"all", "main"}:
        plot_main_block(conditioning, conditioning_ylabel, matched, metrics, outdir)

    if args.figure_set in {"all", "supplementary"}:
        by_fold = read_csv(replicate_dir / "forward_drift_by_fold.csv", "replicate-decoupling by-fold")
        sensitivity = read_csv(replicate_dir / "forward_drift_sensitivity_by_fold.csv", "replicate-decoupling sensitivity by fold")
        reliability = read_csv(replicate_dir / "forward_drift_reliability_by_bin.csv", "replicate-decoupling reliability")
        envelope = read_csv(ordering_dir / "pseudo_reverse_pair_envelope.csv", "ordering-robustness reverse-pair envelope")
        subject_metrics = read_csv(
            ordering_dir / "pseudo_permutation_subject_metrics.csv",
            "ordering-robustness subject permutation metrics", required=False
        )
        assert by_fold is not None and sensitivity is not None and reliability is not None and envelope is not None
        required_reps = {"cross_AB", "cross_BA"}
        reps = set(by_fold["representation"].dropna().astype(str))
        if not required_reps.issubset(reps):
            raise ValueError("Replicate-decoupling by-fold table lacks: {}".format(sorted(required_reps - reps)))
        required_sens = {"cross_median_AB", "cross_median_BA"}
        sens_reps = set(sensitivity["representation"].dropna().astype(str))
        if not required_sens.issubset(sens_reps):
            raise ValueError("Replicate-decoupling sensitivity table lacks: {}".format(sorted(required_sens - sens_reps)))
        plot_supplementary_block(
            by_fold, matched, sensitivity, reliability, metrics, envelope, subject_metrics, outdir
        )

    manifest_rows=[]
    for stem, family in [
        ("01_pseudo_conditioning_benchmark_ABCD", "main"),
        ("02_conditioning_x0_midpoint_xstar", "main"),
        ("03_matched_same_vs_cross", "main"),
        ("04_ordering_centered_drift", "main"),
        ("05_ordering_slope", "main"),
        ("06_same_minus_cross_coupling", "main"),
        ("Sx_replicate_decoupling_diagnostics", "supplementary"),
        ("Sy_pseudotime_ordering_robustness", "supplementary"),
        ("Sz_reliability_and_subject_consistency", "supplementary"),
    ]:
        png = outdir / (stem + ".png")
        pdf = outdir / (stem + ".pdf")
        if png.exists() or pdf.exists():
            manifest_rows.append({
                "figure": stem,
                "family": family,
                "png": png.name if png.exists() else "",
                "pdf": pdf.name if pdf.exists() else "",
            })
    pd.DataFrame(manifest_rows).to_csv(outdir / "figure_manifest.csv", index=False)

    print("[DONE] Step-7 pseudo-longitudinal benchmark figures written to {}".format(outdir))


if __name__ == "__main__":
    main()
