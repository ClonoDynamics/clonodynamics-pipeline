def metric_arrays(metrics: pd.DataFrame, metric: str) -> Tuple[np.ndarray, np.ndarray]:
    require_columns(metrics, ["representation", metric], "pseudo reverse-pair metrics")
    same = pd.to_numeric(
        metrics.loc[metrics["representation"] == "same_combined", metric],
        errors="coerce",
    ).to_numpy(dtype=float)
    cross = pd.to_numeric(
        metrics.loc[metrics["representation"] == "cross_combined", metric],
        errors="coerce",
    ).to_numpy(dtype=float)
    same = same[np.isfinite(same)]
    cross = cross[np.isfinite(cross)]
    if same.size == 0 or cross.size == 0:
        raise ValueError(
            f"Pseudo reverse-pair metrics do not contain finite same_combined and cross_combined values for {metric}."
        )
    return same, cross


def panel_metric_boxplot(
    ax: plt.Axes,
    metrics: pd.DataFrame,
    metric: str,
    ylabel: str,
    showfliers: bool = False,
    annotate_reduction: bool = False,
    annotate_pair_count: bool = False,
) -> None:
    same, cross = metric_arrays(metrics, metric)
    ax.boxplot(
        [same, cross],
        positions=[1, 2],
        showfliers=bool(showfliers),
        widths=0.55,
    )
    ax.set_xticks([1, 2])
    ax.set_xticklabels([r"Same $x_0$", r"Decoupled $x_0$"])
    ax.set_ylabel(ylabel)
    ax.set_xlabel("Conditioning strategy")

    if annotate_reduction:
        same_med = float(np.median(same))
        cross_med = float(np.median(cross))
        if np.isfinite(same_med) and same_med != 0:
            reduction = 100.0 * (1.0 - cross_med / same_med)
            ax.text(
                0.50,
                0.985,
                f"{reduction:.0f}% reduction",
                transform=ax.transAxes,
                ha="center",
                va="top",
            )

    if annotate_pair_count:
        if "reverse_pair_id" in metrics.columns:
            n_pairs = int(pd.to_numeric(
                metrics["reverse_pair_id"], errors="coerce"
            ).dropna().nunique())
        else:
            n_pairs = int(min(same.size, cross.size))
        ax.text(
            0.50,
            0.895,
            f"{n_pairs:,} order/reverse pairs",
            transform=ax.transAxes,
            ha="center",
            va="top",
            fontsize=max(float(plt.rcParams.get("font.size", 8.0)) - 1.5, 6.0),
        )


