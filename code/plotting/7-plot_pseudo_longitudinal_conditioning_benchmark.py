def subject_boxplot(ax: plt.Axes, subject_metrics: pd.DataFrame) -> None:
    require_columns(
        subject_metrics,
        ["subject", "representation", "centered_mean_abs_drift"],
        "subject-level permutation metrics",
    )
    subject_numeric = pd.to_numeric(subject_metrics["subject"], errors="coerce")
    subjects = sorted(subject_numeric.dropna().unique())
    if not subjects:
        raise ValueError("No subjects found in subject-level permutation metrics")

    # Reuse the first two colors of the standard matplotlib cycle so the visual
    # convention matches the main conditioning figure: same-replicate first,
    # replicate-decoupled second.
    cycle_colors = plt.rcParams["axes.prop_cycle"].by_key().get("color", [])
    same_color = cycle_colors[0] if len(cycle_colors) >= 1 else None
    cross_color = cycle_colors[1] if len(cycle_colors) >= 2 else None

    centers = np.arange(1, len(subjects) + 1, dtype=float)
    offset = 0.17
    same_arrays: List[np.ndarray] = []
    cross_arrays: List[np.ndarray] = []
    valid_centers: List[float] = []
    valid_labels: List[str] = []

    for center, s in zip(centers, subjects):
        d = subject_metrics[subject_numeric == s]
        same = finite(
            d.loc[d["representation"] == "same_combined", "centered_mean_abs_drift"]
        )
        cross = finite(
            d.loc[d["representation"] == "cross_combined", "centered_mean_abs_drift"]
        )
        if same.size == 0 or cross.size == 0:
            continue
        same_arrays.append(same)
        cross_arrays.append(cross)
        valid_centers.append(float(center))
        valid_labels.append("S{}".format(int(s)))

    if not same_arrays:
        raise ValueError("No paired same/cross subject-level metric distributions available")

    same_bp = ax.boxplot(
        same_arrays,
        positions=[c - offset for c in valid_centers],
        widths=0.28,
        showfliers=False,
        patch_artist=True,
    )
    cross_bp = ax.boxplot(
        cross_arrays,
        positions=[c + offset for c in valid_centers],
        widths=0.28,
        showfliers=False,
        patch_artist=True,
    )

    if same_color is not None:
        for box in same_bp["boxes"]:
            box.set_facecolor(same_color)
            box.set_alpha(0.55)
    if cross_color is not None:
        for box in cross_bp["boxes"]:
            box.set_facecolor(cross_color)
            box.set_alpha(0.55)

    ax.set_xticks(valid_centers)
    ax.set_xticklabels(valid_labels)
    ax.set_xlabel("Pseudo subject")
    ax.set_ylabel("Centered mean absolute drift")

    handles = [
        Patch(facecolor=same_color, alpha=0.55, label=r"Same-replicate $x_0$"),
        Patch(facecolor=cross_color, alpha=0.55, label=r"Replicate-decoupled $x_0$"),
    ]
    ax.legend(
        handles=handles,
        frameon=False,
        loc="lower center",
        bbox_to_anchor=(0.5, 1.015),
        ncol=2,
        fontsize=max(float(plt.rcParams.get("font.size", 8.0)) - 1.0, 6.0),
        columnspacing=1.0,
        handletextpad=0.5,
    )


