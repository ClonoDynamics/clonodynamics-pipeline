def panel_A_ccdf(
    ax: plt.Axes,
    files: List[Path],
    args: argparse.Namespace,
) -> None:
    pooled_list: List[np.ndarray] = []

    for path in files:
        x = read_freqs(path, file_sep=args.file_sep)
        pooled_list.append(x)
        xx, yy = empirical_ccdf(x)

        if xx.size > 0:
            ax.plot(
                xx,
                yy,
                color=COLOR_SINGLE,
                alpha=args.single_alpha,
                linewidth=args.single_lw,
            )

    if pooled_list:
        pooled = np.concatenate(pooled_list)
        xx, yy = empirical_ccdf(pooled)
        ax.plot(
            xx,
            yy,
            color=COLOR_POOLED,
            linewidth=args.pooled_lw,
            label="Pooled",
        )
    else:
        ax.text(
            0.5,
            0.5,
            "No raw repertoire files",
            ha="center",
            va="center",
            transform=ax.transAxes,
        )

    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_xlabel("Clone frequency")
    ax.set_ylabel("CCDF")


def _prepare_tail_model_categories(
    scan_df: pd.DataFrame,
) -> Tuple[pd.DataFrame, pd.DataFrame, List[str]]:
    """Validate the corrected Step-1 scan and summarize AICc categories."""
    needed = {
        "threshold_quantile",
        "tln_fit_success",
        "tln_at_powerlaw_boundary",
        "pl_preferred_aicc",
        "pl_preferred_bic",
    }
    missing = needed.difference(scan_df.columns)

    if missing:
        raise ValueError(
            "repertoire_tail_model_scan.csv is missing columns required "
            "for the corrected PL-vs-TLN panel: "
            + ", ".join(sorted(missing))
        )

    df = scan_df.copy()
    df["threshold_quantile"] = pd.to_numeric(
        df["threshold_quantile"],
        errors="coerce",
    )

    for col in [
        "tln_fit_success",
        "tln_at_powerlaw_boundary",
        "pl_preferred_aicc",
        "pl_preferred_bic",
    ]:
        df[col] = coerce_bool_series(df[col])

    df = df[
        np.isfinite(df["threshold_quantile"])
        & df["tln_fit_success"]
    ].copy()

    category_boundary = "TLN optimum at PL boundary"
    category_pl = "Interior TLN; PL retained by AICc"
    category_tln = "Interior TLN favored by AICc"
    category_order = [category_boundary, category_pl, category_tln]

    if df.empty:
        return df, pd.DataFrame(columns=category_order), category_order

    df["model_category"] = np.where(
        df["tln_at_powerlaw_boundary"],
        category_boundary,
        np.where(
            df["pl_preferred_aicc"],
            category_pl,
            category_tln,
        ),
    )

    summary = (
        df.groupby(["threshold_quantile", "model_category"])
        .size()
        .unstack(fill_value=0)
        .reindex(columns=category_order, fill_value=0)
        .sort_index()
    )

    return df, summary, category_order


def panel_B_model_compare(
    ax: plt.Axes,
    scan_df: pd.DataFrame,
    args: argparse.Namespace,
) -> None:
    """Plot the corrected Figure 2B AICc-based model comparison.

    Each bar partitions one threshold-specific set of repertoire evaluations
    into three mutually exclusive categories:

      1. the jointly fitted TLN reaches its optimum at the PL boundary;
      2. the TLN has an interior optimum, but AICc retains the PL;
      3. the TLN has an interior optimum and is favored by AICc.

    No explanatory summary box is drawn inside the plotting area. Overall
    counts are printed to the console and belong in the figure legend/caption.
    """
    needed = {
        "threshold_quantile",
        "tln_fit_success",
        "tln_at_powerlaw_boundary",
        "pl_preferred_aicc",
        "pl_preferred_bic",
    }
    missing = needed.difference(scan_df.columns)

    if missing:
        raise ValueError(
            "repertoire_tail_model_scan.csv is missing columns: "
            + ", ".join(sorted(missing))
        )

    df = scan_df.copy()
    df["threshold_quantile"] = pd.to_numeric(
        df["threshold_quantile"],
        errors="coerce",
    )
    for col in [
        "tln_fit_success",
        "tln_at_powerlaw_boundary",
        "pl_preferred_aicc",
        "pl_preferred_bic",
    ]:
        df[col] = coerce_bool_series(df[col])

    df = df[
        np.isfinite(df["threshold_quantile"])
        & df["tln_fit_success"]
    ].copy()

    if df.empty:
        ax.text(
            0.5,
            0.5,
            "No successful TLN comparison rows",
            ha="center",
            va="center",
            transform=ax.transAxes,
        )
        ax.set_axis_off()
        return

    category_boundary = "PL boundary"
    category_pl = "Interior TLN; PL by AICc"
    category_tln = "Interior TLN; TLN by AICc"
    category_order = [category_boundary, category_pl, category_tln]

    df["panel_b_category"] = np.where(
        df["tln_at_powerlaw_boundary"],
        category_boundary,
        np.where(df["pl_preferred_aicc"], category_pl, category_tln),
    )

    color_map = {
        category_boundary: "0.78",
        category_pl: "0.48",
        category_tln: COLOR_THRESHOLD,
    }

    summary = (
        df.groupby(["threshold_quantile", "panel_b_category"])
        .size()
        .unstack(fill_value=0)
        .reindex(columns=category_order, fill_value=0)
        .sort_index()
    )

    thresholds = summary.index.to_numpy(dtype=float)
    totals = summary.sum(axis=1).to_numpy(dtype=float)
    if np.any(totals <= 0):
        raise ValueError("At least one threshold has no valid model comparisons.")

    percentages = summary.div(totals, axis=0) * 100.0
    x = np.arange(len(thresholds), dtype=float)
    bottom = np.zeros(len(thresholds), dtype=float)

    bar_handles = {}
    for category in category_order:
        heights = percentages[category].to_numpy(dtype=float)
        bars = ax.bar(
            x,
            heights,
            bottom=bottom,
            width=0.70,
            color=color_map[category],
            edgecolor="white",
            linewidth=0.55,
            label=category,
        )
        bar_handles[category] = bars
        bottom += heights

    # Minimal data labels: retain the dominant boundary count and the number
    # of AICc-favored interior TLN fits. The very small middle-category counts
    # are intentionally left to the source table/caption to avoid clutter.
    boundary_counts = summary[category_boundary].to_numpy(dtype=int)
    boundary_heights = percentages[category_boundary].to_numpy(dtype=float)
    for xpos, count, height in zip(x, boundary_counts, boundary_heights):
        if count > 0 and height >= 12.0:
            ax.text(
                xpos,
                height / 2.0,
                str(int(count)),
                ha="center",
                va="center",
                fontsize=max(args.font_size - 0.5, 5.5),
            )

    tln_counts = summary[category_tln].to_numpy(dtype=int)
    tln_heights = percentages[category_tln].to_numpy(dtype=float)
    tln_bottom = (
        percentages[category_boundary].to_numpy(dtype=float)
        + percentages[category_pl].to_numpy(dtype=float)
    )
    for xpos, count, height, y0 in zip(x, tln_counts, tln_heights, tln_bottom):
        if count <= 0:
            continue
        if height >= 4.5:
            y = y0 + height / 2.0
            va = "center"
        else:
            y = 101.0
            va = "bottom"
        ax.text(
            xpos,
            y,
            str(int(count)),
            ha="center",
            va=va,
            fontsize=max(args.font_size - 0.5, 5.5),
            clip_on=False,
        )

    # The legend is always external for this panel; no explanatory inset is
    # placed over the data.
    ax._force_legend_outside = True

    unique_totals = np.unique(totals.astype(int))
    if unique_totals.size != 1:
        print(
            "[WARN] Figure 2B threshold totals differ: "
            + ", ".join(map(str, unique_totals.tolist()))
        )

    overall_n = int(len(df))
    overall_boundary = int(df["tln_at_powerlaw_boundary"].sum())
    overall_pl_aicc = int(df["pl_preferred_aicc"].sum())
    overall_pl_bic = int(df["pl_preferred_bic"].sum())
    print(
        "[FIGURE 2B] evaluations={}; PL-boundary={}; "
        "PL-by-AICc={}; PL-by-BIC={}".format(
            overall_n,
            overall_boundary,
            overall_pl_aicc,
            overall_pl_bic,
        )
    )

    ax.set_xticks(x)
    ax.set_xticklabels([f"{q:.2f}" for q in thresholds])
    ax.set_xlim(-0.55, len(thresholds) - 0.45)
    ax.set_ylim(0, 104)
    ax.set_yticks([0, 25, 50, 75, 100])
    ax.set_xlabel("Tail threshold quantile")
    ax.set_ylabel("Repertoires (%)")

def panel_C_threshold(
    ax: plt.Axes,
    scan_df: pd.DataFrame,
    args: argparse.Namespace,
) -> None:
    """Backward-compatible output alias for the corrected Figure 2B panel.

    Historically, the final manuscript assembler used
    ``figC_threshold_stability`` as Figure 2B. Keeping this wrapper ensures
    that both the old output stem and the canonical model-comparison stem now
    render the corrected AICc-based stacked-bar panel.
    """
    panel_B_model_compare(ax, scan_df, args)


def panel_D_gamma_concordance(
    ax: plt.Axes,
    characteristics: pd.DataFrame,
    args: argparse.Namespace,
) -> None:
    pairs = build_gamma_pairs(characteristics)

    if pairs.empty:
        ax.text(
            0.5,
            0.5,
            "No complete fitted replicate pairs",
            ha="center",
            va="center",
            transform=ax.transAxes,
        )
        ax.set_xlabel(r"$\gamma$ rep. 1")
        ax.set_ylabel(r"$\gamma$ rep. 2")
        return

    ax.scatter(
        pairs["gamma_rep1"],
        pairs["gamma_rep2"],
        s=args.marker_s,
        alpha=args.marker_alpha,
        color=COLOR_GAMMA,
        edgecolors="none",
        label=f"Replicate pairs (n={len(pairs)})",
    )

    x = pairs["gamma_rep1"].to_numpy(float)
    y = pairs["gamma_rep2"].to_numpy(float)

    lo = float(min(np.nanmin(x), np.nanmin(y)))
    hi = float(max(np.nanmax(x), np.nanmax(y)))
    pad = 0.05 * max(hi - lo, 1e-6)

    ax.plot(
        [lo - pad, hi + pad],
        [lo - pad, hi + pad],
        linewidth=args.ref_lw,
        color=COLOR_REF,
        linestyle="--",
    )

    ax.set_xlabel(r"$\gamma$ rep. 1")
    ax.set_ylabel(r"$\gamma$ rep. 2")


