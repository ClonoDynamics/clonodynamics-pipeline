def make_single_panel(
    panel_fn: Callable[[plt.Axes], None],
    fig_dir: Path,
    name: str,
    args: argparse.Namespace,
    title: str = "",
    xlim: Optional[Tuple[float, float]] = None,
    ylim: Optional[Tuple[float, float]] = None,
) -> None:
    fig = plt.figure(figsize=resolve_figure_size(name, args))
    ax = fig.add_subplot(111)

    panel_fn(ax)
    ax.tick_params(
        width=args.tick_w,
        length=args.tick_len,
        pad=args.tick_pad,
    )

    if title and not args.no_titles:
        ax.set_title(title)

    maybe_apply_limits(ax, xlim, ylim)
    apply_axis_config(ax, name)
    apply_legend(ax, args)
    apply_layout(fig)
    save_fig(fig, fig_dir / name, args)
    plt.close(fig)


def make_multipanel(
    fig_dir: Path,
    files: List[Path],
    characteristics: pd.DataFrame,
    scan_df: pd.DataFrame,
    args: argparse.Namespace,
) -> None:
    fig, axes = plt.subplots(
        2,
        2,
        figsize=resolve_figure_size("fig1_repertoire_characterization_multipanel", args, multipanel=True),
        constrained_layout=False,
    )
    axes = axes.ravel()

    panel_A_ccdf(axes[0], files, args)
    panel_B_model_compare(axes[1], scan_df, args)
    panel_D_gamma_concordance(axes[2], characteristics, args)
    axes[3].axis("off")

    panel_stems = [
        "figA_ccdf_pooled",
        "figB_model_compare_density",
        "figD_gamma_replicate_concordance",
    ]

    for ax, label, stem in zip(axes[:3], ["A", "B", "C"], panel_stems):
        ax.tick_params(
            width=args.tick_w,
            length=args.tick_len,
            pad=args.tick_pad,
        )
        apply_axis_config(ax, stem)
        label_panel(ax, label, args)
        apply_legend(ax, args)

    fig.subplots_adjust(
        left=args.multi_left,
        right=args.multi_right,
        bottom=args.multi_bottom,
        top=args.multi_top,
        wspace=args.multi_wspace,
        hspace=args.multi_hspace,
    )

    save_fig(
        fig,
        fig_dir / "fig1_repertoire_characterization_multipanel",
        args,
    )
    plt.close(fig)


