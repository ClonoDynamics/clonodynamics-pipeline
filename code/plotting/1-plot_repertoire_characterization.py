def coerce_bool_series(series: pd.Series) -> pd.Series:
    """Robust boolean parser for mixed-type CSV columns."""
    return (
        series.astype(str)
        .str.strip()
        .str.lower()
        .isin(["true", "1", "yes", "y", "ok", "pass", "passed"])
    )


def clean_repertoire_characteristics(
    characteristics: pd.DataFrame,
) -> pd.DataFrame:
    required = {
        "subject",
        "time",
        "replica",
        "pl_fit_success",
        "pl_gamma_hat",
    }
    missing = required.difference(characteristics.columns)

    if missing:
        raise ValueError(
            "repertoire_characteristics.csv is missing columns: "
            + ", ".join(sorted(missing))
        )

    df = characteristics.copy()

    for col in [
        "subject",
        "time",
        "replica",
        "pl_gamma_hat",
    ]:
        df[col] = pd.to_numeric(df[col], errors="coerce")

    # This is not a QC filter. A failed fit simply has no valid gamma estimate
    # and therefore cannot contribute to gamma-based plots.
    df["pl_fit_success"] = coerce_bool_series(df["pl_fit_success"])

    return df


def build_gamma_pairs(characteristics: pd.DataFrame) -> pd.DataFrame:
    """
    Reconstruct complete replicate pairs directly from repertoire-level fits.

    Only pairs with a successful finite gamma estimate in both replicas are
    included. No concordance threshold or QC decision is applied.
    """
    df = clean_repertoire_characteristics(characteristics)

    df = df[
        df["pl_fit_success"]
        & np.isfinite(df["subject"])
        & np.isfinite(df["time"])
        & df["replica"].isin([1, 2])
        & np.isfinite(df["pl_gamma_hat"])
    ].copy()

    if df.empty:
        return pd.DataFrame(
            columns=[
                "subject",
                "time",
                "gamma_rep1",
                "gamma_rep2",
                "delta_gamma",
            ]
        )

    # Detect duplicate repertoire rows before pivoting; silently choosing one
    # would make the replicate-concordance panel ambiguous.
    duplicate_mask = df.duplicated(
        subset=["subject", "time", "replica"],
        keep=False,
    )
    if duplicate_mask.any():
        dup = df.loc[
            duplicate_mask,
            ["subject", "time", "replica"],
        ].drop_duplicates()
        raise ValueError(
            "repertoire_characteristics.csv contains duplicate rows for "
            "subject/time/replica combinations; cannot construct unique "
            "gamma pairs. Examples:\n"
            + dup.head(10).to_string(index=False)
        )

    wide = df.pivot(
        index=["subject", "time"],
        columns="replica",
        values="pl_gamma_hat",
    )

    if 1 not in wide.columns or 2 not in wide.columns:
        return pd.DataFrame(
            columns=[
                "subject",
                "time",
                "gamma_rep1",
                "gamma_rep2",
                "delta_gamma",
            ]
        )

    wide = wide.dropna(subset=[1, 2]).reset_index()
    wide = wide.rename(columns={1: "gamma_rep1", 2: "gamma_rep2"})
    wide["delta_gamma"] = (
        wide["gamma_rep1"] - wide["gamma_rep2"]
    ).abs()

    return wide[
        [
            "subject",
            "time",
            "gamma_rep1",
            "gamma_rep2",
            "delta_gamma",
        ]
    ]


