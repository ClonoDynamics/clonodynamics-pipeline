def read_repertoire_table(path: Path, file_sep: str) -> pd.DataFrame:
    suffix = path.suffix.lower()

    if suffix in {".parquet", ".pq"}:
        return pd.read_parquet(path)

    if suffix in {".feather", ".arrow"}:
        return pd.read_feather(path)

    try:
        df = pd.read_csv(path, sep=file_sep)
        if df.shape[1] > 1:
            return df
    except Exception:
        pass

    last_err = None
    for sep in ["\t", ",", ";", "|"]:
        try:
            df = pd.read_csv(path, sep=sep)
            if df.shape[1] > 1:
                return df
        except Exception as exc:
            last_err = exc

    try:
        df = pd.read_csv(path, sep=None, engine="python")
        if df.shape[1] > 1:
            return df
    except Exception as exc:
        last_err = exc

    raise ValueError(f"Could not parse repertoire file: {path}") from last_err


def frequencies_from_repertoire(
    df: pd.DataFrame,
    source_name: str = "",
) -> np.ndarray:
    cols_lower = {str(c).strip().lower(): c for c in df.columns}

    if "readfraction" in cols_lower:
        freqs = pd.to_numeric(
            df[cols_lower["readfraction"]],
            errors="coerce",
        ).to_numpy(float)
        freqs = freqs[np.isfinite(freqs) & (freqs > 0)]
        if freqs.size > 0:
            return freqs

    if "readcount" in cols_lower:
        counts = pd.to_numeric(
            df[cols_lower["readcount"]],
            errors="coerce",
        ).to_numpy(float)
        counts = counts[np.isfinite(counts) & (counts > 0)]
        if counts.size > 0:
            return counts / counts.sum()

    raise ValueError(
        f"{source_name}: missing readFraction/readCount columns. "
        f"Found: {list(df.columns)}"
    )


def read_freqs(path: Path, file_sep: str) -> np.ndarray:
    df = read_repertoire_table(path, file_sep=file_sep)
    return frequencies_from_repertoire(df, source_name=path.name)


def list_valid_repertoire_files(
    repertoires_dir: Path,
    pattern_str: str,
    file_sep: str,
) -> List[Path]:
    pattern = re.compile(pattern_str)
    files: List[Path] = []

    for path in sorted(repertoires_dir.iterdir()):
        if not path.is_file() or path.name.startswith("."):
            continue
        if not pattern.match(path.name):
            continue

        try:
            read_freqs(path, file_sep=file_sep)
            files.append(path)
        except Exception as exc:
            print(f"[WARN] Skipping {path.name}: {exc}")

    return files


def empirical_ccdf(x: np.ndarray) -> Tuple[np.ndarray, np.ndarray]:
    x = np.sort(np.asarray(x, dtype=float))
    x = x[np.isfinite(x) & (x > 0)]
    n = len(x)

    if n == 0:
        return np.array([]), np.array([])

    ccdf = (n - np.arange(n)) / n
    return x, ccdf


