def parse_lim(value: str) -> Optional[Tuple[float, float]]:
    value = (value or "").strip()
    if not value:
        return None

    parts = [x.strip() for x in value.split(",")]
    if len(parts) != 2:
        raise ValueError(
            f"Axis limit must contain exactly two comma-separated values: {value}"
        )

    return float(parts[0]), float(parts[1])


def maybe_apply_limits(
    ax: plt.Axes,
    xlim: Optional[Tuple[float, float]],
    ylim: Optional[Tuple[float, float]],
) -> None:
    if xlim is not None:
        ax.set_xlim(*xlim)
    if ylim is not None:
        ax.set_ylim(*ylim)



def apply_axis_config(
    ax: plt.Axes,
    stem: str,
) -> None:
    """Apply the optional manual axis settings defined in AXIS_CONFIG."""
    cfg = AXIS_CONFIG.get(stem, {})

    if cfg.get("xscale"):
        ax.set_xscale(str(cfg["xscale"]))
    if cfg.get("yscale"):
        ax.set_yscale(str(cfg["yscale"]))
    if cfg.get("xlim") is not None:
        ax.set_xlim(*cfg["xlim"])
    if cfg.get("ylim") is not None:
        ax.set_ylim(*cfg["ylim"])
    if cfg.get("xticks") is not None:
        ax.set_xticks(cfg["xticks"])
    if cfg.get("yticks") is not None:
        ax.set_yticks(cfg["yticks"])


