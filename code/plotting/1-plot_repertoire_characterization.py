def main() -> None:
    args = parse_args()

    data_dir = Path(args.analysis_dir).expanduser().resolve()
    fig_dir = ensure_dir(Path(args.figures_dir).expanduser().resolve())

    apply_rcparams(args)

    characteristics = read_csv_required(
        data_dir / "repertoire_characteristics.csv"
    )
    scan_df = read_csv_required(
        data_dir / "repertoire_tail_model_scan.csv"
    )

    # Validate the main analysis table early so schema mismatches fail clearly.
    characteristics_clean = clean_repertoire_characteristics(characteristics)
    gamma_pairs = build_gamma_pairs(characteristics_clean)

    files: List[Path] = []
    if args.repertoires_dir:
        repertoire_dir = Path(args.repertoires_dir).expanduser().resolve()

        if repertoire_dir.exists():
            files = list_valid_repertoire_files(
                repertoire_dir,
                args.pattern,
                args.file_sep,
            )
        else:
            print(f"[WARN] repertoires_dir not found: {repertoire_dir}")

    outputs: List[str] = []

    if args.make_single_panels:
        if files:
            make_single_panel(
                lambda ax: panel_A_ccdf(ax, files, args),
                fig_dir,
                "figA_ccdf_pooled",
                args,
                title="Heavy-tailed clone-size structure",
            )
            outputs.append("figA_ccdf_pooled")
        else:
            print(
                "[WARN] No valid repertoire files found for panel A. "
                "Provide --repertoires_dir to enable CCDF plotting."
            )

        make_single_panel(
            lambda ax: panel_B_model_compare(ax, scan_df, args),
            fig_dir,
            "figB_model_compare_density",
            args,
            title="Complexity-adjusted PL vs TLN comparison",
        )
        outputs.append("figB_model_compare_density")

        make_single_panel(
            lambda ax: panel_C_threshold(ax, scan_df, args),
            fig_dir,
            "figC_threshold_stability",
            args,
            title="Complexity-adjusted PL vs TLN comparison",
        )
        outputs.append("figC_threshold_stability")

        make_single_panel(
            lambda ax: panel_D_gamma_concordance(
                ax,
                characteristics_clean,
                args,
            ),
            fig_dir,
            "figD_gamma_replicate_concordance",
            args,
            title="Replicate concordance of the power-law exponent",
            xlim=parse_lim(args.xlim_gamma),
            ylim=parse_lim(args.ylim_gamma),
        )
        outputs.append("figD_gamma_replicate_concordance")

    if args.make_multipanel:
        make_multipanel(
            fig_dir=fig_dir,
            files=files,
            characteristics=characteristics_clean,
            scan_df=scan_df,
            args=args,
        )
        outputs.append("fig1_repertoire_characterization_multipanel")

    print(
        "✅ Completed plotting with 1-plot_repertoire_characterization_vs2.py."
    )
    print(f"[DATA] {data_dir}")
    print(
        "[DATA] repertoires: {}; successful primary fits: {}; "
        "complete gamma replicate pairs: {}".format(
            len(characteristics_clean),
            int(characteristics_clean["pl_fit_success"].sum()),
            len(gamma_pairs),
        )
    )
    print(f"[FIGS] {fig_dir}")

    for output in outputs:
        print(f"[OUT]  {output}")


if __name__ == "__main__":
    main()
