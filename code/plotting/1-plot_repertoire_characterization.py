def apply_legend(ax: plt.Axes, args: argparse.Namespace) -> None:
    handles, _ = ax.get_legend_handles_labels()
    if not handles or args.legend_mode == "none":
        return


    # Figure 2B deliberately keeps all explanatory material outside the axes.
    # This prevents overlap with the stacked bars in both single-panel and
    # multipanel exports, even if an upstream caller requests inside legends.
    force_outside = bool(getattr(ax, "_force_legend_outside", False))
    legend_mode = "outside" if force_outside else args.legend_mode

    common_kwargs = dict(
        frameon=False if force_outside else bool(args.legend_frame),
        fontsize=args.legend_fontsize,
        handlelength=1.0,
        borderpad=0.15,
        labelspacing=0.25,
        handletextpad=0.35,
    )

    if legend_mode == "outside":
        loc = args.legend_loc
        if loc == "best":
            loc = "upper left"
        ax.legend(
            loc=loc,
            bbox_to_anchor=(args.legend_bbox_x, args.legend_bbox_y),
            borderaxespad=0.0,
            **common_kwargs,
        )
    else:
        ax.legend(loc=args.legend_loc, **common_kwargs)


