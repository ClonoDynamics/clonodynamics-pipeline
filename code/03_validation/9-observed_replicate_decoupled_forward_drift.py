def fold_concordance(
    ab: pl.DataFrame,
    ba: pl.DataFrame,
) -> pl.DataFrame:
    a = (
        ab.filter(pl.col("meets_min_n"))
        .select(
            [
                "bin",
                pl.col("mean_dx").alias("AB"),
            ]
        )
    )
    b = (
        ba.filter(pl.col("meets_min_n"))
        .select(
            [
                "bin",
                pl.col("mean_dx").alias("BA"),
            ]
        )
    )

    d = (
        a.join(b, on="bin", how="inner")
        .filter(
            pl.col("AB").is_finite()
            & pl.col("BA").is_finite()
        )
    )

    if d.is_empty():
        return pl.DataFrame()

    x = d["AB"].to_numpy().astype(float)
    y = d["BA"].to_numpy().astype(float)
    delta = x - y

    return pl.DataFrame(
        [
            {
                "n_matched_bins": int(len(x)),
                "pearson_r_AB_BA": safe_pearson(x, y),
                "mean_abs_difference": float(
                    np.mean(np.abs(delta))
                ),
                "rms_difference": float(
                    np.sqrt(np.mean(delta * delta))
                ),
                "max_abs_difference": float(
                    np.max(np.abs(delta))
                ),
            }
        ]
    )


def subject_interval_support(
    transitions: Path,
    dt: int,
) -> pl.DataFrame:
    lf = (
        pl.scan_parquet(transitions)
        .filter(
            pl.col("dt").cast(pl.Int64, strict=False) == int(dt)
        )
        .select(
            [
                pl.col("subject").cast(pl.Int64, strict=False),
                pl.col("t0").cast(pl.Int64, strict=False),
                pl.col("t1").cast(pl.Int64, strict=False),
                parse_bool_expr("forward_ab_eligible").alias("ab"),
                parse_bool_expr("forward_ba_eligible").alias("ba"),
                parse_bool_expr("common4").alias("common4"),
            ]
        )
        .group_by(["subject", "t0", "t1"])
        .agg(
            [
                pl.len().alias("n_transitions"),
                pl.col("ab").sum().alias("n_forward_ab_eligible"),
                pl.col("ba").sum().alias("n_forward_ba_eligible"),
                pl.col("common4").sum().alias("n_common4"),
                pl.col("ab").mean().alias(
                    "fraction_forward_ab_eligible"
                ),
                pl.col("ba").mean().alias(
                    "fraction_forward_ba_eligible"
                ),
                pl.col("common4").mean().alias(
                    "fraction_common4"
                ),
            ]
        )
        .sort(["subject", "t0", "t1"])
    )
    return collect_streaming(lf)


