def curve_descriptors(
    frame: pl.DataFrame,
    min_bins: int,
) -> Dict[str, object]:
    if frame.is_empty():
        return {
            "n_bins_valid": 0,
            "mean_abs_bin_mean_dx": np.nan,
            "rms_bin_mean_dx": np.nan,
            "max_abs_bin_mean_dx": np.nan,
            "mean_abs_probability_bias": np.nan,
            "slope_mean_dx_vs_x": np.nan,
            "intercept_mean_dx_vs_x": np.nan,
            "x_zero": np.nan,
        }

    d = frame.filter(
        pl.col("meets_min_n").fill_null(False)
        & pl.col("mean_dx").is_finite()
        & pl.col("x_center").is_finite()
    )

    if d.height < int(min_bins):
        return {
            "n_bins_valid": int(d.height),
            "mean_abs_bin_mean_dx": np.nan,
            "rms_bin_mean_dx": np.nan,
            "max_abs_bin_mean_dx": np.nan,
            "mean_abs_probability_bias": np.nan,
            "slope_mean_dx_vs_x": np.nan,
            "intercept_mean_dx_vs_x": np.nan,
            "x_zero": np.nan,
        }

    x = d["x_center"].to_numpy().astype(float)
    y = d["mean_dx"].to_numpy().astype(float)
    p = d["p_dx_gt0"].to_numpy().astype(float)

    slope, intercept, x_zero = safe_slope_intercept(x, y)

    return {
        "n_bins_valid": int(d.height),
        "mean_abs_bin_mean_dx": float(np.mean(np.abs(y))),
        "rms_bin_mean_dx": float(np.sqrt(np.mean(y * y))),
        "max_abs_bin_mean_dx": float(np.max(np.abs(y))),
        "mean_abs_probability_bias": float(np.mean(np.abs(p - 0.5))),
        "slope_mean_dx_vs_x": slope,
        "intercept_mean_dx_vs_x": intercept,
        "x_zero": x_zero,
    }


def summarize_bootstrap_linear(
    linear_boot: pl.DataFrame,
) -> pl.DataFrame:
    if linear_boot.is_empty():
        return pl.DataFrame()

    rows = []
    for rep in sorted(
        linear_boot["representation"].drop_nulls().unique().to_list()
    ):
        d = linear_boot.filter(pl.col("representation") == rep)

        for metric in ["slope", "intercept", "x_zero"]:
            values = finite_array(
                d[metric].to_numpy().astype(float)
            )
            if values.size == 0:
                continue

            rows.append(
                {
                    "representation": rep,
                    "metric": metric,
                    "n_bootstrap_valid": int(values.size),
                    "median": float(np.median(values)),
                    "bootstrap_q025": float(
                        np.quantile(values, 0.025)
                    ),
                    "bootstrap_q975": float(
                        np.quantile(values, 0.975)
                    ),
                    "mean": float(np.mean(values)),
                }
            )

    return pl.DataFrame(rows)


