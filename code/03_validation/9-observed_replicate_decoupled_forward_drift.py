#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
9-observed_replicate_decoupled_forward_drift.py
================================================

Canonical ClonoDynamics Step 9 under the final replicate-resolved framework.

PURPOSE
-------
Apply to the genuine longitudinal cohort the observed replicate-decoupled
forward estimator validated in the pseudo-longitudinal technical null
(Step 7).

The primary estimand is abundance-conditioned observed displacement at a fixed
longitudinal lag, using different technical replicates for conditioning and
outcome.

PRIMARY ESTIMANDS
-----------------
Let technical replicate 1 = A and replicate 2 = B.

AB:
    conditioning = x_observed_rep1_t0
    displacement = dx_observed_rep2
                 = x_observed_rep2_t1 - x_observed_rep2_t0
    support      = forward_ab_eligible

BA:
    conditioning = x_observed_rep2_t0
    displacement = dx_observed_rep1
                 = x_observed_rep1_t1 - x_observed_rep1_t0
    support      = forward_ba_eligible

The two folds are correlated reciprocal views of the same biological
transitions. They are estimated separately and are combined only AFTER
binning with equal fold weight:

    cross_combined_b
        = 0.5 * (cross_AB_b + cross_BA_b)

AB and BA are never concatenated and treated as independent biological
observations.

PRIMARY SUPPORT
---------------
Step 9 does NOT use TT/TF/FT/FF as a primary filter.

The primary supports are the Step-5 estimand-specific eligibility fields:

    forward_ab_eligible
    forward_ba_eligible

These are realized-positive observed-measurement support definitions, not
posterior-quality filters and not biological presence/absence states.

MATCHED SAME-VERSUS-CROSS CONTROL
---------------------------------
To quantify the technical amplification caused by reusing the same measurement
for conditioning and displacement, Step 9 also performs a matched comparison on
the stricter `common4` support:

    same_A:
        x_A(t0) -> Delta x_A

    cross_AB_matched:
        x_A(t0) -> Delta x_B

    same_B:
        x_B(t0) -> Delta x_B

    cross_BA_matched:
        x_B(t0) -> Delta x_A

Because all four observed endpoint measurements are positive on common4, these
comparisons use exactly the same biological transitions within each fold.

The matched comparison is a diagnostic/control. The primary longitudinal
forward estimator remains the broader AB/BA estimand-specific support.

INPUT
-----
The canonical input is the current generic Step-5 transition table:

    longitudinal_transitions.parquet

generated by:

    5-longitudinal_transition_assembly.py

Required columns:

    subject
    aaSeqCDR3
    t0
    t1
    dt

    x_observed_rep1_t0
    x_observed_rep2_t0

    dx_observed_rep1
    dx_observed_rep2

    forward_ab_eligible
    forward_ba_eligible
    common4

The script no longer reads the old latent trajectory table and no longer
requires replicate-specific latent posterior means/medians.

PRIMARY LAG
-----------
The default primary analysis is:

    dt = 1 week

to quantify forward structure over adjacent longitudinal sampling times.

Other lags can be analyzed explicitly with `--dt`, but the main Step-9
longitudinal forward analysis is intended for dt=1.

BINNING
-------
A common fixed observed-abundance grid is used by every Step-9 representation.

Default:
    n_bins  = 20
    binning = quantile
    q_low   = 0.005
    q_high  = 0.995

The default bin geometry is derived from the two PRIMARY conditioning
distributions with EXACT equal fold mass:

    0.5 mass:
        x_observed_rep1_t0 on forward_ab_eligible

    0.5 mass:
        x_observed_rep2_t0 on forward_ba_eligible

Each AB observation therefore receives weight 0.5/n_AB and each BA observation
weight 0.5/n_BA during edge construction. The bin geometry is consequently
invariant to unequal AB/BA eligible row counts.

The same resulting edges are then used for AB, BA and the common4 matched
same/cross controls.

An external bin-edge file can be supplied with `--bin-edges-file`.

POINT ESTIMATES
---------------
For each representation x abundance bin:

    n
    n_subjects
    x_mean
    x_median
    mean_dx
    median_dx
    p_dx_gt0
    sd_dx

A bin is marked as valid when:

    n >= --min-n

The default is 50 rows/bin.

PRIMARY COHORT CURVE
--------------------
For every bin where AB and BA are both valid:

    mean_dx_cross
        = 0.5 * (mean_dx_AB + mean_dx_BA)

    median_dx_cross
        = 0.5 * (median_dx_AB + median_dx_BA)

    p_dx_gt0_cross
        = 0.5 * (p_AB + p_BA)

The x coordinate is the fixed bin center.

For combined curves, support is reported fold-by-fold. The script does not
report a generic summed row count because AB and BA can contain overlapping
biological transitions and are not independent samples.

SUBJECT-CLUSTER BOOTSTRAP
-------------------------
Biological uncertainty is quantified by resampling SUBJECTS with replacement.

Default:
    n_bootstrap   = 2000
    bootstrap_seed = 123

The SAME subject draw is used for AB and BA and for all matched same/cross
controls.

Within each bootstrap draw:
    1. each fold is reconstructed separately from subject x bin sufficient
       statistics;
    2. AB and BA are combined with equal fold weight;
    3. same_A/same_B and matched cross folds are combined analogously.

The 2.5th–97.5th bootstrap percentiles are biological subject-cluster
confidence intervals.

LINEAR DESCRIPTORS
------------------
For each valid binned representation the script reports an unweighted linear
descriptor across valid bin centers:

    mean_dx = intercept + slope * x

and, when finite:

    x_zero = -intercept / slope

The line is a compact descriptor of the abundance-dependent curve; it is not
assumed to be the generative dynamical law.

Bootstrap distributions of slope, intercept and x_zero are reported for:
    cross_combined
    same_combined
    cross_combined_matched

Bootstrap linear descriptors are evaluated on the SAME fixed valid-bin set as
the corresponding point estimate. Bootstrap resampling therefore changes the
subject composition, not the definition of the abundance domain used by the
descriptor.

AB/BA CONCORDANCE
-----------------
Primary AB and BA mean-displacement curves are compared across matched valid
bins using:
    Pearson r
    mean absolute difference
    RMS difference
    maximum absolute difference

SUBJECT AND LOSO ROBUSTNESS
---------------------------
The primary cross_combined curve is reconstructed:
    - separately for each biological subject;
    - after leaving each subject out in turn.

These are descriptive robustness diagnostics.

OUTPUT
------
<outdir>/
    00_run_config.json
    00_pipeline_manifest.csv
    README_outputs.md

    01_forward_bin_edges.csv
    02_primary_forward_by_bin.csv
    03_matched_same_vs_cross_by_bin.csv
    04_forward_global_summary.csv
    05_subject_forward_by_bin.csv
    06_loso_forward_by_bin.csv
    07_AB_BA_concordance.csv
    08_subject_interval_support.csv
    09_bootstrap_linear_descriptors.csv

Optional:
    10_bootstrap_draws.parquet
        only with --keep-bootstrap-draws

PRIMARY RUN
-----------
python3 9-observed_replicate_decoupled_forward_drift.py \
    --transitions \
    ./results_4/5-longitudinal_transition_assembly/longitudinal_transitions.parquet \
    --outdir \
    ./results_4/9-observed_replicate_decoupled_forward_drift \
    --dataset-label healthy_longitudinal \
    --dt 1 \
    --n-bins 20 \
    --binning quantile \
    --q-low 0.005 \
    --q-high 0.995 \
    --min-n 50 \
    --n-bootstrap 2000 \
    --bootstrap-seed 123

INTERPRETATION
--------------
Step 9 asks whether a systematic abundance-dependent forward profile remains in
the genuine longitudinal cohort after direct same-replicate
conditioning/displacement coupling has been removed.

It does not compare the real curve to the pseudo ensemble. That empirical
real-versus-pseudo comparison belongs to Step 10.
"""

