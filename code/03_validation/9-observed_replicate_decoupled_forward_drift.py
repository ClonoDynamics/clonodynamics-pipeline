def sufficient_to_arrays(
    suff: pl.DataFrame,
    subjects: Sequence[int],
    n_bins: int,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    si = {int(subject): i for i, subject in enumerate(subjects)}

    n = np.zeros((len(subjects), n_bins), dtype=float)
    sums = np.zeros_like(n)
    pos = np.zeros_like(n)

    for row in suff.iter_rows(named=True):
        subject = int(row["subject"])
        if subject not in si:
            continue
        i = si[subject]
        b = int(row["bin"])
        n[i, b] = float(row["n"])
        sums[i, b] = float(row["sum_dx"])
        pos[i, b] = float(row["n_pos"])

    return n, sums, pos


def all_subjects_from_sufficient(
    suff_by_rep: Mapping[str, pl.DataFrame],
) -> List[int]:
    subjects = set()
    for frame in suff_by_rep.values():
        if "subject" in frame.columns:
            subjects.update(
                int(x)
                for x in frame["subject"].drop_nulls().unique().to_list()
            )
    return sorted(subjects)


def bootstrap_curves(
    suff_by_rep: Mapping[str, pl.DataFrame],
    edges: np.ndarray,
    n_bootstrap: int,
    seed: int,
) -> pl.DataFrame:
    if int(n_bootstrap) <= 0:
        return pl.DataFrame()

    subjects = all_subjects_from_sufficient(suff_by_rep)
    if len(subjects) < 2:
        raise RuntimeError(
            "Need at least two biological subjects for subject-cluster bootstrap."
        )

    n_bins = len(edges) - 1
    arrays = {
        rep: sufficient_to_arrays(frame, subjects, n_bins)
        for rep, frame in suff_by_rep.items()
    }

    rng = np.random.default_rng(int(seed))
    rows: List[Dict[str, object]] = []

    for boot in range(int(n_bootstrap)):
        draw = rng.integers(
            0,
            len(subjects),
            size=len(subjects),
        )
        mult = np.bincount(
            draw,
            minlength=len(subjects),
        ).astype(float)[:, None]

        fold_values: Dict[str, Tuple[np.ndarray, np.ndarray]] = {}

        for rep, (n_arr, sum_arr, pos_arr) in arrays.items():
            n = np.sum(mult * n_arr, axis=0)
            s = np.sum(mult * sum_arr, axis=0)
            p = np.sum(mult * pos_arr, axis=0)

            mean_dx = np.divide(
                s,
                n,
                out=np.full(n_bins, np.nan),
                where=n > 0,
            )
            p_pos = np.divide(
                p,
                n,
                out=np.full(n_bins, np.nan),
                where=n > 0,
            )
            fold_values[rep] = (mean_dx, p_pos)

        combined_specs = {
            "cross_combined": ("cross_AB", "cross_BA"),
            "same_combined": ("same_A", "same_B"),
            "cross_combined_matched": (
                "cross_AB_matched",
                "cross_BA_matched",
            ),
        }

        # Store primary fold curves and combined controls.
        for rep in ["cross_AB", "cross_BA"]:
            if rep not in fold_values:
                continue
            mean_dx, p_pos = fold_values[rep]
            for b in range(n_bins):
                rows.append(
                    {
                        "bootstrap": int(boot),
                        "representation": rep,
                        "bin": int(b),
                        "mean_dx": float(mean_dx[b]),
                        "p_dx_gt0": float(p_pos[b]),
                    }
                )

        for combined, (left, right) in combined_specs.items():
            if left not in fold_values or right not in fold_values:
                continue
            l_mean, l_p = fold_values[left]
            r_mean, r_p = fold_values[right]

            mean_dx = 0.5 * (l_mean + r_mean)
            p_pos = 0.5 * (l_p + r_p)

            for b in range(n_bins):
                rows.append(
                    {
                        "bootstrap": int(boot),
                        "representation": combined,
                        "bin": int(b),
                        "mean_dx": float(mean_dx[b]),
                        "p_dx_gt0": float(p_pos[b]),
                    }
                )

    return pl.DataFrame(rows)


def bootstrap_ci(
    boot: pl.DataFrame,
    valid_bins_by_rep: Mapping[str, Sequence[int]],
) -> pl.DataFrame:
    """Bootstrap intervals on the fixed point-estimate valid-bin domain."""
    if boot.is_empty():
        return pl.DataFrame()

    allowed_rows = []
    for rep, bins in valid_bins_by_rep.items():
        for b in sorted(set(int(x) for x in bins)):
            allowed_rows.append({"representation": str(rep), "bin": int(b)})

    if not allowed_rows:
        return pl.DataFrame()

    allowed = pl.DataFrame(allowed_rows)
    return (
        boot.lazy()
        .join(allowed.lazy(), on=["representation", "bin"], how="inner")
        .filter(pl.col("mean_dx").is_finite())
        .group_by(["representation", "bin"])
        .agg([
            pl.col("mean_dx").quantile(0.025, interpolation="linear").alias("mean_dx_ci025"),
            pl.col("mean_dx").quantile(0.975, interpolation="linear").alias("mean_dx_ci975"),
            pl.col("p_dx_gt0").quantile(0.025, interpolation="linear").alias("p_dx_gt0_ci025"),
            pl.col("p_dx_gt0").quantile(0.975, interpolation="linear").alias("p_dx_gt0_ci975"),
            pl.len().alias("n_bootstrap_valid"),
        ])
        .sort(["representation", "bin"])
        .collect()
    )


def bootstrap_linear_descriptors(
    boot: pl.DataFrame,
    edges: np.ndarray,
    min_bins: int,
    valid_bins_by_rep: Mapping[str, Sequence[int]],
) -> pl.DataFrame:
    """Bootstrap linear descriptors on each point estimator's fixed valid bins."""
    if boot.is_empty():
        return pl.DataFrame()

    centers = 0.5 * (edges[:-1] + edges[1:])
    target_reps = {
        "cross_combined",
        "same_combined",
        "cross_combined_matched",
    }

    rows: List[Dict[str, object]] = []

    for rep in sorted(target_reps):
        allowed = sorted(set(int(x) for x in valid_bins_by_rep.get(rep, [])))
        if len(allowed) < int(min_bins):
            continue

        d = boot.filter(
            (pl.col("representation") == rep)
            & pl.col("bin").is_in(allowed)
        )
        if d.is_empty():
            continue

        for boot_id, g in d.group_by("bootstrap", maintain_order=True):
            if isinstance(boot_id, tuple):
                boot_id = boot_id[0]

            by_bin = {
                int(row["bin"]): row["mean_dx"]
                for row in g.iter_rows(named=True)
            }
            x_values = []
            y_values = []
            for b in allowed:
                value = by_bin.get(b)
                if value is None or not np.isfinite(float(value)):
                    continue
                x_values.append(float(centers[b]))
                y_values.append(float(value))

            if len(x_values) < int(min_bins):
                continue

            slope, intercept, x_zero = safe_slope_intercept(
                np.asarray(x_values, dtype=float),
                np.asarray(y_values, dtype=float),
            )
            rows.append({
                "bootstrap": int(boot_id),
                "representation": rep,
                "n_bins": int(len(x_values)),
                "slope": slope,
                "intercept": intercept,
                "x_zero": x_zero,
            })

    return pl.DataFrame(rows)


