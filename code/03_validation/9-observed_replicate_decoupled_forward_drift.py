def parse_bool_expr(column: str) -> pl.Expr:
    s = pl.col(column)
    return (
        pl.when(s.cast(pl.Boolean, strict=False).is_not_null())
        .then(s.cast(pl.Boolean, strict=False).fill_null(False))
        .otherwise(
            s.cast(pl.String, strict=False)
            .str.strip_chars()
            .str.to_lowercase()
            .is_in(["true", "t", "1", "yes", "y"])
            .fill_null(False)
        )
    )


def json_safe(x):
    if isinstance(x, Path):
        return str(x)
    if isinstance(x, np.integer):
        return int(x)
    if isinstance(x, np.floating):
        return None if np.isnan(x) else float(x)
    if isinstance(x, np.bool_):
        return bool(x)
    if isinstance(x, dict):
        return {str(k): json_safe(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [json_safe(v) for v in x]
    return x


def stable_json_sha256(payload: Mapping[str, object]) -> str:
    import hashlib
    raw = json.dumps(
        json_safe(dict(payload)),
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=True,
    )
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()


def path_identity(path: Path) -> Dict[str, object]:
    p = path.expanduser().resolve(strict=True)
    stat = p.stat()
    return {
        "path": str(p),
        "size_bytes": int(stat.st_size),
        "mtime_ns": int(stat.st_mtime_ns),
    }


def finite_array(values) -> np.ndarray:
    x = np.asarray(values, dtype=float)
    return x[np.isfinite(x)]


def safe_slope_intercept(
    x: np.ndarray,
    y: np.ndarray,
) -> Tuple[float, float, float]:
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)
    ok = np.isfinite(x) & np.isfinite(y)
    if int(ok.sum()) < 2:
        return np.nan, np.nan, np.nan

    xv = x[ok]
    yv = y[ok]
    if np.ptp(xv) <= 0:
        return np.nan, np.nan, np.nan

    slope, intercept = np.polyfit(xv, yv, 1)
    slope = float(slope)
    intercept = float(intercept)

    if np.isfinite(slope) and abs(slope) > 1e-12:
        x_zero = float(-intercept / slope)
    else:
        x_zero = np.nan

    return slope, intercept, x_zero


def safe_pearson(
    x: np.ndarray,
    y: np.ndarray,
) -> float:
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)
    ok = np.isfinite(x) & np.isfinite(y)
    if int(ok.sum()) < 2:
        return np.nan

    xv = x[ok]
    yv = y[ok]
    if np.std(xv) <= 0 or np.std(yv) <= 0:
        return np.nan
    return float(np.corrcoef(xv, yv)[0, 1])


