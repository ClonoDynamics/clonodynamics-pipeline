def sufficient_lookup(
    frame: pl.DataFrame,
) -> Dict[Tuple[int, int], Tuple[float, float, float]]:
    out = {}
    for row in frame.iter_rows(named=True):
        out[(int(row["subject"]), int(row["bin"]))] = (
            float(row["n"]),
            float(row["sum_dx"]),
            float(row["n_pos"]),
        )
    return out


def build_subject_primary_curves(
    suff_ab: pl.DataFrame,
    suff_ba: pl.DataFrame,
    edges: np.ndarray,
) -> pl.DataFrame:
    ab = sufficient_lookup(suff_ab)
    ba = sufficient_lookup(suff_ba)

    subjects = sorted(
        {s for s, _ in ab}
        | {s for s, _ in ba}
    )

    rows = []
    for subject in subjects:
        for b in range(len(edges) - 1):
            a = ab.get((subject, b))
            z = ba.get((subject, b))
            if a is None or z is None:
                continue
            if a[0] <= 0 or z[0] <= 0:
                continue

            mean_ab = a[1] / a[0]
            mean_ba = z[1] / z[0]
            p_ab = a[2] / a[0]
            p_ba = z[2] / z[0]

            rows.append(
                {
                    "subject": int(subject),
                    "representation": "cross_combined",
                    "bin": int(b),
                    "x_left": float(edges[b]),
                    "x_right": float(edges[b + 1]),
                    "x_center": float(
                        0.5 * (edges[b] + edges[b + 1])
                    ),
                    "n_AB": int(a[0]),
                    "n_BA": int(z[0]),
                    "mean_dx_AB": float(mean_ab),
                    "mean_dx_BA": float(mean_ba),
                    "mean_dx": float(
                        0.5 * (mean_ab + mean_ba)
                    ),
                    "p_dx_gt0": float(
                        0.5 * (p_ab + p_ba)
                    ),
                }
            )

    return (
        pl.DataFrame(rows).sort(["subject", "bin"])
        if rows else pl.DataFrame()
    )


def build_loso_primary_curves(
    suff_ab: pl.DataFrame,
    suff_ba: pl.DataFrame,
    edges: np.ndarray,
) -> pl.DataFrame:
    ab = sufficient_lookup(suff_ab)
    ba = sufficient_lookup(suff_ba)

    subjects = sorted(
        {s for s, _ in ab}
        | {s for s, _ in ba}
    )
    if len(subjects) < 2:
        return pl.DataFrame()

    rows = []

    for omitted in subjects:
        kept = [s for s in subjects if s != omitted]

        for b in range(len(edges) - 1):
            n_ab = sum(
                ab.get((s, b), (0.0, 0.0, 0.0))[0]
                for s in kept
            )
            sum_ab = sum(
                ab.get((s, b), (0.0, 0.0, 0.0))[1]
                for s in kept
            )
            pos_ab = sum(
                ab.get((s, b), (0.0, 0.0, 0.0))[2]
                for s in kept
            )

            n_ba = sum(
                ba.get((s, b), (0.0, 0.0, 0.0))[0]
                for s in kept
            )
            sum_ba = sum(
                ba.get((s, b), (0.0, 0.0, 0.0))[1]
                for s in kept
            )
            pos_ba = sum(
                ba.get((s, b), (0.0, 0.0, 0.0))[2]
                for s in kept
            )

            if n_ab <= 0 or n_ba <= 0:
                continue

            mean_ab = sum_ab / n_ab
            mean_ba = sum_ba / n_ba
            p_ab = pos_ab / n_ab
            p_ba = pos_ba / n_ba

            rows.append(
                {
                    "omitted_subject": int(omitted),
                    "representation": "cross_combined",
                    "bin": int(b),
                    "x_left": float(edges[b]),
                    "x_right": float(edges[b + 1]),
                    "x_center": float(
                        0.5 * (edges[b] + edges[b + 1])
                    ),
                    "n_AB": int(n_ab),
                    "n_BA": int(n_ba),
                    "mean_dx_AB": float(mean_ab),
                    "mean_dx_BA": float(mean_ba),
                    "mean_dx": float(
                        0.5 * (mean_ab + mean_ba)
                    ),
                    "p_dx_gt0": float(
                        0.5 * (p_ab + p_ba)
                    ),
                }
            )

    return (
        pl.DataFrame(rows).sort(["omitted_subject", "bin"])
        if rows else pl.DataFrame()
    )


