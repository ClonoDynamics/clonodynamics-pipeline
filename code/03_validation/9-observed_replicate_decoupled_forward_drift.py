def read_edges_file(path: Path) -> np.ndarray:
    path = Path(path)

    if path.suffix.lower() == ".csv":
        d = pl.read_csv(path)
    elif path.suffix.lower() in {".parquet", ".pq"}:
        d = pl.read_parquet(path)
    else:
        values = [
            float(line.strip())
            for line in path.read_text().splitlines()
            if line.strip()
        ]
        edges = np.unique(np.asarray(values, dtype=float))
        if edges.size < 3:
            raise ValueError("External bin-edge file contains too few edges.")
        return edges

    if "edge" in d.columns:
        edges = np.asarray(d["edge"].to_numpy(), dtype=float)
    elif {"x_left", "x_right"}.issubset(set(d.columns)):
        left = np.asarray(d["x_left"].to_numpy(), dtype=float)
        right = np.asarray(d["x_right"].to_numpy(), dtype=float)
        edges = np.r_[left[:1], right]
    elif {"x_lo", "x_hi"}.issubset(set(d.columns)):
        left = np.asarray(d["x_lo"].to_numpy(), dtype=float)
        right = np.asarray(d["x_hi"].to_numpy(), dtype=float)
        edges = np.r_[left[:1], right]
    else:
        raise ValueError(
            f"{path}: could not infer bin edges. Expected edge or x_left/x_right."
        )

    edges = np.unique(edges[np.isfinite(edges)])
    edges.sort()
    if edges.size < 3:
        raise ValueError("External bin-edge file contains too few finite edges.")
    return edges


def equal_fold_weighted_quantiles(
    x_ab: np.ndarray,
    x_ba: np.ndarray,
    probs: np.ndarray,
) -> np.ndarray:
    """Deterministic empirical quantiles with exact 0.5/0.5 fold mass."""
    a = np.asarray(x_ab, dtype=float)
    b = np.asarray(x_ba, dtype=float)
    a = a[np.isfinite(a)]
    b = b[np.isfinite(b)]

    if a.size == 0 or b.size == 0:
        raise ValueError(
            "Both AB and BA conditioning distributions must contain finite values."
        )

    values = np.concatenate([a, b])
    weights = np.concatenate([
        np.full(a.size, 0.5 / float(a.size), dtype=float),
        np.full(b.size, 0.5 / float(b.size), dtype=float),
    ])

    order = np.argsort(values, kind="mergesort")
    values = values[order]
    weights = weights[order]

    # Mid-weight CDF positions give deterministic linear interpolation while
    # preserving exact fold mass.
    cdf_mid = np.cumsum(weights) - 0.5 * weights
    xp = np.concatenate([[0.0], cdf_mid, [1.0]])
    fp = np.concatenate([[values[0]], values, [values[-1]]])

    q = np.asarray(probs, dtype=float)
    if np.any(~np.isfinite(q)) or np.any((q < 0) | (q > 1)):
        raise ValueError("Weighted quantile probabilities must lie in [0,1].")

    return np.interp(q, xp, fp)


def estimate_primary_edges(
    transitions: Path,
    dt: int,
    n_bins: int,
    mode: str,
    q_low: float,
    q_high: float,
) -> Tuple[np.ndarray, Dict[str, object]]:
    """Derive one common observed-abundance grid with exact AB/BA fold mass."""
    base = (
        pl.scan_parquet(transitions)
        .filter(pl.col("dt").cast(pl.Int64, strict=False) == int(dt))
        .select([
            pl.col("x_observed_rep1_t0").cast(pl.Float64, strict=False).alias("xA0"),
            pl.col("x_observed_rep2_t0").cast(pl.Float64, strict=False).alias("xB0"),
            parse_bool_expr("forward_ab_eligible").alias("ab"),
            parse_bool_expr("forward_ba_eligible").alias("ba"),
        ])
    )

    ab = collect_streaming(
        base.filter(pl.col("ab") & pl.col("xA0").is_finite())
        .select(pl.col("xA0").alias("x"))
    )
    ba = collect_streaming(
        base.filter(pl.col("ba") & pl.col("xB0").is_finite())
        .select(pl.col("xB0").alias("x"))
    )

    x_ab = np.asarray(ab["x"].to_numpy(), dtype=float)
    x_ba = np.asarray(ba["x"].to_numpy(), dtype=float)

    if x_ab.size == 0 or x_ba.size == 0:
        raise RuntimeError(
            "Could not derive observed forward bin edges: one primary fold has "
            "no finite eligible conditioning values."
        )

    if mode == "quantile":
        probs = np.linspace(float(q_low), float(q_high), int(n_bins) + 1)
        edges = equal_fold_weighted_quantiles(x_ab, x_ba, probs)
    elif mode == "equal_width":
        lo, hi = equal_fold_weighted_quantiles(
            x_ab, x_ba, np.asarray([float(q_low), float(q_high)])
        )
        edges = np.linspace(float(lo), float(hi), int(n_bins) + 1)
    else:
        raise ValueError(f"Unknown binning mode: {mode}")

    edges = np.unique(edges[np.isfinite(edges)])
    edges.sort()
    if edges.size < 3:
        raise RuntimeError("Could not derive at least two abundance bins.")

    info = {
        "policy": "exact_equal_fold_mass",
        "AB_mass": 0.5,
        "BA_mass": 0.5,
        "AB_row_count_weighting": False,
        "n_AB_conditioning_values": int(x_ab.size),
        "n_BA_conditioning_values": int(x_ba.size),
        "weighted_quantile_interpolation": "weighted_CDF_midpoint_linear",
        "requested_mode": str(mode),
        "q_low": float(q_low),
        "q_high": float(q_high),
        "n_bins": int(len(edges) - 1),
        "x_min": float(edges[0]),
        "x_max": float(edges[-1]),
    }
    return edges, info


def save_edges(
    edges: np.ndarray,
    path: Path,
) -> None:
    pl.DataFrame(
        {
            "bin": np.arange(len(edges) - 1, dtype=np.int32),
            "x_left": edges[:-1],
            "x_right": edges[1:],
            "x_center": 0.5 * (edges[:-1] + edges[1:]),
        }
    ).write_csv(path)


def bin_expr(
    x_col: str,
    edges: np.ndarray,
) -> pl.Expr:
    x = pl.col(x_col).cast(pl.Float64, strict=False)
    expr = pl.lit(None, dtype=pl.Int32)

    for i in range(len(edges) - 2, -1, -1):
        lo = float(edges[i])
        hi = float(edges[i + 1])
        if i == len(edges) - 2:
            cond = (x >= lo) & (x <= hi)
        else:
            cond = (x >= lo) & (x < hi)
        expr = (
            pl.when(cond)
            .then(pl.lit(i, dtype=pl.Int32))
            .otherwise(expr)
        )

    return expr.alias("bin")


