def fold_point_stats(
    transitions: Path,
    edges: np.ndarray,
    dt: int,
    representation: str,
    min_n: int,
) -> pl.DataFrame:
    spec = ALL_FOLDS[representation]
    x_col = str(spec["x"])
    dx_col = str(spec["dx"])
    support_col = str(spec["support"])

    lf = (
        pl.scan_parquet(transitions)
        .filter(
            pl.col("dt").cast(pl.Int64, strict=False) == int(dt)
        )
        .select(
            [
                pl.col("subject").cast(pl.Int64, strict=False),
                pl.col(x_col).cast(pl.Float64, strict=False).alias("x"),
                pl.col(dx_col).cast(pl.Float64, strict=False).alias("dx"),
                parse_bool_expr(support_col).alias("eligible"),
            ]
        )
        .filter(
            pl.col("eligible")
            & pl.col("x").is_finite()
            & pl.col("dx").is_finite()
        )
        .with_columns(bin_expr("x", edges))
        .filter(pl.col("bin").is_not_null())
        .group_by("bin")
        .agg(
            [
                pl.len().alias("n"),
                pl.col("subject").n_unique().alias("n_subjects"),
                pl.col("x").mean().alias("x_mean"),
                pl.col("x").median().alias("x_median"),
                pl.col("dx").mean().alias("mean_dx"),
                pl.col("dx").median().alias("median_dx"),
                (pl.col("dx") > 0).mean().alias("p_dx_gt0"),
                pl.col("dx").std().alias("sd_dx"),
            ]
        )
        .sort("bin")
    )

    out = collect_streaming(lf).with_columns(
        [
            pl.lit(representation).alias("representation"),
            (pl.col("n") >= int(min_n)).alias("meets_min_n"),
        ]
    )
    return out


def fold_subject_sufficient(
    transitions: Path,
    edges: np.ndarray,
    dt: int,
    representation: str,
) -> pl.DataFrame:
    spec = ALL_FOLDS[representation]
    x_col = str(spec["x"])
    dx_col = str(spec["dx"])
    support_col = str(spec["support"])

    lf = (
        pl.scan_parquet(transitions)
        .filter(
            pl.col("dt").cast(pl.Int64, strict=False) == int(dt)
        )
        .select(
            [
                pl.col("subject").cast(pl.Int64, strict=False),
                pl.col(x_col).cast(pl.Float64, strict=False).alias("x"),
                pl.col(dx_col).cast(pl.Float64, strict=False).alias("dx"),
                parse_bool_expr(support_col).alias("eligible"),
            ]
        )
        .filter(
            pl.col("eligible")
            & pl.col("x").is_finite()
            & pl.col("dx").is_finite()
        )
        .with_columns(bin_expr("x", edges))
        .filter(pl.col("bin").is_not_null())
        .group_by(["subject", "bin"])
        .agg(
            [
                pl.len().alias("n"),
                pl.col("dx").sum().alias("sum_dx"),
                (pl.col("dx") > 0).sum().alias("n_pos"),
            ]
        )
        .sort(["subject", "bin"])
    )

    return collect_streaming(lf).with_columns(
        pl.lit(representation).alias("representation")
    )


def attach_edges(
    frame: pl.DataFrame,
    edges: np.ndarray,
) -> pl.DataFrame:
    edge_df = pl.DataFrame(
        {
            "bin": np.arange(len(edges) - 1, dtype=np.int32),
            "x_left": edges[:-1],
            "x_right": edges[1:],
            "x_center": 0.5 * (edges[:-1] + edges[1:]),
        }
    )
    return edge_df.join(frame, on="bin", how="left")


def combine_two_folds(
    left: pl.DataFrame,
    right: pl.DataFrame,
    edges: np.ndarray,
    representation: str,
    left_label: str,
    right_label: str,
) -> pl.DataFrame:
    a = left.select(
        [
            "bin",
            pl.col("n").alias(f"n_{left_label}"),
            pl.col("n_subjects").alias(f"n_subjects_{left_label}"),
            pl.col("x_mean").alias(f"x_mean_{left_label}"),
            pl.col("x_median").alias(f"x_median_{left_label}"),
            pl.col("mean_dx").alias(f"mean_dx_{left_label}"),
            pl.col("median_dx").alias(f"median_dx_{left_label}"),
            pl.col("p_dx_gt0").alias(f"p_dx_gt0_{left_label}"),
            pl.col("meets_min_n").alias(f"valid_{left_label}"),
        ]
    )
    b = right.select(
        [
            "bin",
            pl.col("n").alias(f"n_{right_label}"),
            pl.col("n_subjects").alias(f"n_subjects_{right_label}"),
            pl.col("x_mean").alias(f"x_mean_{right_label}"),
            pl.col("x_median").alias(f"x_median_{right_label}"),
            pl.col("mean_dx").alias(f"mean_dx_{right_label}"),
            pl.col("median_dx").alias(f"median_dx_{right_label}"),
            pl.col("p_dx_gt0").alias(f"p_dx_gt0_{right_label}"),
            pl.col("meets_min_n").alias(f"valid_{right_label}"),
        ]
    )

    m = a.join(b, on="bin", how="inner")

    m = m.with_columns(
        [
            (
                0.5
                * (
                    pl.col(f"mean_dx_{left_label}")
                    + pl.col(f"mean_dx_{right_label}")
                )
            ).alias("mean_dx"),
            (
                0.5
                * (
                    pl.col(f"median_dx_{left_label}")
                    + pl.col(f"median_dx_{right_label}")
                )
            ).alias("median_dx"),
            (
                0.5
                * (
                    pl.col(f"p_dx_gt0_{left_label}")
                    + pl.col(f"p_dx_gt0_{right_label}")
                )
            ).alias("p_dx_gt0"),
            (
                0.5
                * (
                    pl.col(f"x_mean_{left_label}")
                    + pl.col(f"x_mean_{right_label}")
                )
            ).alias("x_mean"),
            (
                0.5
                * (
                    pl.col(f"x_median_{left_label}")
                    + pl.col(f"x_median_{right_label}")
                )
            ).alias("x_median"),
            pl.min_horizontal(
                f"n_subjects_{left_label}",
                f"n_subjects_{right_label}",
            ).alias("n_subjects_min_fold"),
            pl.min_horizontal(
                f"n_{left_label}",
                f"n_{right_label}",
            ).alias("n_min_fold"),
            (
                pl.col(f"valid_{left_label}")
                & pl.col(f"valid_{right_label}")
            ).alias("meets_min_n"),
            pl.lit(representation).alias("representation"),
        ]
    )

    return attach_edges(m, edges)


def valid_bins(frame: pl.DataFrame) -> List[int]:
    if frame.is_empty():
        return []
    return [
        int(x)
        for x in (
            frame
            .filter(
                pl.col("meets_min_n").fill_null(False)
                & pl.col("mean_dx").is_finite()
            )["bin"]
            .drop_nulls()
            .unique()
            .sort()
            .to_list()
        )
    ]


