def build_matched_table(
    point: Mapping[str, pl.DataFrame],
    edges: np.ndarray,
    ci: pl.DataFrame,
) -> pl.DataFrame:
    same_combined = combine_two_folds(
        point["same_A"],
        point["same_B"],
        edges,
        representation="same_combined",
        left_label="A",
        right_label="B",
    )
    cross_combined = combine_two_folds(
        point["cross_AB_matched"],
        point["cross_BA_matched"],
        edges,
        representation="cross_combined_matched",
        left_label="AB",
        right_label="BA",
    )

    same = same_combined.select(
        [
            "bin",
            "x_left",
            "x_right",
            "x_center",
            pl.col("n_A").alias("n_fold_A"),
            pl.col("n_B").alias("n_fold_B"),
            pl.col("n_subjects_A").alias("n_subjects_fold_A"),
            pl.col("n_subjects_B").alias("n_subjects_fold_B"),
            pl.col("n_min_fold").alias("n_min_fold"),
            pl.col("n_subjects_min_fold").alias("n_subjects_min_fold"),
            pl.col("mean_dx").alias("mean_dx_same"),
            pl.col("median_dx").alias("median_dx_same"),
            pl.col("p_dx_gt0").alias("p_dx_gt0_same"),
            pl.col("meets_min_n").alias("valid_same"),
        ]
    )

    cross = cross_combined.select(
        [
            "bin",
            pl.col("n_AB").alias("n_cross_fold_AB"),
            pl.col("n_BA").alias("n_cross_fold_BA"),
            pl.col("n_subjects_AB").alias("n_subjects_cross_fold_AB"),
            pl.col("n_subjects_BA").alias("n_subjects_cross_fold_BA"),
            pl.col("n_min_fold").alias("n_cross_min_fold"),
            pl.col("n_subjects_min_fold").alias("n_subjects_cross_min_fold"),
            pl.col("mean_dx").alias("mean_dx_cross"),
            pl.col("median_dx").alias("median_dx_cross"),
            pl.col("p_dx_gt0").alias("p_dx_gt0_cross"),
            pl.col("meets_min_n").alias("valid_cross"),
        ]
    )

    out = same.join(cross, on="bin", how="inner").with_columns(
        [
            (
                pl.col("mean_dx_same")
                - pl.col("mean_dx_cross")
            ).alias("delta_mean_same_minus_cross"),
            (
                pl.col("p_dx_gt0_same")
                - pl.col("p_dx_gt0_cross")
            ).alias("delta_p_same_minus_cross"),
        ]
    )

    if not ci.is_empty():
        same_ci = (
            ci.filter(
                pl.col("representation") == "same_combined"
            )
            .select(
                [
                    "bin",
                    pl.col("mean_dx_ci025").alias(
                        "same_mean_dx_ci025"
                    ),
                    pl.col("mean_dx_ci975").alias(
                        "same_mean_dx_ci975"
                    ),
                ]
            )
        )
        cross_ci = (
            ci.filter(
                pl.col("representation")
                == "cross_combined_matched"
            )
            .select(
                [
                    "bin",
                    pl.col("mean_dx_ci025").alias(
                        "cross_mean_dx_ci025"
                    ),
                    pl.col("mean_dx_ci975").alias(
                        "cross_mean_dx_ci975"
                    ),
                ]
            )
        )
        out = (
            out.join(same_ci, on="bin", how="left")
            .join(cross_ci, on="bin", how="left")
        )

    return out.sort("bin")


