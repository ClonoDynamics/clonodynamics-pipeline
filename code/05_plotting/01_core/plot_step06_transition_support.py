"""
plot_step06_transition_support.py
============================================

Plot-only companion to ClonoDynamics Step 6:

    6-transition_support_characterization.py

Purpose
-------
Visualize the descriptive structure and estimand support of the generic
longitudinal transition universe generated by Step 5 and characterized in
Step 6.

This plotter is deliberately estimand-aware but inference-free. It does not
reconstruct transitions, refit latent states, re-threshold observation status,
filter transitions, estimate drift or fluctuation dynamics, or perform
statistical tests. It reads only Step-6 summary tables.

The plotting contract follows the replicate-resolved ClonoDynamics framework:

    * latent quantities are model-based representations/conditioning variables;
    * observed technical replicates remain separate for primary dynamics;
    * AB/BA/common4 are support/eligibility definitions, not biological states;
    * TT/TF/FT/FF are operational observation classes at a reference alpha.

Required Step-6 inputs
----------------------
--analysis-dir must contain:

    02_subject_interval_coverage.csv
    04_coverage_summary_by_dt.csv
    06_reference_observation_class_composition_by_dt.csv
    08_estimand_support_by_dt.csv

Optional audit inputs, read when present:

    09_estimand_support_overall.csv
    14_dataset_overview.csv

Generated single-panel figures
------------------------------

    transition_support_A_longitudinal_coverage_by_dt
        Median number of transitions per available subject-specific interval,
        with interquartile range and the number of contributing
        subject-interval units shown for each temporal lag.

    transition_support_B_subject_interval_coverage_heatmap
        Subject x nominal interval-pair coverage for the primary longitudinal
        dataset. The plotter refuses to collapse extra-group configurations
        into biological subjects.

    transition_support_C_estimand_support_by_dt
        Fractions of transitions eligible for replicate-decoupled forward AB,
        reciprocal BA, and cross-replicate fluctuation analysis (common4).

    transition_support_D_reference_observation_classes_by_dt
        Relative TT/TF/FT/FF composition at the stored reference operational
        observation threshold.

No multipanel figure is assembled here. Editorial figure numbering and panel
assembly are intentionally kept outside the analysis plotter.

Input audits
------------
Before plotting, the script checks that:

    * lag-level transition counts agree between coverage and support tables;
    * support fractions are finite and lie in [0, 1];
    * observation-class fractions lie in [0, 1] and sum to 1 within each lag;
    * a single reference_alpha is represented;
    * observation classes are restricted to TT/TF/FT/FF;
    * the subject x interval table has one row per subject/t0/t1/dt unit;
    * the subject heatmap is not asked to merge extra-group configurations.

These are plotting-input consistency checks only; the full production gate is
implemented by Step 6 itself.

Example
-------
python3 code/plotting/plot_step06_transition_support.py \
    --analysis-dir results/6-transition_support_characterization/p_05 \
    --figures-dir results/6-transition_support_characterization/p_05/figures

PDF and high-resolution PNG outputs are generated by default. SVG can be added
with --svg. Use --no-pdf or --no-png to disable a default format.
"""

