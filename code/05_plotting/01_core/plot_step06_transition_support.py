def prepare_dt_coverage(df: pd.DataFrame) -> pd.DataFrame:
    source = "04_coverage_summary_by_dt.csv"
    required = {
        "dt",
        "n_transitions",
        "n_biological_subjects",
        "n_group_subject_units",
        "n_group_subject_interval_pairs",
        "median_transitions_per_group_subject_interval",
        "q25_transitions_per_group_subject_interval",
        "q75_transitions_per_group_subject_interval",
    }
    require_columns(df, required, source)
    out = numeric(df, required)
    if out[list(required)].isna().any().any():
        raise ValueError(f"{source} contains non-numeric or missing required values")
    if out["dt"].duplicated().any():
        raise ValueError(f"{source} contains duplicate dt rows")
    if (out["n_transitions"] <= 0).any():
        raise ValueError(f"{source} contains non-positive transition counts")
    return out.sort_values("dt").reset_index(drop=True)


def prepare_subject_interval(df: pd.DataFrame) -> pd.DataFrame:
    source = "02_subject_interval_coverage.csv"
    required = {"subject", "t0", "t1", "dt", "n_transitions"}
    require_columns(df, required, source)
    out = numeric(df, ["t0", "t1", "dt", "n_transitions"])
    if out[list(required)].isna().any().any():
        raise ValueError(f"{source} contains missing required values")
    duplicate_key = out.duplicated(subset=["subject", "t0", "t1", "dt"], keep=False)
    if duplicate_key.any():
        raise ValueError(
            f"{source} contains duplicate subject/t0/t1/dt units. "
            "This plotter will not collapse extra-group configurations into biological subjects."
        )
    if (out["n_transitions"] <= 0).any():
        raise ValueError(f"{source} contains non-positive transition counts")
    return out.sort_values(["subject", "dt", "t0", "t1"]).reset_index(drop=True)


def prepare_estimand_support(df: pd.DataFrame) -> pd.DataFrame:
    source = "08_estimand_support_by_dt.csv"
    required = {
        "dt",
        "n_transitions",
        "fraction_forward_ab_eligible",
        "fraction_forward_ba_eligible",
        "fraction_common4",
    }
    require_columns(df, required, source)
    out = numeric(df, required)
    if out[list(required)].isna().any().any():
        raise ValueError(f"{source} contains non-numeric or missing required values")
    if out["dt"].duplicated().any():
        raise ValueError(f"{source} contains duplicate dt rows")
    for col in (
        "fraction_forward_ab_eligible",
        "fraction_forward_ba_eligible",
        "fraction_common4",
    ):
        assert_fraction(out[col], f"{source}:{col}")
    return out.sort_values("dt").reset_index(drop=True)


def prepare_reference_classes(df: pd.DataFrame) -> Tuple[pd.DataFrame, float]:
    source = "06_reference_observation_class_composition_by_dt.csv"
    required = {
        "dt",
        "obs_class_reference",
        "n_transitions",
        "transition_fraction",
        "reference_alpha",
    }
    require_columns(df, required, source)
    out = numeric(df, ["dt", "n_transitions", "transition_fraction", "reference_alpha"])
    out["obs_class_reference"] = out["obs_class_reference"].astype(str).str.upper()
    if out[list(required)].isna().any().any():
        raise ValueError(f"{source} contains missing required values")
    invalid = sorted(set(out["obs_class_reference"]).difference(OBS_CLASSES))
    if invalid:
        raise ValueError(f"{source} contains invalid reference classes: {invalid}")
    if out.duplicated(subset=["dt", "obs_class_reference"]).any():
        raise ValueError(f"{source} contains duplicate dt/class rows")
    assert_fraction(out["transition_fraction"], f"{source}:transition_fraction")

    alphas = np.sort(out["reference_alpha"].unique())
    if len(alphas) != 1 or not np.isfinite(alphas[0]) or not (0.0 < alphas[0] < 1.0):
        raise ValueError(f"{source} must contain exactly one valid reference_alpha")
    alpha = float(alphas[0])

    sums = out.groupby("dt", sort=True)["transition_fraction"].sum()
    if not np.allclose(sums.to_numpy(float), 1.0, atol=1e-8, rtol=1e-8):
        bad = sums.loc[~np.isclose(sums, 1.0, atol=1e-8, rtol=1e-8)]
        raise ValueError(
            f"{source} class fractions do not sum to 1 for dt values: {bad.to_dict()}"
        )

    return out.sort_values(["dt", "obs_class_reference"]).reset_index(drop=True), alpha


def audit_cross_table_consistency(
    dt_coverage: pd.DataFrame,
    estimand_support: pd.DataFrame,
    class_by_dt: pd.DataFrame,
    subject_interval: pd.DataFrame,
) -> pd.DataFrame:
    rows: List[Dict[str, object]] = []

    cov = dt_coverage.set_index("dt").sort_index()
    sup = estimand_support.set_index("dt").sort_index()
    same_lags = cov.index.equals(sup.index)
    rows.append(
        {
            "check": "coverage_vs_estimand_same_dt_set",
            "passed": bool(same_lags),
            "detail": f"coverage={list(cov.index)}; support={list(sup.index)}",
        }
    )
    if not same_lags:
        raise ValueError("Coverage and estimand-support tables contain different dt sets")

    same_counts = np.array_equal(
        cov["n_transitions"].to_numpy(np.int64),
        sup["n_transitions"].to_numpy(np.int64),
    )
    rows.append(
        {
            "check": "coverage_vs_estimand_transition_counts",
            "passed": bool(same_counts),
            "detail": "n_transitions agrees by dt" if same_counts else "n_transitions differs by dt",
        }
    )
    if not same_counts:
        raise ValueError("Coverage and estimand-support transition counts disagree")

    class_totals = (
        class_by_dt.groupby("dt", sort=True)["n_transitions"].sum().astype(np.int64)
    )
    class_matches = np.array_equal(
        class_totals.reindex(cov.index).to_numpy(np.int64),
        cov["n_transitions"].to_numpy(np.int64),
    )
    rows.append(
        {
            "check": "reference_classes_vs_coverage_transition_counts",
            "passed": bool(class_matches),
            "detail": "class counts sum to transition universe by dt" if class_matches else "class counts disagree",
        }
    )
    if not class_matches:
        raise ValueError("Reference observation-class counts do not match transition counts by dt")

    interval_totals = (
        subject_interval.groupby("dt", sort=True)["n_transitions"].sum().astype(np.int64)
    )
    interval_matches = np.array_equal(
        interval_totals.reindex(cov.index).to_numpy(np.int64),
        cov["n_transitions"].to_numpy(np.int64),
    )
    rows.append(
        {
            "check": "subject_interval_vs_coverage_transition_counts",
            "passed": bool(interval_matches),
            "detail": "subject-interval counts sum to transition universe by dt" if interval_matches else "subject-interval counts disagree",
        }
    )
    if not interval_matches:
        raise ValueError("Subject-interval transition counts do not match coverage counts by dt")

    no_extra_group_collapse = bool(
        np.allclose(
            dt_coverage["n_biological_subjects"].to_numpy(float),
            dt_coverage["n_group_subject_units"].to_numpy(float),
            equal_nan=False,
        )
    )
    rows.append(
        {
            "check": "heatmap_has_no_extra_group_subject_multiplicity",
            "passed": no_extra_group_collapse,
            "detail": (
                "group-subject units equal biological subjects"
                if no_extra_group_collapse
                else "extra grouping creates multiple group-subject units per biological subject"
            ),
        }
    )
    if not no_extra_group_collapse:
        raise ValueError(
            "The subject heatmap would collapse extra-group configurations into biological subjects. "
            "Use this plotter on the primary longitudinal Step-6 output without extra grouping, or create a configuration-aware plotter."
        )

    return pd.DataFrame(rows)


