def clean_axes(ax: plt.Axes) -> None:
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)


def apply_axis_config(ax: plt.Axes, stem: str, right_ax: Optional[plt.Axes] = None) -> None:
    cfg = AXIS_CONFIG.get(stem, {})
    if cfg.get("xlim") is not None:
        ax.set_xlim(*cfg["xlim"])
    if cfg.get("ylim") is not None:
        ax.set_ylim(*cfg["ylim"])
    if cfg.get("xticks") is not None:
        ax.set_xticks(cfg["xticks"])
    if cfg.get("yticks") is not None:
        ax.set_yticks(cfg["yticks"])
    if right_ax is not None:
        if cfg.get("right_ylim") is not None:
            right_ax.set_ylim(*cfg["right_ylim"])
        if cfg.get("right_yticks") is not None:
            right_ax.set_yticks(cfg["right_yticks"])


