def ensure_dir(path: Path) -> Path:
    path.mkdir(parents=True, exist_ok=True)
    return path


def read_required(path: Path) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError(f"Required Step-6 table not found: {path}")
    return pd.read_csv(path)


def read_optional(path: Path) -> Optional[pd.DataFrame]:
    if not path.exists():
        return None
    return pd.read_csv(path)


def require_columns(df: pd.DataFrame, required: Iterable[str], source: str) -> None:
    missing = sorted(set(required).difference(df.columns))
    if missing:
        raise ValueError(f"{source} is missing required columns: {', '.join(missing)}")


def numeric(df: pd.DataFrame, columns: Iterable[str]) -> pd.DataFrame:
    out = df.copy()
    for column in columns:
        out[column] = pd.to_numeric(out[column], errors="coerce")
    return out


def assert_fraction(values: pd.Series, label: str) -> None:
    arr = pd.to_numeric(values, errors="coerce").to_numpy(float)
    if not np.all(np.isfinite(arr)):
        raise ValueError(f"{label} contains non-finite values")
    if np.any((arr < -1e-12) | (arr > 1.0 + 1e-12)):
        raise ValueError(f"{label} contains values outside [0, 1]")


