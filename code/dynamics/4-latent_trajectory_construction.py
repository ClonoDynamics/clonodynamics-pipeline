def eprint(*args, **kwargs) -> None:
    print(*args, file=sys.stderr, **kwargs)


def ensure_dir(path: Path) -> Path:
    path = Path(path)
    path.mkdir(parents=True, exist_ok=True)
    return path


def split_csv(text: Optional[str]) -> list[str]:
    if text is None:
        return []
    return [x.strip() for x in str(text).split(",") if x.strip()]


def list_table_files(directory: Path) -> list[Path]:
    directory = Path(directory)
    files: list[Path] = []
    for pat in ("*.parquet", "*.pq"):
        files.extend(sorted(directory.glob(pat)))
    if files:
        return files
    for pat in ("*.feather", "*.arrow"):
        files.extend(sorted(directory.glob(pat)))
    if files:
        return files
    for pat in ("*.csv", "*.tsv", "*.txt"):
        files.extend(sorted(directory.glob(pat)))
    return files


def file_kind(path: Path) -> str:
    s = Path(path).suffix.lower()
    if s in PARQUET_EXTS:
        return "parquet"
    if s in FEATHER_EXTS:
        return "feather"
    if s in CSV_EXTS:
        return "csv"
    raise ValueError(f"Unsupported table extension: {path}")


def scan_one(path: Path, sep: str = "\t") -> pl.LazyFrame:
    path = Path(path)
    kind = file_kind(path)
    if kind == "parquet":
        return pl.scan_parquet(str(path))
    if kind == "feather":
        # Polars has no universally stable lazy feather scan across versions.
        return pl.read_ipc(str(path)).lazy()
    delimiter = "," if path.suffix.lower() == ".csv" else sep
    return pl.scan_csv(str(path), separator=delimiter, infer_schema_length=10000)


def scan_input(per_clone: Optional[Path], per_clone_dir: Optional[Path], sep: str) -> tuple[pl.LazyFrame, str, list[Path]]:
    if per_clone is None and per_clone_dir is None:
        raise ValueError("Provide either --per-clone or --per-clone-dir")
    if per_clone is not None and per_clone_dir is not None:
        raise ValueError("Use only one input mode: --per-clone OR --per-clone-dir")

    if per_clone is not None:
        if not Path(per_clone).exists():
            raise FileNotFoundError(f"Input file not found: {per_clone}")
        return scan_one(Path(per_clone), sep=sep), str(per_clone), [Path(per_clone)]

    assert per_clone_dir is not None
    if not Path(per_clone_dir).exists():
        raise FileNotFoundError(f"Input directory not found: {per_clone_dir}")
    files = list_table_files(Path(per_clone_dir))
    if not files:
        raise FileNotFoundError(f"No table files found in: {per_clone_dir}")

    # Fast path for parquet directories: scan a glob as one lazy dataset.
    kinds = {file_kind(fp) for fp in files}
    if kinds == {"parquet"}:
        pattern = str(Path(per_clone_dir) / "*.parquet")
        pq_files = list(Path(per_clone_dir).glob("*.parquet"))
        if pq_files:
            return pl.scan_parquet(pattern), str(per_clone_dir), files
        pattern = str(Path(per_clone_dir) / "*.pq")
        return pl.scan_parquet(pattern), str(per_clone_dir), files

    # Compatibility path for csv/feather or mixed directories.
    lfs = [scan_one(fp, sep=sep) for fp in files]
    return pl.concat(lfs, how="diagonal_relaxed"), str(per_clone_dir), files


def collect_schema_names(lf: pl.LazyFrame) -> list[str]:
    try:
        return list(lf.collect_schema().names())
    except Exception:
        return list(lf.schema.keys())


def infer_freq_col(columns: Sequence[str], requested: str) -> str:
    cols = set(columns)
    if requested in cols:
        return requested
    for c in FREQ_FALLBACKS:
        if c in cols:
            eprint(f"[WARNING] Requested --freq-col {requested!r} not found; using {c!r}")
            return c
    raise ValueError(
        f"No usable frequency column found. Requested {requested!r}; "
        f"fallbacks={FREQ_FALLBACKS}; available={list(columns)}"
    )


def observable_expr(columns: Sequence[str], observable_col: str, observable_cutoff_col: str) -> pl.Expr:
    cols = set(columns)
    source = observable_col if observable_col in cols else observable_cutoff_col if observable_cutoff_col in cols else None
    if source is None:
        return pl.lit(False).alias("observable")

    s = pl.col(source)
    # Robust string-based conversion also handles bool and numeric columns.
    return (
        s.cast(pl.Utf8, strict=False)
        .str.strip_chars()
        .str.to_lowercase()
        .is_in(TRUE_STRINGS)
        .fill_null(False)
        .alias("observable")
    )


def infer_optional_col(columns: Sequence[str], requested: str, fallbacks: Sequence[str]) -> Optional[str]:
    cols = set(columns)
    if requested and requested in cols:
        return requested
    for c in fallbacks:
        if c in cols:
            if requested and requested != c:
                eprint(f"[WARNING] Requested optional column {requested!r} not found; using {c!r}")
            return c
    return None


def build_trajectory_lazy(
    lf: pl.LazyFrame,
    columns: Sequence[str],
    subject_col: str,
    time_col: str,
    clone_col: str,
    freq_col_requested: str,
    log_freq_col_requested: str,
    observable_col: str,
    observable_cutoff_col: str,
    epsilon: float,
    extra_group_cols: Sequence[str],
    sort_output: bool,
) -> tuple[pl.LazyFrame, str, Optional[str], list[str]]:
    freq_col = infer_freq_col(columns, freq_col_requested)
    log_freq_col = infer_optional_col(columns, log_freq_col_requested, LOG_FREQ_FALLBACKS)
    required = [subject_col, time_col, clone_col, freq_col]
    missing = [c for c in required if c not in set(columns)]
    if missing:
        raise ValueError(f"Input is missing required columns: {missing}")

    extra_missing = [c for c in extra_group_cols if c not in set(columns)]
    if extra_missing:
        raise ValueError(f"--extra-group-cols not found in input: {extra_missing}")

    group_cols = list(extra_group_cols) + ["subject", "aaSeqCDR3", "time"]

    select_exprs: list[pl.Expr] = []
    for c in extra_group_cols:
        select_exprs.append(pl.col(c))
    select_exprs.extend(
        [
            pl.col(subject_col).cast(pl.Int64, strict=False).alias("subject"),
            pl.col(clone_col).cast(pl.Utf8, strict=False).alias("aaSeqCDR3"),
            pl.col(time_col).cast(pl.Int64, strict=False).alias("time"),
            pl.col(freq_col).cast(pl.Float64, strict=False).alias("freq_raw"),
            observable_expr(columns, observable_col, observable_cutoff_col),
        ]
    )


    # Optional latent posterior summaries. These keep uncertainty available for
    # downstream transition builders without changing the core trajectory interface.
    optional_map = {

    # latent uncertainty
    "f_latent_q025": "freq_q025_raw",
    "f_latent_q975": "freq_q975_raw",

    "x_latent_q025": "log_freq_q025_raw",
    "x_latent_q975": "log_freq_q975_raw",
    "x_latent_sd":   "log_freq_sd_raw",

    # state-level detectability (primary)
    "p_dropout_state": "p_dropout_state_raw",
    "p_detect_state":  "p_detect_state_raw",

    # replicate-specific detectability (QC)
    "p_dropout_rep1": "p_dropout_rep1_raw",
    "p_dropout_rep2": "p_dropout_rep2_raw",
    "p_detect_rep1":  "p_detect_rep1_raw",
    "p_detect_rep2":  "p_detect_rep2_raw",

    # observed quantities
    "freq_geo": "freq_obs_raw",
    "x_obs_geo": "x_obs_raw",

    # counts
    "count_rep1": "count_rep1_raw",
    "count_rep2": "count_rep2_raw",
    "count_latent_median": "count_latent_median_raw",
    "x_count_latent_median": "x_count_latent_median_raw",

    # depth
    "depth_rep1": "depth_rep1_raw",
    "depth_rep2": "depth_rep2_raw",
    "depth_mean": "depth_mean_raw",
    }

    # Preserve single-replicate latent posterior summaries without changing
    # their public names in the final trajectory table. A *_raw alias is used
    # only during the projection/aggregation stage.
    for c in SINGLE_REP_LATENT_COLS + SINGLE_REP_ALIAS_COLS:
        optional_map[c] = f"{c}_raw"

    if log_freq_col is not None:
        select_exprs.append(pl.col(log_freq_col).cast(pl.Float64, strict=False).alias("log_freq_raw"))
    for src, dst in optional_map.items():
        if src in set(columns):
            select_exprs.append(pl.col(src).cast(pl.Float64, strict=False).alias(dst))

    out = (
        lf.select(select_exprs)
        .filter(
            pl.col("subject").is_not_null()
            & pl.col("time").is_not_null()
            & pl.col("aaSeqCDR3").is_not_null()
            & pl.col("freq_raw").is_not_null()
            & pl.col("freq_raw").is_finite()
            & (pl.col("freq_raw") >= 0)
        )
        .group_by(group_cols)
        .agg(
            [
                pl.col("freq_raw").mean().alias("freq"),
                pl.col("observable").max().alias("observable"),
            ]
            + ([pl.col("log_freq_raw").mean().alias("log_freq")] if log_freq_col is not None else [])
            + ([pl.col("freq_q025_raw").mean().alias("freq_q025")] if "f_latent_q025" in set(columns) else [])
            + ([pl.col("freq_q975_raw").mean().alias("freq_q975")] if "f_latent_q975" in set(columns) else [])
            + ([pl.col("log_freq_q025_raw").mean().alias("log_freq_q025")] if "x_latent_q025" in set(columns) else [])
            + ([pl.col("log_freq_q975_raw").mean().alias("log_freq_q975")] if "x_latent_q975" in set(columns) else [])
            + ([pl.col("log_freq_sd_raw").mean().alias("log_freq_sd")] if "x_latent_sd" in set(columns) else [])
            + ([pl.col("p_dropout_state_raw").mean().alias("p_dropout_state")] if "p_dropout_state" in set(columns) else [])
            + ([pl.col("p_detect_state_raw").mean().alias("p_detect_state")] if "p_detect_state" in set(columns) else [])
            + ([pl.col("p_dropout_rep1_raw").mean().alias("p_dropout_rep1")] if "p_dropout_rep1" in set(columns) else [])
            + ([pl.col("p_dropout_rep2_raw").mean().alias("p_dropout_rep2")] if "p_dropout_rep2" in set(columns) else [])
            + ([pl.col("p_detect_rep1_raw").mean().alias("p_detect_rep1")] if "p_detect_rep1" in set(columns) else [])
            + ([pl.col("p_detect_rep2_raw").mean().alias("p_detect_rep2")] if "p_detect_rep2" in set(columns) else [])
            + ([pl.col("freq_obs_raw").mean().alias("freq_obs")] if "freq_geo" in set(columns) else [])
            + ([pl.col("x_obs_raw").mean().alias("x_obs")] if "x_obs_geo" in set(columns) else [])
            + ([pl.col("count_rep1_raw").sum().alias("count_rep1")] if "count_rep1" in set(columns) else [])
            + ([pl.col("count_rep2_raw").sum().alias("count_rep2")] if "count_rep2" in set(columns) else [])
            + ([pl.col("count_latent_median_raw").mean().alias("count_latent_median")] if "count_latent_median" in set(columns) else [])
            + ([pl.col("x_count_latent_median_raw").mean().alias("x_count_latent_median")] if "x_count_latent_median" in set(columns) else [])
            + ([pl.col("depth_rep1_raw").max().alias("depth_rep1")] if "depth_rep1" in set(columns) else [])
            + ([pl.col("depth_rep2_raw").max().alias("depth_rep2")] if "depth_rep2" in set(columns) else [])
            + ([pl.col("depth_mean_raw").max().alias("depth_mean_from_step2")] if "depth_mean" in set(columns) else [])
            + [
                pl.col(f"{c}_raw").mean().alias(c)
                for c in (SINGLE_REP_LATENT_COLS + SINGLE_REP_ALIAS_COLS)
                if c in set(columns)
            ]
        )
    )

    if log_freq_col is None:
        out = out.with_columns((pl.col("freq") + float(epsilon)).log().alias("log_freq"))

    # Xstar-ready aliases and count/depth-derived quantities.
    # These keep old compatibility (freq/log_freq) while adding explicit names
    # expected by downstream multilag transition/decomposition scripts.
    out_schema = set(collect_schema_names(out))
    derived_exprs = [
        pl.col("freq").alias("freq_latent"),
        pl.col("log_freq").alias("x_latent"),
    ]
    if "log_freq_sd" in out_schema:
        derived_exprs.append(pl.col("log_freq_sd").alias("x_latent_sd"))
    if {"count_rep1", "count_rep2"}.issubset(out_schema):
        derived_exprs.append((pl.col("count_rep1") + pl.col("count_rep2")).alias("count_sum"))
        derived_exprs.append(((pl.col("count_rep1") + pl.col("count_rep2")) + 1.0).log().alias("x_count_sum"))
    if {"depth_rep1", "depth_rep2"}.issubset(out_schema):
        derived_exprs.append((pl.col("depth_rep1") + pl.col("depth_rep2")).alias("depth_sum"))
        derived_exprs.append((0.5 * (pl.col("depth_rep1") + pl.col("depth_rep2"))).alias("depth_mean"))
    out = out.with_columns(derived_exprs)

    out_schema = set(collect_schema_names(out))
    if {"count_sum", "depth_sum"}.issubset(out_schema):
        out = out.with_columns(
            (pl.col("count_sum") / pl.when(pl.col("depth_sum") > 0).then(pl.col("depth_sum")).otherwise(None)).alias("freq_count_sum")
        )

    final_cols = list(extra_group_cols) + ["subject", "aaSeqCDR3", "time", "freq", "observable", "log_freq", "freq_latent", "x_latent"]
    optional_final_cols = [
        "freq_obs", "x_obs",
        "count_rep1", "count_rep2", "count_sum",
        "depth_rep1", "depth_rep2", "depth_sum", "depth_mean", "depth_mean_from_step2",
        "freq_count_sum", "x_count_sum",
        "count_latent_median", "x_count_latent_median",
        "freq_q025", "freq_q975", "log_freq_q025", "log_freq_q975", "log_freq_sd", "x_latent_sd",
        "p_dropout_state", "p_detect_state",
        "p_dropout_rep1", "p_dropout_rep2", "p_detect_rep1", "p_detect_rep2",
    ] + SINGLE_REP_LATENT_COLS + SINGLE_REP_ALIAS_COLS
    out_schema = set(collect_schema_names(out))
    final_cols += [c for c in optional_final_cols if c in out_schema and c not in final_cols]
    out = out.select(final_cols)
    if sort_output:
        out = out.sort(list(extra_group_cols) + ["subject", "aaSeqCDR3", "time"])
    return out, freq_col, log_freq_col, group_cols


def write_lazy_or_collect(
    lf: pl.LazyFrame,
    out_path: Path,
    output_format: str,
    parquet_compression: str,
    streaming: bool,
) -> Path:
    ensure_dir(out_path.parent)
    fmt = output_format.lower()
    if fmt == "parquet":
        out = out_path.with_suffix(".parquet")
        # sink_parquet is the most memory-safe path when available.
        if hasattr(lf, "sink_parquet"):
            try:
                lf.sink_parquet(str(out), compression=parquet_compression)
                return out
            except TypeError:
                lf.sink_parquet(str(out))
                return out
        df = lf.collect(streaming=streaming)
        df.write_parquet(str(out), compression=parquet_compression)
        return out

    df = lf.collect(streaming=streaming)
    if fmt == "csv":
        out = out_path.with_suffix(".csv")
        df.write_csv(str(out))
        return out
    if fmt == "feather":
        out = out_path.with_suffix(".feather")
        df.write_ipc(str(out))
        return out
    raise ValueError(f"Unknown output format: {output_format}")


def write_partitioned(
    lf: pl.LazyFrame,
    out_root: Path,
    partition_cols: Sequence[str],
    output_format: str,
    parquet_compression: str,
    streaming: bool,
) -> tuple[Path, int]:
    """Write one file per partition value combination.

    This intentionally collects the already-aggregated trajectory table, not the
    raw per-clone table. For very large outputs without enough RAM, prefer no
    --partition-by and write a single parquet via sink_parquet.
    """
    out_root = ensure_dir(out_root)
    df = lf.collect(streaming=streaming)
    if df.is_empty():
        return out_root, 0

    n = 0
    for key, sub in df.partition_by(list(partition_cols), as_dict=True).items():
        if not isinstance(key, tuple):
            key = (key,)
        name_parts = [f"{col}={val}" for col, val in zip(partition_cols, key)]
        subdir = ensure_dir(out_root.joinpath(*name_parts[:-1])) if len(name_parts) > 1 else out_root
        stem = "trajectories_" + "__".join(str(x).replace("/", "-") for x in name_parts)
        path_base = subdir / stem
        if output_format == "parquet":
            sub.write_parquet(str(path_base.with_suffix(".parquet")), compression=parquet_compression)
        elif output_format == "csv":
            sub.write_csv(str(path_base.with_suffix(".csv")))
        elif output_format == "feather":
            sub.write_ipc(str(path_base.with_suffix(".feather")))
        else:
            raise ValueError(output_format)
        n += 1
    return out_root, n


def write_report(path: Path, payload: dict) -> None:
    ensure_dir(path.parent)
    with open(path, "w", encoding="utf-8") as f:
        f.write("# Latent trajectory construction report — Polars/Lazy\n\n")
        for k, v in payload.items():
            if isinstance(v, (list, dict)):
                v = json.dumps(v, ensure_ascii=False)
            f.write(f"- {k}: {v}\n")


def build_argparser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        description="Construct standardized long-format latent clonotype trajectories from Step-2 per-clone latent tables.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    p.add_argument("--per-clone", type=Path, default=None, help="Single per_clone_latent table")
    p.add_argument("--per-clone-dir", type=Path, default=None, help="Directory of per_clone_latent table parts")
    p.add_argument("--outdir", type=Path, default=Path("results/4-latent_trajectory_construction"))
    p.add_argument("--output-format", choices=["parquet", "csv", "feather"], default="parquet")
    p.add_argument("--parquet-compression", default="zstd")
    p.add_argument("--file-sep", default="\t")
    p.add_argument("--streaming", action="store_true", help="Use streaming collect when collection is needed")

    p.add_argument("--subject-col", default="subject")
    p.add_argument("--time-col", default="time")
    p.add_argument("--clone-col", default="aaSeqCDR3")
    p.add_argument("--freq-col", default="f_latent_median", help="Latent frequency column to use as trajectory freq")
    p.add_argument("--log-freq-col", default="x_latent_median", help="Latent log-frequency column to use as trajectory log_freq when available")
    p.add_argument("--observable-col", default="observable")
    p.add_argument("--observable-cutoff-col", default="observable_cutoff")
    p.add_argument("--epsilon", type=float, default=1e-15)

    p.add_argument("--extra-group-cols", default="", help="Comma-separated columns preserved in trajectory key, e.g. experiment,null_id")
    p.add_argument("--partition-by", default="", help="Comma-separated output partition columns, e.g. experiment,null_id or null_id")
    p.add_argument("--no-sort", action="store_true", help="Skip final sort for speed")
    p.add_argument("--no-included-clones", action="store_true", help="Do not write included_clones")
    p.add_argument("--write-csv-compat", action="store_true", help="Also write CSV copy when output is parquet/feather")
    p.add_argument("--skip-summary-stats", action="store_true", help="Skip final summary counts to avoid a second scan of large inputs")
    return p


def main() -> None:
    args = build_argparser().parse_args()
    outdir = ensure_dir(args.outdir)
    extra_cols = split_csv(args.extra_group_cols)
    partition_cols = split_csv(args.partition_by)

    print("[INFO] Step 4 latent trajectory construction — Polars/Lazy")
    lf0, input_label, input_files = scan_input(args.per_clone, args.per_clone_dir, sep=args.file_sep)
    columns = collect_schema_names(lf0)
    missing_state_detectability = [c for c in ("p_detect_state", "p_dropout_state") if c not in set(columns)]
    if missing_state_detectability:
        raise ValueError(
            "Input Step-2 table is missing state-level detectability columns: "
            f"{missing_state_detectability}. Re-run the updated Step 2 with the updated noiseK_latent.py."
        )
    print(f"[INFO] Input: {input_label}")
    print(f"[INFO] Input files: {len(input_files)}")
    print(f"[INFO] Extra group columns: {extra_cols if extra_cols else '<none>'}")

    traj_lf, freq_col_used, log_freq_col_used, group_cols = build_trajectory_lazy(
        lf=lf0,
        columns=columns,
        subject_col=args.subject_col,
        time_col=args.time_col,
        clone_col=args.clone_col,
        freq_col_requested=args.freq_col,
        log_freq_col_requested=args.log_freq_col,
        observable_col=args.observable_col,
        observable_cutoff_col=args.observable_cutoff_col,
        epsilon=float(args.epsilon),
        extra_group_cols=extra_cols,
        sort_output=not bool(args.no_sort),
    )

    trajectories_path = outdir / "latent_trajectories_long"
    n_partitions = 0
    if partition_cols:
        missing = [c for c in partition_cols if c not in (extra_cols + ["subject", "aaSeqCDR3", "time"])]
        if missing:
            raise ValueError(f"--partition-by columns must be in output/group columns. Missing: {missing}")
        trajectories_path = outdir / "trajectories_long_parts"
        written_path, n_partitions = write_partitioned(
            traj_lf,
            trajectories_path,
            partition_cols=partition_cols,
            output_format=args.output_format,
            parquet_compression=args.parquet_compression,
            streaming=bool(args.streaming),
        )
        print(f"[INFO] Wrote partitioned trajectories: {written_path} partitions={n_partitions}")
    else:
        written_path = write_lazy_or_collect(
            traj_lf,
            trajectories_path,
            output_format=args.output_format,
            parquet_compression=args.parquet_compression,
            streaming=bool(args.streaming),
        )
        print(f"[INFO] Wrote trajectories: {written_path}")

    included_path = None
    if not args.no_included_clones:
        included_lf = traj_lf.select(extra_cols + ["subject", "aaSeqCDR3"]).unique()
        if not args.no_sort:
            included_lf = included_lf.sort(extra_cols + ["subject", "aaSeqCDR3"])
        included_path = write_lazy_or_collect(
            included_lf,
            outdir / "included_clones",
            output_format=args.output_format,
            parquet_compression=args.parquet_compression,
            streaming=bool(args.streaming),
        )
        print(f"[INFO] Wrote included clones: {included_path}")

    if args.write_csv_compat and args.output_format != "csv" and not partition_cols:
        csv_path = write_lazy_or_collect(
            traj_lf,
            outdir / "latent_trajectories_long",
            output_format="csv",
            parquet_compression=args.parquet_compression,
            streaming=bool(args.streaming),
        )
        print(f"[INFO] Wrote CSV compatibility copy: {csv_path}")

    # Lightweight counts: only after main write; may trigger a second scan.
    if args.skip_summary_stats:
        stats = {}
        print("[INFO] Skipped summary stats")
    else:
        try:
            stats = traj_lf.select(
                [
                    pl.len().alias("n_rows_trajectories_long"),
                    pl.col("subject").n_unique().alias("n_subjects"),
                    pl.struct(extra_cols + ["subject", "aaSeqCDR3"]).n_unique().alias("n_unique_subject_clone_pairs"),
                ]
            ).collect(engine="streaming" if args.streaming else "auto").to_dicts()[0]
        except Exception as exc:
            eprint(f"[WARNING] Could not compute summary stats: {exc}")
            stats = {}

    report_payload = {
        "timestamp": datetime.now().isoformat(timespec="seconds"),
        "script": Path(__file__).name,
        "engine": "polars_lazy",
        "input": input_label,
        "n_input_files": len(input_files),
        "outdir": str(outdir),
        "output_format": args.output_format,
        "parquet_compression": args.parquet_compression,
        "freq_col_requested": args.freq_col,
        "freq_col_used": freq_col_used,
        "log_freq_col_requested": args.log_freq_col,
        "log_freq_col_used": log_freq_col_used,
        "state_detectability_columns": ["p_detect_state", "p_dropout_state"],
        "epsilon": args.epsilon,
        "group_cols": group_cols,
        "extra_group_cols": extra_cols,
        "partition_by": partition_cols,
        "n_partitions": n_partitions,
        "trajectories_output": str(written_path),
        "included_clones_output": str(included_path) if included_path else None,
        "sort_output": not bool(args.no_sort),
        **stats,
    }
    report_path = outdir / "trajectory_build_report.md"
    write_report(report_path, report_payload)
    print(f"[INFO] Wrote report: {report_path}")
    print("[DONE]")


if __name__ == "__main__":
    main()
