def metric_summary(lf: pl.LazyFrame, metrics) -> pl.DataFrame:
    rows = []
    for metric in metrics:
        rows.append(lf.select([
            pl.lit(metric).alias("metric"),
            pl.col(metric).is_not_null().sum().alias("n_non_null"),
            pl.col(metric).is_finite().sum().alias("n_finite"),
            pl.col(metric).min().alias("min"),
            pl.col(metric).quantile(0.01).alias("q01"),
            pl.col(metric).quantile(0.025).alias("q025"),
            pl.col(metric).quantile(0.10).alias("q10"),
            pl.col(metric).quantile(0.25).alias("q25"),
            pl.col(metric).median().alias("median"),
            pl.col(metric).quantile(0.75).alias("q75"),
            pl.col(metric).quantile(0.90).alias("q90"),
            pl.col(metric).quantile(0.95).alias("q95"),
            pl.col(metric).quantile(0.975).alias("q975"),
            pl.col(metric).quantile(0.99).alias("q99"),
            pl.col(metric).max().alias("max"),
            pl.col(metric).mean().alias("mean"),
            pl.col(metric).std().alias("sd"),
        ]).collect(engine="streaming"))
    return pl.concat(rows)


