def write_abundance_summary(lf: pl.LazyFrame, output_path: Path, bin_width: float) -> None:
    if "x_latent_median" not in lf.collect_schema().names():
        return
    binned = lf.with_columns(
        ((pl.col("x_latent_median") / pl.lit(bin_width)).floor() * pl.lit(bin_width))
        .alias("x_bin_left")
    ).with_columns((pl.col("x_bin_left") + pl.lit(bin_width)).alias("x_bin_right"))
    grouped_summary(binned, ["x_bin_left", "x_bin_right"], output_path)



def write_detection_summary(lf: pl.LazyFrame, output_path: Path, bin_width: float) -> None:
    """Summarize posterior width and replicate overlap across state detectability."""
    d = lf.with_columns(
        ((pl.col("cqc_state_detectability").clip(0.0, 1.0 - EPS) / pl.lit(bin_width)).floor() * pl.lit(bin_width))
        .alias("detection_bin_left")
    ).with_columns(
        (pl.col("detection_bin_left") + pl.lit(bin_width)).clip(upper_bound=1.0)
        .alias("detection_bin_right")
    )
    out = d.group_by(["detection_bin_left", "detection_bin_right"]).agg([
        pl.len().alias("n_clonotype_timepoints"),
        pl.col("cqc_posterior_width95_x").median().alias("posterior_width95_median"),
        pl.col("cqc_posterior_width95_x").quantile(0.25).alias("posterior_width95_q25"),
        pl.col("cqc_posterior_width95_x").quantile(0.75).alias("posterior_width95_q75"),
        pl.col("cqc_replicate_bhattacharyya").median().alias("replicate_bc_median"),
        pl.col("cqc_replicate_bhattacharyya").quantile(0.25).alias("replicate_bc_q25"),
        pl.col("cqc_replicate_bhattacharyya").quantile(0.75).alias("replicate_bc_q75"),
    ]).sort("detection_bin_left")
    write_csv(out, output_path)


def write_replicate_z_summary(
    lf: pl.LazyFrame, output_path: Path, bin_width: float, z_max: float
) -> None:
    """Summarize posterior uncertainty across standardized replicate differences."""
    z = pl.col("cqc_replicate_standardized_delta").clip(0.0, z_max - EPS)
    d = lf.with_columns(
        ((z / pl.lit(bin_width)).floor() * pl.lit(bin_width)).alias("replicate_z_bin_left")
    ).with_columns(
        (pl.col("replicate_z_bin_left") + pl.lit(bin_width)).clip(upper_bound=z_max)
        .alias("replicate_z_bin_right")
    )
    out = d.group_by(["replicate_z_bin_left", "replicate_z_bin_right"]).agg([
        pl.len().alias("n_clonotype_timepoints"),
        pl.col("cqc_posterior_width95_x").median().alias("posterior_width95_median"),
        pl.col("cqc_posterior_width95_x").quantile(0.25).alias("posterior_width95_q25"),
        pl.col("cqc_posterior_width95_x").quantile(0.75).alias("posterior_width95_q75"),
    ]).sort("replicate_z_bin_left")
    write_csv(out, output_path)


SPEARMAN_BASE_METRICS = [
    "cqc_posterior_width95_x",
    "cqc_posterior_entropy",
    "cqc_state_detectability",
    "cqc_union_detectability",
    "cqc_replicate_bhattacharyya",
]


def _full_data_spearman_pair(lf: pl.LazyFrame, a: str, b: str) -> tuple:
    """Return pairwise-finite n and Spearman rho using only two columns in memory."""
    pair = lf.select([a, b]).filter(
        pl.col(a).is_finite() & pl.col(b).is_finite()
    )
    out = pair.select([
        pl.len().alias("n_complete"),
        pl.corr(a, b, method="spearman").alias("spearman_rho"),
    ]).collect()
    return int(out["n_complete"][0]), float(out["spearman_rho"][0])


def write_full_dataset_spearman(lf: pl.LazyFrame, output_dir: Path) -> None:
    """Export manuscript Spearman statistics from the full QC dataset.

    Correlations are computed pairwise from the complete QC parquet. Processing
    one metric pair at a time deliberately limits peak memory use on large
    clonotype-level tables; plotting subsamples are never used for these values.
    """
    names = lf.collect_schema().names()
    matrix_metrics = [c for c in SPEARMAN_BASE_METRICS if c in names]
    if "cqc_effective_posterior_support_simpson" in names:
        matrix_metrics.append("cqc_effective_posterior_support_simpson")

    required_for_key = [
        "cqc_posterior_width95_x",
        "cqc_state_detectability",
        "cqc_abs_delta_detectability",
    ]
    missing = [c for c in required_for_key if c not in names]
    if missing:
        raise ValueError(
            "Cannot compute full-dataset QC correlations; missing columns: %s" %
            ", ".join(missing)
        )

    requested_pairs = []
    for i, a in enumerate(matrix_metrics):
        for j in range(i + 1, len(matrix_metrics)):
            requested_pairs.append((a, matrix_metrics[j]))
    requested_pairs.extend([
        ("cqc_posterior_width95_x", "cqc_abs_delta_detectability"),
        ("cqc_state_detectability", "cqc_abs_delta_detectability"),
    ])

    # Deduplicate without changing deterministic order.
    unique_pairs = []
    seen = set()
    for a, b in requested_pairs:
        key = tuple(sorted((a, b)))
        if key not in seen:
            seen.add(key)
            unique_pairs.append((a, b))

    pair_stats = {}
    total = len(unique_pairs)
    for idx, (a, b) in enumerate(unique_pairs, start=1):
        print("[CQC-v7] Full-data Spearman %d/%d: %s vs %s" % (idx, total, a, b))
        n_complete, rho = _full_data_spearman_pair(lf, a, b)
        pair_stats[(a, b)] = (n_complete, rho)
        pair_stats[(b, a)] = (n_complete, rho)

    matrix_rows = []
    n_rows = []
    for a in matrix_metrics:
        corr_row = {"metric": a}
        n_row = {"metric": a}
        for b in matrix_metrics:
            if a == b:
                # The diagonal is exactly one; n is the finite count for that metric.
                n_diag = int(
                    lf.select(pl.col(a).is_finite().sum().alias("n")).collect()["n"][0]
                )
                corr_row[b] = 1.0
                n_row[b] = n_diag
            else:
                n_complete, rho = pair_stats[(a, b)]
                corr_row[b] = rho
                n_row[b] = n_complete
        matrix_rows.append(corr_row)
        n_rows.append(n_row)

    pl.DataFrame(matrix_rows).write_csv(
        output_dir / "qc_metric_spearman_correlations.csv"
    )
    pl.DataFrame(n_rows).write_csv(
        output_dir / "qc_metric_spearman_n_complete.csv"
    )

    key_pairs = [
        (
            "posterior_width95_vs_abs_delta_detectability",
            "cqc_posterior_width95_x",
            "cqc_abs_delta_detectability",
        ),
        (
            "state_detectability_vs_abs_delta_detectability",
            "cqc_state_detectability",
            "cqc_abs_delta_detectability",
        ),
    ]
    key_rows = []
    for relationship, x_metric, y_metric in key_pairs:
        n_complete, rho = pair_stats[(x_metric, y_metric)]
        key_rows.append({
            "relationship": relationship,
            "x_metric": x_metric,
            "y_metric": y_metric,
            "n_complete": n_complete,
            "spearman_rho": rho,
        })
    pl.DataFrame(key_rows).write_csv(
        output_dir / "clonotype_latent_posterior_qc_key_relationships.csv"
    )

    pl.DataFrame({
        "matrix_metrics": [";".join(matrix_metrics)],
        "correlation_definition": ["Spearman rank correlation"],
        "data_scope": ["full QC parquet; pairwise finite rows"],
        "plotting_sample_used": [False],
    }).write_csv(output_dir / "qc_metric_spearman_metadata.csv")

def write_summaries(parquet_path: Path, output_dir: Path, abundance_bin_width: float, detection_bin_width: float, replicate_z_bin_width: float, replicate_z_max: float) -> None:
    lf = pl.scan_parquet(parquet_path)
    metrics = [
        "cqc_posterior_width95_x", "cqc_posterior_fold_range95",
        "cqc_posterior_sd_x", "cqc_posterior_entropy",
        "cqc_effective_posterior_support", "cqc_posterior_entropy_normalized",
        "cqc_state_detectability", "cqc_state_dropout",
        "cqc_union_detectability", "cqc_delta_detectability",
        "cqc_abs_delta_detectability",
        "cqc_replicate_joint_detection_evidence", "cqc_joint_detection_evidence",
        "cqc_detection_imbalance",
        "cqc_replicate_abs_delta_x", "cqc_replicate_standardized_delta",
        "cqc_replicate_bhattacharyya", "cqc_replicate_hellinger",
        "cqc_replicate_bhattacharyya_gaussian",
    ]
    names = lf.collect_schema().names()
    for optional in ["cqc_posterior_relative_width95_f", "cqc_replicate_bhattacharyya_exact", "cqc_effective_posterior_support_simpson", "logP"]:
        if optional in names:
            metrics.append(optional)
    metric_summary(lf, metrics).write_csv(
        output_dir / "clonotype_latent_posterior_qc_metric_summary.csv"
    )
    write_state_detectability_validation(lf, output_dir)
    write_full_dataset_spearman(lf, output_dir)

    status = (
        lf.group_by(["cqc_diagnostic_status", "cqc_replicate_agreement_source"])
        .agg(pl.len().alias("n"))
        .with_columns((pl.col("n") / pl.col("n").sum()).alias("fraction"))
        .sort("n", descending=True)
    )
    write_csv(status, output_dir / "clonotype_latent_posterior_qc_status_summary.csv")
    grouped_summary(lf, ["subject"], output_dir / "clonotype_latent_posterior_qc_subject_summary.csv")
    grouped_summary(lf, ["subject", "time"], output_dir / "clonotype_latent_posterior_qc_pair_summary.csv")
    write_abundance_reference(
        lf, output_dir / "clonotype_latent_posterior_qc_abundance_reference.csv"
    )
    write_abundance_summary(
        lf, output_dir / "clonotype_latent_posterior_qc_by_abundance.csv", abundance_bin_width
    )
    write_detection_summary(
        lf, output_dir / "clonotype_latent_posterior_qc_by_detection.csv", detection_bin_width
    )
    write_replicate_z_summary(
        lf, output_dir / "clonotype_latent_posterior_qc_by_replicate_difference.csv",
        replicate_z_bin_width, replicate_z_max
    )


def write_state_detectability_validation(lf: pl.LazyFrame, output_dir: Path) -> None:
    """Export whole-dataset validation of posterior-integrated state detectability."""
    finite = lf.filter(
        pl.all_horizontal([
            pl.col("cqc_state_detectability").is_finite(),
            pl.col("cqc_union_detectability").is_finite(),
            pl.col("cqc_delta_detectability").is_finite(),
            pl.col("cqc_abs_delta_detectability").is_finite(),
            pl.col("cqc_state_dropout").is_finite(),
        ])
    )
    summary = finite.select([
        pl.len().alias("n_clonotype_timepoints"),
        pl.col("cqc_delta_detectability").mean().alias("mean_signed_delta_state_minus_union"),
        pl.col("cqc_abs_delta_detectability").mean().alias("mean_absolute_delta"),
        pl.col("cqc_abs_delta_detectability").median().alias("median_absolute_delta"),
        pl.col("cqc_abs_delta_detectability").quantile(0.99).alias("q99_absolute_delta"),
        pl.col("cqc_abs_delta_detectability").max().alias("max_absolute_delta"),
        (pl.col("cqc_abs_delta_detectability") > 1e-12).mean().alias("fraction_abs_delta_gt_1e_12"),
        (pl.col("cqc_abs_delta_detectability") > 1e-6).mean().alias("fraction_abs_delta_gt_1e_6"),
        (pl.col("cqc_abs_delta_detectability") > 1e-3).mean().alias("fraction_abs_delta_gt_1e_3"),
        (pl.col("cqc_state_detectability") + pl.col("cqc_state_dropout") - 1.0)
            .abs().max().alias("max_state_dropout_complementarity_error"),
        pl.corr("cqc_state_detectability", "cqc_union_detectability", method="pearson")
            .alias("pearson_state_vs_union"),
        pl.corr("cqc_state_detectability", "cqc_union_detectability", method="spearman")
            .alias("spearman_state_vs_union"),
    ]).collect(engine="streaming")
    summary.write_csv(output_dir / "state_detectability_validation_summary.csv")


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        description="Characterize clonotype-level latent posterior quality without scoring."
    )
    p.add_argument("--input", type=Path, required=True)
    p.add_argument("--input-pattern", default="per_clone_latent_subject.parquet")
    p.add_argument("--output-dir", type=Path, required=True)
    p.add_argument("--clone-col", default="aaSeqCDR3")
    p.add_argument("--grid-size", type=int, default=500)
    p.add_argument("--abundance-bin-width", type=float, default=1.0)
    p.add_argument("--compression", default="zstd")
    p.add_argument("--detection-bin-width", type=float, default=0.02,
                   help="Bin width for joint detection evidence summaries.")
    p.add_argument("--replicate-z-bin-width", type=float, default=0.25,
                   help="Bin width for standardized replicate-difference summaries.")
    p.add_argument("--replicate-z-max", type=float, default=5.0,
                   help="Upper clipping bound for standardized-difference summaries.")
    p.add_argument("--exact-overlap-table", type=Path, default=None,
                   help="Optional table keyed by subject,time,clone with exact discrete-posterior BC.")
    p.add_argument("--exact-bc-col", default=None,
                   help="Name of exact BC column in input or --exact-overlap-table.")
    p.add_argument("--require-exact-overlap", action="store_true",
                   help="Fail rather than use Gaussian fallback when exact overlap is unavailable.")
    p.add_argument("--posterior-support-table", type=Path, default=None,
                   help="Optional table keyed by subject,time,clone containing exact inverse-Simpson posterior support.")
    p.add_argument("--inverse-simpson-col", default=None,
                   help="Name of the inverse-Simpson support column in input or support table.")
    p.add_argument("--require-inverse-simpson", action="store_true",
                   help="Fail if exact inverse-Simpson posterior support is unavailable.")
    return p


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = build_parser().parse_args(argv)
    if args.grid_size < 8:
        raise ValueError("--grid-size must be >= 8")
    if args.abundance_bin_width <= 0:
        raise ValueError("--abundance-bin-width must be > 0")
    if args.detection_bin_width <= 0 or args.detection_bin_width > 1:
        raise ValueError("--detection-bin-width must be in (0, 1]")
    if args.replicate_z_bin_width <= 0:
        raise ValueError("--replicate-z-bin-width must be > 0")
    if args.replicate_z_max <= 0:
        raise ValueError("--replicate-z-max must be > 0")

    input_path = resolve_input(args.input, args.input_pattern)
    output_dir = ensure_dir(args.output_dir)
    output_path = output_dir / "clonotype_latent_posterior_qc.parquet"

    print("[CQC-v7] Input:", input_path)
    diagnostics, exact_source, support_source = build_diagnostics(
        scan_table(input_path), args.clone_col, args.grid_size,
        args.exact_overlap_table, args.exact_bc_col, args.require_exact_overlap,
        args.posterior_support_table, args.inverse_simpson_col, args.require_inverse_simpson,
    )
    diagnostics.sink_parquet(
        output_path, compression=args.compression, statistics=True, mkdir=True
    )
    write_summaries(output_path, output_dir, args.abundance_bin_width, args.detection_bin_width, args.replicate_z_bin_width, args.replicate_z_max)

    manifest = {
        "script": Path(__file__).name,
        "input": str(input_path),
        "output": str(output_path),
        "grid_size": args.grid_size,
        "abundance_bin_width": args.abundance_bin_width,
        "detection_bin_width": args.detection_bin_width,
        "replicate_z_bin_width": args.replicate_z_bin_width,
        "replicate_z_max": args.replicate_z_max,
        "primary_domains": {
            "posterior_uncertainty": [
                "cqc_posterior_width95_x", "cqc_posterior_fold_range95",
                "cqc_posterior_entropy", "cqc_effective_posterior_support",
                "cqc_effective_posterior_support_simpson",
                "cqc_posterior_relative_width95_f",
            ],
            "state_detectability": [
                "cqc_state_detectability", "cqc_state_dropout",
            ],
            "replicate_detection_qc": [
                "cqc_replicate_joint_detection_evidence",
                "cqc_joint_detection_evidence",
                "cqc_detection_imbalance",
            ],
            "replicate_agreement": [
                "cqc_replicate_bhattacharyya", "cqc_replicate_hellinger",
                "cqc_replicate_standardized_delta",
            ],
            "model_compatibility": ["logP"],
        },
        "exact_overlap_source": exact_source,
        "inverse_simpson_support_source": support_source,
        "state_detectability_policy": (
            "p_detect_state is the primary posterior-predictive detectability of the latent state "
            "under the paired-replicate observation design. Replicate-specific detectabilities and "
            "their geometric mean are retained only as technical/QC diagnostics."
        ),
        "agreement_policy": (
            "Exact discrete-posterior Bhattacharyya overlap is preferred. "
            "Gaussian BC is used only for rows lacking exact overlap and is marked "
            "in cqc_replicate_agreement_source."
        ),
        "inverse_simpson_policy": (
            "Inverse-Simpson support is computed as 1/sum(p_i^2) on the full discrete posterior. "
            "It is never approximated from entropy; the field is present only when supplied by Step 2 or an external keyed table."
        ),
        "manuscript_statistics_policy": (
            "Metric quantiles and Spearman correlations are computed from the full QC parquet. "
            "Plotting subsamples are used only for graphical rendering and smoothing."
        ),
        "composite_score": False,
        "quality_classes": False,
        "filtering": False,
    }
    with open(output_dir / "clonotype_latent_posterior_qc_manifest.json", "w", encoding="utf-8") as fh:
        json.dump(manifest, fh, indent=2)

    print("[CQC-v7] Completed. No clonotypes were excluded.")
    if exact_source:
        print("[CQC-v7] Exact posterior overlap source:", exact_source)
    else:
        print("[CQC-v7] WARNING: exact overlap unavailable; Gaussian fallback used.")
    print("[CQC-v7] Main output:", output_path)
    return 0


