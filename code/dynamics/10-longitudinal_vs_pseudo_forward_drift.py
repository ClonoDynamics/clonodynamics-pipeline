def interpolate_curve(x: np.ndarray, y: np.ndarray, grid: np.ndarray) -> np.ndarray:
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)
    grid = np.asarray(grid, dtype=float)
    keep = np.isfinite(x) & np.isfinite(y)
    x = x[keep]
    y = y[keep]
    if x.size < 2:
        return np.full(grid.shape, np.nan, dtype=float)
    order = np.argsort(x)
    x = x[order]
    y = y[order]
    ux, inverse = np.unique(x, return_inverse=True)
    if ux.size != x.size:
        sy = np.zeros(ux.size, dtype=float)
        nn = np.zeros(ux.size, dtype=float)
        for i, group in enumerate(inverse):
            if np.isfinite(y[i]):
                sy[group] += y[i]
                nn[group] += 1.0
        yy = np.full(ux.size, np.nan, dtype=float)
        ok = nn > 0
        yy[ok] = sy[ok] / nn[ok]
        x = ux[ok]
        y = yy[ok]
    if x.size < 2:
        return np.full(grid.shape, np.nan, dtype=float)
    out = np.full(grid.shape, np.nan, dtype=float)
    inside = (grid >= x.min()) & (grid <= x.max())
    out[inside] = np.interp(grid[inside], x, y)
    return out


def curve_metrics(x: np.ndarray, y: np.ndarray) -> Dict[str, float]:
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)
    keep = np.isfinite(x) & np.isfinite(y)
    x = x[keep]
    y = y[keep]
    if y.size < 3:
        return {
            "mean_dx": float("nan"),
            "slope": float("nan"),
            "centered_mean_abs_drift": float("nan"),
            "centered_rms_drift": float("nan"),
            "n_points": int(y.size),
        }
    mean_y = float(np.mean(y))
    centered = y - mean_y
    slope = float(np.polyfit(x, y, 1)[0]) if np.ptp(x) > 0 else float("nan")
    return {
        "mean_dx": mean_y,
        "slope": slope,
        "centered_mean_abs_drift": float(np.mean(np.abs(centered))),
        "centered_rms_drift": float(np.sqrt(np.mean(centered ** 2))),
        "n_points": int(y.size),
    }


def summarize_null(values: np.ndarray) -> Dict[str, float]:
    values = np.asarray(values, dtype=float)
    values = values[np.isfinite(values)]
    if values.size == 0:
        return {
            "n": 0,
            "mean": float("nan"),
            "sd": float("nan"),
            "q005": float("nan"),
            "q025": float("nan"),
            "median": float("nan"),
            "q975": float("nan"),
            "q995": float("nan"),
        }
    q = np.quantile(values, [0.005, 0.025, 0.5, 0.975, 0.995])
    return {
        "n": int(values.size),
        "mean": float(np.mean(values)),
        "sd": float(np.std(values, ddof=1)) if values.size > 1 else 0.0,
        "q005": float(q[0]),
        "q025": float(q[1]),
        "median": float(q[2]),
        "q975": float(q[3]),
        "q995": float(q[4]),
    }


def empirical_p_lower(null_values: np.ndarray, observed: float) -> float:
    v = np.asarray(null_values, dtype=float)
    v = v[np.isfinite(v)]
    if v.size == 0 or not np.isfinite(observed):
        return float("nan")
    return float((1.0 + np.sum(v <= observed)) / (v.size + 1.0))


def empirical_p_upper(null_values: np.ndarray, observed: float) -> float:
    v = np.asarray(null_values, dtype=float)
    v = v[np.isfinite(v)]
    if v.size == 0 or not np.isfinite(observed):
        return float("nan")
    return float((1.0 + np.sum(v >= observed)) / (v.size + 1.0))


def empirical_p_two_sided_about_median(null_values: np.ndarray, observed: float) -> float:
    v = np.asarray(null_values, dtype=float)
    v = v[np.isfinite(v)]
    if v.size == 0 or not np.isfinite(observed):
        return float("nan")
    median = float(np.median(v))
    d_obs = abs(float(observed) - median)
    d_null = np.abs(v - median)
    return float((1.0 + np.sum(d_null >= d_obs)) / (v.size + 1.0))


