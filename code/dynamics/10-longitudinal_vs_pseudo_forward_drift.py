def prepare_subject_drift(df: pd.DataFrame, representation: str) -> pd.DataFrame:
    d = select_representation(df, representation, "longitudinal subject drift")
    require_columns(d, ["subject", "x_center", "mean_dx"], "longitudinal subject drift")
    return d.sort_values(["subject", "x_center"]).reset_index(drop=True)


def prepare_loso_drift(df: pd.DataFrame, representation: str) -> pd.DataFrame:
    d = select_representation(df, representation, "longitudinal LOSO drift")
    require_columns(
        d, ["omitted_subject", "x_center", "mean_dx"], "longitudinal LOSO drift"
    )
    return d.sort_values(["omitted_subject", "x_center"]).reset_index(drop=True)


def build_comparison_summary(
    tests: pd.DataFrame,
    shared: pd.DataFrame,
    support: pd.DataFrame,
    fold_concordance: pd.DataFrame,
) -> pd.DataFrame:
    row: Dict[str, object] = {}

    for _, r in tests.iterrows():
        metric = str(r["metric"])
        row["longitudinal_{}".format(metric)] = float(r["longitudinal_value"])
        row["pseudo_median_{}".format(metric)] = float(r["pseudo_median"])
        row["empirical_p_{}".format(metric)] = float(r["empirical_p"])

    outside = shared["longitudinal_outside_pseudo_95"].astype(bool).to_numpy()
    row["n_shared_grid_points"] = int(len(shared))
    row["n_outside_pseudo_95"] = int(np.sum(outside))
    row["fraction_outside_pseudo_95"] = float(np.mean(outside))

    if not support.empty:
        row["shared_support_min"] = float(support["shared_support_min"].iloc[0])
        row["shared_support_max"] = float(support["shared_support_max"].iloc[0])
        row["shared_support_width"] = float(support["shared_support_width"].iloc[0])

    if not fold_concordance.empty:
        f = fold_concordance.iloc[0]
        for c in fold_concordance.columns:
            val = f[c]
            row["fold_{}".format(c)] = val.item() if hasattr(val, "item") else val

    return pd.DataFrame([row])


