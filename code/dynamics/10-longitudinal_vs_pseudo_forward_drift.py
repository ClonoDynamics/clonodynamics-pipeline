def prepare_longitudinal_native(by_bin: pd.DataFrame, representation: str) -> pd.DataFrame:
    h = select_representation(by_bin, representation, "longitudinal forward drift")
    require_columns(
        h,
        ["x_center", "mean_dx", "mean_dx_ci025", "mean_dx_ci975"],
        "longitudinal forward drift",
    )
    h = finite_xy(h, "x_center", "mean_dx")
    out = pd.DataFrame({
        "dataset": "longitudinal",
        "representation": representation,
        "x_center": pd.to_numeric(h["x_center"], errors="coerce"),
        "mean_dx": pd.to_numeric(h["mean_dx"], errors="coerce"),
        "lower": pd.to_numeric(h["mean_dx_ci025"], errors="coerce"),
        "upper": pd.to_numeric(h["mean_dx_ci975"], errors="coerce"),
    })
    for c in ["bin", "x_left", "x_right", "n", "n_subjects", "x_mean"]:
        out[c] = pd.to_numeric(h[c], errors="coerce") if c in h.columns else np.nan
    return out.sort_values("x_center").reset_index(drop=True)


def prepare_pseudo_native(envelope: pd.DataFrame, representation: str) -> pd.DataFrame:
    p = select_representation(envelope, representation, "pseudo ordering envelope")
    require_columns(
        p,
        ["x_center", "mean_dx_median", "mean_dx_q025", "mean_dx_q975"],
        "pseudo ordering envelope",
    )
    p = finite_xy(p, "x_center", "mean_dx_median")
    out = pd.DataFrame({
        "dataset": "pseudo",
        "representation": representation,
        "x_center": pd.to_numeric(p["x_center"], errors="coerce"),
        "mean_dx": pd.to_numeric(p["mean_dx_median"], errors="coerce"),
        "lower": pd.to_numeric(p["mean_dx_q025"], errors="coerce"),
        "upper": pd.to_numeric(p["mean_dx_q975"], errors="coerce"),
    })
    for c in ["bin", "x_left", "x_right", "n_orderings"]:
        out[c] = pd.to_numeric(p[c], errors="coerce") if c in p.columns else np.nan
    for c in ["n", "n_subjects", "x_mean"]:
        out[c] = np.nan
    return out.sort_values("x_center").reset_index(drop=True)


def compute_shared_support(
    longitudinal_native: pd.DataFrame,
    pseudo_native: pd.DataFrame,
) -> Tuple[float, float]:
    hmin = float(longitudinal_native["x_center"].min())
    hmax = float(longitudinal_native["x_center"].max())
    pmin = float(pseudo_native["x_center"].min())
    pmax = float(pseudo_native["x_center"].max())
    lo = max(hmin, pmin)
    hi = min(hmax, pmax)
    if not (np.isfinite(lo) and np.isfinite(hi) and hi > lo):
        raise ValueError(
            "Longitudinal and pseudo absolute-abundance supports do not overlap: "
            "longitudinal=[{:.6g}, {:.6g}], pseudo=[{:.6g}, {:.6g}]".format(
                hmin, hmax, pmin, pmax
            )
        )
    return lo, hi


def build_shared_grid(
    longitudinal_native: pd.DataFrame,
    pseudo_native: pd.DataFrame,
    overlap_min: float,
    overlap_max: float,
    n_grid_points: int,
) -> pd.DataFrame:
    grid = np.linspace(overlap_min, overlap_max, int(n_grid_points), dtype=float)
    h_x = longitudinal_native["x_center"].to_numpy(dtype=float)
    p_x = pseudo_native["x_center"].to_numpy(dtype=float)

    out = pd.DataFrame({"x": grid})
    out["longitudinal_mean_dx"] = interpolate_curve(
        h_x, longitudinal_native["mean_dx"].to_numpy(dtype=float), grid
    )
    out["longitudinal_ci025"] = interpolate_curve(
        h_x, longitudinal_native["lower"].to_numpy(dtype=float), grid
    )
    out["longitudinal_ci975"] = interpolate_curve(
        h_x, longitudinal_native["upper"].to_numpy(dtype=float), grid
    )
    out["pseudo_median_dx"] = interpolate_curve(
        p_x, pseudo_native["mean_dx"].to_numpy(dtype=float), grid
    )
    out["pseudo_q025"] = interpolate_curve(
        p_x, pseudo_native["lower"].to_numpy(dtype=float), grid
    )
    out["pseudo_q975"] = interpolate_curve(
        p_x, pseudo_native["upper"].to_numpy(dtype=float), grid
    )
    out["longitudinal_minus_pseudo"] = (
        out["longitudinal_mean_dx"] - out["pseudo_median_dx"]
    )
    out["longitudinal_outside_pseudo_95"] = (
        (out["longitudinal_mean_dx"] < out["pseudo_q025"])
        | (out["longitudinal_mean_dx"] > out["pseudo_q975"])
    )
    return out


