def ensure_dir(path: Path) -> Path:
    path = Path(path)
    path.mkdir(parents=True, exist_ok=True)
    return path


def read_csv(path: Path, label: str, usecols: Optional[Sequence[str]] = None) -> pd.DataFrame:
    path = Path(path)
    if not path.exists():
        raise FileNotFoundError("{} not found: {}".format(label, path))
    df = pd.read_csv(path, usecols=usecols)
    if df.empty:
        raise ValueError("{} is empty: {}".format(label, path))
    return df


def require_columns(df: pd.DataFrame, required: Sequence[str], label: str) -> None:
    missing = [c for c in required if c not in df.columns]
    if missing:
        raise ValueError(
            "{} is missing required columns {}. Available: {}".format(
                label, missing, list(df.columns)
            )
        )


def resolve_ordering_dir(pseudo_benchmark_dir: Path) -> Path:
    root = Path(pseudo_benchmark_dir)
    candidate = root / "03_ordering_robustness"
    if candidate.is_dir():
        return candidate
    # Permit the ordering directory itself for convenient isolated reruns.
    required = [
        root / "pseudo_reverse_pair_envelope.csv",
        root / "pseudo_reverse_pair_curves.csv",
    ]
    if all(p.exists() for p in required):
        return root
    raise FileNotFoundError(
        "Could not locate pseudo ordering-robustness outputs. Expected "
        "<pseudo-benchmark-dir>/03_ordering_robustness/ containing "
        "pseudo_reverse_pair_envelope.csv and pseudo_reverse_pair_curves.csv."
    )


def select_representation(df: pd.DataFrame, representation: str, label: str) -> pd.DataFrame:
    require_columns(df, ["representation"], label)
    available = sorted(df["representation"].dropna().astype(str).unique().tolist())
    if representation not in available:
        raise ValueError(
            "Representation {!r} not present in {}. Available: {}".format(
                representation, label, available
            )
        )
    return df.loc[df["representation"].astype(str) == representation].copy()


def finite_xy(df: pd.DataFrame, x_col: str, y_col: str) -> pd.DataFrame:
    out = df.copy()
    out[x_col] = pd.to_numeric(out[x_col], errors="coerce")
    out[y_col] = pd.to_numeric(out[y_col], errors="coerce")
    out = out.loc[np.isfinite(out[x_col]) & np.isfinite(out[y_col])].copy()
    out = out.sort_values(x_col)
    if out[x_col].duplicated().any():
        numeric_cols = [
            c for c in out.columns
            if c != x_col and pd.api.types.is_numeric_dtype(out[c])
        ]
        agg: Dict[str, str] = {c: "mean" for c in numeric_cols}
        for c in out.columns:
            if c not in agg and c != x_col:
                agg[c] = "first"
        out = out.groupby(x_col, as_index=False).agg(agg)
    return out


