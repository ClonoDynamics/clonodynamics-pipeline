def pseudo_metrics_on_overlap(
    pseudo_curves: pd.DataFrame,
    representation: str,
    grid: np.ndarray,
) -> pd.DataFrame:
    p = select_representation(pseudo_curves, representation, "pseudo reverse-pair curves")
    require_columns(
        p,
        ["reverse_pair_id", "x_center", "mean_dx"],
        "pseudo reverse-pair curves",
    )

    rows: List[Dict[str, float]] = []
    for reverse_pair_id, group in p.groupby("reverse_pair_id", sort=True):
        gg = finite_xy(group, "x_center", "mean_dx")
        yi = interpolate_curve(
            gg["x_center"].to_numpy(dtype=float),
            gg["mean_dx"].to_numpy(dtype=float),
            grid,
        )
        metrics = curve_metrics(grid, yi)
        row: Dict[str, float] = {"reverse_pair_id": int(reverse_pair_id)}
        row.update(metrics)
        rows.append(row)

    out = pd.DataFrame(rows)
    if out.empty:
        raise ValueError("No pseudo reverse-pair overlap metrics could be computed")
    return out


def empirical_tests(
    longitudinal_metrics: Dict[str, float],
    pseudo_metrics: pd.DataFrame,
) -> pd.DataFrame:
    specs = [
        ("slope", "lower", "Longitudinal slope more negative than pseudo null"),
        (
            "centered_mean_abs_drift",
            "upper",
            "Longitudinal centered mean-absolute drift exceeds pseudo null",
        ),
        (
            "centered_rms_drift",
            "upper",
            "Longitudinal centered RMS drift exceeds pseudo null",
        ),
        (
            "mean_dx",
            "two_sided_about_median",
            "Longitudinal mean offset differs from pseudo-null median",
        ),
    ]

    rows: List[Dict[str, object]] = []
    for metric, tail, interpretation in specs:
        obs = float(longitudinal_metrics.get(metric, float("nan")))
        null_values = pd.to_numeric(
            pseudo_metrics[metric], errors="coerce"
        ).to_numpy(dtype=float)
        summary = summarize_null(null_values)
        if tail == "lower":
            p_emp = empirical_p_lower(null_values, obs)
        elif tail == "upper":
            p_emp = empirical_p_upper(null_values, obs)
        else:
            p_emp = empirical_p_two_sided_about_median(null_values, obs)
        rows.append({
            "metric": metric,
            "longitudinal_value": obs,
            "pseudo_n": int(summary["n"]),
            "pseudo_mean": summary["mean"],
            "pseudo_sd": summary["sd"],
            "pseudo_q005": summary["q005"],
            "pseudo_q025": summary["q025"],
            "pseudo_median": summary["median"],
            "pseudo_q975": summary["q975"],
            "pseudo_q995": summary["q995"],
            "empirical_p": p_emp,
            "tail": tail,
            "interpretation": interpretation,
        })
    return pd.DataFrame(rows)


