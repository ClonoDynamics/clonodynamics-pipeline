def conditioning_summary_rows(conditioning_dir: Path) -> List[Dict[str, object]]:
    curves = read_csv_if_exists(conditioning_dir / "03_pooled_bias_curves.csv")
    if curves.empty:
        return []

    if "used_in_benchmark_summary" in curves.columns:
        curves = curves.loc[normalize_bool(curves["used_in_benchmark_summary"])].copy()

    rows: List[Dict[str, object]] = []
    for candidate, d in curves.groupby("candidate", sort=False):
        mean_dx = finite_numeric(d["mean_dx"]) if "mean_dx" in d.columns else np.asarray([])
        median_dx = finite_numeric(d["median_dx"]) if "median_dx" in d.columns else np.asarray([])
        ppos = finite_numeric(d["ppos"]) if "ppos" in d.columns else np.asarray([])
        rows.append(
            {
                "section": "conditioning_geometry",
                "representation": str(candidate),
                "metric": "n_common_plotted_bins",
                "value": int(len(d)),
            }
        )
        if mean_dx.size:
            rows.append(
                {
                    "section": "conditioning_geometry",
                    "representation": str(candidate),
                    "metric": "mean_abs_mean_dx",
                    "value": float(np.mean(np.abs(mean_dx))),
                }
            )
        if median_dx.size:
            rows.append(
                {
                    "section": "conditioning_geometry",
                    "representation": str(candidate),
                    "metric": "mean_abs_median_dx",
                    "value": float(np.mean(np.abs(median_dx))),
                }
            )
        if ppos.size:
            rows.append(
                {
                    "section": "conditioning_geometry",
                    "representation": str(candidate),
                    "metric": "mean_abs_probability_bias",
                    "value": float(np.mean(np.abs(ppos - 0.5))),
                }
            )
    return rows


def fold_concordance_rows(crossfit_dir: Path) -> List[Dict[str, object]]:
    d = read_csv_if_exists(crossfit_dir / "forward_drift_by_fold.csv")
    if d.empty or "representation" not in d.columns:
        return []

    a = d.loc[d["representation"].astype(str) == "cross_AB", ["bin", "mean_dx"]].copy()
    b = d.loc[d["representation"].astype(str) == "cross_BA", ["bin", "mean_dx"]].copy()
    if a.empty or b.empty:
        return []
    a = a.rename(columns={"mean_dx": "mean_dx_AB"})
    b = b.rename(columns={"mean_dx": "mean_dx_BA"})
    m = a.merge(b, on="bin", how="inner")
    x = pd.to_numeric(m["mean_dx_AB"], errors="coerce").to_numpy(dtype=float)
    y = pd.to_numeric(m["mean_dx_BA"], errors="coerce").to_numpy(dtype=float)
    good = np.isfinite(x) & np.isfinite(y)
    x, y = x[good], y[good]
    if x.size == 0:
        return []
    r = float(np.corrcoef(x, y)[0, 1]) if x.size >= 2 and np.std(x) > 0 and np.std(y) > 0 else np.nan
    delta = x - y
    return [
        {
            "section": "replicate_decoupling",
            "representation": "cross_AB_vs_cross_BA",
            "metric": "n_matched_bins",
            "value": int(x.size),
        },
        {
            "section": "replicate_decoupling",
            "representation": "cross_AB_vs_cross_BA",
            "metric": "pearson_r",
            "value": r,
        },
        {
            "section": "replicate_decoupling",
            "representation": "cross_AB_vs_cross_BA",
            "metric": "mean_abs_difference",
            "value": float(np.mean(np.abs(delta))),
        },
        {
            "section": "replicate_decoupling",
            "representation": "cross_AB_vs_cross_BA",
            "metric": "rms_difference",
            "value": float(np.sqrt(np.mean(delta * delta))),
        },
    ]


def matched_same_cross_rows(crossfit_dir: Path) -> List[Dict[str, object]]:
    d = read_csv_if_exists(crossfit_dir / "forward_drift_matched_same_vs_cross.csv")
    if d.empty:
        return []
    needed = {"bin", "x_center", "mean_dx_same", "mean_dx_cross"}
    if not needed.issubset(d.columns):
        return []
    c = (
        d.groupby(["bin", "x_center"], as_index=False)
        .agg(mean_dx_same=("mean_dx_same", "mean"), mean_dx_cross=("mean_dx_cross", "mean"))
        .sort_values("bin")
    )
    same = finite_numeric(c["mean_dx_same"])
    cross = finite_numeric(c["mean_dx_cross"])
    if same.size == 0 or cross.size == 0 or same.size != cross.size:
        return []
    same_mad = float(np.mean(np.abs(same)))
    cross_mad = float(np.mean(np.abs(cross)))
    reduction = float(100.0 * (1.0 - cross_mad / same_mad)) if same_mad != 0 else np.nan
    retention = float(cross_mad / same_mad) if same_mad != 0 else np.nan
    return [
        {
            "section": "replicate_decoupling",
            "representation": "same_combined",
            "metric": "mean_abs_bin_drift",
            "value": same_mad,
        },
        {
            "section": "replicate_decoupling",
            "representation": "cross_combined",
            "metric": "mean_abs_bin_drift",
            "value": cross_mad,
        },
        {
            "section": "replicate_decoupling",
            "representation": "cross_vs_same",
            "metric": "percent_reduction_mean_abs_bin_drift",
            "value": reduction,
        },
        {
            "section": "replicate_decoupling",
            "representation": "cross_vs_same",
            "metric": "retained_fraction_mean_abs_bin_drift",
            "value": retention,
        },
    ]


def reliability_rows(crossfit_dir: Path) -> List[Dict[str, object]]:
    d = read_csv_if_exists(crossfit_dir / "forward_drift_reliability_by_bin.csv")
    if d.empty or "fold" not in d.columns:
        return []
    rows: List[Dict[str, object]] = []
    for fold, g in d.groupby("fold", sort=True):
        for col in ["fraction_four_positive", "median_cond_sd", "median_min_count_four"]:
            if col not in g.columns:
                continue
            vals = finite_numeric(g[col])
            if vals.size:
                rows.append(
                    {
                        "section": "reliability",
                        "representation": str(fold),
                        "metric": "median_{}".format(col),
                        "value": float(np.median(vals)),
                    }
                )
    return rows


def permutation_rows(permutation_dir: Path) -> List[Dict[str, object]]:
    d = read_csv_if_exists(permutation_dir / "pseudo_reverse_pair_metrics.csv")
    if d.empty:
        return []
    rows: List[Dict[str, object]] = []
    for rep in ["same_combined", "cross_combined"]:
        g = d.loc[d["representation"].astype(str) == rep].copy()
        if g.empty:
            continue
        n_pairs = int(g["reverse_pair_id"].nunique()) if "reverse_pair_id" in g.columns else int(len(g))
        rows.append(
            {
                "section": "ordering_robustness",
                "representation": rep,
                "metric": "n_order_reverse_pairs",
                "value": n_pairs,
            }
        )
        for metric in ["slope", "centered_mean_abs_drift", "centered_rms_drift", "mean_abs_probability_bias"]:
            if metric not in g.columns:
                continue
            vals = finite_numeric(g[metric])
            if vals.size:
                rows.append(
                    {
                        "section": "ordering_robustness",
                        "representation": rep,
                        "metric": "median_{}".format(metric),
                        "value": float(np.median(vals)),
                    }
                )

    # reduction in the primary centered magnitude descriptor
    if "centered_mean_abs_drift" in d.columns:
        same = finite_numeric(
            d.loc[d["representation"].astype(str) == "same_combined", "centered_mean_abs_drift"]
        )
        cross = finite_numeric(
            d.loc[d["representation"].astype(str) == "cross_combined", "centered_mean_abs_drift"]
        )
        if same.size and cross.size:
            same_med = float(np.median(same))
            cross_med = float(np.median(cross))
            rows.append(
                {
                    "section": "ordering_robustness",
                    "representation": "cross_vs_same",
                    "metric": "percent_reduction_median_centered_mean_abs_drift",
                    "value": float(100.0 * (1.0 - cross_med / same_med)) if same_med != 0 else np.nan,
                }
            )
    return rows


def write_master_summary(outdir: Path) -> Path:
    rows: List[Dict[str, object]] = []
    rows.extend(conditioning_summary_rows(outdir / CONDITIONING_DIRNAME))
    rows.extend(fold_concordance_rows(outdir / CROSSFIT_DIRNAME))
    rows.extend(matched_same_cross_rows(outdir / CROSSFIT_DIRNAME))
    rows.extend(reliability_rows(outdir / CROSSFIT_DIRNAME))
    rows.extend(permutation_rows(outdir / PERMUTATION_DIRNAME))
    summary = pd.DataFrame(rows, columns=["section", "representation", "metric", "value"])
    path = outdir / "00_benchmark_summary.csv"
    summary.to_csv(path, index=False)
    return path


def write_manifest(outdir: Path) -> Path:
    rows: List[Dict[str, object]] = []
    for stage, dirname in [
        ("conditioning_geometry", CONDITIONING_DIRNAME),
        ("replicate_decoupling", CROSSFIT_DIRNAME),
        ("ordering_robustness", PERMUTATION_DIRNAME),
    ]:
        base = outdir / dirname
        if not base.exists():
            continue
        for p in sorted(base.iterdir()):
            if p.is_file() and not p.name.startswith("."):
                rows.append(
                    {
                        "stage": stage,
                        "relative_path": str(p.relative_to(outdir)),
                        "suffix": p.suffix.lower(),
                        "size_bytes": int(p.stat().st_size),
                    }
                )
    path = outdir / "00_pipeline_manifest.csv"
    pd.DataFrame(rows).to_csv(path, index=False)
    return path


