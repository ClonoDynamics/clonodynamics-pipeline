def materialize_bundled_engine(bundle_key: str, filename: str) -> Path:
    if bundle_key not in BUNDLED_ENGINE_PAYLOADS:
        raise KeyError("Unknown bundled engine: {}".format(bundle_key))
    tempdir = Path(tempfile.mkdtemp(prefix="clonodynamics_pseudo_engine_"))
    _BUNDLED_TEMP_DIRS.append(tempdir)
    target = tempdir / filename
    payload = "".join(BUNDLED_ENGINE_PAYLOADS[bundle_key].split())
    raw = zlib.decompress(base64.b64decode(payload.encode("ascii")))
    target.write_bytes(raw)
    return target


