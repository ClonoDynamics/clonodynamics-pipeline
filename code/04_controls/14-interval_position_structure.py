def profile_statistics(
    positions: np.ndarray,
    profile: np.ndarray,
) -> Dict[str, float]:
    positions = np.asarray(
        positions,
        dtype=float,
    )
    profile = np.asarray(
        profile,
        dtype=float,
    )

    ok = (
        np.isfinite(positions)
        & np.isfinite(profile)
    )

    x = positions[ok]
    y = profile[ok]

    if y.size < 2:
        return {
            "rms_position_deviation": np.nan,
            "position_range": np.nan,
            "calendar_slope": np.nan,
        }

    centered = y - float(
        np.mean(y)
    )

    rms = float(
        np.sqrt(
            np.mean(
                centered ** 2
            )
        )
    )

    value_range = float(
        np.max(y) - np.min(y)
    )

    if np.unique(x).size >= 2:
        slope = float(
            np.polyfit(
                x,
                y,
                1,
            )[0]
        )
    else:
        slope = np.nan

    return {
        "rms_position_deviation": rms,
        "position_range": value_range,
        "calendar_slope": slope,
    }


def subject_position_matrix(
    frame: pd.DataFrame,
    metric: str,
    subject_universe: Sequence[int],
    min_subjects_per_position: int,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    positions = sorted(
        int(x)
        for x in frame["t0"].unique()
    )

    valid_positions = []

    for position in positions:
        g = frame[
            frame["t0"].eq(
                int(position)
            )
        ]
        n = int(
            np.isfinite(
                pd.to_numeric(
                    g[metric],
                    errors="coerce",
                )
            ).sum()
        )
        if n >= int(
            min_subjects_per_position
        ):
            valid_positions.append(
                int(position)
            )

    positions_array = np.asarray(
        valid_positions,
        dtype=float,
    )

    matrix = np.full(
        (
            len(subject_universe),
            len(valid_positions),
        ),
        np.nan,
        dtype=float,
    )

    subject_index = {
        int(subject): i
        for i, subject in enumerate(
            subject_universe
        )
    }
    position_index = {
        int(position): j
        for j, position in enumerate(
            valid_positions
        )
    }

    for row in frame[
        ["subject", "t0", metric]
    ].itertuples(
        index=False
    ):
        subject = int(
            row.subject
        )
        position = int(
            row.t0
        )
        value = float(
            getattr(
                row,
                metric,
            )
        ) if pd.notna(
            getattr(
                row,
                metric,
            )
        ) else np.nan

        if (
            subject in subject_index
            and position in position_index
            and np.isfinite(value)
        ):
            matrix[
                subject_index[subject],
                position_index[position],
            ] = value

    counts = np.sum(
        np.isfinite(matrix),
        axis=0,
    ).astype(int)

    return (
        positions_array,
        matrix,
        counts,
    )


def permute_subject_positions(
    matrix: np.ndarray,
    rng: np.random.Generator,
) -> np.ndarray:
    out = matrix.copy()

    for i in range(
        matrix.shape[0]
    ):
        finite_idx = np.flatnonzero(
            np.isfinite(
                matrix[i]
            )
        )

        if finite_idx.size <= 1:
            continue

        values = matrix[
            i,
            finite_idx,
        ].copy()

        rng.shuffle(
            values
        )

        out[
            i,
            finite_idx,
        ] = values

    return out


def run_single_position_test(
    frame: pd.DataFrame,
    metric: str,
    subject_universe: Sequence[int],
    min_subjects_per_position: int,
    min_interval_positions: int,
    n_perm: int,
    rng: np.random.Generator,
) -> Dict[str, object]:
    positions, matrix, counts = (
        subject_position_matrix(
            frame,
            metric,
            subject_universe,
            min_subjects_per_position,
        )
    )

    result: Dict[str, object] = {
        "n_interval_positions": int(len(positions)),
        "interval_positions": ",".join(
            str(int(x))
            for x in positions
        ),
        "min_subjects_across_positions": (
            int(counts.min())
            if counts.size
            else 0
        ),
        "max_subjects_across_positions": (
            int(counts.max())
            if counts.size
            else 0
        ),
        "n_subjects_with_any_position": int(
            np.sum(
                np.any(
                    np.isfinite(matrix),
                    axis=1,
                )
            )
        ) if matrix.size else 0,
        "n_permutations_requested": int(n_perm),
    }

    if len(positions) < int(min_interval_positions):
        result.update(
            {
                "test_status": "insufficient_interval_positions",
                "n_permutations_valid": 0,
                "rms_position_deviation": np.nan,
                "position_range": np.nan,
                "calendar_slope": np.nan,
                "p_rms_position_structure": np.nan,
                "p_abs_calendar_slope": np.nan,
                "null_rms_median": np.nan,
                "null_rms_q025": np.nan,
                "null_rms_q975": np.nan,
                "null_abs_slope_median": np.nan,
                "null_abs_slope_q025": np.nan,
                "null_abs_slope_q975": np.nan,
            }
        )
        return result

    with np.errstate(invalid="ignore"):
        profile = np.nanmean(
            matrix,
            axis=0,
        )

    observed = profile_statistics(
        positions,
        profile,
    )

    # -----------------------------------------------------------------
    # Vectorized within-subject permutation null.
    #
    # Each subject retains exactly the same missingness/calendar-position
    # pattern. Only that subject's finite metric values are permuted among
    # their own available positions. This is identical to the original
    # permutation design but avoids a Python loop over n_perm.
    # -----------------------------------------------------------------
    n_perm = int(n_perm)
    n_subjects, n_positions = matrix.shape

    cube = np.broadcast_to(
        matrix,
        (n_perm, n_subjects, n_positions),
    ).copy()

    for i in range(n_subjects):
        finite_idx = np.flatnonzero(
            np.isfinite(matrix[i])
        )
        k = int(finite_idx.size)

        if k <= 1:
            continue

        values = matrix[
            i,
            finite_idx,
        ].copy()

        # Sorting independent continuous random keys yields a uniform random
        # permutation of the finite values for each permutation replicate.
        order = np.argsort(
            rng.random((n_perm, k)),
            axis=1,
        )
        cube[
            :,
            i,
            finite_idx,
        ] = values[order]

    with np.errstate(invalid="ignore"):
        perm_profiles = np.nanmean(
            cube,
            axis=1,
        )

    centered = (
        perm_profiles
        - np.nanmean(
            perm_profiles,
            axis=1,
            keepdims=True,
        )
    )
    null_rms = np.sqrt(
        np.nanmean(
            centered ** 2,
            axis=1,
        )
    )

    x = np.asarray(
        positions,
        dtype=float,
    )
    xc = x - float(np.mean(x))
    denom = float(
        np.sum(xc ** 2)
    )

    if denom > 0:
        # Because sum(xc)=0, centering each profile is unnecessary in the
        # numerator of the OLS slope with intercept.
        null_slopes = (
            np.nansum(
                perm_profiles * xc[None, :],
                axis=1,
            )
            / denom
        )
        null_abs_slope = np.abs(
            null_slopes
        )
    else:
        null_abs_slope = np.full(
            n_perm,
            np.nan,
            dtype=float,
        )

    observed_abs_slope = (
        abs(
            float(
                observed[
                    "calendar_slope"
                ]
            )
        )
        if np.isfinite(
            observed[
                "calendar_slope"
            ]
        )
        else np.nan
    )

    result.update(
        {
            "test_status": "ok",
            **observed,
            "n_permutations_valid": int(
                np.isfinite(
                    null_rms
                ).sum()
            ),
            "p_rms_position_structure": empirical_upper_tail(
                null_rms,
                float(
                    observed[
                        "rms_position_deviation"
                    ]
                ),
            ),
            "p_abs_calendar_slope": empirical_upper_tail(
                null_abs_slope,
                observed_abs_slope,
            ),
            "null_rms_median": float(
                np.nanmedian(
                    null_rms
                )
            ),
            "null_rms_q025": float(
                np.nanquantile(
                    null_rms,
                    0.025,
                )
            ),
            "null_rms_q975": float(
                np.nanquantile(
                    null_rms,
                    0.975,
                )
            ),
            "null_abs_slope_median": float(
                np.nanmedian(
                    null_abs_slope
                )
            ),
            "null_abs_slope_q025": float(
                np.nanquantile(
                    null_abs_slope,
                    0.025,
                )
            ),
            "null_abs_slope_q975": float(
                np.nanquantile(
                    null_abs_slope,
                    0.975,
                )
            ),
        }
    )

    return result


def add_bh(
    frame: pd.DataFrame,
    group_cols: Sequence[str],
) -> pd.DataFrame:
    if frame.empty:
        return frame

    out = frame.copy()

    for column in [
        "p_rms_position_structure",
        "p_abs_calendar_slope",
    ]:
        if column not in out.columns:
            out[column] = np.nan

    out[
        "q_bh_rms_position_structure"
    ] = np.nan
    out[
        "q_bh_abs_calendar_slope"
    ] = np.nan

    grouped = (
        out.groupby(
            list(group_cols),
            dropna=False,
            sort=False,
        )
        if group_cols
        else [(None, out)]
    )

    for _, group in grouped:
        idx = group.index

        out.loc[
            idx,
            "q_bh_rms_position_structure",
        ] = benjamini_hochberg(
            pd.to_numeric(
                group[
                    "p_rms_position_structure"
                ],
                errors="coerce",
            )
        )

        out.loc[
            idx,
            "q_bh_abs_calendar_slope",
        ] = benjamini_hochberg(
            pd.to_numeric(
                group[
                    "p_abs_calendar_slope"
                ],
                errors="coerce",
            )
        )

    return out


def core_position_tests(
    subject_core: pd.DataFrame,
    metrics: Sequence[str],
    complete_subjects: Sequence[int],
    dt_values: Sequence[int],
    min_subjects_per_position: int,
    min_interval_positions: int,
    n_perm: int,
    seed: int,
) -> pd.DataFrame:
    rng = np.random.default_rng(
        int(seed)
    )

    rows = []

    for metric in metrics:
        for dt in dt_values:
            g = subject_core[
                subject_core["dt"].eq(
                    int(dt)
                )
            ].copy()

            result = run_single_position_test(
                g,
                metric,
                complete_subjects,
                min_subjects_per_position,
                min_interval_positions,
                n_perm,
                rng,
            )

            rows.append(
                {
                    "metric": metric,
                    "dt": int(dt),
                    **result,
                }
            )

    out = pd.DataFrame(rows)

    # Primary multiplicity family: valid dt tests within each metric.
    out = add_bh(
        out,
        ["metric"],
    )

    return out.sort_values(
        ["metric", "dt"]
    )


def binwise_position_tests(
    interval_table: pd.DataFrame,
    metrics: Sequence[str],
    complete_subjects: Sequence[int],
    dt_values: Sequence[int],
    core_bins: Sequence[int],
    min_subject_interval_bin_n: int,
    min_subjects_per_position: int,
    min_interval_positions: int,
    n_perm: int,
    seed: int,
) -> pd.DataFrame:
    rng = np.random.default_rng(
        int(seed) + 17011
    )

    rows = []

    d = interval_table[
        interval_table["subject"].isin(
            [int(x) for x in complete_subjects]
        )
        & interval_table["dt"].isin(
            [int(x) for x in dt_values]
        )
        & interval_table["bin"].isin(
            [int(x) for x in core_bins]
        )
        & interval_table["n"].ge(
            int(
                min_subject_interval_bin_n
            )
        )
    ].copy()

    for metric in metrics:
        metric_data = d[
            np.isfinite(
                pd.to_numeric(
                    d[metric],
                    errors="coerce",
                )
            )
        ].copy()

        for dt in dt_values:
            for bin_id in core_bins:
                g = metric_data[
                    metric_data["dt"].eq(
                        int(dt)
                    )
                    & metric_data["bin"].eq(
                        int(bin_id)
                    )
                ].copy()

                if g.empty:
                    rows.append(
                        {
                            "metric": metric,
                            "dt": int(dt),
                            "bin": int(bin_id),
                            "test_status": "no_data",
                        }
                    )
                    continue

                ref = g.iloc[0]

                result = run_single_position_test(
                    g,
                    metric,
                    complete_subjects,
                    min_subjects_per_position,
                    min_interval_positions,
                    n_perm,
                    rng,
                )

                rows.append(
                    {
                        "metric": metric,
                        "dt": int(dt),
                        "bin": int(bin_id),
                        "x_left": float(
                            ref["x_left"]
                        ),
                        "x_right": float(
                            ref["x_right"]
                        ),
                        "x_center": float(
                            ref["x_center"]
                        ),
                        **result,
                    }
                )

    out = pd.DataFrame(rows)

    # Secondary multiplicity family: all valid dt x bin tests within metric.
    out = add_bh(
        out,
        ["metric"],
    )

    return out.sort_values(
        [
            "metric",
            "dt",
            "bin",
        ]
    )


