def anchor_filter(
    subject_core: pd.DataFrame,
    anchor: str,
    min_t0: int,
    max_t1: int,
) -> pd.DataFrame:
    if anchor == "common_start":
        return subject_core[
            subject_core["t0"].eq(
                int(min_t0)
            )
        ].copy()

    if anchor == "common_end":
        return subject_core[
            subject_core["t1"].eq(
                int(max_t1)
            )
        ].copy()

    raise ValueError(
        anchor
    )


def anchor_matrix(
    frame: pd.DataFrame,
    metric: str,
    subjects: Sequence[int],
    dt_values: Sequence[int],
) -> np.ndarray:
    matrix = np.full(
        (
            len(subjects),
            len(dt_values),
        ),
        np.nan,
        dtype=float,
    )

    s_index = {
        int(s): i
        for i, s in enumerate(
            subjects
        )
    }

    d_index = {
        int(dt): j
        for j, dt in enumerate(
            dt_values
        )
    }

    for row in frame[
        ["subject", "dt", metric]
    ].itertuples(
        index=False
    ):
        subject = int(
            row.subject
        )
        dt = int(
            row.dt
        )
        value = getattr(
            row,
            metric,
        )

        if (
            subject in s_index
            and dt in d_index
            and pd.notna(value)
            and np.isfinite(
                float(value)
            )
        ):
            matrix[
                s_index[subject],
                d_index[dt],
            ] = float(
                value
            )

    return matrix


def weighted_subject_mean(
    matrix: np.ndarray,
    multiplicity: np.ndarray,
) -> np.ndarray:
    valid = np.isfinite(
        matrix
    )

    numerator = np.sum(
        np.nan_to_num(
            matrix,
            nan=0.0,
        )
        * multiplicity[:, None],
        axis=0,
    )

    denominator = np.sum(
        valid
        * multiplicity[:, None],
        axis=0,
    )

    return np.divide(
        numerator,
        denominator,
        out=np.full(
            matrix.shape[1],
            np.nan,
            dtype=float,
        ),
        where=denominator > 0,
    )


def bootstrap_anchor(
    matrix: np.ndarray,
    dt_values: Sequence[int],
    n_bootstrap: int,
    seed: int,
    min_dt_points: int,
) -> Tuple[
    np.ndarray,
    np.ndarray,
    Dict[str, float],
]:
    dt_array = np.asarray(
        dt_values,
        dtype=float,
    )

    multiplicity = np.ones(
        matrix.shape[0],
        dtype=float,
    )

    observed_profile = weighted_subject_mean(
        matrix,
        multiplicity,
    )

    observed_fit = safe_linear_fit(
        dt_array,
        observed_profile,
    )

    if observed_fit[
        "n_dt"
    ] < int(
        min_dt_points
    ):
        return (
            observed_profile,
            np.array(
                [],
                dtype=float,
            ),
            observed_fit,
        )

    rng = np.random.default_rng(
        int(seed)
    )

    boot_slopes = np.full(
        int(n_bootstrap),
        np.nan,
        dtype=float,
    )

    n_subjects = int(
        matrix.shape[0]
    )

    if n_subjects < 2:
        return (
            observed_profile,
            boot_slopes,
            observed_fit,
        )

    for b in range(
        int(n_bootstrap)
    ):
        sampled = rng.integers(
            0,
            n_subjects,
            size=n_subjects,
        )

        multiplicity = np.bincount(
            sampled,
            minlength=n_subjects,
        ).astype(float)

        profile = weighted_subject_mean(
            matrix,
            multiplicity,
        )

        fit = safe_linear_fit(
            dt_array,
            profile,
        )

        if fit[
            "n_dt"
        ] >= int(
            min_dt_points
        ):
            boot_slopes[b] = fit[
                "slope_per_week"
            ]

    return (
        observed_profile,
        boot_slopes,
        observed_fit,
    )


def build_anchor_matching_diagnostic(
    subject_core: pd.DataFrame,
    complete_subjects: Sequence[int],
    dt_values: Sequence[int],
    metrics: Sequence[str],
) -> pd.DataFrame:
    min_t0 = int(
        subject_core["t0"].min()
    )
    max_t1 = int(
        subject_core["t1"].max()
    )

    rows = []

    for anchor in ANCHORS:
        anchored = anchor_filter(
            subject_core,
            anchor,
            min_t0,
            max_t1,
        )

        for metric in metrics:
            for subject in complete_subjects:
                g = anchored[
                    anchored["subject"].eq(
                        int(subject)
                    )
                ]

                finite_dts = sorted(
                    int(row.dt)
                    for row in g[
                        ["dt", metric]
                    ].itertuples(
                        index=False
                    )
                    if pd.notna(
                        getattr(
                            row,
                            metric,
                        )
                    )
                    and np.isfinite(
                        float(
                            getattr(
                                row,
                                metric,
                            )
                        )
                    )
                )

                missing = [
                    int(dt)
                    for dt in dt_values
                    if int(dt)
                    not in finite_dts
                ]

                rows.append(
                    {
                        "anchor_type": anchor,
                        "metric": metric,
                        "subject": int(
                            subject
                        ),
                        "n_requested_dt": int(
                            len(
                                dt_values
                            )
                        ),
                        "n_available_dt": int(
                            len(
                                finite_dts
                            )
                        ),
                        "available_dt_values": ",".join(
                            str(x)
                            for x in finite_dts
                        ),
                        "missing_dt_values": ",".join(
                            str(x)
                            for x in missing
                        ),
                        "complete_all_requested_dt": bool(
                            len(missing) == 0
                        ),
                    }
                )

    return pd.DataFrame(rows)


def anchored_core_analysis(
    subject_core: pd.DataFrame,
    complete_subjects: Sequence[int],
    dt_values: Sequence[int],
    metrics: Sequence[str],
    n_bootstrap: int,
    seed: int,
    min_anchor_dt_points: int,
    min_matched_anchor_subjects: int,
    step13_reference: Mapping[str, float],
) -> Tuple[
    pd.DataFrame,
    pd.DataFrame,
    pd.DataFrame,
]:
    min_t0 = int(
        subject_core["t0"].min()
    )
    max_t1 = int(
        subject_core["t1"].max()
    )

    profile_rows = []
    slope_rows = []
    subject_slope_rows = []

    for anchor_index, anchor in enumerate(
        ANCHORS
    ):
        anchored = anchor_filter(
            subject_core,
            anchor,
            min_t0,
            max_t1,
        )

        for metric_index, metric in enumerate(
            metrics
        ):
            full_matrix = anchor_matrix(
                anchored,
                metric,
                complete_subjects,
                dt_values,
            )

            for mode_index, mode in enumerate(
                SUBJECT_MODES
            ):
                if mode == "available":
                    subjects = list(
                        complete_subjects
                    )
                    matrix = full_matrix
                else:
                    mask = np.all(
                        np.isfinite(
                            full_matrix
                        ),
                        axis=1,
                    )
                    subjects = [
                        int(
                            complete_subjects[i]
                        )
                        for i in np.flatnonzero(
                            mask
                        )
                    ]
                    matrix = full_matrix[
                        mask,
                        :
                    ]

                n_subjects = int(
                    len(subjects)
                )

                status = "ok"

                if n_subjects < 2:
                    status = "insufficient_subjects"

                if (
                    mode == "matched_all_dt"
                    and n_subjects
                    < int(
                        min_matched_anchor_subjects
                    )
                ):
                    status = "insufficient_matched_subjects"

                profile, boot_slopes, fit = (
                    bootstrap_anchor(
                        matrix,
                        dt_values,
                        (
                            int(
                                n_bootstrap
                            )
                            if status == "ok"
                            else 0
                        ),
                        int(
                            seed
                        )
                        + 1000 * anchor_index
                        + 100 * metric_index
                        + 10 * mode_index,
                        int(
                            min_anchor_dt_points
                        ),
                    )
                )

                counts = (
                    np.sum(
                        np.isfinite(
                            matrix
                        ),
                        axis=0,
                    ).astype(int)
                    if matrix.size
                    else np.zeros(
                        len(
                            dt_values
                        ),
                        dtype=int,
                    )
                )

                if fit[
                    "n_dt"
                ] < int(
                    min_anchor_dt_points
                ):
                    if status == "ok":
                        status = "insufficient_dt_points"

                for j, dt in enumerate(
                    dt_values
                ):
                    profile_rows.append(
                        {
                            "anchor_type": anchor,
                            "subject_matching": mode,
                            "metric": metric,
                            "dt": int(dt),
                            "value": (
                                float(
                                    profile[j]
                                )
                                if j
                                < len(
                                    profile
                                )
                                and np.isfinite(
                                    profile[j]
                                )
                                else np.nan
                            ),
                            "n_subjects": int(
                                counts[j]
                            ),
                            "analysis_subject_ids": ";".join(
                                str(x)
                                for x in subjects
                            ),
                        }
                    )

                lo, med, hi, n_valid = (
                    percentile_summary(
                        boot_slopes
                    )
                )

                slope_row = {
                    "anchor_type": anchor,
                    "subject_matching": mode,
                    "metric": metric,
                    "test_status": status,
                    "n_subjects_analysis": int(
                        n_subjects
                    ),
                    "analysis_subject_ids": ";".join(
                        str(x)
                        for x in subjects
                    ),
                    "n_observed_dt": int(
                        fit[
                            "n_dt"
                        ]
                    ),
                    "observed_intercept_at_dt1": fit[
                        "intercept_at_dt1"
                    ],
                    "observed_slope_per_week": fit[
                        "slope_per_week"
                    ],
                    "bootstrap_median_slope": med,
                    "bootstrap_q025": lo,
                    "bootstrap_q975": hi,
                    "n_bootstrap_valid": int(
                        n_valid
                    ),
                    "bootstrap_positive_slope_fraction": (
                        float(
                            np.mean(
                                finite_numeric(
                                    boot_slopes
                                )
                                > 0
                            )
                        )
                        if n_valid
                        else np.nan
                    ),
                    "bootstrap_negative_slope_fraction": (
                        float(
                            np.mean(
                                finite_numeric(
                                    boot_slopes
                                )
                                < 0
                            )
                        )
                        if n_valid
                        else np.nan
                    ),
                    "subject_counts_by_dt": ",".join(
                        str(int(x))
                        for x in counts
                    ),
                }

                if metric == PRIMARY_METRIC:
                    slope_row.update(
                        step13_reference
                    )
                    slope_row[
                        "slope_difference_vs_step13"
                    ] = (
                        float(
                            fit[
                                "slope_per_week"
                            ]
                        )
                        - float(
                            step13_reference[
                                "step13_observed_slope_per_week"
                            ]
                        )
                        if np.isfinite(
                            fit[
                                "slope_per_week"
                            ]
                        )
                        else np.nan
                    )

                slope_rows.append(
                    slope_row
                )

                if (
                    mode == "matched_all_dt"
                    and matrix.size
                    and matrix.shape[1]
                    == len(
                        dt_values
                    )
                ):
                    dt_array = np.asarray(
                        dt_values,
                        dtype=float,
                    )

                    local_slopes = []

                    for i, subject in enumerate(
                        subjects
                    ):
                        fit_subject = safe_linear_fit(
                            dt_array,
                            matrix[
                                i,
                                :,
                            ],
                        )

                        local_slopes.append(
                            fit_subject[
                                "slope_per_week"
                            ]
                        )

                        subject_slope_rows.append(
                            {
                                "anchor_type": anchor,
                                "metric": metric,
                                "subject": int(
                                    subject
                                ),
                                "n_dt": int(
                                    fit_subject[
                                        "n_dt"
                                    ]
                                ),
                                "intercept_at_dt1": fit_subject[
                                    "intercept_at_dt1"
                                ],
                                "slope_per_week": fit_subject[
                                    "slope_per_week"
                                ],
                            }
                        )

                    test = exact_signflip(
                        np.asarray(
                            local_slopes,
                            dtype=float,
                        )
                    )

                    slope_rows[
                        -1
                    ].update(
                        {
                            "signflip_n_subjects": test[
                                "n_subjects"
                            ],
                            "signflip_two_sided_p": test[
                                "two_sided_p"
                            ],
                            "signflip_one_sided_negative_p": test[
                                "one_sided_negative_p"
                            ],
                            "signflip_one_sided_positive_p": test[
                                "one_sided_positive_p"
                            ],
                            "signflip_n_negative_subject_slopes": test[
                                "n_negative_subject_slopes"
                            ],
                            "signflip_n_positive_subject_slopes": test[
                                "n_positive_subject_slopes"
                            ],
                        }
                    )

    return (
        pd.DataFrame(
            profile_rows
        ),
        pd.DataFrame(
            slope_rows
        ),
        pd.DataFrame(
            subject_slope_rows
        ),
    )


def binwise_anchor_analysis(
    interval_table: pd.DataFrame,
    complete_subjects: Sequence[int],
    dt_values: Sequence[int],
    core_bins: Sequence[int],
    min_subject_interval_bin_n: int,
    n_bootstrap: int,
    seed: int,
    min_anchor_dt_points: int,
    min_matched_anchor_subjects: int,
) -> pd.DataFrame:
    d = interval_table[
        interval_table["subject"].isin(
            [int(x) for x in complete_subjects]
        )
        & interval_table["dt"].isin(
            [int(x) for x in dt_values]
        )
        & interval_table["bin"].isin(
            [int(x) for x in core_bins]
        )
        & interval_table["n"].ge(
            int(
                min_subject_interval_bin_n
            )
        )
        & np.isfinite(
            pd.to_numeric(
                interval_table[
                    PRIMARY_METRIC
                ],
                errors="coerce",
            )
        )
    ].copy()

    if d.empty:
        return pd.DataFrame()

    min_t0 = int(
        d["t0"].min()
    )
    max_t1 = int(
        d["t1"].max()
    )

    rows = []

    for anchor_index, anchor in enumerate(
        ANCHORS
    ):
        if anchor == "common_start":
            anchored = d[
                d["t0"].eq(
                    min_t0
                )
            ].copy()
        else:
            anchored = d[
                d["t1"].eq(
                    max_t1
                )
            ].copy()

        for bin_index, bin_id in enumerate(
            core_bins
        ):
            g = anchored[
                anchored["bin"].eq(
                    int(bin_id)
                )
            ].copy()

            if g.empty:
                continue

            ref = g.iloc[0]

            full_matrix = anchor_matrix(
                g,
                PRIMARY_METRIC,
                complete_subjects,
                dt_values,
            )

            for mode_index, mode in enumerate(
                SUBJECT_MODES
            ):
                if mode == "available":
                    subjects = list(
                        complete_subjects
                    )
                    matrix = full_matrix
                else:
                    mask = np.all(
                        np.isfinite(
                            full_matrix
                        ),
                        axis=1,
                    )
                    subjects = [
                        int(
                            complete_subjects[i]
                        )
                        for i in np.flatnonzero(
                            mask
                        )
                    ]
                    matrix = full_matrix[
                        mask,
                        :
                    ]

                status = "ok"

                if len(subjects) < 2:
                    status = "insufficient_subjects"

                if (
                    mode == "matched_all_dt"
                    and len(subjects)
                    < int(
                        min_matched_anchor_subjects
                    )
                ):
                    status = "insufficient_matched_subjects"

                profile, boot_slopes, fit = (
                    bootstrap_anchor(
                        matrix,
                        dt_values,
                        (
                            int(
                                n_bootstrap
                            )
                            if status == "ok"
                            else 0
                        ),
                        int(
                            seed
                        )
                        + 50000
                        + 1000 * anchor_index
                        + 50 * bin_index
                        + mode_index,
                        int(
                            min_anchor_dt_points
                        ),
                    )
                )

                if fit[
                    "n_dt"
                ] < int(
                    min_anchor_dt_points
                ):
                    if status == "ok":
                        status = "insufficient_dt_points"

                lo, med, hi, n_valid = (
                    percentile_summary(
                        boot_slopes
                    )
                )

                rows.append(
                    {
                        "anchor_type": anchor,
                        "subject_matching": mode,
                        "metric": PRIMARY_METRIC,
                        "bin": int(
                            bin_id
                        ),
                        "x_left": float(
                            ref[
                                "x_left"
                            ]
                        ),
                        "x_right": float(
                            ref[
                                "x_right"
                            ]
                        ),
                        "x_center": float(
                            ref[
                                "x_center"
                            ]
                        ),
                        "test_status": status,
                        "n_subjects_analysis": int(
                            len(
                                subjects
                            )
                        ),
                        "observed_slope_per_week": fit[
                            "slope_per_week"
                        ],
                        "bootstrap_median_slope": med,
                        "bootstrap_q025": lo,
                        "bootstrap_q975": hi,
                        "n_bootstrap_valid": int(
                            n_valid
                        ),
                        "bootstrap_positive_slope_fraction": (
                            float(
                                np.mean(
                                    finite_numeric(
                                        boot_slopes
                                    )
                                    > 0
                                )
                            )
                            if n_valid
                            else np.nan
                        ),
                        "bootstrap_negative_slope_fraction": (
                            float(
                                np.mean(
                                    finite_numeric(
                                        boot_slopes
                                    )
                                    < 0
                                )
                            )
                            if n_valid
                            else np.nan
                        ),
                        "analysis_subject_ids": ";".join(
                            str(x)
                            for x in subjects
                        ),
                    }
                )

    return pd.DataFrame(rows).sort_values(
        [
            "subject_matching",
            "anchor_type",
            "bin",
        ]
    )


