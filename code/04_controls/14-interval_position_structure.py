def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
        description=(
            "Step 14: calendar-position and anchored composition-control "
            "analysis for genuine cross-replicate fluctuation covariance."
        ),
    )

    p.add_argument(
        "--step11-dir",
        required=True,
        type=Path,
    )
    p.add_argument(
        "--step13-dir",
        required=True,
        type=Path,
    )
    p.add_argument(
        "--outdir",
        required=True,
        type=Path,
    )

    p.add_argument(
        "--metrics",
        nargs="+",
        default=list(
            DEFAULT_METRICS
        ),
        choices=[
            "cross_cov",
            "same_var_mean",
            "replicate_specific_excess",
            "shared_fraction",
        ],
    )

    p.add_argument(
        "--dt-values",
        nargs="*",
        type=int,
        default=None,
        help=(
            "Optional lag subset. Default: exact Step-13 dt_values."
        ),
    )

    p.add_argument(
        "--min-subject-interval-bin-n",
        type=int,
        default=None,
        help=(
            "Minimum transitions for a subject x interval x abundance-bin "
            "covariance cell. Default: inherit Step-13 min_subject_cell_n; "
            "set explicitly only for a stricter support sensitivity."
        ),
    )

    p.add_argument(
        "--min-subjects-per-position",
        type=int,
        default=3,
    )

    p.add_argument(
        "--min-interval-positions",
        type=int,
        default=3,
    )

    p.add_argument(
        "--min-anchor-dt-points",
        type=int,
        default=4,
    )

    p.add_argument(
        "--min-matched-anchor-subjects",
        type=int,
        default=3,
    )

    p.add_argument(
        "--n-perm",
        type=int,
        default=2000,
    )

    p.add_argument(
        "--n-bootstrap",
        type=int,
        default=2000,
    )

    p.add_argument(
        "--seed",
        type=int,
        default=123,
    )

    return p


def validate_args(
    args: argparse.Namespace,
) -> None:
    if (
        args.min_subject_interval_bin_n is not None
        and int(args.min_subject_interval_bin_n) < 2
    ):
        raise ValueError(
            "--min-subject-interval-bin-n must be >=2"
        )

    if int(
        args.min_subjects_per_position
    ) < 2:
        raise ValueError(
            "--min-subjects-per-position must be >=2"
        )

    if int(
        args.min_interval_positions
    ) < 2:
        raise ValueError(
            "--min-interval-positions must be >=2"
        )

    if int(
        args.min_anchor_dt_points
    ) < 3:
        raise ValueError(
            "--min-anchor-dt-points must be >=3"
        )

    if int(
        args.min_matched_anchor_subjects
    ) < 2:
        raise ValueError(
            "--min-matched-anchor-subjects must be >=2"
        )

    if int(
        args.n_perm
    ) < 1:
        raise ValueError(
            "--n-perm must be >=1"
        )

    if int(
        args.n_bootstrap
    ) < 1:
        raise ValueError(
            "--n-bootstrap must be >=1"
        )


# =============================================================================
# Main
# =============================================================================

def main(
    argv: Optional[Sequence[str]] = None,
) -> int:
    args = build_parser().parse_args(
        argv
    )
    validate_args(args)

    metrics = list(
        dict.fromkeys(
            args.metrics
        )
    )

    if PRIMARY_METRIC not in metrics:
        raise ValueError(
            "cross_cov must be included because it defines the primary Step-14 estimand."
        )

    step11_dir = (
        args.step11_dir
        .expanduser()
        .resolve(strict=True)
    )
    step13_dir = (
        args.step13_dir
        .expanduser()
        .resolve(strict=True)
    )
    outdir = ensure_dir(
        args.outdir
        .expanduser()
        .resolve()
    )

    step11_config_path = step11_dir / "00_run_config.json"
    step11_signature_path = step11_dir / "00_run_signature.json"
    step11_config = read_json(
        step11_config_path
    )
    step11_signature = read_json(
        step11_signature_path
    )
    validate_step11_config(
        step11_config,
        step11_signature,
    )

    (
        core_contract,
        step13_config,
        core_bins,
        complete_subjects,
        step13_dt_values,
    ) = load_step13_contract(
        step13_dir
    )

    inherited_interval_min_n = int(
        step13_config.get(
            "core_selection", {}
        ).get(
            "min_subject_cell_n", 2
        )
    )
    interval_min_n = (
        int(args.min_subject_interval_bin_n)
        if args.min_subject_interval_bin_n is not None
        else inherited_interval_min_n
    )

    dt_values = (
        parse_int_list(
            args.dt_values
        )
        if args.dt_values
        else list(
            step13_dt_values
        )
    )

    missing_dt = sorted(
        set(dt_values)
        - set(step13_dt_values)
    )
    if missing_dt:
        raise ValueError(
            f"Requested dt values are outside the Step-13 contract: {missing_dt}"
        )

    step13_reference = load_step13_primary_slope(
        step13_dir
    )

    interval_path, interval_raw = (
        read_required_table(
            step11_dir,
            "05_subject_interval_fluctuation_by_bin",
            "Step-11 subject-interval fluctuation table",
        )
    )

    interval_table = normalize_interval_table(
        interval_raw,
        metrics,
    )

    selected = interval_table[
        interval_table["subject"].isin(
            complete_subjects
        )
        & interval_table["dt"].isin(
            dt_values
        )
        & interval_table["bin"].isin(
            core_bins
        )
    ].copy()

    if selected.empty:
        raise ValueError(
            "No Step-11 interval rows remain after applying the Step-13 subject/core contract."
        )

    subject_core = (
        build_subject_interval_core_metrics(
            interval_table,
            core_bins,
            complete_subjects,
            dt_values,
            metrics,
            int(interval_min_n),
        )
    )

    composition = (
        interval_composition_by_pair(
            interval_table,
            subject_core,
            complete_subjects,
            dt_values,
            core_bins,
            metrics,
            int(interval_min_n),
        )
    )

    cohort_profiles = cohort_interval_profiles(
        subject_core,
        metrics,
    )

    support_audit = interval_support_audit(
        subject_core,
        dt_values,
        PRIMARY_METRIC,
        int(args.min_subjects_per_position),
    )

    print(
        "[1/4] Calendar-position permutation tests..."
    )

    core_tests = core_position_tests(
        subject_core,
        metrics,
        complete_subjects,
        dt_values,
        int(
            args.min_subjects_per_position
        ),
        int(
            args.min_interval_positions
        ),
        int(
            args.n_perm
        ),
        int(
            args.seed
        ),
    )

    binwise_tests = binwise_position_tests(
        interval_table,
        metrics,
        complete_subjects,
        dt_values,
        core_bins,
        int(interval_min_n),
        int(
            args.min_subjects_per_position
        ),
        int(
            args.min_interval_positions
        ),
        int(
            args.n_perm
        ),
        int(
            args.seed
        ),
    )

    print(
        "[2/4] Common-start/common-end anchored controls..."
    )

    matching = build_anchor_matching_diagnostic(
        subject_core,
        complete_subjects,
        dt_values,
        metrics,
    )

    (
        anchored_profiles,
        anchored_slopes,
        anchored_subject_slopes,
    ) = anchored_core_analysis(
        subject_core,
        complete_subjects,
        dt_values,
        metrics,
        int(
            args.n_bootstrap
        ),
        int(
            args.seed
        ),
        int(
            args.min_anchor_dt_points
        ),
        int(
            args.min_matched_anchor_subjects
        ),
        step13_reference,
    )

    print(
        "[3/4] Abundance-resolved anchored sensitivity..."
    )

    binwise_anchor = binwise_anchor_analysis(
        interval_table,
        complete_subjects,
        dt_values,
        core_bins,
        int(interval_min_n),
        int(
            args.n_bootstrap
        ),
        int(
            args.seed
        ),
        int(
            args.min_anchor_dt_points
        ),
        int(
            args.min_matched_anchor_subjects
        ),
    )

    summary = build_analysis_summary(
        core_tests,
        binwise_tests,
        anchored_slopes,
    )

    # -----------------------------------------------------------------
    # Output tables.
    # -----------------------------------------------------------------
    print(
        "[4/4] Writing outputs..."
    )

    step13_config_path = step13_dir / "00_run_config.json"
    step13_signature_path = step13_dir / "00_run_signature.json"

    signature_payload = {
        "script_version": SCRIPT_VERSION,
        "step11_analysis_signature": step11_config.get(
            "analysis_signature"
        ),
        "step13_analysis_signature": step13_config.get(
            "analysis_signature"
        ),
        "step11_interval_table": path_identity(interval_path),
        "step13_contract": path_identity(
            step13_dir / "11_step14_contract.csv"
        ),
        "parameters": {
            "metrics": list(metrics),
            "dt_values": [int(x) for x in dt_values],
            "min_subject_interval_bin_n": int(interval_min_n),
            "interval_min_n_source": (
                "explicit_cli"
                if args.min_subject_interval_bin_n is not None
                else "inherited_step13_min_subject_cell_n"
            ),
            "min_subjects_per_position": int(args.min_subjects_per_position),
            "min_interval_positions": int(args.min_interval_positions),
            "min_anchor_dt_points": int(args.min_anchor_dt_points),
            "min_matched_anchor_subjects": int(args.min_matched_anchor_subjects),
            "n_perm": int(args.n_perm),
            "n_bootstrap": int(args.n_bootstrap),
            "seed": int(args.seed),
        },
        "core_bins": [int(x) for x in core_bins],
        "complete_case_subjects": [int(x) for x in complete_subjects],
    }
    analysis_signature = stable_sha256(signature_payload)

    (outdir / "00_run_signature.json").write_text(
        json.dumps(
            {
                "analysis_signature": analysis_signature,
                "signature_payload": signature_payload,
            },
            indent=2,
            sort_keys=True,
        ) + "\n",
        encoding="utf-8",
    )

    input_manifest = pd.DataFrame(
        [
            {
                "step11_dir": str(
                    step11_dir
                ),
                "step13_dir": str(
                    step13_dir
                ),
                "step11_interval_table": str(
                    interval_path
                ),
                "step11_script_version": step11_config.get(
                    "script_version"
                ),
                "step13_script_version": step13_config.get(
                    "script_version"
                ),
                "step11_analysis_signature": step11_config.get(
                    "analysis_signature"
                ),
                "step13_analysis_signature": step13_config.get(
                    "analysis_signature"
                ),
                "step14_analysis_signature": analysis_signature,
                "primary_estimand": (
                    "Cov(dx_observed_rep1, dx_observed_rep2 | "
                    "xmid_latent, dt, common4)"
                ),
                "n_step13_complete_case_subjects": int(
                    len(
                        complete_subjects
                    )
                ),
                "step13_complete_case_subjects": ";".join(
                    str(x)
                    for x in complete_subjects
                ),
                "n_step13_core_bins": int(
                    len(
                        core_bins
                    )
                ),
                "step13_core_bins": ",".join(
                    str(x)
                    for x in core_bins
                ),
                "core_x_min": float(
                    core_contract[
                        "x_left"
                    ].min()
                ),
                "core_x_max": float(
                    core_contract[
                        "x_right"
                    ].max()
                ),
                "dt_values": ",".join(
                    str(x)
                    for x in dt_values
                ),
                "min_subject_interval_bin_n": int(interval_min_n),
                "n_selected_interval_bin_rows": int(
                    len(
                        selected
                    )
                ),
            }
        ]
    )

    input_manifest.to_csv(
        outdir
        / "01_input_manifest.csv",
        index=False,
    )

    core_contract[
        [
            "bin",
            "x_left",
            "x_right",
            "x_center",
            "complete_case_subjects",
            "n_complete_case_subjects",
            "dt_values",
            "primary_metric",
            "primary_estimator",
        ]
    ].to_csv(
        outdir
        / "02_core_bin_definitions.csv",
        index=False,
    )

    composition.to_csv(
        outdir
        / "03_interval_composition_by_pair.csv",
        index=False,
    )

    subject_core.to_csv(
        outdir
        / "04_subject_interval_core_metrics.csv",
        index=False,
    )

    cohort_profiles.to_csv(
        outdir
        / "05_cohort_interval_profiles.csv",
        index=False,
    )

    core_tests.to_csv(
        outdir
        / "06_core_interval_position_tests.csv",
        index=False,
    )

    binwise_tests.to_csv(
        outdir
        / "07_binwise_interval_position_tests.csv",
        index=False,
    )

    anchored_profiles.to_csv(
        outdir
        / "08_anchored_core_profiles.csv",
        index=False,
    )

    anchored_slopes.to_csv(
        outdir
        / "09_anchored_core_slope_bootstrap.csv",
        index=False,
    )

    anchored_subject_slopes.to_csv(
        outdir
        / "10_anchored_subject_slopes.csv",
        index=False,
    )

    matching.to_csv(
        outdir
        / "11_anchor_subject_matching_diagnostic.csv",
        index=False,
    )

    binwise_anchor.to_csv(
        outdir
        / "12_binwise_anchor_slope_bootstrap.csv",
        index=False,
    )

    summary.to_csv(
        outdir
        / "00_analysis_summary.csv",
        index=False,
    )

    step15_contract = core_contract[
        [
            "bin",
            "x_left",
            "x_right",
            "x_center",
        ]
    ].copy()
    step15_contract[
        "complete_case_subjects"
    ] = ";".join(
        str(x)
        for x in complete_subjects
    )
    step15_contract[
        "n_complete_case_subjects"
    ] = int(
        len(
            complete_subjects
        )
    )
    step15_contract[
        "dt_values"
    ] = ",".join(
        str(x)
        for x in dt_values
    )
    step15_contract[
        "primary_metric"
    ] = PRIMARY_METRIC
    step15_contract[
        "primary_support"
    ] = "common4"
    step15_contract[
        "primary_conditioning"
    ] = "xmid_latent"
    step15_contract[
        "step14_analysis_signature"
    ] = analysis_signature
    step15_contract[
        "min_subject_interval_bin_n"
    ] = int(interval_min_n)

    step15_contract.to_csv(
        outdir
        / "13_step15_contract.csv",
        index=False,
    )

    support_audit.to_csv(
        outdir
        / "14_interval_support_audit.csv",
        index=False,
    )

    run_config = {
        "script": Path(
            __file__
        ).name,
        "script_version": SCRIPT_VERSION,
        "analysis_signature": analysis_signature,
        "step11_dir": str(
            step11_dir
        ),
        "step13_dir": str(
            step13_dir
        ),
        "outdir": str(
            outdir
        ),
        "primary_estimand": (
            "cross_cov = Cov(dx_observed_rep1, dx_observed_rep2 | "
            "xmid_latent, dt, common4)"
        ),
        "primary_support": "common4",
        "operational_class_filter": None,
        "primary_conditioning": "xmid_latent",
        "step12_used_computationally": False,
        "step13_core_redefined": False,
        "step13_complete_case_subject_universe_redefined": False,
        "metrics": metrics,
        "primary_metric": PRIMARY_METRIC,
        "dt_values": dt_values,
        "core_bins": core_bins,
        "core_x_min": float(
            core_contract[
                "x_left"
            ].min()
        ),
        "core_x_max": float(
            core_contract[
                "x_right"
            ].max()
        ),
        "complete_case_subjects": complete_subjects,
        "min_subject_interval_bin_n": int(interval_min_n),
        "calendar_position_test": {
            "unit": "subject-level fixed-core interval metric",
            "position": "t0",
            "primary_statistic": (
                "RMS deviation of equal-subject calendar-position profile"
            ),
            "secondary_statistic": (
                "absolute linear slope versus t0"
            ),
            "permutation": (
                "independent within-subject shuffling of finite interval values "
                "across that subject's available calendar positions"
            ),
            "permutation_implementation":
                "vectorized; identical within-subject exchangeability design",
            "n_permutations": int(
                args.n_perm
            ),
            "seed": int(
                args.seed
            ),
            "min_subjects_per_position": int(
                args.min_subjects_per_position
            ),
            "min_interval_positions": int(
                args.min_interval_positions
            ),
            "multiple_testing_core": (
                "Benjamini-Hochberg within metric across valid dt tests"
            ),
            "multiple_testing_binwise": (
                "Benjamini-Hochberg within metric across valid dt x bin tests"
            ),
        },
        "anchored_control": {
            "anchors": list(
                ANCHORS
            ),
            "subject_modes": list(
                SUBJECT_MODES
            ),
            "core_aggregation": (
                "equal-bin within subject x anchor x dt; "
                "equal-subject cohort"
            ),
            "signed_slope_model": (
                "M(dt)=intercept_at_dt1+slope_per_week*(dt-1)"
            ),
            "bootstrap_unit": "biological subject jointly across dt",
            "n_bootstrap": int(
                args.n_bootstrap
            ),
            "min_anchor_dt_points": int(
                args.min_anchor_dt_points
            ),
            "min_matched_anchor_subjects": int(
                args.min_matched_anchor_subjects
            ),
        },
        "step13_reference": step13_reference,
    }

    (
        outdir
        / "00_run_config.json"
    ).write_text(
        json.dumps(
            json_safe(
                run_config
            ),
            indent=2,
            sort_keys=True,
        )
        + "\n",
        encoding="utf-8",
    )

    write_readme(
        outdir
    )
    write_manifest(
        outdir
    )

    # -----------------------------------------------------------------
    # Console summary.
    # -----------------------------------------------------------------
    print(
        "\n[DONE] Step 14 interval-position / anchored composition control"
    )
    print(
        "Step-13 core bins        :",
        core_bins,
    )
    print(
        "Step-13 subjects         :",
        complete_subjects,
    )
    print(
        "Interval-bin min n       :",
        int(interval_min_n),
    )

    primary_core = core_tests[
        core_tests[
            "metric"
        ].astype(str).eq(
            PRIMARY_METRIC
        )
        & core_tests[
            "test_status"
        ].astype(str).eq(
            "ok"
        )
    ]

    if not primary_core.empty:
        print(
            "Primary calendar tests  :",
            len(
                primary_core
            ),
        )
        print(
            "RMS q<0.05              :",
            int(
                (
                    primary_core[
                        "q_bh_rms_position_structure"
                    ]
                    < 0.05
                ).sum()
            ),
        )
        print(
            "Minimum RMS q           :",
            f"{primary_core['q_bh_rms_position_structure'].min():.6f}",
        )

    primary_anchor = anchored_slopes[
        anchored_slopes[
            "metric"
        ].astype(str).eq(
            PRIMARY_METRIC
        )
    ]

    if not primary_anchor.empty:
        print(
            "\nPrimary anchored slopes:"
        )
        for row in primary_anchor.itertuples(
            index=False
        ):
            print(
                " -",
                row.anchor_type,
                row.subject_matching,
                "n=",
                row.n_subjects_analysis,
                "slope=",
                (
                    f"{row.observed_slope_per_week:.6f}"
                    if np.isfinite(
                        row.observed_slope_per_week
                    )
                    else "nan"
                ),
                "CI=[",
                (
                    f"{row.bootstrap_q025:.6f}"
                    if np.isfinite(
                        row.bootstrap_q025
                    )
                    else "nan"
                ),
                ",",
                (
                    f"{row.bootstrap_q975:.6f}"
                    if np.isfinite(
                        row.bootstrap_q975
                    )
                    else "nan"
                ),
                "]",
            )

    print(
        "\nOutputs:"
    )
    for filename in [
        "00_analysis_summary.csv",
        "01_input_manifest.csv",
        "02_core_bin_definitions.csv",
        "03_interval_composition_by_pair.csv",
        "04_subject_interval_core_metrics.csv",
        "05_cohort_interval_profiles.csv",
        "06_core_interval_position_tests.csv",
        "07_binwise_interval_position_tests.csv",
        "08_anchored_core_profiles.csv",
        "09_anchored_core_slope_bootstrap.csv",
        "10_anchored_subject_slopes.csv",
        "11_anchor_subject_matching_diagnostic.csv",
        "12_binwise_anchor_slope_bootstrap.csv",
        "13_step15_contract.csv",
        "14_interval_support_audit.csv",
        "00_run_signature.json",
    ]:
        print(
            " -",
            outdir / filename,
        )

    return 0


if __name__ == "__main__":
    raise SystemExit(
        main()
    )
