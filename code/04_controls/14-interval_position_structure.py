def normalize_interval_table(
    frame: pd.DataFrame,
    metrics: Sequence[str],
) -> pd.DataFrame:
    required = [
        "subject",
        "t0",
        "t1",
        "dt",
        "bin",
        "n",
        "x_left",
        "x_right",
        "x_center",
        *metrics,
    ]
    require_columns(
        frame,
        required,
        "Step-11 subject-interval fluctuation table",
    )

    d = frame.copy()

    numeric_cols = [
        "subject",
        "t0",
        "t1",
        "dt",
        "bin",
        "n",
        "x_left",
        "x_right",
        "x_center",
        *metrics,
    ]

    for c in numeric_cols:
        d[c] = pd.to_numeric(
            d[c],
            errors="coerce",
        )

    d = d.replace(
        [np.inf, -np.inf],
        np.nan,
    )

    d = d.dropna(
        subset=[
            "subject",
            "t0",
            "t1",
            "dt",
            "bin",
            "n",
            "x_center",
        ]
    ).copy()

    for c in [
        "subject",
        "t0",
        "t1",
        "dt",
        "bin",
    ]:
        d[c] = d[c].astype(int)

    duplicated = d.duplicated(
        subset=[
            "subject",
            "t0",
            "t1",
            "dt",
            "bin",
        ],
        keep=False,
    )

    if duplicated.any():
        bad = d.loc[
            duplicated,
            [
                "subject",
                "t0",
                "t1",
                "dt",
                "bin",
            ],
        ].drop_duplicates()
        raise ValueError(
            "Step-11 interval table contains duplicate subject × interval × bin rows. "
            f"Examples:\n{bad.head(10)}"
        )

    return d


def build_subject_interval_core_metrics(
    interval_table: pd.DataFrame,
    core_bins: Sequence[int],
    complete_subjects: Sequence[int],
    dt_values: Sequence[int],
    metrics: Sequence[str],
    min_subject_interval_bin_n: int,
) -> pd.DataFrame:
    d = interval_table[
        interval_table["subject"].isin(
            [int(x) for x in complete_subjects]
        )
        & interval_table["dt"].isin(
            [int(x) for x in dt_values]
        )
        & interval_table["bin"].isin(
            [int(x) for x in core_bins]
        )
    ].copy()

    rows: List[Dict[str, object]] = []

    for (
        subject,
        dt,
        t0,
        t1,
    ), g in d.groupby(
        [
            "subject",
            "dt",
            "t0",
            "t1",
        ],
        sort=True,
    ):
        bins_present = sorted(
            int(x)
            for x in g["bin"].unique()
        )

        base = {
            "subject": int(subject),
            "dt": int(dt),
            "t0": int(t0),
            "t1": int(t1),
            "interval_label": f"{int(t0)}->{int(t1)}",
            "n_core_bins_required": int(
                len(core_bins)
            ),
            "n_core_bins_present": int(
                len(bins_present)
            ),
        }

        for metric in metrics:
            valid = (
                g["bin"].isin(
                    [int(x) for x in core_bins]
                )
                & g["n"].ge(
                    int(
                        min_subject_interval_bin_n
                    )
                )
                & np.isfinite(
                    pd.to_numeric(
                        g[metric],
                        errors="coerce",
                    )
                )
            )

            gv = g.loc[
                valid,
                [
                    "bin",
                    "n",
                    metric,
                ],
            ].copy()

            n_valid_bins = int(
                gv["bin"].nunique()
            )

            complete_core = (
                n_valid_bins
                == len(core_bins)
            )

            base[
                f"{metric}_n_valid_bins"
            ] = n_valid_bins
            base[
                f"{metric}_complete_core"
            ] = bool(
                complete_core
            )
            base[
                f"{metric}_min_bin_n"
            ] = (
                int(
                    gv["n"].min()
                )
                if not gv.empty
                else 0
            )
            base[
                f"{metric}_sum_bin_n"
            ] = (
                int(
                    gv["n"].sum()
                )
                if not gv.empty
                else 0
            )
            base[
                metric
            ] = (
                float(
                    gv[metric].mean()
                )
                if complete_core
                else np.nan
            )

        rows.append(
            dict(base)
        )

    out = pd.DataFrame(rows)

    if out.empty:
        raise ValueError(
            "No subject × interval rows remain after Step-13 core/subject filtering."
        )

    return out.sort_values(
        [
            "dt",
            "t0",
            "subject",
        ]
    )


def interval_composition_by_pair(
    interval_table: pd.DataFrame,
    subject_core: pd.DataFrame,
    complete_subjects: Sequence[int],
    dt_values: Sequence[int],
    core_bins: Sequence[int],
    metrics: Sequence[str],
    min_subject_interval_bin_n: int,
) -> pd.DataFrame:
    raw = interval_table[
        interval_table["subject"].isin(
            [int(x) for x in complete_subjects]
        )
        & interval_table["dt"].isin(
            [int(x) for x in dt_values]
        )
        & interval_table["bin"].isin(
            [int(x) for x in core_bins]
        )
    ].copy()

    rows = []

    pairs = (
        raw[
            ["dt", "t0", "t1"]
        ]
        .drop_duplicates()
        .sort_values(
            ["dt", "t0", "t1"]
        )
    )

    for pair in pairs.itertuples(
        index=False
    ):
        g = raw[
            raw["dt"].eq(
                int(pair.dt)
            )
            & raw["t0"].eq(
                int(pair.t0)
            )
            & raw["t1"].eq(
                int(pair.t1)
            )
        ]

        c = subject_core[
            subject_core["dt"].eq(
                int(pair.dt)
            )
            & subject_core["t0"].eq(
                int(pair.t0)
            )
            & subject_core["t1"].eq(
                int(pair.t1)
            )
        ]

        row: Dict[str, object] = {
            "dt": int(pair.dt),
            "t0": int(pair.t0),
            "t1": int(pair.t1),
            "interval_label": f"{int(pair.t0)}->{int(pair.t1)}",
            "n_subjects_step13_universe": int(
                len(complete_subjects)
            ),
            "n_subjects_with_any_core_cell": int(
                g["subject"].nunique()
            ),
            "n_interval_bin_rows": int(
                len(g)
            ),
            "n_interval_bin_rows_meeting_n": int(
                g["n"].ge(
                    int(
                        min_subject_interval_bin_n
                    )
                ).sum()
            ),
            "median_interval_bin_n": float(
                g["n"].median()
            ) if not g.empty else np.nan,
            "min_interval_bin_n": int(
                g["n"].min()
            ) if not g.empty else 0,
        }

        for metric in metrics:
            row[
                f"n_subjects_complete_core_{metric}"
            ] = int(
                np.isfinite(
                    pd.to_numeric(
                        c[metric],
                        errors="coerce",
                    )
                ).sum()
            )

        rows.append(row)

    return pd.DataFrame(rows)


def cohort_interval_profiles(
    subject_core: pd.DataFrame,
    metrics: Sequence[str],
) -> pd.DataFrame:
    rows = []

    for (
        dt,
        t0,
        t1,
    ), g in subject_core.groupby(
        ["dt", "t0", "t1"],
        sort=True,
    ):
        for metric in metrics:
            values = pd.to_numeric(
                g[metric],
                errors="coerce",
            )
            finite = values[
                np.isfinite(values)
            ]

            rows.append(
                {
                    "metric": metric,
                    "dt": int(dt),
                    "t0": int(t0),
                    "t1": int(t1),
                    "interval_label": f"{int(t0)}->{int(t1)}",
                    "n_subjects": int(
                        finite.size
                    ),
                    "equal_subject_value": (
                        float(
                            finite.mean()
                        )
                        if finite.size
                        else np.nan
                    ),
                    "subject_sd": (
                        float(
                            finite.std(
                                ddof=1
                            )
                        )
                        if finite.size >= 2
                        else np.nan
                    ),
                }
            )

    return pd.DataFrame(rows).sort_values(
        [
            "metric",
            "dt",
            "t0",
        ]
    )


def interval_support_audit(
    subject_core: pd.DataFrame,
    dt_values: Sequence[int],
    primary_metric: str,
    min_subjects_per_position: int,
) -> pd.DataFrame:
    rows = []

    for dt in dt_values:
        g = subject_core[
            subject_core["dt"].eq(
                int(dt)
            )
        ].copy()

        finite = g[
            np.isfinite(
                pd.to_numeric(
                    g[primary_metric],
                    errors="coerce",
                )
            )
        ].copy()

        by_position = (
            finite.groupby("t0")["subject"]
            .nunique()
            if not finite.empty
            else pd.Series(dtype=float)
        )

        min_bin_n_col = (
            f"{primary_metric}_min_bin_n"
        )

        min_bin_n = (
            pd.to_numeric(
                finite[min_bin_n_col],
                errors="coerce",
            ).to_numpy(float)
            if (
                not finite.empty
                and min_bin_n_col in finite.columns
            )
            else np.asarray([], dtype=float)
        )
        min_bin_n = min_bin_n[
            np.isfinite(min_bin_n)
        ]

        rows.append(
            {
                "dt": int(dt),
                "n_calendar_intervals": int(
                    g[
                        ["t0", "t1"]
                    ].drop_duplicates().shape[0]
                ),
                "n_subject_interval_rows": int(
                    len(g)
                ),
                "n_primary_complete_core_rows": int(
                    len(finite)
                ),
                "n_subjects_with_primary_complete_core": int(
                    finite["subject"].nunique()
                ),
                "n_positions_meeting_min_subjects": int(
                    np.sum(
                        by_position.to_numpy()
                        >= int(min_subjects_per_position)
                    )
                ) if len(by_position) else 0,
                "min_subjects_at_finite_position": (
                    int(by_position.min())
                    if len(by_position)
                    else 0
                ),
                "max_subjects_at_finite_position": (
                    int(by_position.max())
                    if len(by_position)
                    else 0
                ),
                "min_primary_interval_bin_n": (
                    float(np.min(min_bin_n))
                    if min_bin_n.size
                    else np.nan
                ),
                "median_primary_interval_min_bin_n": (
                    float(np.median(min_bin_n))
                    if min_bin_n.size
                    else np.nan
                ),
            }
        )

    return pd.DataFrame(rows)


