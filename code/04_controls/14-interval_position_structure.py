def ensure_dir(path: Path) -> Path:
    path = Path(path)
    path.mkdir(parents=True, exist_ok=True)
    return path


def json_safe(value):
    if isinstance(value, Path):
        return str(value)
    if isinstance(value, np.integer):
        return int(value)
    if isinstance(value, np.floating):
        return None if np.isnan(value) else float(value)
    if isinstance(value, np.bool_):
        return bool(value)
    if isinstance(value, dict):
        return {str(k): json_safe(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [json_safe(v) for v in value]
    return value


def read_json(path: Path) -> Dict[str, object]:
    if not path.is_file():
        raise FileNotFoundError(path)
    with path.open("r", encoding="utf-8") as handle:
        obj = json.load(handle)
    if not isinstance(obj, dict):
        raise ValueError(f"JSON object expected: {path}")
    return obj


def find_table(folder: Path, stem: str) -> Path:
    for suffix in (".csv", ".parquet", ".pq"):
        path = folder / f"{stem}{suffix}"
        if path.is_file():
            return path
    raise FileNotFoundError(
        f"Could not find {stem}.csv/.parquet in {folder}"
    )


def read_table(path: Path) -> pd.DataFrame:
    suffix = path.suffix.lower()
    if suffix == ".csv":
        return pd.read_csv(path)
    if suffix in {".parquet", ".pq"}:
        return pd.read_parquet(path)
    raise ValueError(f"Unsupported table format: {path}")


def read_required_table(folder: Path, stem: str, label: str) -> Tuple[Path, pd.DataFrame]:
    path = find_table(folder, stem)
    frame = read_table(path)
    if frame.empty:
        raise ValueError(f"{label} is empty: {path}")
    return path, frame


def require_columns(
    frame: pd.DataFrame,
    columns: Sequence[str],
    label: str,
) -> None:
    missing = [c for c in columns if c not in frame.columns]
    if missing:
        raise ValueError(
            f"{label}: missing required columns {missing}; "
            f"available={list(frame.columns)}"
        )


def finite_numeric(values) -> np.ndarray:
    x = pd.to_numeric(
        pd.Series(values),
        errors="coerce",
    ).to_numpy(dtype=float)
    return x[np.isfinite(x)]


def parse_int_list(values: Optional[Sequence[int]]) -> List[int]:
    if values is None:
        return []
    return sorted(set(int(x) for x in values))


def parse_subject_list(text: object) -> List[int]:
    raw = str(text or "").strip()
    if not raw:
        return []
    parts = raw.replace(",", ";").split(";")
    values = []
    for part in parts:
        part = part.strip()
        if not part:
            continue
        values.append(int(float(part)))
    return sorted(set(values))


def benjamini_hochberg(values: Sequence[float]) -> np.ndarray:
    p = np.asarray(values, dtype=float)
    q = np.full(p.shape, np.nan, dtype=float)

    valid_idx = np.flatnonzero(np.isfinite(p))
    if valid_idx.size == 0:
        return q

    pv = p[valid_idx]
    order = np.argsort(pv)
    ranked = pv[order]
    m = float(len(ranked))

    adjusted = (
        ranked * m
        / np.arange(
            1,
            len(ranked) + 1,
            dtype=float,
        )
    )
    adjusted = np.minimum.accumulate(
        adjusted[::-1]
    )[::-1]
    adjusted = np.clip(
        adjusted,
        0.0,
        1.0,
    )

    inverse = np.empty_like(order)
    inverse[order] = np.arange(len(order))
    q[valid_idx] = adjusted[inverse]

    return q


def empirical_upper_tail(
    null: np.ndarray,
    observed: float,
) -> float:
    null = np.asarray(null, dtype=float)
    finite = null[np.isfinite(null)]
    if finite.size == 0 or not np.isfinite(observed):
        return np.nan
    return float(
        (
            1.0
            + np.sum(finite >= observed)
        )
        / (
            finite.size + 1.0
        )
    )


def percentile_summary(
    values: np.ndarray,
) -> Tuple[float, float, float, int]:
    values = np.asarray(values, dtype=float)
    values = values[np.isfinite(values)]
    if values.size == 0:
        return np.nan, np.nan, np.nan, 0
    return (
        float(np.quantile(values, 0.025)),
        float(np.median(values)),
        float(np.quantile(values, 0.975)),
        int(values.size),
    )


def safe_linear_fit(
    dt_values: np.ndarray,
    y: np.ndarray,
) -> Dict[str, float]:
    dt_values = np.asarray(dt_values, dtype=float)
    y = np.asarray(y, dtype=float)

    ok = np.isfinite(dt_values) & np.isfinite(y)
    if int(ok.sum()) < 2:
        return {
            "n_dt": int(ok.sum()),
            "intercept_at_dt1": np.nan,
            "slope_per_week": np.nan,
        }

    x = dt_values[ok] - 1.0
    values = y[ok]

    if np.ptp(x) <= 0:
        return {
            "n_dt": int(ok.sum()),
            "intercept_at_dt1": np.nan,
            "slope_per_week": np.nan,
        }

    slope, intercept = np.polyfit(
        x,
        values,
        1,
    )

    return {
        "n_dt": int(ok.sum()),
        "intercept_at_dt1": float(intercept),
        "slope_per_week": float(slope),
    }


def exact_signflip(
    slopes: np.ndarray,
) -> Dict[str, float]:
    slopes = np.asarray(slopes, dtype=float)
    slopes = slopes[np.isfinite(slopes)]

    n = len(slopes)
    if n == 0:
        return {
            "n_subjects": 0,
            "mean_subject_slope": np.nan,
            "two_sided_p": np.nan,
            "one_sided_negative_p": np.nan,
            "one_sided_positive_p": np.nan,
            "n_negative_subject_slopes": 0,
            "n_positive_subject_slopes": 0,
            "n_zero_subject_slopes": 0,
        }

    if n > 20:
        raise ValueError(
            "Exact sign-flip enumeration is limited to <=20 subjects."
        )

    observed = float(np.mean(slopes))
    null = np.empty(2 ** n, dtype=float)

    for mask in range(2 ** n):
        signs = np.array(
            [
                1.0 if ((mask >> i) & 1) else -1.0
                for i in range(n)
            ],
            dtype=float,
        )
        null[mask] = float(
            np.mean(signs * slopes)
        )

    eps = 1e-15

    return {
        "n_subjects": int(n),
        "mean_subject_slope": observed,
        "two_sided_p": float(
            np.mean(
                np.abs(null)
                >= abs(observed) - eps
            )
        ),
        "one_sided_negative_p": float(
            np.mean(
                null <= observed + eps
            )
        ),
        "one_sided_positive_p": float(
            np.mean(
                null >= observed - eps
            )
        ),
        "n_negative_subject_slopes": int(
            np.sum(slopes < 0)
        ),
        "n_positive_subject_slopes": int(
            np.sum(slopes > 0)
        ),
        "n_zero_subject_slopes": int(
            np.sum(slopes == 0)
        ),
    }


def stable_sha256(payload: Mapping[str, object]) -> str:
    import hashlib
    raw = json.dumps(
        json_safe(dict(payload)),
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=True,
    )
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()


def path_identity(path: Path) -> Dict[str, object]:
    p = path.expanduser().resolve(strict=True)
    st = p.stat()
    return {
        "path": str(p),
        "size_bytes": int(st.st_size),
        "mtime_ns": int(st.st_mtime_ns),
    }


